package main

/*
Дана целочисленная матрица размера m x n.
Если элемент равен 0, установите всю его строку и столбец в 0.
Вы должны сделать это на месте.

Пример 1:
https://assets.leetcode.com/uploads/2020/08/17/mat1.jpg
Вход: matrix = [[1,1,1],[1,0,1],[1,1,1]]
Выход: [[1,0,1],[0,0,0],[1,0,1]]

Пример 2:
https://assets.leetcode.com/uploads/2020/08/17/mat2.jpg
Вход: matrix = [[0,1,2,0],[3,4,5,2],[1,3,1,5]]
Выход: [[0,0,0,0],[0,4,5,0],[0,3,1,0]]

Ограничения:
m == matrix.length
n == matrix[0].length
1 <= m, n <= 200
-2^31 <= matrix[i][j] <= 2^31 - 1
*/

// setZeroes использует первую строку и столбец как метки будущих нулей.
// m = len(matrix), n = len(matrix[0]); время O(m*n), рабочая память O(1).
// Результата нет; побочный эффект — изменение всей входной матрицы.
// Контракт гарантирует непустую прямоугольную матрицу.
func setZeroes(matrix [][]int) {
    ROWS, COLS := len(matrix), len(matrix[0])
    // matrix[0][0] кодирует нули первого столбца, rowZero — первой строки.
    // Один общий угол не может независимо хранить два этих признака.
    rowZero := false

    // Сначала собираем метки, не обнуляя внутреннюю область.
    // Строка 0 прочитана до чужих меток; столбец 0 каждой строки — до
    // её собственных меток, поэтому искусственные нули не размножаются.
    for r := range ROWS {
        for c := range COLS {
            if matrix[r][c] == 0 {
                matrix[0][c] = 0
                if r > 0 {
                    matrix[r][0] = 0
                } else {
                    rowZero = true
                }
            }
        }
    }

    // Внутренние клетки читают устойчивые метки; край пока не портим.
    for r := 1; r < ROWS; r++ {
        for c := 1; c < COLS; c++ {
            if matrix[0][c] == 0 || matrix[r][0] == 0 {
                matrix[r][c] = 0
            }
        }
    }

    // Края обнуляются последними, когда их метки уже использованы.
    if matrix[0][0] == 0 {
        for r := range ROWS {
            matrix[r][0] = 0
        }
    }

    if rowZero {
        for c := range COLS {
            matrix[0][c] = 0
        }
    }
}
