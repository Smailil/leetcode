package main

/*
В очереди за билетами стоят n человек. Человек с индексом 0 находится в
начале очереди, а человек с индексом n - 1 — в её конце.

Дан целочисленный массив tickets длиной n с индексацией от 0, где tickets[i]
— количество билетов, которое хочет купить i-й человек.

На покупку одного билета каждый человек тратит ровно 1 секунду. За один раз
можно купить только один билет. Чтобы купить следующий билет, человек должен
мгновенно перейти в конец очереди. Купив все нужные билеты, человек покидает
очередь.

Верните время, за которое человек, изначально находившийся на позиции k
(индексация с 0), купит все свои билеты.

Пример 1:
Вход: tickets = [2,3,2], k = 2
Выход: 6
Пояснение:
Изначально очередь имеет вид [2,3,2], а человек с индексом k подчёркнут.
После покупки билета человеком в начале очереди она становится [3,2,1],
проходит 1 секунда.
Затем очередь становится [2,1,2] через 2 секунды.
Затем очередь становится [1,2,1] через 3 секунды.
Затем очередь становится [2,1] через 4 секунды. Человек в начале очереди
купил все нужные билеты и ушёл.
Затем очередь становится [1,1] через 5 секунд.
Затем очередь становится [1] через 6 секунд. Человек с индексом k купил все
свои билеты, поэтому возвращаем 6.

Пример 2:
Вход: tickets = [5,1,1,1], k = 0
Выход: 8
Пояснение:
Изначально очередь имеет вид [5,1,1,1], а человек с индексом k подчёркнут.
После покупки билета человеком в начале очереди она становится [1,1,1,4],
проходит 1 секунда.
Если продолжать процесс ещё 3 секунды, через 4 секунды очередь примет
вид [4].
Ещё через 4 секунды очередь станет пустой. Человек с индексом k купит все
свои билеты через 8 секунд, поэтому возвращаем 8.

Ограничения:
n == tickets.length
1 <= n <= 100
1 <= tickets[i] <= 100
0 <= k < n
*/

// timeRequiredToBuy возвращает число секунд до последней покупки человека k.
// Вместо посекундного моделирования очереди функция суммирует количество
// покупок, которое каждый человек успеет сделать до завершения процесса.
// Время: O(n), где n = len(tickets). Дополнительная память: O(1).
func timeRequiredToBuy(tickets []int, k int) int {
    // Каждая покупка занимает одну секунду.
    // Поэтому сумма покупок равна общему времени.
    res := 0

    // Вклад каждого человека можно вычислить независимо от остальных.
    for i := range tickets {
        if i <= k {
            // Люди до k включительно участвуют в последнем круге очереди,
            // в котором человек k покупает свой последний билет.
            res += min(tickets[i], tickets[k])
        } else {
            // До людей после k последний круг уже не доходит, поэтому они
            // успевают купить максимум tickets[k]-1 билетов.
            res += min(tickets[i], tickets[k]-1)
        }
    }

    return res
}