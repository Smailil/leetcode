package main

/*
Пиковый элемент — элемент, который строго больше своих соседей.

Дан целочисленный массив nums с индексацией с 0.
Найдите пиковый элемент и верните его индекс.
Если в массиве несколько пиков, верните индекс любого из них.

Можно представить, что nums[-1] = nums[n] = -∞.
Иными словами, элемент всегда считается строго больше соседа,
который находится за границами массива.

Необходимо написать алгоритм, работающий за время O(log n).

Пример 1:
Вход: nums = [1,2,3,1]
Выход: 2
Пояснение: 3 — пиковый элемент, поэтому функция должна вернуть индекс 2.

Пример 2:
Вход: nums = [1,2,1,3,5,6,4]
Выход: 5
Пояснение:
Функция может вернуть индекс 1, где пиковый элемент равен 2,
или индекс 5, где пиковый элемент равен 6.

Ограничения:
1 <= nums.length <= 1000
-2^31 <= nums[i] <= 2^31 - 1
nums[i] != nums[i + 1] для всех допустимых i.
*/

// findPeakElement возвращает индекс любого строгого локального максимума.
// Бинарный поиск по направлению склона сохраняет отрезок хотя бы с одним пиком.
// Время: O(log n), где n = len(nums); дополнительная память: O(1).
// Входной срез nums не изменяется.
func findPeakElement(nums []int) int {
    // Массив непустой, а за его границами по условию находятся значения -∞.
    // При неравных соседях максимум всего массива обязательно будет пиком.
    l, r := 0, len(nums)-1

    // Инвариант: [l, r] содержит хотя бы один пик исходного массива.
    // Слева: l == 0 или nums[l] > nums[l-1].
    // Справа: r == n-1 или nums[r] > nums[r+1].
    // При неравных соседях максимум такого отрезка — пик всего массива.
    // Пример [1,2,3,1]: m = 1, 2 < 3, поэтому l = 2;
    // затем m = 2, 3 > 1, поэтому r = 2 и искомый индекс равен 2.
    for l < r {
        // При l < r получаем l <= m < r, поэтому m+1 не выходит за r.
        // Индексы неотрицательны: >> 1 делит на 2 с округлением вниз.
        // По условию n <= 1000, так что сумма l+r не переполняет int.
        m := (l + r) >> 1
        if nums[m] > nums[m+1] {
            // Между m и m+1 спуск: новый правый край m выше внешнего соседа.
            // Левая граница прежняя, поэтому в [l, m] по-прежнему есть пик.
            // Сам m тоже может быть пиком: оставляем его, устанавливая r = m.
            r = m
        } else {
            // Соседи неравны, значит здесь nums[m] < nums[m+1].
            // Новый левый край m+1 выше внешнего соседа; правый край прежний.
            // В [m+1, r] остаётся пик, а m не пик: правый сосед больше него.
            l = m + 1
        }
    }

    // Границы сошлись: по инварианту единственный оставшийся индекс пиковый.
    // При n = 1 цикл сразу пропускается и возвращается индекс 0.
    return l
}