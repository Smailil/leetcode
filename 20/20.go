package main

// Исходный strings не используется; импорт оставлен без изменения.
import "strings"

/*
Дана строка s, содержащая только символы '(', ')', '{', '}', '[' и ']'.
Определите, является ли входная строка допустимой.
Входная строка допустима, если:
Открывающие скобки закрываются скобками того же типа.
Открывающие скобки закрываются в правильном порядке.
Каждой закрывающей скобке соответствует открывающая скобка того же типа.

Пример 1:
Вход: s = "()"
Выход: true

Пример 2:
Вход: s = "()[]{}"
Выход: true

Пример 3:
Вход: s = "(]"
Выход: false

Пример 4:
Вход: s = "([])"
Выход: true

Пример 5:
Вход: s = "([)]"
Выход: false

Ограничения:
1 <= s.length <= 10^4
s состоит только из скобок '()[]{}'.
*/

// isValid проверяет вложенность скобок через стек открывающих.
// Закрывающая должна соответствовать последней ещё не закрытой скобке.
// Время O(n), n = len(s); рабочая память O(n), ответ bool занимает O(1).
// Карта из трёх ключей rune имеет постоянный размер и стоимость операций.
// s не меняется; исходный неиспользуемый импорт мешает компиляции.
func isValid(s string) bool {
	// Допустимые скобки — ASCII: байтовой длины хватает для rune-стека.
	// Даже при малой глубине сразу резервируется место для n rune.
	stack := make([]rune, 0, len(s))
	hash := map[rune]rune{')': '(', ']': '[', '}': '{'}
	for _, c := range s {
		if open, isClose := hash[c]; isClose {
			lenStack := len(stack)
			// Длина защищает индекс; совпадение типов разрешает снять вершину.
			// Внутренняя пара должна закрыться раньше охватывающей её пары.
			if lenStack > 0 && stack[lenStack-1] == open {
				stack = stack[:lenStack-1]
			} else {
				// Пустой стек или иной тип нарушают правильную вложенность.
				return false
			}
		} else {
			stack = append(stack, c)
		}
	}
	// Оставшиеся открывающие скобки тоже делают строку недопустимой.
	return len(stack) == 0
}
