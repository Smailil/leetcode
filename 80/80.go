package main

/*
Дан целочисленный массив nums, отсортированный по неубыванию.
Удалите часть дубликатов на месте так, чтобы каждый уникальный элемент
встречался не более двух раз.
Относительный порядок элементов должен остаться прежним.

Поскольку в некоторых языках нельзя изменить длину массива,
результат нужно поместить в начало массива nums.
Формально: если после удаления дубликатов осталось k элементов,
то первые k элементов nums должны содержать итоговый результат.
Содержимое массива после первых k элементов не имеет значения.

Верните k, поместив итоговый результат в первые k ячеек массива nums.

Не выделяйте дополнительную память для другого массива.
Изменяйте входной массив на месте, используя O(1) дополнительной памяти.

Проверяющая система:
Система проверит ваше решение следующим кодом:
int[] nums = [...]; // Входной массив
int[] expectedNums = [...]; // Ожидаемый ответ с правильной длиной
int k = removeDuplicates(nums); // Вызывает вашу реализацию
assert k == expectedNums.length;
for (int i = 0; i < k; i++) {
    assert nums[i] == expectedNums[i];
}
Если все проверки пройдут, ваше решение будет принято.

Пример 1:
Вход: nums = [1,1,1,2,2,3]
Выход: 5, nums = [1,1,2,2,3,_]
Пояснение: функция должна вернуть k = 5, а первые пять элементов nums
должны быть равны 1, 1, 2, 2 и 3 соответственно.
Содержимое после возвращённого k не имеет значения,
поэтому эти элементы обозначены подчёркиваниями.

Пример 2:
Вход: nums = [0,0,1,1,1,1,2,3,3]
Выход: 7, nums = [0,0,1,1,2,3,3,_,_]
Пояснение: функция должна вернуть k = 7, а первые семь элементов nums
должны быть равны 0, 0, 1, 1, 2, 3 и 3 соответственно.
Содержимое после возвращённого k не имеет значения,
поэтому эти элементы обозначены подчёркиваниями.

Ограничения:
1 <= nums.length <= 3 * 10^4
-10^4 <= nums[i] <= 10^4
nums отсортирован по неубыванию.
*/

// removeDuplicates оставляет не более двух копий каждого числа.
// Предполагает, что nums отсортирован по неубыванию.
// За один проход собирает допустимые числа в начале того же nums.
// Возвращает длину собранного префикса; исходный nums изменяется.
// Время: O(n), где n = len(nums).
// Рабочая память O(1); новый буфер результата не выделяется.
// Возвращаемое число занимает O(1); префикс лежит в исходном массиве.
func removeDuplicates(nums []int) int {
    // l — длина готового префикса nums[:l] и индекс следующей записи.
    // В этом префиксе каждое число встречается не более двух раз.
    l := 0

    // Читаем числа слева направо; num — очередное прочитанное значение.
    // l не больше индекса чтения, так как не каждое число сохраняется.
    // Поэтому запись в nums[l] не затрагивает будущие элементы обхода.
    for _, num := range nums {
        // При l < 2 число можно сохранить без сравнения.
        // Благодаря короткому замыканию || индекс l-2 не вычисляется.
        // Иначе сравниваем num с предпоследним числом готового префикса.
        // Если nums[l-2] == num, то nums[l-1] тоже равен num:
        // префикс отсортирован, а num не меньше его последнего числа.
        // Две копии уже сохранены, поэтому очередную пропускаем.
        // При отличии nums[l-2] в префиксе не более одной копии num.
        if l < 2 || num != nums[l-2] {
            // Добавляем допустимое число в префикс и расширяем его.
            nums[l] = num
            l++
        }
    }

    // Хвост массива не очищаем: результатом считаются только nums[:l].
    return l
}