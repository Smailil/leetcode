package main

/*
Дан массив nums из n целых чисел с индексацией с нуля.

Разбиение массива nums после индекса i считается допустимым, если:
- сумма первых i + 1 элементов не меньше суммы последних n - i - 1
  элементов;
- справа от i есть хотя бы один элемент, то есть 0 <= i < n - 1.
Верните количество допустимых разбиений массива nums.

Пример 1:
Вход: nums = [10,4,-8,7]
Выход: 2
Пояснение:
Есть три способа разбить nums на две непустые части:
- Разбиение после индекса 0.
  Первая часть — [10], её сумма — 10.
  Вторая часть — [4,-8,7], её сумма — 3.
  Поскольку 10 >= 3, разбиение при i = 0 допустимо.
- Разбиение после индекса 1.
  Первая часть — [10,4], её сумма — 14.
  Вторая часть — [-8,7], её сумма — -1.
  Поскольку 14 >= -1, разбиение при i = 1 допустимо.
- Разбиение после индекса 2.
  Первая часть — [10,4,-8], её сумма — 6.
  Вторая часть — [7], её сумма — 7.
  Поскольку 6 < 7, разбиение при i = 2 недопустимо.
Таким образом, количество допустимых разбиений массива nums равно 2.

Пример 2:
Вход: nums = [2,3,1,0]
Выход: 2
Пояснение:
В массиве nums есть два допустимых разбиения:
- Разбиение после индекса 1.
  Первая часть — [2,3], её сумма — 5.
  Вторая часть — [1,0], её сумма — 1.
  Поскольку 5 >= 1, разбиение при i = 1 допустимо.
- Разбиение после индекса 2.
  Первая часть — [2,3,1], её сумма — 6.
  Вторая часть — [0], её сумма — 0.
  Поскольку 6 >= 0, разбиение при i = 2 допустимо.

Ограничения:
2 <= nums.length <= 10^5
-10^5 <= nums[i] <= 10^5
*/

// waysToSplitArray считает разбиения на две непустые части,
// в которых сумма левой части не меньше суммы правой.
// Идея: найти общую сумму, затем перемещать границу, обновляя обе суммы.
// n = len(nums). Время: O(n), дополнительная память: O(1).
// nums не изменяется. По ограничениям суммы могут достигать по модулю
// 10^10, поэтому эта реализация рассчитана на 64-битный int.
func waysToSplitArray(nums []int) int {
    // Пока слева нет элементов, вся сумма находится в правой части.
    // Первый проход нужен, чтобы затем не пересчитывать её для каждой границы.
    right := 0
    for _, num := range nums {
        right += num
    }

    // left хранит сумму левой части, res — число допустимых разбиений.
    left, res := 0, 0
    // Последний элемент не переносим влево: правая часть должна быть непустой.
    // На первом шаге переносим nums[0], поэтому левая часть тоже непуста.
    for i := 0; i < len(nums)-1; i++ {
        // До переноса left — сумма nums[0:i], right — сумма nums[i:n].
        // Перенос nums[i] даёт суммы nums[0:i+1] и nums[i+1:n] соответственно.
        // Например, для [10,4,-8,7] при i = 0 получаем left = 10, right = 3.
        left += nums[i]
        right -= nums[i]
        // Сравниваем только после обоих обновлений: суммы относятся к одной
        // границе после i. Равенство тоже подходит, как требует условие.
        if left >= right {
            res++
        }
    }

    return res
}