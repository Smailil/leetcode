package main

/*
Дана строка s, содержащая только три типа символов: '(', ')' и '*'.
Верните true, если s допустима.

Следующие правила определяют допустимую строку:
Любая левая скобка '(' должна иметь соответствующую правую скобку ')'.
Любая правая скобка ')' должна иметь соответствующую левую скобку '('.
Левая скобка '(' должна стоять перед соответствующей правой скобкой ')'.
'*' можно рассматривать как одну правую скобку ')',
или одну левую скобку '(', или пустую строку "".

Пример 1:
Вход: s = "()"
Выход: true

Пример 2:
Вход: s = "(*)"
Выход: true

Пример 3:
Вход: s = "(*))"
Выход: true

Ограничения:
1 <= s.length <= 100
s[i] — это '(', ')' или '*'.
*/

// checkValidString поддерживает диапазон возможных незакрытых левых скобок.
// leftMin — минимум, leftMax — максимум среди допустимых разборов префикса.
// Время O(n), n=len(s); рабочая память и результат bool O(1).
// Строка не изменяется; по условию все символы — ASCII-скобки или "*".
func checkValidString(s string) bool {
    leftMin, leftMax := 0, 0

    for _, c := range s {
        switch c {
		case '(':
            leftMin, leftMax = leftMin+1, leftMax+1
        case ')':
            leftMin, leftMax = leftMin-1, leftMax-1
        // По условию это "*": крайние варианты — ")" и "(",
        // а пустой символ позволяет получить промежуточные значения диапазона.
        default:
            leftMin, leftMax = leftMin-1, leftMax+1
        }
        // Даже максимум отрицателен: закрывающую скобку ничем не парировать.
        if leftMax < 0 {
            return false
        }
        // Отрицательные количества нельзя использовать; 0 остаётся достижимым,
        // если максимум не отрицателен. Отбрасываем только невозможную часть.
        if leftMin < 0 {
            leftMin = 0
        }
    }
    // Если минимум 0, существует разбор без оставшихся открытых скобок.
    return leftMin == 0
}
