package main

/*
Дана строка s.
Вы можете превратить её в палиндром, добавляя символы в начало строки.

Верните кратчайший палиндром, который можно получить таким преобразованием.

Пример 1:
Вход: s = "aacecaaa"
Выход: "aaacecaaa"

Пример 2:
Вход: s = "abcd"
Выход: "dcbabcd"

Ограничения:
0 <= s.length <= 5 * 10^4
s состоит только из строчных букв английского алфавита.
*/

// shortestPalindrome строит кратчайший палиндром добавлением символов слева.
// Если s = p + t и p — палиндром, подходит reverse(t) + p + t.
// Чем длиннее p, тем меньше нужно добавить: ищем самый длинный такой префикс.
// Его длину находим префикс-функцией КМП для s + "#" + reverse(s).
// Время: O(n), где n = len(s); откаты КМП суммарно линейны.
// Рабочая память: O(n) для chars, reverse, combined и prefix.
// Память результата: O(n), длина не больше 2*n; входная строка не меняется.
func shortestPalindrome(s string) string {
	// По условию символы ASCII, поэтому байт соответствует одному символу.
	// []byte создаёт отдельный буфер: перестановки не изменяют строку s.
	// i < j гарантирует допустимость индексов; пустая строка пропускается.
	chars := []byte(s)
	for i, j := 0, len(chars)-1; i < j; i, j = i+1, j-1 {
		chars[i], chars[j] = chars[j], chars[i]
	}
	reverse := string(chars)

	// Граница строки — её собственный префикс, совпадающий с суффиксом.
	// Здесь граница длины L сопоставляет s[:L] с reverse(s[:L]).
	// Равенство означает, что первые L символов s образуют палиндром.
	// Символа # нет во входе: он не позволяет границе пересечь разделитель,
	// поэтому длина искомой границы не превышает len(s).
	combined := s + "#" + reverse

	// prefix[i] — длина наибольшей собственной границы combined[:i+1].
	// «Собственная» исключает всю подстроку целиком; prefix[0] равен нулю.
	// Даже при пустой s строка combined содержит #, так что массив не пуст.
	prefix := make([]int, len(combined))
	for i := 1; i < len(combined); i++ {
		// Пробуем продлить границу предыдущего префикса символом combined[i].
		// j — её длина, а combined[j] — следующий ожидаемый символ.
		// j <= i-1, поэтому чтение combined[j] остаётся внутри строки.
		j := prefix[i-1]

		// При несовпадении подходит только более короткая граница прежней.
		// prefix[j-1] даёт самого длинного из оставшихся кандидатов:
		// уже совпавшие символы заново не перебираем. j > 0 защищает j-1.
		// За весь цикл j растёт не более O(n) раз и столько же убывает,
		// поэтому вложенный цикл не увеличивает время до O(n²).
		for j > 0 && combined[i] != combined[j] {
			j = prefix[j-1]
		}

		// Совпадение продлевает найденную границу на один символ.
		// Если и при j = 0 совпадения нет, граница остаётся пустой.
		if combined[i] == combined[j] {
			j++
		}
		prefix[i] = j
	}

	// Последний элемент prefix задаёт L — длину палиндромного префикса s.
	// Оставшийся суффикс длины n-L нужно отразить перед s; его отражение
	// уже находится в первых n-L байтах reverse. Из 0 <= L <= n следует,
	// что граница среза допустима, в том числе для пустой строки.
	// Например, для abcd: L = 1, добавляем dcb и получаем dcbabcd.
	// Если добавить m < n символов, первые n-m символов самой s должны
	// образовать палиндром: они зеркально сопоставляются друг с другом.
	// Поэтому m >= n-L, и найденное число добавлений действительно минимально.
	return reverse[:len(s)-prefix[len(prefix)-1]] + s
}
