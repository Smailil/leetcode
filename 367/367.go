package main

/*
Дано положительное целое число num.
Верните true, если num является полным квадратом, иначе верните false.

Полный квадрат — целое число, являющееся квадратом целого числа.
Иными словами, это произведение некоторого целого числа на само себя.

Нельзя использовать встроенные библиотечные функции, например sqrt.

Пример 1:
Вход: num = 16
Выход: true
Пояснение: возвращаем true, потому что 4 * 4 = 16, а 4 — целое число.

Пример 2:
Вход: num = 14
Выход: false
Пояснение: возвращаем false, потому что 3.742 * 3.742 = 14,
а 3.742 не является целым числом.

Ограничения:
1 <= num <= 2^31 - 1
*/

// isPerfectSquare проверяет, равен ли num квадрату целого числа.
// Идея: бинарным поиском ищем корень, сравнивая его квадрат с num.
// Время: O(1) при заданной границе num <= 2^31 - 1: не более 31 итерации.
// В общем виде число итераций — O(log num). Дополнительная память: O(1).
func isPerfectSquare(num int) bool {
    // Если целый корень существует, он лежит в [1, num], так как num >= 1.
    // Инвариант: после каждого сужения такой корень остаётся внутри [l, r].
    l, r := 1, num

    for l <= r {
        // Такая запись середины не складывает l и r: результат лежит в [l, r].
        // При l <= r разность r-l неотрицательна и не превышает num-1.
        m := l + (r-l)/2
        // Здесь нужен 64-битный int: m <= num <= 2^31-1, значит m*m < 2^62.
        // Это помещается в int64, но на 32-битной платформе возможно
        // переполнение. Например, для num = 16 середина m = 8 даёт sq = 64.
        sq := m * m
        if sq > num {
            // На положительных целых квадрат строго возрастает: если m*m
            // уже слишком велик, ни m, ни числа правее не подходят.
            // Для num = 16: m = 8 даёт r = 7; затем m = 4 и 4*4 = 16.
            r = m - 1
        } else if sq < num {
            // Если квадрат мал, исключаем m и всё левее него. Сам m
            // исключается в обеих ветках, поэтому диапазон уменьшается.
            l = m + 1
        } else {
            // Найдено точное равенство m*m = num: целый корень существует.
            return true
        }
    }

    // l > r: все возможные целые корни исключены, полного квадрата нет.
    return false
}