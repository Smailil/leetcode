package main

/*
Даны две строки order и s. Все символы строки order уникальны и заранее
расположены в некотором пользовательском порядке.

Переставьте символы строки s так, чтобы они соответствовали порядку из order.
Точнее, если символ x находится в order раньше символа y, то в переставленной
строке x также должен находиться раньше y.

Верните любую перестановку строки s, удовлетворяющую этому условию.

Пример 1:
Вход: order = "cba", s = "abcd"
Выход: "cbad"
Пояснение: символы "a", "b" и "c" встречаются в order, поэтому в результате
они должны идти в порядке "c", "b", "a".
Поскольку символа "d" нет в order, он может находиться в любой позиции
возвращаемой строки. Варианты "dcba", "cdba" и "cbda" также допустимы.

Пример 2:
Вход: order = "bcafg", s = "abcd"
Выход: "bcad"
Пояснение: символы "b", "c" и "a" из order задают взаимный порядок этих же
символов в s. Символа "d" из s нет в order, поэтому его позиция не ограничена.
Согласно order, символы "b", "c" и "a" из s должны располагаться именно в
таком порядке. Символ "d" можно поставить в любую позицию, поскольку его нет
в order. Результат "bcad" следует этому правилу. Варианты "dbca" и "bcda"
также допустимы, пока символы "b", "c" и "a" сохраняют указанный порядок.

Ограничения:
1 <= order.length <= 26
1 <= s.length <= 200
order и s состоят из строчных английских букв.
Все символы строки order уникальны.
*/

// customSortString строит перестановку s, в которой символы из order идут
// в заданном порядке. Входные строки order и s не изменяются.
// Время работы — O(n + m + A), где n = len(s), m = len(order), A = 26 —
// размер алфавита. При фиксированном A это O(n + m), а с m <= 26 — O(n).
// Дополнительная рабочая память — O(n + A): массив частот занимает O(A),
// временный срез res — O(n). Возвращаемая строка также занимает O(n).
func customSortString(order string, s string) string {
    // По условию order и s содержат только байты 'a'..'z', поэтому вычитание
    // 'a' всегда даёт безопасный индекс 0..25 для массива частот.
    count := make([]int, 26)
    for i := 0; i < len(s); i++ {
        count[s[i]-'a']++
    }

    var res []byte

    // Сначала переносим все символы, перечисленные в order. Обнулённая
    // частота не позволит добавить их повторно на следующем этапе.
    for i := 0; i < len(order); i++ {
        idx := order[i] - 'a'
        for count[idx] > 0 {
            res = append(res, order[i])
            count[idx]--
        }
    }

    // Оставшиеся символы отсутствуют в order, поэтому их допустимо поставить
    // после упорядоченной части. Обход 0..25 делает результат
    // детерминированным.
    for idx := range 26 {
        c := byte('a' + idx)
        for count[idx] > 0 {
            res = append(res, c)
            count[idx]--
        }
    }

    // Преобразуем накопленные байты в итоговую строку длины n.
    return string(res)
}
