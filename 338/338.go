package main

/*
Дано целое число n.
Верните массив ans длины n + 1 такой, что для каждого i (0 <= i <= n)
ans[i] — это количество единиц в двоичном представлении i.

Пример 1:
Вход: n = 2
Выход: [0,1,1]
Объяснение:
0 --> 0
1 --> 1
2 --> 10

Пример 2:
Вход: n = 5
Выход: [0,1,1,2,1,2]
Объяснение:
0 --> 0
1 --> 1
2 --> 10
3 --> 11
4 --> 100
5 --> 101

Ограничения:
0 <= n <= 10^5
*/

// countBits считает popcount всех чисел от 0 до n рекуррентной формулой.
// Время O(n+1), рабочая память без результата O(1), результат O(n+1).
// n не меняется; n+1<=100001 безопасно для размера нового буфера.
func countBits(n int) []int {
    dp := make([]int, n+1)
    // dp[0]=0 уже задан нулевой инициализацией; n=0 возвращает [0].
    // Для i>=1 удаление младшего бита даёт i>>1=floor(i/2)<i,
    // значит dp[i>>1] известен. i&1 возвращает удалённый бит (0 или 1).
    // Например, 5=101₂: dp[2]+1=1+1=2; сдвиг применяется к неотрицательному i.
    for i := 1; i <= n; i++ {
        dp[i] = dp[i >> 1] + (i & 1)
    }
    return dp
}
