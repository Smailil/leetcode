package main

import "sort"

/*
Дан массив nums из n целых чисел.
Верните массив всех уникальных четвёрок [nums[a], nums[b], nums[c], nums[d]],
для которых:
0 <= a, b, c, d < n
a, b, c и d попарно различны.
nums[a] + nums[b] + nums[c] + nums[d] == target
Ответ можно вернуть в любом порядке.

Пример 1:
Вход: nums = [1,0,-1,0,-2,2], target = 0
Выход: [[-2,-1,1,2],[-2,0,0,2],[-1,0,0,1]]

Пример 2:
Вход: nums = [2,2,2,2,2], target = 8
Выход: [[2,2,2,2]]

Ограничения:
1 <= nums.length <= 200
-10^9 <= nums[i] <= 10^9
-10^9 <= target <= 10^9
*/

// fourSum сортирует nums и сводит 4-Sum к выбору двух чисел и 2-Sum.
// Пропуск равных значений на каждом уровне даёт уникальные четвёрки.
// Время: O(n^3), n = len(nums); сортировка O(n log n) не доминирует.
// Рабочая память: O(log n) для сортировки и O(1) для пути/стека k-Sum.
// Результат: O(R), R — число четвёрок; каждая содержит ровно 4 числа.
// Побочный эффект: nums сортируется на месте.
// Суммы до 4 * 10^9 требуют 64-битного int в используемой среде.
func fourSum(nums []int, target int) [][]int {
	// Сортировка необходима для:
	// 1. Упрощённого пропуска дубликатов.
	// 2. Работы двух указателей в базовом случае.
	sort.Ints(nums)
	
	res := [][]int{} // Результирующий срез уникальных четвёрок.
	quad := []int{}  // Временный срез для хранения текущей комбинации чисел.

	// Рекурсивная функция для решения задачи k-Sum.
	// k: сколько ещё чисел нужно подобрать.
	// start: индекс начала перебора в отсортированном массиве.
	// target: оставшаяся сумма, которую необходимо набрать.
	var kSum func(k, start, target int)
	// kSum дополняет quad: k чисел выбираются из nums[start:].
	// target равен исходной цели минус сумма уже выбранных чисел quad.
	// При фиксированном k время O(n^(k-1)), рабочий стек/путь O(k).
	// Результат пополняется в общем res; длина quad после вызова прежняя.
	kSum = func(k, start, target int) {
		// Базовый случай: задача сводится к 2-Sum.
		if k == 2 {
			// Между l и r находятся ещё не исключённые кандидаты пары.
			// В отсортированном массиве малая сумма исключает текущий l,
			// а большая — текущий r: другие пары с этим концом не подходят.
			l, r := start, len(nums)-1
			for l < r {
				sum := nums[l] + nums[r]
				if sum < target {
					l++ // Сумма мала: двигаем левый указатель вправо, увеличивая сумму.
				} else if sum > target {
					r-- // Сумма велика: двигаем правый указатель влево, уменьшая сумму.
				} else {
					// Нашли пару, дающую нужную сумму.
					// quad ссылается на буфер, используемый следующими ветвями.
					// Копия отделяет сохранённую четвёрку от будущих изменений.
					temp := make([]int, len(quad))
					copy(temp, quad)
					temp = append(temp, nums[l], nums[r])
					res = append(res, temp)

					// Сдвигаем оба указателя и пропускаем дубликаты.
					// После сдвига l-1 и r+1 — прежние, допустимые индексы.
					// Проверка l < r защищает доступ к новым позициям.
					l++
					r--
					for l < r && nums[l] == nums[l-1] {
						l++
					}
					for l < r && nums[r] == nums[r+1] {
						r--
					}
				}
			}
			return
		}

		// Рекурсивный случай: k > 2.
		// Перебираем возможные первые числа для текущей комбинации.
		// При i <= len(nums)-k справа останется не менее k-1 элементов.
		for i := start; i <= len(nums)-k; i++ {
			// Пропускаем дубликаты на текущем уровне рекурсии,
			// чтобы избежать повторных одинаковых четвёрок.
			if i > start && nums[i] == nums[i-1] {
				continue
			}
			
			// Добавляем текущее число в путь.
			quad = append(quad, nums[i])
			
			// Рекурсивно ищем оставшиеся k-1 чисел с обновлённой целью.
			// start = i+1 запрещает повторно брать тот же индекс.
			// Остаточная цель может выходить за исходные ±10^9,
			// но при k <= 4 помещается в 64-битный int.
			kSum(k-1, i+1, target-nums[i])
			
			// Поиск с возвратом: удаляем последнее число,
			// чтобы попробовать следующий вариант.
			quad = quad[:len(quad)-1]
		}
	}

	// Запускаем рекурсию для поиска 4 чисел, начиная с индекса 0.
	kSum(4, 0, target)
	return res
}
