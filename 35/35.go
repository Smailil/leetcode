package main

/*
Дан отсортированный массив различных целых чисел и целевое значение.
Верни индекс, если цель найдена.
Если нет — верни индекс, по которому она была бы вставлена,
сохраняя порядок сортировки.

Необходимо написать алгоритм со временной сложностью O(log n).

Пример 1:
Вход: nums = [1,3,5,6], target = 5
Выход: 2

Пример 2:
Вход: nums = [1,3,5,6], target = 2
Выход: 1

Пример 3:
Вход: nums = [1,3,5,6], target = 7
Выход: 4

Ограничения:
1 <= nums.length <= 10^4
-10^4 <= nums[i] <= 10^4
nums содержит различные значения, отсортированные в порядке возрастания.
-10^4 <= target <= 10^4
*/

// searchInsert ищет target бинарным поиском по включённым границам.
// Если target отсутствует, пересечение границ даёт позицию вставки.
// Время: O(log n), n = len(nums); дополнительная память: O(1).
// Вход не изменяется, даже когда возвращённый индекс равен n.
func searchInsert(nums []int, target int) int {
    l, r := 0, len(nums)-1
    // Все значения до l меньше target, все значения после r больше target.
    // Только [l, r] ещё может содержать target.
    for l <= r {
        // l и r лежат внутри массива; n <= 10^4, сумма не переполняет int.
        // Целочисленное деление даёт индекс внутри текущего [l, r].
        mid := (l + r) / 2
        if nums[mid] == target {
            return mid
        }
        // При большем nums[mid] исключаем mid и всё справа от него.
        // После проверки равенства другая ветвь означает nums[mid] < target.
        if nums[mid] > target {
            r = mid - 1
        } else {
            l = mid + 1
        }
    }
    // Теперь l == r+1: слева значения меньше target, справа — больше.
    // l может быть n; это вставка в конец, а не обращение к nums[n].
    return l
}
