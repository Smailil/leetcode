package main

/*
Дана строка, содержащая цифры от 2 до 9 включительно.
Верните все возможные комбинации букв, которые может представлять число.
Ответ можно вернуть в любом порядке.
Соответствие цифр буквам, как на кнопках телефона, приведено ниже.
Цифре 1 не соответствует ни одна буква.
https://assets.leetcode.com/uploads/2022/03/15/1200px-telephone-keypad2svg.png

Пример 1:
Вход: digits = "23"
Выход: ["ad","ae","af","bd","be","bf","cd","ce","cf"]

Пример 2:
Вход: digits = "2"
Выход: ["a","b","c"]

Ограничения:
1 <= digits.length <= 4
digits[i] — цифра в диапазоне ['2', '9'].
*/

// letterCombinations строит все варианты букв поиском с возвратом.
// Каждая ветвь выбирает одну букву для очередной цифры.
// Пусть n = len(digits), C — произведение чисел букв для всех цифр.
// Время: O(n * C), включая копирование строк при конкатенации.
// Рабочая память: O(n^2) для префиксов строк на стеке глубины O(n).
// Результат: O(n * C) байтов строк и O(C) заголовков. Вход не меняется.
func letterCombinations(digits string) []string {
    // Отдельно поддержан пустой ввод: возвращаем пустую коллекцию,
    // а не комбинацию из одной пустой строки.
    if len(digits) == 0 {
		return []string{}
	}
	var result []string
	// Таблица имеет постоянный размер и соответствует цифрам 2..9.
	phoneMap := []string{"abc", "def", "ghi", "jkl", "mno", "pqrs", "tuv", "wxyz"}
	var backtrack func(int, string)
	// backtrack продолжает префикс curS длины i до полной комбинации.
	// Для t оставшихся цифр с P продолжениями время O(n * P).
	// Стек и одновременно живые префиксы занимают O(n^2) без результата.
	// Замыкание добавляет листья в result; строки не изменяются на месте.
	backtrack = func(i int, curS string) {
		// В curS уже выбрано ровно по одной букве для первых i цифр.
		// При i == n получается один лист дерева вариантов.
		if len(digits) == i {
			result = append(result, curS)
			return 
		}
		// До этого места i меньше n; ASCII-цифры 2..9 дают индекс 0..7.
		letters := phoneMap[digits[i]-'2']
		// Конкатенация создаёт новую строку для дочерней ветви.
		// Родительский curS сохраняется, поэтому отдельный откат не нужен.
		for _, c := range letters {
			backtrack(i+1, curS+string(c))
		}
	}
	// Пустой префикс задаёт корень, последовательные выборы дают все C листьев.
	backtrack(0, "")
	return result
}
