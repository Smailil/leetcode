package main

/*
Задача о n ферзях состоит в размещении n ферзей на доске размера n x n
так, чтобы никакие два ферзя не атаковали друг друга.

Дано целое число n.
Верните количество различных решений задачи о n ферзях.

Пример 1:
https://assets.leetcode.com/uploads/2020/11/13/queens.jpg
Вход: n = 4
Выход: 2
Пояснение: существует два различных решения задачи о 4 ферзях,
как показано на изображении.

Пример 2:
Вход: n = 1
Выход: 1

Ограничения:
1 <= n <= 9
*/

// totalNQueens считает расстановки, выбирая один столбец в каждой строке.
// Время O(n*n!) в среднем: верхняя оценка учитывает n проверок на узел
// дерева частичных перестановок и средний O(1) поиска int-ключа map.
// Рабочая память O(n) для трёх карт и рекурсии; результат — число.
// Внешнего состояния нет, карты содержат лишь текущую расстановку.
func totalNQueens(n int) int {
    // Для проверки угроз за O(1) в среднем используем хеш-карты
    // вместо двумерного массива.
    // Математика диагоналей:
    // - Диагонали с одинаковой суммой r + c.
    // - Диагонали с одинаковой разностью r - c.
    // При диагональном шаге (r+1,c-1) сумма постоянна,
    // а при шаге (r+1,c+1) постоянна разность.
    col := make(map[int]bool)     // Занятые вертикали (столбцы).
    posDiag := make(map[int]bool) // Диагонали с одинаковой суммой r+c.
    negDiag := make(map[int]bool) // Диагонали с одинаковой разностью r-c.
    
    res := 0 // Счётчик найденных допустимых решений.

    // Рекурсивная функция для перебора вариантов с возвратом.
    // Принимает номер строки r, в которую пытаемся поставить ферзя.
    var backtrack func(r int)
    // Перед входом заняты ровно столбцы и диагонали ферзей строк [0,r).
    // q = n-r — число оставшихся строк; время O(n*q!) в среднем.
    // Рабочий стек O(q+1), три карты занимают O(n), ответ — счётчик res.
    // Карты меняются с откатом; res накапливает все найденные решения.
    backtrack = func(r int) {
        // Базовый случай: если успешно дошли до строки n,
        // значит все n ферзей расставлены и не бьют друг друга.
        if r == n {
            res++ // Засчитываем найденную расстановку.
            return
        }

        // Пробуем поставить ферзя в каждый столбец c текущей строки r.
        for c := range n {
            // Если столбец или одна из диагоналей уже заняты другим ферзём,
            // ставить сюда нельзя — переходим к следующему столбцу.
            if col[c] || posDiag[r+c] || negDiag[r-c] {
                continue
            }

            // Ставим ферзя: помечаем столбец и обе диагонали как занятые.
            col[c] = true
            posDiag[r+c] = true
            negDiag[r-c] = true

            // Рекурсивно расставляем ферзей в следующей строке r + 1.
            backtrack(r + 1)

            // Возвращаемся назад: убираем ферзя, чтобы освободить
            // столбец и диагонали для проверки других вариантов в цикле.
            delete(col, c)
            delete(posDiag, r+c)
            delete(negDiag, r-c)
        }
    }

    // Запускаем поиск с самой верхней строки, с индекса 0.
    backtrack(0)
    
    return res
}