package main

/*
Дан журнал посещений магазина, представленный строкой customers.
Индексация строки начинается с 0.
Строка состоит только из символов 'N' и 'Y':

Если i-й символ равен 'Y', в i-й час приходят покупатели.
Символ 'N' означает, что в i-й час покупатели не приходят.
Если магазин закрывается в j-й час (0 <= j <= n), штраф считается так:

За каждый час, когда магазин открыт, но покупателей нет, штраф растёт на 1.
За каждый час, когда магазин закрыт, но покупатели есть, штраф растёт на 1.
Верните самый ранний час закрытия магазина с минимальным штрафом.

Если магазин закрывается в j-й час, то в этот час он уже закрыт.

Пример 1:
Вход: customers = "YYNY"
Выход: 2
Пояснение:
- Закрытие в 0-й час даёт штраф 1+1+0+1 = 3.
- Закрытие в 1-й час даёт штраф 0+1+0+1 = 2.
- Закрытие во 2-й час даёт штраф 0+0+0+1 = 1.
- Закрытие в 3-й час даёт штраф 0+0+1+1 = 2.
- Закрытие в 4-й час даёт штраф 0+0+1+0 = 1.
Закрытие во 2-й или 4-й час даёт минимальный штраф.
Поскольку 2 раньше 4, оптимальный час закрытия — 2.

Пример 2:
Вход: customers = "NNNNN"
Выход: 0
Пояснение: лучше закрыться в 0-й час, так как покупатели не приходят.

Пример 3:
Вход: customers = "YYYY"
Выход: 4
Пояснение: лучше закрыться в 4-й час, так как покупатели приходят каждый час.

Ограничения:
1 <= customers.length <= 10^5
customers состоит только из символов 'Y' и 'N'.
*/

// bestClosingTime возвращает самый ранний час закрытия с минимальным штрафом.
// Идея: вместо полного штрафа считаем его уменьшение относительно закрытия в 0.
// Чем больше это уменьшение, тем меньше итоговый штраф.
// Время: O(n), где n = len(customers). Дополнительная память: O(1).
// Входная строка не изменяется.
func bestClosingTime(customers string) int {
    // При закрытии в 0 штраф P(0) равен общему числу 'Y': все покупатели
    // приходят в закрытый магазин. Для закрытия в j первые j часов открыты.
    // Каждый 'Y' в этих часах убирает единицу штрафа,
    // а каждый 'N' добавляет её.
    // Значит, P(j) = P(0) - G(j), где G(j) = число 'Y' минус число 'N'
    // среди первых j символов. P(0) одинаков для всех j, считать его не нужно.
    // Несмотря на имена, penalty хранит G(j), а minPenalty — максимум G(j).
    // Изначально G(0) = 0, поэтому исходный лучший час res равен 0.
    res, minPenalty, penalty := 0, 0, 0

    // Переносим закрытие с часа i на i + 1: теперь час i тоже будет открытым.
    // До обработки символа penalty = G(i), после обработки — G(i + 1).
    for i := 0; i < len(customers); i++ {
        if customers[i] == 'Y' {
            // Покупатели в час i теперь обслужены: штраф уменьшается на 1,
            // поэтому выигрыш penalty относительно закрытия в 0 растёт на 1.
            penalty++
        } else {
            // По условию здесь только 'N': открытый час без покупателей
            // добавляет единицу штрафа, поэтому выигрыш уменьшается на 1.
            penalty--
        }

        // Больший G(i + 1) означает меньший P(i + 1), поэтому запоминаем
        // именно i + 1: в час закрытия магазин уже не работает.
        // Обновляем только при строгом улучшении. Часы идут по возрастанию,
        // поэтому при равном штрафе сохраняется самый ранний из них.
        // Например, для "YYNY" часы 2 и 4 дают G = 2; res останется равным 2.
        if penalty > minPenalty {
            minPenalty = penalty
            res = i + 1
        }
    }

    // Проверены все часы закрытия 0..n, включая закрытие после последнего часа.
    // Для одних 'N' лучший час останется 0; для одних 'Y' станет равным n.
    return res
}