package main

/*
Вам дана сетка размером m x n, где каждая ячейка может иметь одно из трех
значений:
0 представляет пустую ячейку,
1 представляет собой свежий апельсин или
2 представляет собой гнилой апельсин.

Каждую минуту любой свежий апельсин, примыкающий к гнилому апельсину в четырех
направлениях, становится гнилым.
Верните минимальное число минут, через которое в сетке
не останется ни одного свежего апельсина.
Если это невозможно, верните -1.

Пример 1:
https://assets.leetcode.com/uploads/2019/02/16/oranges.png
Вход: grid = [[2,1,1],[1,1,0],[0,1,1]]
Выход: 4

Пример 2:
Вход: grid = [[2,1,1],[0,1,1],[1,0,1]]
Выход: -1
Пояснение: Апельсин в левом нижнем углу (строка 2, столбец 0) никогда не бывает
гнилым, поскольку гниение происходит только в 4 направлениях.

Пример 3:
Вход: grid = [[0,2]]
Выход: 0
Пояснение: Поскольку на минуте 0 свежих апельсинов уже нет, ответ будет всего
лишь 0.

Ограничения:
m == grid.length
n == grid[i].length
1 <= m, n <= 10
grid[i][j] равна 0, 1 или 2.
*/

type orangesCoords struct {
	row int
	col int
}

// orangesRotting распространяет гниение BFS от всех исходных источников.
// m = len(grid), n = len(grid[0]): время и рабочая память O(m*n).
// Очередь, включая удерживаемый буфер, содержит O(m*n) координат.
// Результат — число O(1); свежие ячейки grid меняются с 1 на 2.
func orangesRotting(grid [][]int) int {
	directions := [][2]int{
		{0, 1},
		{0, -1},
		{1, 0},
		{-1, 0},
	}
	q := []orangesCoords{}
	time, fresh := 0, 0
	// По контракту сетка непустая и прямоугольная: grid[0] существует.
	rows, cols := len(grid), len(grid[0])

	// Все исходные гнилые апельсины — одна волна минуты 0.
	// fresh считает ещё не заражённые ячейки независимо от числа источников.
	for r := range rows {
		for c := range cols {
			switch grid[r][c] {
			case 1:
				fresh++
			case 2:
				q = append(q, orangesCoords{r, c})
			}
		}
	}
	// В начале шага q хранит только источники текущей минуты.
	// Новые заражения дописываются после них и ждут следующего шага.
	for len(q) != 0 && fresh > 0 {
		// Снимок длины не позволяет обработать новые ячейки в ту же минуту.
		currentRotten := len(q)
		for range currentRotten {
			cur := q[0]
			q = q[1:]
			for _, d := range directions {
				r, c := d[0]+cur.row, d[1]+cur.col
				// cur допустим, сдвиг равен -1, 0 или 1: выход за сетку
				// возможен только через -1 или rows/cols. || сначала проверяет
				// границы и только затем обращается к grid[r][c].
				if r < 0 || r == rows ||
					c < 0 || c == cols ||
					grid[r][c] != 1 {
					continue
				}
				// Помечаем до постановки в очередь: другая волна не добавит
				// эту ячейку повторно. Каждая свежая ячейка заражается один раз.
				grid[r][c] = 2
				q = append(q, orangesCoords{r, c})
				fresh--
			}
		}
		// Завершили одну волну: заражённые соседи относятся к time+1.
		time++
	}
	// Если свежих не было изначально, цикл пропущен и time равен 0.
	// Пустая очередь при fresh > 0 означает недостижимые свежие апельсины.
	if fresh == 0 {
		return time
	} else {
		return -1
	}
}
