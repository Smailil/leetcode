package main

/*
В ряд стоят n костяшек домино, каждая изначально расположена вертикально.
Сначала мы одновременно толкаем некоторые костяшки влево или вправо.

Каждую секунду падающая влево костяшка толкает соседнюю костяшку слева.
Аналогично падающая вправо костяшка толкает соседнюю стоящую костяшку справа.

Если на вертикально стоящую костяшку одновременно падают костяшки с обеих
сторон, она остаётся на месте из-за равновесия сил.

В этой задаче считаем, что падающая костяшка не оказывает дополнительного
усилия на костяшку, которая тоже падает или уже упала.

Дана строка dominoes, описывающая исходное состояние:
- dominoes[i] = 'L', если i-ю костяшку толкнули влево;
- dominoes[i] = 'R', если i-ю костяшку толкнули вправо;
- dominoes[i] = '.', если i-ю костяшку не толкали.
Верните строку, описывающую конечное состояние.

Пример 1:
Вход: dominoes = "RR.L"
Выход: "RR.L"
Пояснение: первая костяшка не оказывает дополнительного усилия на вторую.

Пример 2:
https://s3-lc-upload.s3.amazonaws.com/uploads/2018/05/18/domino.png
Вход: dominoes = ".L.R...LR..L.."
Выход: "LL.RR.LLRRLL.."

Ограничения:
n == dominoes.length
1 <= n <= 10^5
dominoes[i] имеет значение 'L', 'R' или '.'.

*/

// pushDominoes возвращает состояние домино после распространения толчков.
// Толчки обрабатываются очередью по секундам, начиная с исходных.
// Время O(n), дополнительная рабочая память O(n), где n = len(dominoes).
// Возвращаемая строка занимает ещё O(n) памяти.
func pushDominoes(dominoes string) string {
    // dom позволяет отмечать упавшие костяшки, а q хранит позиции и
    // направления толчков, влияние которых ещё предстоит обработать.
    dom := []byte(dominoes)
    q := [][2]int{}

    // Все исходные толчки происходят одновременно: сначала ставим их
    // в очередь слева направо как первую временную волну.
    for i := range dom {
        if dom[i] != '.' {
            q = append(q, [2]int{i, int(dom[i])})
        }
    }

    // Новые падения идут в конец очереди и обрабатываются после
    // остальных событий той же секунды.
    for len(q) > 0 {
        curr := q[0]
        q = q[1:]
        i, d := curr[0], byte(curr[1])

        // Толчок влево затрагивает только ещё стоящую соседнюю костяшку.
        // Сразу помечаем её, чтобы не добавлять в очередь повторно.
        if d == 'L' && i > 0 && dom[i-1] == '.' {
            q = append(q, [2]int{i - 1, int('L')})
            dom[i-1] = 'L'
        } else if d == 'R' {
            if i+1 < len(dom) && dom[i+1] == '.' {
                // R и L через одну позицию достигнут середины одновременно.
                // Эта L-волна идёт в очереди следующей: убираем её,
                // а среднюю костяшку оставляем вертикальной.
                if i+2 < len(dom) && dom[i+2] == 'L' {
                    q = q[1:]
                } else {
                    // Без встречной волны падение распространяется вправо.
                    q = append(q, [2]int{i + 1, int('R')})
                    dom[i+1] = 'R'
                }
            }
        }
    }

    return string(dom)
}