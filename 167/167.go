package main

/*
Дан массив целых чисел numbers с индексацией от 1,
который уже отсортирован в неубывающем порядке.
Найдите два числа, сумма которых даёт заданное целевое число.
Пусть это numbers[index1] и numbers[index2], где:
1 <= index1 < index2 <= numbers.length
Верните индексы index1 и index2
в виде целочисленного массива [index1, index2] длины 2.
Индексы результата отсчитываются от 1.

Тесты генерируются так, что существует ровно одно решение.
Вы не можете использовать один и тот же элемент дважды.

Ваше решение должно использовать только постоянное дополнительное пространство.

Пример 1:
Вход: numbers = [2,7,11,15], target = 9
Выход: [1,2]
Пояснение: Сумма 2 и 7 равна 9.
Следовательно, index1 = 1, index2 = 2.
Мы возвращаем [1, 2].

Пример 2:
Вход: numbers = [2,3,4], target = 6
Выход: [1,3]
Пояснение: Сумма 2 и 4 равна 6.
Следовательно, index1 = 1, index2 = 3.
Мы возвращаем [1, 3].

Пример 3:
Вход: numbers = [-1,0], target = -1
Выход: [1,2]
Пояснение: Сумма -1 и 0 равна -1.
Следовательно, index1 = 1, index2 = 2.
Мы возвращаем [1, 2].

Ограничения:
2 <= numbers.length <= 3 * 10^4
-1000 <= numbers[i] <= 1000
numbers отсортирован в порядке неубывания.
-1000 <= target <= 1000
Тесты генерируются так, что существует ровно одно решение.
*/

// twoSum ищет пару в отсортированном массиве встречными указателями.
// Время O(n), n=len(numbers); рабочая память O(1), результат — два int O(1).
// numbers не изменяется; наличие решения гарантировано условием.
func twoSum(numbers []int, target int) []int {
    l, r := 0, len(numbers)-1
	// l меньше r: читаем разные элементы внутри допустимого диапазона.
	for l < r {
		sum := numbers[l]+numbers[r]
		// С этим r любой левый индекс не раньше l даст не меньшую сумму.
		// Поэтому при слишком большой сумме правый элемент можно исключить.
		// Сумма в [-2000,2000] безопасна для int по ограничениям задачи.
		if sum > target {
			r--
		// С этим l любой правый индекс не позже r даст не большую сумму.
		// Поэтому при слишком малой сумме левый элемент можно исключить.
		} else if sum < target {
			l++
		} else {
			break
		}
	}
	// Решение найдено до пересечения границ; переводим индексы в базу 1.
	return []int{l+1,r+1}
}
