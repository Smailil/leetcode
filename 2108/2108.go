package main

/*
Дан массив строк words.
Верните первую строку-палиндром в этом массиве.
Если такой строки нет, верните пустую строку "".

Палиндром — строка, которая одинаково читается в обоих направлениях.

Пример 1:
Вход: words = ["abc","car","ada","racecar","cool"]
Выход: "ada"
Пояснение: первая строка-палиндром — "ada".
Строка "racecar" тоже является палиндромом, но встречается позже.

Пример 2:
Вход: words = ["notapalindrome","racecar"]
Выход: "racecar"
Пояснение: первая и единственная строка-палиндром — "racecar".

Пример 3:
Вход: words = ["def","ghi"]
Выход: ""
Пояснение: строк-палиндромов нет, поэтому возвращается пустая строка.

Ограничения:
1 <= words.length <= 100
1 <= words[i].length <= 100
words[i] состоит только из строчных букв английского алфавита.
*/

// firstPalindrome возвращает первый палиндром в words или пустую строку.
// Для каждого слова два указателя сравнивают симметричные байты от краёв
// к центру. Первое несовпадение исключает слово, полное совпадение даёт ответ.
// Время: O(S) в худшем случае, S — сумма длин всех строк в words.
// Дополнительная рабочая память: O(1); входные данные не изменяются.
// Результат использует исходные байты слова без копирования:
// создаётся только дескриптор строки O(1), а не отдельный буфер.
func firstPalindrome(words []string) string {
	// Обход сохраняет порядок words, поэтому первый найденный палиндром
	// сразу является ответом; последующие слова проверять не требуется.
	for _, w := range words {
		// По условию w непустая, поэтому оба начальных индекса допустимы.
		// Строчные английские буквы занимают по одному байту: w[l] и w[r]
		// соответствуют целым символам, декодирование UTF-8 не требуется.
		l, r := 0, len(w)-1
		// Все симметричные пары снаружи [l, r] уже совпали.
		// Продолжаем проверку, пока совпадает и текущая пара байтов.
		for w[l] == w[r] {
			// При l == r остался только центр, равный самому себе.
			// При l > r указатели пересеклись: все пары уже проверены.
			// Для "abba": (0, 3) -> (1, 2) -> (2, 1). Последняя
			// проверка сравнивает ту же пару наоборот и тоже проходит.
			// Значит, после встречи или пересечения слово — палиндром.
			if l >= r {
				return w
			}
			// Сдвиг выполняется только при l < r: оба новых индекса
			// остаются внутри w. Поэтому условие цикла безопасно
			// читает w[l] и w[r] ещё до следующей проверки l >= r.
			l++
			r--
		}
		// Цикл завершился из-за несовпадения: w не палиндром.
		// Переходим к следующему слову, не проверяя оставшиеся пары.
	}
	// Ни одно слово не прошло проверку всех симметричных пар.
	return ""
}