package main

import "strings"

/*
Каждый корректный адрес электронной почты состоит из локального имени
и доменного имени, разделённых символом '@'. Помимо строчных букв,
адрес может содержать один или несколько символов '.' или '+'.

Например, в адресе "alice@leetcode.com" строка "alice" является локальным
именем, а "leetcode.com" — доменным именем.

Если добавить точки '.' между некоторыми символами локального имени,
отправленное на этот адрес письмо будет доставлено на тот же адрес без точек
в локальном имени. Обратите внимание, что это правило не применяется
к доменным именам.

Например, адреса "alice.z@leetcode.com" и "alicez@leetcode.com" перенаправляют
письма на один и тот же адрес.

Если добавить знак плюс '+' в локальное имя, всё после первого знака плюс
будет проигнорировано. Это позволяет фильтровать определённые письма.
Обратите внимание, что это правило не применяется к доменным именам.

Например, письмо на адрес "m.y+name@email.com" будет перенаправлено
на адрес "my@email.com".

Оба правила можно применять одновременно.

Дан массив строк emails. Для каждого emails[i] отправляется одно письмо.
Верните количество различных адресов, которые фактически получат письма.

Пример 1:
Вход: emails = [
    "test.email+alex@leetcode.com",
    "test.e.mail+bob.cathy@leetcode.com",
    "testemail+david@lee.tcode.com"
]
Выход: 2
Пояснение: письма фактически получат адреса "testemail@leetcode.com"
и "testemail@lee.tcode.com".

Пример 2:
Вход: emails = [
    "a@leetcode.com",
    "b@leetcode.com",
    "c@leetcode.com"
]
Выход: 3

Ограничения:
1 <= emails.length <= 100
1 <= emails[i].length <= 100
emails[i] состоят из строчных английских букв и символов '+', '.' и '@'.
Каждая строка emails[i] содержит ровно один символ '@'.
Все локальные и доменные имена непусты.
Локальные имена не начинаются с символа '+'.
Доменные имена заканчиваются суффиксом ".com".
Перед суффиксом ".com" в доменном имени есть хотя бы один символ.
*/

// numUniqueEmails приводит адреса к каноническому виду и считает
// различные адреса после применения правил к локальному имени.
// Время: O(S), память: O(S), где S — суммарная длина всех адресов.
func numUniqueEmails(emails []string) int {
    // Карта используется как множество уже полученных канонических адресов.
    unique := make(map[string]bool)

    for _, e := range emails {
        // По условию адрес содержит ровно один символ '@', поэтому части
        // до и после него однозначно задают локальное и доменное имена.
        parts := strings.Split(e, "@")
        local, domain := parts[0], parts[1]

        // Сначала отбрасываем игнорируемый суффикс после первого символа '+'.
        // Затем удаляем точки только из оставшейся части локального имени.
        local = strings.Split(local, "+")[0]
        local = strings.ReplaceAll(local, ".", "")

        // Канонический адрес служит ключом: эквивалентные исходные адреса
        // после нормализации попадут в одну и ту же запись множества.
        key := local + "@" + domain
        unique[key] = true
    }

    // Количество ключей равно числу реально различающихся получателей.
    return len(unique)
}
