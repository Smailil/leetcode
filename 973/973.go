package main

import "container/heap"

/*
Даны массив points, где points[i] = [x_i, y_i] — точка на плоскости XY,
и целое число k.
Верните k ближайших точек к началу координат (0, 0).
Расстояние между двумя точками на плоскости XY — евклидово расстояние:
sqrt((x_1 - x_2)^2 + (y_1 - y_2)^2).
Ответ можно вернуть в любом порядке.
Гарантируется, что набор точек ответа уникален, если не учитывать их порядок.

Пример 1:
Вход: points = [[1,3],[-2,2]], k = 1
Выход: [[-2,2]]
Объяснение:
Расстояние между (1, 3) и началом координат равно sqrt(10).
Расстояние между (-2, 2) и началом координат равно sqrt(8).
Поскольку sqrt(8) < sqrt(10), (-2, 2) ближе к началу координат.
Нам нужны только ближайшие k = 1 точки от начала координат, поэтому ответ —
просто [[-2,2]].

Пример 2:
Вход: points = [[3,3],[5,-1],[-2,4]], k = 2
Выход: [[3,3],[-2,4]]
Пояснение: Ответ [[-2,4],[3,3]] также будет принят.

Ограничения:
1 <= k <= points.length <= 10^4
-10^4 <= x_i, y_i <= 10^4
*/

type MaxHeap [][3]int

// Len читает размер за O(1) времени и памяти без изменений.
func (h MaxHeap) Len() int {return len(h)}
// Less обращает порядок квадратов расстояния: вершина — самая далёкая.
// Время, память и bool O(1); индексы гарантирует heap.
func (h MaxHeap) Less(i, j int) bool {return h[i][0] > h[j][0]}
// Swap меняет общий срез за O(1) времени и рабочей памяти.
func (h MaxHeap) Swap(i, j int) {h[i], h[j] = h[j], h[i]}
// Push добавляет [3]int: время O(1) амортизированно, O(q) при росте.
// Рабочая память при росте O(q), q — размер кучи; меняет очередь.
// Тип x гарантирует caller, это callback, не вся операция heap.Push.
func (h *MaxHeap) Push(x interface{}) {*h = append(*h, x.([3]int))}
// Pop снимает последний элемент после перестановки heap в непустой куче.
// Время, рабочая память и результат [3]int O(1); очередь укорачивается.
func (h *MaxHeap) Pop() interface{} {
    n := len(*h)
    x := (*h)[n-1]
    *h = (*h)[0:n-1]
    return x
}

// kClosest хранит не более k ближайших точек в max-heap: при переполнении
// удаляет самую далёкую из кандидатов, сохраняя k лучших по префиксу.
// Время O(N*log(k+1)+k), N=len(points); рабочая память O(k).
// Результат O(k): новые пары координат, вход points не меняется.
// Квадрат расстояния сохраняет порядок без sqrt; ответ не обязан быть sorted.
func kClosest(points [][]int, k int) [][]int {
    // Пустая куча уже корректна, поэтому отдельный heap.Init здесь не нужен.
    mh := MaxHeap{}
    for _, point := range points {
		// По условию у точки два числа; сумма квадратов до2*10^8 безопасна
		// для int32. В куче сохраняются значения, не ссылки на входные строки.
		var p [3]int = [3]int{(point[0]*point[0]+point[1]*point[1]), point[0], point[1]}
        heap.Push(&mh, p)
        if len(mh) > k { heap.Pop(&mh) }
    }
    res := make([][]int, 0, len(mh))
	for _, m := range mh {
		res = append(res, []int{m[1], m[2]})
	}
	return res
}
