package main

import "math"

/*
Разность произведений двух пар (a, b) и (c, d) определяется как
(a * b) - (c * d).

Например, разность произведений пар (5, 6) и (2, 7) равна
(5 * 6) - (2 * 7) = 16.

Дан целочисленный массив nums. Выберите четыре различных индекса w, x, y и z
так, чтобы разность произведений пар (nums[w], nums[x]) и
(nums[y], nums[z]) была максимальной.

Верните максимальную разность произведений.

Пример 1:
Вход: nums = [5,6,2,7,4]
Выход: 34
Пояснение: для первой пары можно выбрать индексы 1 и 3 (6, 7),
а для второй — индексы 2 и 4 (2, 4).
Разность произведений равна (6 * 7) - (2 * 4) = 34.

Пример 2:
Вход: nums = [4,2,5,9,7,4,8]
Выход: 64
Пояснение: для первой пары можно выбрать индексы 3 и 6 (9, 8),
а для второй — индексы 1 и 5 (2, 4).
Разность произведений равна (9 * 8) - (2 * 4) = 64.

Ограничения:
4 <= nums.length <= 10^4
1 <= nums[i] <= 10^4
*/

// maxProductDifference находит максимальную разность произведений за один
// проход, сохраняя две наибольшие и две наименьшие величины массива.
// Время: O(n), где n = len(nums). Дополнительная память: O(1).
func maxProductDifference(nums []int) int {
    // Нулевые максимумы безопасны, поскольку по условию nums[i] >= 1.
    // MaxInt32 гарантированно не меньше ни одного допустимого элемента.
    max1, max2 := 0, 0
    min1, min2 := math.MaxInt32, math.MaxInt32

    // После каждой итерации max1 и max2 — два наибольших элемента
    // просмотренной части, а min1 и min2 — два наименьших.
    for _, num := range nums {
        // Новый лидер сдвигает прежний максимум на второе место;
        // иначе num может заменить только второй максимум.
        if num > max1 {
            max2 = max1
            max1 = num
        } else if num > max2 {
            max2 = num
        }

        // Новый минимум сдвигает прежний минимум на второе место;
        // иначе num может заменить только второй минимум.
        if num < min1 {
            min2 = min1
            min1 = num
        } else if num < min2 {
            min2 = num
        }
    }

    // Два максимума дают наибольшее произведение, а два минимума —
    // наименьшее. При nums[i] <= 10^4 оба произведения помещаются в int.
    return (max1 * max2) - (min1 * min2)
}