package main

/*
Предположим, LeetCode скоро начнет IPO.
Чтобы выгодно продать свои акции венчурным инвесторам,
LeetCode хочет выполнить несколько проектов и увеличить капитал перед IPO.
Поскольку ресурсы ограничены,
до IPO можно завершить не более k различных проектов.
Помогите LeetCode выбрать лучший способ максимизировать общий капитал
после завершения не более k различных проектов.

Даны n проектов: i-й проект приносит чистую прибыль profits[i],
а для его запуска нужен минимальный капитал capital[i].

Изначально у вас есть капитал w.
Когда вы завершаете проект, вы получаете его чистую прибыль,
и эта прибыль добавляется к вашему общему капиталу.

Выберите список из не более чем k различных проектов среди данных,
чтобы максимизировать итоговый капитал,
и верните максимальный итоговый капитал.

Гарантируется, что ответ помещается в 32-битное знаковое целое число.

Пример 1:
Вход: k = 2, w = 0, profits = [1,2,3], capital = [0,1,1]
Выход: 4
Пояснение: поскольку начальный капитал равен 0,
вы можете начать только проект с индексом 0.
После его завершения вы получите прибыль 1,
и ваш капитал станет равен 1.
С капиталом 1 можно начать либо проект с индексом 1,
либо проект с индексом 2.
Так как можно выбрать не более 2 проектов,
нужно завершить проект с индексом 2, чтобы получить максимальный капитал.
Поэтому итоговый максимальный капитал равен 0 + 1 + 3 = 4.

Пример 2:
Вход: k = 3, w = 0, profits = [1,2,3], capital = [0,1,2]
Выход: 6

Ограничения:
1 <= k <= 10^5
0 <= w <= 10^9
n == profits.length
n == capital.length
1 <= n <= 10^5
0 <= profits[i] <= 10^4
0 <= capital[i] <= 10^9
*/

import (
    "container/heap"
)

// MinCapitalHeap — куча с минимумом по стартовому капиталу.
// Каждый элемент — это [capital, profit]
// (минимальный капитал, требуемый для проекта, и его прибыль).
// Используется для быстрого выбора всех проектов,
// которые мы можем себе позволить с текущим капиталом w.
// Все пары в главной функции имеют два int: индексы 0 и 1 допустимы.
// Пары созданы отдельно и не являются срезами profits или capital.
type MinCapitalHeap [][]int
func (h MinCapitalHeap) Len() int           { return len(h) }
func (h MinCapitalHeap) Less(i, j int) bool { return h[i][0] < h[j][0] }
func (h MinCapitalHeap) Swap(i, j int)      { h[i], h[j] = h[j], h[i] }
// Push дописывает пару в буфер h; порядок восстанавливает внешний heap.Push.
// H — длина h: время амортизированно O(1), при росте буфера O(H+1).
// Рабочая память O(1) без буфера кучи; новый буфер при росте требует O(H+1).
// Изменяет h, не содержимое пары x; x имеет тип []int по вызовам алгоритма.
func (h *MinCapitalHeap) Push(x any)        { *h = append(*h, x.([]int)) }
// Pop удаляет последний элемент после перестановок внешнего heap.Pop.
// Время и рабочая память O(1); результат — существующая пара из двух int, O(1).
// Меняет длину h; внешний heap.Pop вызывается только при непустой куче.
func (h *MinCapitalHeap) Pop() any {
    old := *h
    n := len(old)
    x := old[n-1]
    // Срезание не очищает старый хвост: буфер может удерживать ссылку на x.
    // Поэтому память всей кучи не оценивается лишь по оставшейся длине.
    *h = old[0 : n-1]
    return x
}

// MaxProfitHeap — куча с максимумом по прибыли.
// Хранит только прибыли доступных нам проектов
// (те, что требуют капитала <= текущего w).
// На каждом шаге мы берём отсюда самый выгодный проект.
type MaxProfitHeap []int
func (h MaxProfitHeap) Len() int           { return len(h) }
func (h MaxProfitHeap) Less(i, j int) bool { return h[i] > h[j] } // >: max-куча
func (h MaxProfitHeap) Swap(i, j int)      { h[i], h[j] = h[j], h[i] }
// Push дописывает прибыль; восстановление порядка делает внешний heap.Push.
// H — длина h: время амортизированно O(1), при росте буфера O(H+1).
// Рабочая память O(1) без буфера кучи; новый буфер при росте требует O(H+1).
// Меняет h; x имеет тип int, поскольку сюда переносятся прибыли проектов.
func (h *MaxProfitHeap) Push(x any)        { *h = append(*h, x.(int)) }
// Pop срезает последний элемент после перестановок внешнего heap.Pop.
// Время, рабочая память и скалярный результат O(1); изменяет длину h.
// Алгоритм проверяет непустоту перед heap.Pop, поэтому индекс n-1 допустим.
// Буфер сохраняет capacity после уменьшения длины и не освобождается целиком.
func (h *MaxProfitHeap) Pop() any {
    old := *h
    n := len(old)
    x := old[n-1]
    *h = old[0 : n-1]
    return x
}

// findMaximizedCapital выбирает не более k проектов с максимальным капиталом.
// Время O((n+min(k,n))*log(n+1)) = O(n*log(n+1)), n = len(profits).
// Длина capital тоже n; каждый проект вставляется в обе кучи не более раза.
// Рабочая память O(n) для куч, удерживаемых буферов и двухэлементных пар.
// Результат int O(1); profits и capital не меняются, w изменяется локально.
// Идея (жадный алгоритм):
//   1. Кладём все проекты в min-кучу по требуемому капиталу.
//   2. На каждом из k шагов перекладываем в max-кучу по прибыли все проекты,
//      которые мы можем себе позволить (требуемый капитал <= w).
//   3. Берём из max-кучи проект с максимальной прибылью — это жадный выбор,
//      дающий наибольший прирост капитала на данном шаге.
//   4. Увеличиваем капитал w на полученную прибыль и повторяем.
// Если лучший доступный проект есть в оптимальном плане позже, переносим
// его вперёд и выбранный первым проект на его место: суммы затем совпадут,
// а промежуточный капитал не меньше прежнего. Если его нет, заменяем первый.
// Неотрицательные прибыли сохраняют доступность остальных шагов
// в обоих случаях: такие обмены не ухудшают конечный капитал.
func findMaximizedCapital(k int, w int, profits []int, capital []int) int {
    minCapital := &MinCapitalHeap{}
    maxProfit := &MaxProfitHeap{}

    // Начальные вставки идут через heap.Push: это O(n*log(n+1)),
    // а не линейный heap.Init, которого в этой реализации нет.
    // Заполняем min-кучу парами [требуемый капитал, прибыль].
    for i := range capital {
        heap.Push(minCapital, []int{capital[i], profits[i]})
    }

    // Выполняем не более k проектов.
    for range k {
        // Перекладываем из minCapitalHeap в maxProfitHeap все проекты,
        // которые мы теперь можем себе позволить с текущим капиталом w.
        // Благодаря min-куче мы гарантированно перебираем их
        // в порядке возрастания требуемого капитала.
        // w не убывает: уже доступные проекты можно держать в maxProfit.
        // Перенос удаляет пару из minCapital, выбор удаляет её прибыль;
        // один и тот же проект поэтому не выполняется повторно.
        for minCapital.Len() > 0 && (*minCapital)[0][0] <= w {
            item := heap.Pop(minCapital).([]int)
            heap.Push(maxProfit, item[1]) // кладём только прибыль
        }

        // Если доступных проектов нет —
        // дальнейшее увеличение капитала невозможно.
        if maxProfit.Len() == 0 {
            break
        }

        // Жадно выбираем самый прибыльный проект
        // и добавляем его прибыль к нашему капиталу.
        // w начинается не выше 10^9, прибыль не выше 10^4, шагов до 10^5.
        // Сумма не больше 2*10^9, поэтому даже int32 не переполняется.
        w += heap.Pop(maxProfit).(int)
    }

    return w
}