package main

/*
Подъёмом в целочисленном массиве nums называется пара индексов (i, j),
для которой i < j и nums[i] <= nums[j].
Ширина подъёма равна j - i.

Дан целочисленный массив nums.
Верните максимальную ширину подъёма в nums.
Если в nums нет подъёмов, верните 0.

Пример 1:
Вход: nums = [6,0,8,2,1,5]
Выход: 4
Пояснение: Максимальная ширина достигается при (i, j) = (1, 5):
nums[1] = 0 и nums[5] = 5.

Пример 2:
Вход: nums = [9,8,1,0,1,9,4,0,4,1]
Выход: 7
Пояснение: Максимальная ширина достигается при (i, j) = (2, 9):
nums[2] = 1 и nums[9] = 1.

Ограничения:
2 <= nums.length <= 5 * 10^4
0 <= nums[i] <= 5 * 10^4
*/

// maxWidthRamp возвращает наибольшую ширину подъёма или 0, если подъёмов нет.
// Храним индексы префиксных минимумов и ищем для них правые концы.
// Время: O(n), где n = len(nums). Каждый индекс добавляем и снимаем
// не более одного раза, поэтому вложенный цикл суммарно тоже занимает O(n).
// Дополнительная память: O(n) в худшем случае (строго убывающий массив).
func maxWidthRamp(nums []int) int {
	// В стеке индексы возрастают, а значения nums по ним строго убывают.
	// Если x не меньше текущего минимума, более ранний индекс с меньшим
	// или равным значением даёт не меньшую ширину для любого правого конца.
	stack := []int{}
	for i, x := range nums {
		if len(stack) == 0 || x < nums[stack[len(stack)-1]] {
			stack = append(stack, i)
		}
	}
	answer := 0
	// Перебираем правый конец j от большего индекса к меньшему.
	// На вершине минимум среди оставшихся кандидатов: если он больше
	// nums[j], ни один индекс в стеке не подходит для этого j.
	// Для [6,0,8,2,1,5] стек содержит [0,1]. При j = 5 индекс 1
	// даёт ширину 4, а индекс 0 остаётся: nums[0] = 6 > nums[5] = 5.
	for j := len(nums) - 1; j >= 0; j-- {
		for len(stack) > 0 && nums[stack[len(stack)-1]] <= nums[j] {
			// Первое подходящее j — самое правое для этого i.
			// Меньший j не улучшит результат, поэтому снимаем i.
			// Ширина j - i <= 0 не увеличит answer: подъём требует i < j.
			answer = max(answer, j-stack[len(stack)-1])
			stack = stack[:len(stack)-1]
		}
	}
	return answer
}
