package main

/*
Файловая система LeetCode записывает в журнал каждую операцию смены папки,
которую выполняет пользователь.

Операции описаны ниже:
"../" : Перейти в родительскую папку текущей папки.
Если вы уже находитесь в корневой папке, остаться в ней.
"./" : Остаться в текущей папке.
"x/" : Перейти в дочернюю папку с именем x.
Гарантируется, что эта папка всегда существует.

Дан список строк logs, где logs[i] — операция, выполненная пользователем
на шаге i.

Изначально файловая система находится в корневой папке,
затем выполняются операции из logs.

Верните минимальное число операций, необходимых для возврата в корневую папку
после выполнения операций смены папки.

Пример 1:
https://assets.leetcode.com/uploads/2020/09/09/sample_11_1957.png
Вход: logs = ["d1/","d2/","../","d21/","./"]
Выход: 2
Пояснение: Выполните операцию "../" два раза, чтобы вернуться в корневую папку.

Пример 2:
https://assets.leetcode.com/uploads/2020/09/09/sample_22_1957.png
Вход: logs = ["d1/","d2/","./","d3/","../","d31/"]
Выход: 3

Пример 3:
Вход: logs = ["d1/","../","../","../"]
Выход: 0

Ограничения:
1 <= logs.length <= 10^3
2 <= logs[i].length <= 10
logs[i] содержит строчные английские буквы, цифры, '.' и '/'.
logs[i] соответствует формату, описанному в условии.
Имена папок состоят из строчных английских букв и цифр.

*/

// minOperations считает минимальное число подъёмов для возврата в корень.
// Вместо полного пути хранит только глубину текущей папки.
// Время: O(n), где n = len(logs). Дополнительная память: O(1).
func minOperations(logs []string) int {
    // В корне глубина равна 0. После каждой операции res хранит число уровней
    // между текущей папкой и корнем; имена пройденных папок не нужны.
    res := 0
    for _, log := range logs {
        // "./" оставляет нас в той же папке, поэтому глубина не меняется.
        if log == "./" {
            continue
        }
        // "../" поднимает на один уровень, но из корня подняться нельзя.
        // Проверка res > 0 сохраняет неотрицательную глубину.
        if log == "../" {
            if res > 0 {
                res--
            }
        } else {
            // По условию все остальные записи ведут в дочернюю папку.
            // Спуск добавляет один уровень независимо от имени папки.
            res++
        }
    }
    // Ровно res операций "../" вернут нас в корень. Меньше не хватит:
    // одна операция уменьшает глубину не более чем на один уровень.
    return res
}
