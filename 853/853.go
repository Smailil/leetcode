package main

import "sort"

/*
На дороге находится n автомобилей, движущихся к отметке target миль.
Начало дороги соответствует отметке 0.

Вам даны два целочисленных массива: position и speed, оба длиной n, где
position[i] — стартовая миля i-го автомобиля,
а speed[i] — скорость i-го автомобиля в милях в час.

Автомобиль не может обогнать другую машину, но может догнать ее и затем поехать
рядом со скоростью более медленной машины.

Колонна – это один автомобиль или группа автомобилей, едущих рядом друг с
другом.
Скорость колонны – это минимальная скорость любого автомобиля в колонне.

Верните количество колонн, которые прибудут в пункт назначения.

Пример 1:
Вход: target = 12, position = [10,8,0,5,3], speed = [2,4,1,1,3]
Выход: 3
Объяснение:
Автомобили с начальных позиций 10 (скорость 2) и 8 (скорость 4)
образуют колонну, встретившись в позиции 12.
Колонна формируется у цели.
Автомобиль, стартующий с 0 (скорость 1), не догоняет ни один другой автомобиль,
поэтому он сам по себе является колонной.
Автомобили с начальных позиций 5 (скорость 1) и 3 (скорость 3)
образуют колонну, встретившись в позиции 6.
Колонна движется со скоростью 1, пока не достигнет цели.

Пример 2:
Вход: target = 10, position = [3], speed = [3]
Выход: 1
Объяснение:
Есть только одна машина, следовательно, есть только одна колонна.

Пример 3:
Вход: target = 100, position = [0,2,4], speed = [4,2,1]
Выход: 1
Объяснение:
Автомобили с начальных позиций 0 (скорость 4) и 2 (скорость 2)
образуют колонну, встретившись в позиции 4.
Автомобиль с начальной позицией 4 (скорость 1) перемещается в позицию 5.
Затем колонна на позиции 4 (скорость 2) и автомобиль на позиции 5 (скорость 1)
становятся одной колонной,
встретившись в позиции 6.
Колонна движется со скоростью 1, пока не достигнет цели.

Ограничения:
n == position.length == speed.length
1 <= n <= 10^5
0 < target <= 10^6
0 <= position[i] < target
Все значения position уникальны.
0 < speed[i] <= 10^6
*/

// carFleet считает колонны по временам прибытия машин спереди назад.
// n = len(position): время O(n log(n + 1)), рабочая память O(n).
// Результат — число O(1); position и speed не изменяются.
func carFleet(target int, position []int, speed []int) int {
	// Копируем связанные позицию и скорость: сортировка не меняет входы.
	pairs := make([][2]int, len(position))
	stack := make([]float64, 0)
	for i := range position {
		pairs[i] = [2]int{position[i], speed[i]}
	}
	// Сравнение позиций за O(1) времени и памяти задаёт порядок сортировки.
	// Меняется только pairs; затем обходим машины от ближайшей к цели.
	sort.Slice(pairs, func(i, j int) bool {
    	return pairs[i][0] < pairs[j][0]
	})
	// stack хранит время каждой отдельной колонны обработанного префикса.
	// Последняя колонна — ближайшая впереди очередной рассматриваемой машины.
	for i := len(pairs) - 1; i > -1; i-- {
		// Из расстояния = скорость * время получаем (target - position)/speed.
		// По контракту скорость положительна, а расстояние лежит в 1..10^6.
		time := float64(target - pairs[i][0])/float64(pairs[i][1])
		// Если машина приехала бы не позже, она догонит переднюю колонну.
		// Равенство включает встречу у самой цели. Более позднее время —
		// новая колонна: обгонять нельзя, догнать предыдущую не получится.
		if len(stack) == 0 || stack[len(stack)-1] < time{
			stack = append(stack, time)
		}
	}
	// Сохраняли только новые колонны, поэтому длина stack даёт их число.
	return len(stack)
}
