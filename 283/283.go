package main

/*
Дан массив целых чисел nums.
Переместите все нули в его конец, сохранив относительный порядок
ненулевых элементов.

Изменения нужно выполнить на месте, не создавая копию массива.

Пример 1:
Вход: nums = [0,1,0,3,12]
Выход: [1,3,12,0,0]

Пример 2:
Вход: nums = [0]
Выход: [0]

Ограничения:
1 <= nums.length <= 10^4
-2^31 <= nums[i] <= 2^31 - 1
*/

// moveZeroes перемещает нули в конец nums, сохраняя порядок остальных значений.
// Два указателя собирают ненулевые значения слева обменами внутри среза.
// Срез nums изменяется на месте; новый срез для результата не создаётся.
// Время: O(n), где n = len(nums): каждый элемент рассматривается один раз.
// Дополнительная память: O(1), используются только индексы l и r.
func moveZeroes(nums []int) {
    // l — позиция, куда нужно поместить следующий ненулевой элемент.
    // Уже собранная часть nums[:l] сохраняет их исходный порядок.
    l := 0

    // r — индекс рассматриваемого элемента. В начале каждой итерации:
    // nums[:l] — уже собранные ненулевые элементы, nums[l:r] — только нули,
    // а nums[r:] ещё не просмотрен. Поэтому всегда 0 <= l <= r < len(nums).
    for r := range nums {
        // Ноль пропускается: r продолжит обход, а l останется на месте.
        // Так промежуток нулей расширяется до встречи ненулевого значения.
        if nums[r] != 0 {
            // При l < r значение nums[l] равно нулю: обмен ставит ненулевой
            // элемент в конец собранной части, а ноль — на уже просмотренное
            // место r. При l == r элемент меняется сам с собой без последствий.
            // Индексы безопасны: l <= r, а r — допустимый индекс из range.
            // Например, [0,1,0,3] при r=1, l=0 станет [1,0,0,3],
            // а затем при r=3, l=1 — [1,3,0,0].
            nums[l], nums[r] = nums[r], nums[l]

            // Собранная часть выросла на один элемент. Следующее значение
            // будет добавлено после него, поэтому порядок не нарушается.
            l++
        }
    }

    // Все элементы просмотрены: l равно числу ненулевых значений.
    // Они находятся в nums[:l], а nums[l:] состоит только из нулей.
    // Отдельный проход для заполнения хвоста нулями не требуется.
}