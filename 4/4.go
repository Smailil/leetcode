package main

import "math"

/*
Даны два отсортированных массива nums1 и nums2 размера m и n соответственно.
Верните медиану двух отсортированных массивов.
Общая временная сложность должна составлять O(log (m+n)).

Пример 1:
Вход: nums1 = [1,3], nums2 = [2]
Выход: 2.00000
Пояснение: объединённый массив = [1,2,3], медиана равна 2.

Пример 2:
Вход: nums1 = [1,2], nums2 = [3,4]
Выход: 2.50000
Пояснение: объединённый массив = [1,2,3,4], медиана равна (2 + 3)/2 = 2,5.

Ограничения:
nums1.length == m
nums2.length == n
0 <= m <= 1000
0 <= n <= 1000
1 <= m + n <= 2000
-10^6 <= nums1[i], nums2[i] <= 10^6
*/

// findMedianSortedArrays ищет медиану через разбиение двух массивов.
// Слева оставляем half элементов; все они должны быть не больше правых.
// Бинарный поиск меняет границу только в более коротком массиве.
// Пусть m = len(nums1), n = len(nums2), k = min(m, n).
// Время O(log(k + 1)) при k > 0 и O(1) при k = 0.
// Рабочая память O(1); результат — одно число. Массивы не изменяются.
func findMedianSortedArrays(nums1 []int, nums2 []int) float64 {
    // A — более короткий массив: поиск ограничен его границами,
    // а перестановка локальных ссылок не меняет входные срезы.
    A, B := nums1, nums2
	if len(A) > len(B) {
		A, B = B, A
	}
	total := len(A) + len(B)
	// p = i+1 и q = j+1 — размеры левых частей: p+q = half.
	// Поэтому q = half-p, j = half-(i+1)-1.
	// При len(A) <= len(B): len(A) <= half <= len(B).
	// Для 0 <= p <= len(A) получаем 0 <= q <= len(B):
	// j лежит от -1 до len(B)-1, поэтому проверки краёв ниже безопасны.
	half := total / 2
	l, r := 0, len(A) - 1
	for {
		// При отрицательном индексе разделение находится перед началом массива.
		i := (l+r)>>1 //Индекс границы A: деление пополам с округлением вниз.
		j := half - (i + 1) - 1 //Индекс границы B с учётом нулевой индексации.
		// Пустой левый край обозначаем минус бесконечностью,
		// пустой правый — плюс бесконечностью. MinInt/MaxInt лежат
		// строго вне допустимых значений [-10^6, 10^6].
		var Aleft, Aright, Bleft, Bright int
		if i >= 0 {
			Aleft = A[i]
		} else {
			Aleft = math.MinInt
		}
		if (i + 1) < len(A) {
			Aright = A[i+1]
		} else {
			Aright = math.MaxInt
		}
		if j >= 0 {
			Bleft = B[j]
		} else {
			Bleft = math.MinInt
		}
		if (j + 1) < len(B) {
			Bright = B[j+1]
		} else {
			Bright = math.MaxInt
		}
		// Каждый массив уже отсортирован; нужны только два перекрёстных
		// сравнения, чтобы максимум слева не превышал минимум справа.
		if Aleft <= Bright && Bleft <= Aright {
			// При нечётной длине справа на один элемент больше:
			// самый маленький правый элемент и есть медиана.
			if total % 2 == 1 {
				return float64(min(Aright, Bright)) 
			}
			// При чётной длине берём среднее двух центральных элементов.
			// Сумма в [-2*10^6, 2*10^6] помещается в int;
			// преобразование в float64 до деления сохраняет половину.
			return float64(max(Aleft, Bleft) + min(Aright, Bright))/2
		} else if Aleft > Bright {
			// Слишком большой левый край A: переносим часть A вправо.
			r = i - 1
		} else {
			// Левый край B слишком велик: увеличиваем левую часть A.
			l = i + 1
		}
	}
}
