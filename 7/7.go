package main

import "math"

/*
Дано 32-битное целое число x со знаком, верните x с цифрами в обратном порядке.
Если перестановка цифр x приводит к выходу значения за пределы диапазона
32-битных целых чисел со знаком [-2^31, 2^31 - 1], верните 0.
Предположим, что среда не позволяет хранить 64-битные целые числа
(со знаком или без знака).

Пример 1:
Вход: x = 123
Выход: 321

Пример 2:
Вход: x = -123
Выход: -321

Пример 3:
Вход: x = 120
Выход: 21

Ограничения:
-2^31 <= x <= 2^31 - 1
*/

// reverse собирает число из извлекаемых справа цифр и проверяет int32.
// Для фиксированных 32 бит время и дополнительная память O(1):
// цикл обрабатывает не более десяти десятичных цифр.
// Результат — число, x изменяется только как локальная копия параметра.
func reverse(x int) int {
    MIN := -2147483648 // -2^31
    MAX := 2147483647  // 2^31 - 1

    res := 0
    for x != 0 {
        // Вход int32 точно представим в float64; Mod сохраняет знак x.
        // Преобразование частного к int отбрасывает дробную часть к нулю,
        // поэтому отрицательное число разбирается без смены знака.
        digit := int(math.Mod(float64(x), 10))
        x = int(float64(x) / 10)

        // Следующее число res*10+digit не должно превысить MAX.
        // Сначала сравниваем res с MAX/10; при равенстве допустимы лишь
        // digit <= MAX%10. Проверка выполняется до умножения.
        if res > MAX/10 || (res == MAX/10 && digit > MAX%10) {
            return 0
        }
        // Для нижней границы деление также округляется к нулю:
        // при res == MIN/10 минимальная допустимая цифра — MIN%10.
        if res < MIN/10 || (res == MIN/10 && digit < MIN%10) {
            return 0
        }
        // После обеих проверок новый res остаётся в диапазоне int32.
        // Уже извлечённые цифры образуют его десятичную запись.
        res = (res * 10) + digit
    }

    return res
}
