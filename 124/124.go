package main

/*
Путь в бинарном дереве — это последовательность узлов, в которой каждая пара
соседних узлов соединена ребром.
Узел может появляться в последовательности не более одного раза.
Обратите внимание, что путь не обязательно должен проходить через корень.
Сумма пути — это сумма значений узлов на этом пути.
По корню бинарного дерева верните максимальную сумму любого непустого пути.

Пример 1:
https://assets.leetcode.com/uploads/2020/10/13/exx1.jpg
Вход: root = [1,2,3]
Выход: 6
Пояснение: Оптимальный путь — 2 -> 1 -> 3 с суммой пути 2 + 1 + 3 = 6.

Пример 2:
https://assets.leetcode.com/uploads/2020/10/13/exx2.jpg
Вход: root = [-10,9,20,null,null,15,7]
Выход: 42
Пояснение: Оптимальный путь — 15 -> 20 -> 7 с суммой пути 15 + 20 + 7 = 42.

Ограничения:
Количество узлов в дереве находится в диапазоне [1, 3 *10^4].
-1000 <= Node.val <= 1000
*/

type TreeNode struct {
	Val   int
	Left  *TreeNode
	Right *TreeNode
}

// maxPathSum находит лучший непустой путь через любой узел дерева.
// n — число узлов, h — высота: время O(n), рабочий стек O(h), ответ O(1).
// Дерево не меняется; по условию root не nil. Суммы по модулю <= 3*10^7,
// поэтому сложение безопасно для int, в том числе 32-битного.
func maxPathSum(root *TreeNode) int {
	// Старт с реального узла сохраняет отрицательный ответ, если все Val < 0.
	res := root.Val
	var dfs func(root *TreeNode) int
	// dfs возвращает лучший нисходящий путь, начинающийся в node.
	// Для s узлов и высоты h: время O(s), стек O(h), возвращаемый int O(1).
	// Меняет общий res; ссылки и значения узлов не меняет.
	dfs = func(node *TreeNode) int {
		if node == nil {
			return 0
		}

		// Отрицательную ветвь не берём: её вклад только ухудшил бы сумму.
		// Нулевой вклад означает отсутствие выбранной дочерней ветви.
		leftMax := max(dfs(node.Left), 0)
		rightMax := max(dfs(node.Right), 0)
		// node — верхняя точка кандидата: две ветви соединяются через него.
		// Это полный путь, его нельзя целиком продолжить через родителя.
		res = max(res, node.Val+leftMax+rightMax)
		// Родителю отдаём только одну ветвь: путь не может разветвляться.
		return node.Val + max(leftMax, rightMax)
	}
	dfs(root)
	return res
}
