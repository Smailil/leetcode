package main

/*
Даны n точек на двумерной плоскости.
Определите, существует ли прямая, параллельная оси y,
относительно которой данные точки симметричны.

Иными словами, существует ли прямая, после отражения всех точек
относительно которой множество исходных точек совпадёт
с множеством отражённых точек.

Учтите, что точки могут повторяться.

Пример 1:
https://fastly.jsdelivr.net/gh/doocs/leetcode@main/solution/0300-0399/0356.Line%20Reflection/images/356_example_1.png
Вход: points = [[1,1],[-1,1]]
Выход: true
Пояснение: Можно выбрать прямую x = 0.

Пример 2:
https://fastly.jsdelivr.net/gh/doocs/leetcode@main/solution/0300-0399/0356.Line%20Reflection/images/356_example_2.png
Вход: points = [[1,1],[-1,-1]]
Выход: false
Пояснение: Нельзя выбрать подходящую прямую.

Ограничения:
n == points.length
1 <= n <= 10^4
-10^8 <= points[i][j] <= 10^8
*/

// isReflected проверяет симметрию множества относительно вертикальной оси.
// Ось обязана проходить через середину минимального и максимального x.
// Среднее время O(n+k), n=len(points), k — число разных точек; это O(n).
// Рабочая память O(k) для множества, результат bool O(1).
// Ключ [2]int имеет постоянный размер; точки входа не меняются.
// Повторы игнорируются: проверяется множество, а не кратности одинаковых точек.
func isReflected(points [][]int) bool {
	// Хотя бы одна точка гарантирована; начинаем экстремумы её координатой.
	minX := points[0][0]
	maxX := points[0][0]
	mapPoints := make(map[[2]int]bool)
	for _, p := range points {
		minX = min(p[0], minX)
		maxX = max(p[0], maxX)
		mapPoints[[2]int{p[0], p[1]}] = true
	}
	// minX+maxX — удвоенная координата оси; деление на 2 не нужно.
	// Сумма не превосходит 2*10^8 по модулю, зеркальный x — не выше 3*10^8:
	// обе операции безопасны даже для 32-битного int.
	s := minX + maxX
	// med = (x'+x)/2, med=s/2 => x' = 2*med - x, s=2*med
	// Из x'=2*ось-x получаем x'=s-x; y при вертикальном отражении тот же.
	// Проверяем реальный ключ координат, а не равенство хешей без сравнения.
	for point := range mapPoints {
		if !mapPoints[[2]int{s - point[0], point[1]}] {
			return false
		}
	}
	return true
}
