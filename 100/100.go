package main

/*
Даны корни двух двоичных деревьев p и q.
Напишите функцию, проверяющую, совпадают они или нет.
Два двоичных дерева считаются одинаковыми, если они структурно идентичны
и узлы имеют одинаковое значение.

Пример 1:
https://assets.leetcode.com/uploads/2020/12/20/ex1.jpg
Вход: p = [1,2,3], q = [1,2,3]
Выход: true

Пример 2:
https://assets.leetcode.com/uploads/2020/12/20/ex2.jpg
Вход: p = [1,2], q = [1,null,2]
Выход: false

Пример 3:
https://assets.leetcode.com/uploads/2020/12/20/ex3.jpg
Вход: p = [1,2,1], q = [1,1,2]
Выход: false

Ограничения:
Количество узлов в обоих деревьях находится в диапазоне [0, 100].
-10^4 <= Node.val <= 10^4
*/

type TreeNode struct {
    Val int
    Left *TreeNode
    Right *TreeNode
}

// isSameTree одновременно сравнивает значения и структуру двух деревьев.
// n,m — числа узлов, h — большая высота; время O(n+m+1) в худшем случае.
// Рабочая память O(h+1) для рекурсии, результат — bool; деревья не меняются.
func isSameTree(p *TreeNode, q *TreeNode) bool {
    // Две пустые ветви совпадают и завершают эту пару рекурсивных путей.
    if p == nil && q == nil {
		return true
	}
	// После первой проверки nil только у одной стороны означает разную
	// форму; короткое замыкание || защищает чтение Val у пустого узла.
	if p == nil || q == nil || p.Val != q.Val {
		return false
	}
	// Равные корни недостаточны: обе соответствующие пары детей
	// должны совпасть; && пропускает правую пару при неуспехе слева.
	return isSameTree(p.Left, q.Left) && isSameTree(p.Right, q.Right)
}
