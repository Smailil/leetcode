package main

/*
Дан массив целых чисел nums. Верните количество хороших пар.

Пара (i, j) называется хорошей, если nums[i] == nums[j] и i < j.

Пример 1:
Вход: nums = [1,2,3,1,1,3]
Выход: 4
Пояснение: существуют 4 хорошие пары: (0,3), (0,4), (3,4) и (2,5).
Индексация начинается с 0.

Пример 2:
Вход: nums = [1,1,1,1]
Выход: 6
Пояснение: каждая пара элементов массива является хорошей.

Пример 3:
Вход: nums = [1,2,3]
Выход: 0

Ограничения:
1 <= nums.length <= 100
1 <= nums[i] <= 100
*/

// numIdenticalPairs подсчитывает пары индексов (i, j), для которых
// nums[i] == nums[j] и i < j.
//
// Время: O(n), поскольку массив просматривается один раз.
// Дополнительная память: O(k), где k — число различных значений.
// По ограничениям задачи k <= 100, поэтому фактически это O(1).
func numIdenticalPairs(nums []int) int {
    // count[x] хранит число вхождений x в уже обработанном префиксе.
    // Так каждая пара учитывается при чтении её правого элемента.
    count := make(map[int]int)
    res := 0
    for _, num := range nums {
        // Каждый из count[num] предыдущих элементов образует новую пару
        // с текущим элементом, поэтому прибавляем всё количество сразу.
        res += count[num]
        // Увеличиваем частоту после подсчёта, чтобы текущий элемент
        // не образовал пару сам с собой.
        count[num]++
    }
    // К этому моменту каждая допустимая пара учтена ровно один раз.
    return res
}