package main

/*
Дан целочисленный массив nums с индексацией с 0 и чётной длиной.
Он содержит одинаковое количество положительных и отрицательных чисел.

Переставьте элементы nums так, чтобы выполнялись следующие условия:
У любой пары соседних элементов противоположные знаки.
Для всех чисел одного знака сохраняется их относительный порядок в nums.
Переставленный массив начинается с положительного числа.
Верните изменённый массив после перестановки элементов
в соответствии с указанными условиями.

Пример 1:
Вход: nums = [3,1,-2,-5,2,-4]
Выход: [3,-2,1,-5,2,-4]
Пояснение: положительные числа в nums — [3,1,2].
Отрицательные числа — [-2,-5,-4].
Единственный вариант перестановки, удовлетворяющий всем условиям:
[3,-2,1,-5,2,-4].
Другие варианты, например [1,-2,2,-5,3,-4], [3,1,2,-2,-5,-4],
[-2,3,-5,1,-4,2], неверны: они нарушают одно или несколько условий.

Пример 2:
Вход: nums = [-1,1]
Выход: [1,-1]
Пояснение: 1 — единственное положительное число в nums,
а -1 — единственное отрицательное.
Поэтому после перестановки получаем [1,-1].

Ограничения:
2 <= nums.length <= 2 * 10^5
nums.length чётно
1 <= |nums[i]| <= 10^5
nums содержит одинаковое количество положительных и отрицательных чисел.
*/

// rearrangeArray возвращает новый массив с чередованием знаков,
// начиная с положительного числа и сохраняя порядок чисел каждого знака.
// За один проход положительные числа занимают чётные позиции результата,
// отрицательные — нечётные.
// Исходный nums не изменяется.
// Время: O(n), где n = len(nums).
// Рабочая память без результата: O(1); память результата res: O(n).
func rearrangeArray(nums []int) []int {
    // i и j — следующие свободные позиции для чисел своего знака:
    // i проходит 0, 2, 4, ...; j проходит 1, 3, 5, ... .
    // Поэтому положительное число стоит первым, а знаки чередуются.
    i, j := 0, 1

    // Отдельный срез позволяет читать nums в исходном порядке,
    // не затирая ещё не обработанные элементы при перестановке.
    res := make([]int, len(nums))

    // Обходим nums слева направо: каждое встретившееся число попадает
    // в следующую позицию своего знака, не обгоняя предыдущие числа
    // того же знака.
    // Так сохраняется их относительный порядок.
    // Например, для [3,1,-2,-5,2,-4] первые три записи:
    // 3 -> res[0], 1 -> res[2], -2 -> res[1].
    for k := range nums {
        if nums[k] > 0 {
            // К этому шагу все чётные позиции до i уже заполнены.
            // Положительных чисел ровно n/2, как и чётных позиций,
            // поэтому при записи i всегда находится внутри res.
            res[i] = nums[k]
            // Перескакиваем через позицию для отрицательного числа.
            i += 2
        } else {
            // Нулей по условию нет, значит эта ветка — для отрицательных.
            // Все нечётные позиции до j уже заполнены.
            // Их тоже n/2,
            // поэтому текущая запись по j безопасна.
            res[j] = nums[k]
            // Продвигаем только j: следующий положительный использует i.
            j += 2
        }
    }

    // Оба знака встретились по n/2 раз: все позиции res заполнены.
    // После последних записей i = n и j = n + 1, но эти индексы
    // больше не используются для обращения к срезу.
    return res
}