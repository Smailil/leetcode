package main

/*
Дан целочисленный параметр rowIndex. Верните строку треугольника Паскаля
с индексом rowIndex (нумерация начинается с 0).

В треугольнике Паскаля каждое число равно сумме двух чисел,
расположенных непосредственно над ним, как показано ниже:
https://upload.wikimedia.org/wikipedia/commons/0/0d/PascalTriangleAnimated2.gif

Пример 1:
Вход: rowIndex = 3
Выход: [1,3,3,1]

Пример 2:
Вход: rowIndex = 0
Выход: [1]

Пример 3:
Вход: rowIndex = 1
Выход: [1,1]

Ограничения:
0 <= rowIndex <= 33
*/

// getRow возвращает строку треугольника Паскаля с индексом rowIndex.
// Элементы вычисляются последовательно как биномиальные коэффициенты,
// поэтому предыдущие строки треугольника хранить не требуется.
//
// Время: O(n), где n = rowIndex.
// Дополнительная память: O(1) без учёта возвращаемого массива;
// сам результат содержит n + 1 элемент и занимает O(n).
func getRow(rowIndex int) []int {
    // Первый элемент любой строки равен C(n, 0) = 1.
    row := []int{1}
    // Из C(n, i-1) получаем следующий коэффициент по формуле
    // C(n, i) = C(n, i-1) * (n-i+1) / i.
    for i := 1; i <= rowIndex; i++ {
        // Деление выполняется без остатка по свойствам биномиальных
        // коэффициентов. При rowIndex <= 33 промежуточное произведение
        // помещается в 64-битный int, используемый средой LeetCode.
        row = append(row, row[len(row)-1]*(rowIndex-i+1)/i)
    }
    // После n итераций собраны коэффициенты C(n, 0), ..., C(n, n).
    return row
}
