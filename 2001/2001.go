package main

/*
Даны n прямоугольников, представленных двумерным целочисленным массивом
rectangles с индексацией с 0, где rectangles[i] = [width_i, height_i] задаёт
ширину и высоту i-го прямоугольника.

Два прямоугольника i и j (i < j) считаются взаимозаменяемыми, если отношение
их ширины к высоте одинаково. Формально два прямоугольника взаимозаменяемы,
если width_i / height_i == width_j / height_j (используется вещественное,
а не целочисленное деление).

Верните количество пар взаимозаменяемых прямоугольников в rectangles.

Пример 1:
Вход: rectangles = [[4,8],[3,6],[10,20],[15,30]]
Выход: 6
Пояснение: ниже перечислены пары взаимозаменяемых прямоугольников по индексам
(с индексацией с 0):
- Прямоугольник 0 и прямоугольник 1: 4/8 == 3/6.
- Прямоугольник 0 и прямоугольник 2: 4/8 == 10/20.
- Прямоугольник 0 и прямоугольник 3: 4/8 == 15/30.
- Прямоугольник 1 и прямоугольник 2: 3/6 == 10/20.
- Прямоугольник 1 и прямоугольник 3: 3/6 == 15/30.
- Прямоугольник 2 и прямоугольник 3: 10/20 == 15/30.

Пример 2:
Вход: rectangles = [[4,5],[7,8]]
Выход: 0
Пояснение: пар взаимозаменяемых прямоугольников нет.

Ограничения:
n == rectangles.length
1 <= n <= 10^5
rectangles[i].length == 2
1 <= width_i, height_i <= 10^5
*/

// interchangeableRectangles подсчитывает пары прямоугольников с одинаковым
// отношением ширины к высоте. Сначала прямоугольники группируются по отношению,
// затем для каждой группы вычисляется количество пар.
// Среднее время: O(n + k) = O(n), где n = len(rectangles), а k — число
// различных отношений сторон; операции с map в среднем занимают O(1).
// Дополнительная память: O(k).
func interchangeableRectangles(rectangles [][]int) int64 {
    // count[ratio] хранит количество уже встреченных прямоугольников
    // с данным отношением ширины к высоте.
    count := make(map[float64]int)
    for _, rect := range rectangles {
        // По условию rect[1] >= 1, поэтому деление на высоту безопасно.
        // Одинаковые отношения сторон дают одинаковый ключ группы.
        ratio := float64(rect[0]) / float64(rect[1])
        count[ratio]++
    }

    // В группе из c прямоугольников находится c * (c - 1) / 2 пар:
    // каждый элемент сочетается с c - 1 другими, а деление на 2 убирает
    // двойной подсчёт каждой пары.
    var res int64 = 0
    for _, c := range count {
        if c > 1 {
            // Приведение выполняется до умножения: при c <= n <= 10^5
            // произведение меньше 10^10 и гарантированно помещается в int64.
            res += int64(c) * int64(c-1) / 2
        }
    }
    return res
}