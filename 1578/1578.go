package main

/*
У Алисы есть n воздушных шаров, расположенных на верёвке.
Дана строка colors с индексацией от 0, где colors[i] — цвет i-го шара.

Алиса хочет, чтобы верёвка была разноцветной.
Она не хочет видеть рядом шары одного цвета, поэтому просит Боба помочь.
Боб может снять с верёвки некоторые шары, чтобы сделать её разноцветной.
Дан целочисленный массив neededTime с индексацией от 0.
Значение neededTime[i] — время в секундах, за которое Боб снимет i-й шар.

Верните минимальное время, за которое Боб сделает верёвку разноцветной.

Пример 1:
https://assets.leetcode.com/uploads/2021/12/13/ballon1.jpg
Вход: colors = "abaac", neededTime = [1,2,3,4,5]
Выход: 3
Пояснение:
На рисунке 'a' — синий цвет, 'b' — красный, а 'c' — зелёный.
Боб может снять синий шар с индексом 2.
Это займёт 3 секунды.
Теперь соседних шаров одного цвета нет.
Общее время = 3.

Пример 2:
https://assets.leetcode.com/uploads/2021/12/13/balloon2.jpg
Вход: colors = "abc", neededTime = [1,2,3]
Выход: 0
Пояснение:
Верёвка уже разноцветная.
Бобу не нужно снимать шары с верёвки.

Пример 3:
https://assets.leetcode.com/uploads/2021/12/13/balloon3.jpg
Вход: colors = "aabaa", neededTime = [1,2,3,4,1]
Выход: 2
Пояснение:
Боб снимет шары с индексами 0 и 4.
Снять каждый из этих шаров можно за 1 секунду.
Теперь соседних шаров одного цвета нет.
Общее время = 1 + 1 = 2.

Ограничения:
n == colors.length == neededTime.length
1 <= n <= 10^5
1 <= neededTime[i] <= 10^4
colors содержит только строчные английские буквы.
*/

// minCost возвращает минимальное время удаления шаров одинакового цвета,
// стоящих рядом. В каждой непрерывной группе оставляет самый дорогой шар.
// Удаления учитываются только в ответе: входные данные не изменяются.
// Время: O(n), где n = len(colors), один проход по строке.
// Дополнительная память: O(1), только индексы и числовой ответ.
func minCost(colors string, neededTime []int) int {
	// В исходной группе одного цвета можно оставить не больше одного шара.
	// Оставив шар со временем t, заплатим S-t, где S — сумма времён группы.
	// Минимум достигается при максимальном t. По одному шару из каждой
	// исходной группы достаточно: цвета соседних групп различаются.
	// l — индекс оставляемого шара, а не обязательно начало группы.
	l, res := 0, 0
	// n >= 1; colors содержит ASCII-буквы, len(neededTime) == len(colors).
	// Поэтому индексы строки и массива соответствуют одним и тем же шарам.
	// Перед шагом l < r и указывает на максимум в текущей группе;
	// res — минимальная цена удаления для префикса до r, не включая r.
	for r := 1; r < len(colors); r++ {
		if colors[l] == colors[r] {
			// Два кандидата одного цвета: оставляем более дорогого,
			// а стоимость удаления более дешёвого сразу прибавляем к res.
			if neededTime[l] < neededTime[r] {
				// Старый максимум теперь дешевле нового шара:
				// оплачиваем его удаление и переносим оставляемый индекс.
				res += neededTime[l]
				l = r
			} else {
				// Удаляем новый шар. При равенстве времён можно выбрать
				// любой из двух; этот код сохраняет прежний индекс l.
				res += neededTime[r]
			}
		} else {
			// Новый цвет завершает прежнюю группу без дополнительных трат.
			// Шар r становится первым кандидатом для следующей группы.
			l = r
		}
	}
	// Например, для "aaa" и [2,5,3] удаляем шары за 2 и 3, оставляя шар за 5.
	// Сумма не больше n*10^4 <= 10^9 и помещается даже в 32-битный int.
	// При n=1 цикл не выполняется, и ответ равен 0.
	return res
}