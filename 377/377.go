package main

/*
Дан массив различных целых чисел nums и целое число target.
Верните количество возможных комбинаций, сумма которых равна target.

Тесты сгенерированы так, что ответ помещается в 32-битное целое число.

Пример 1:
Вход: nums = [1,2,3], target = 4
Выход: 7
Пояснение:
Возможные способы составить комбинации:
(1, 1, 1, 1)
(1, 1, 2)
(1, 2, 1)
(1, 3)
(2, 1, 1)
(2, 2)
(3, 1)
Обратите внимание, что разные последовательности считаются разными комбинациями.

Пример 2:
Вход: nums = [9], target = 3
Выход: 0

Ограничения:
1 <= nums.length <= 200
1 <= nums[i] <= 1000
Все элементы nums уникальны.
1 <= target <= 1000
*/

// combinationSum4 считает последовательности суммы target с учётом порядка.
// Для каждой суммы перебираем последнее число и дописываем его к меньшей сумме.
// m = len(nums), T = target. Время O(m * T), рабочая память O(T) для dp.
// Вход не меняется; возвращаемый счётчик занимает O(1) памяти.
func combinationSum4(nums []int, target int) int {
    // dp[s] — счётчик последовательностей суммы s в машинном int.
    // Положительные nums не позволяют нужным префиксам превысить target.
    dp := make([]int, target+1)
    
    // Пустая последовательность даёт один способ набрать сумму 0.
    // Благодаря базе одиночное число num учитывается через dp[num-num].
    dp[0] = 1

    // Перед обработкой total все меньшие суммы уже обработаны.
    // Из num > 0 следует total-num < total: незавершённых зависимостей нет.
    for total := 1; total <= target; total++ {
        // Разные последние числа задают непересекающиеся группы.
        // nums уникальны, поэтому одну группу не добавляем дважды.
        for _, num := range nums {
            // У допустимого префикса индекс total-num лежит в [0, total).
            // К каждому его варианту дописываем num: получаем новую группу.
            // Например, [1,2] и [2,1] учтены раздельно по последнему числу.
            if total-num >= 0 {
                dp[total] += dp[total-num]
            }
        }
    }

    // Для суммы, из которой можно достроить target, число способов не больше
    // ответа: к каждому варианту дописываем один фиксированный суффикс.
    // Гарантия 32-битного ответа защищает такие счётчики от переполнения.
    // Остальные dp[s] могут переполнить int, но не ведут к dp[target].
    return dp[target]
}