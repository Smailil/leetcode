package main

/*
Дан массив строк ideas, содержащий список имён для выбора
названия компании.
Процесс выбора названия компании следующий:

Выберите 2 различных имени из ideas и обозначьте их ideaA и ideaB.
Поменяйте местами первые буквы ideaA и ideaB.
Если оба новых имени отсутствуют в исходном массиве ideas, то
название ideaA ideaB (соединение ideaA и ideaB через пробел)
считается допустимым названием компании.
Иначе название не является допустимым.
Верните количество различных допустимых названий компании.

Пример 1:
Вход: ideas = ["coffee","donuts","time","toffee"]
Выход: 6
Пояснение: следующие варианты выбора допустимы:
- ("coffee", "donuts"): получаем название компании "doffee conuts".
- ("donuts", "coffee"): получаем название компании "conuts doffee".
- ("donuts", "time"): получаем название компании "tonuts dime".
- ("donuts", "toffee"): получаем название компании "tonuts doffee".
- ("time", "donuts"): получаем название компании "dime tonuts".
- ("toffee", "donuts"): получаем название компании "doffee tonuts".
Следовательно, всего существует 6 различных названий компании.
Примеры недопустимого выбора:
- ("coffee", "time"): полученное после обмена имя "toffee" уже есть
  в исходном массиве.
- ("time", "toffee"): после обмена оба имени остаются прежними
  и присутствуют в исходном массиве.
- ("coffee", "toffee"): оба полученных после обмена имени уже есть
  в исходном массиве.

Пример 2:
Вход: ideas = ["lack","back"]
Выход: 0
Пояснение: допустимых вариантов выбора нет.
Поэтому возвращаем 0.

Ограничения:
2 <= ideas.length <= 5 * 10^4
1 <= ideas[i].length <= 10
ideas[i] состоит из строчных букв английского алфавита.
Все строки в ideas различны.
*/

// distinctNames считает различные допустимые названия компаний.
// Группирует имена по первой букве и считает совместимые пары суффиксов.
// Время: в среднем O(a*n*L), n = len(ideas), L — макс. длина имени.
// Учтены хеширование и сравнение строк; a — число разных первых букв.
// При a <= 26 и L <= 10 по условию это O(n).
// Дополнительная память: O(n) для map, без памяти исходных строк.
// Ключи-срезы могут удерживать буферы входа, но не копируют их байты.
// Входные строки и срез ideas не изменяются.
func distinctNames(ideas []string) int64 {
    // Для каждой первой буквы храним множество оставшихся частей слова.
    // Пустой struct{} служит только меткой присутствия суффикса.
    wordMap := make(map[byte]map[string]struct{})
    for _, word := range ideas {
        // Вход — непустые строки из ASCII a..z: достаточно одного байта.
        // Поэтому и word[0], и срез word[1:] находятся в границах строки.
        key := word[0]
        if wordMap[key] == nil {
            wordMap[key] = make(map[string]struct{})
        }
        // Для слова из одной буквы суффикс равен ""; это допустимый ключ.
        wordMap[key][word[1:]] = struct{}{}
    }

    // Верхняя граница ответа — n*(n-1); при n = 5*10^4
    // она равна 2 499 950 000, поэтому для res используется int64.
    var res int64 = 0
    // Каждое set1 просматривается для остальных a-1 групп.
    // Всего O(a*n) проверок; строковая проверка в среднем стоит O(L).
    for char1, set1 := range wordMap {
        for char2, set2 := range wordMap {
            // Одинаковые первые буквы ничего не меняют:
            // оба исходных имени останутся в ideas, значит пара недопустима.
            if char1 == char2 {
                continue
            }

            // Смена char1 на char2 сохраняет суффикс. Новое имя уже
            // есть в ideas, если этот суффикс есть в set2.
            // Общие суффиксы непригодны для обеих сторон.
            // Например, offee общий для c и t: coffee станет toffee,
            // а toffee уже есть в ideas.
            intersect := 0
            for w := range set1 {
                if _, ok := set2[w]; ok {
                    intersect++
                }
            }

            // Размер разности: |set1 без set2| = |set1| - intersect.
            // Для обратной разности формула симметрична.
            // Любой выбор из первой разности сочетается с любым из второй.
            distinct1 := len(set1) - intersect
            distinct2 := len(set2) - intersect
            // Например, d: {onuts}, t: {ime, offee}, пересечение пусто.
            // Для пары (d,t) вклад равен 1*2 = 2.
            // (t,d) учтётся отдельно, так что ещё на 2 не умножаем.
            // Множители приводим к int64 до умножения.
            res += int64(distinct1) * int64(distinct2)
        }
    }

    return res
}