package main

/*
Дан целочисленный массив height длины n.
Нарисовано n вертикальных линий с концами в (i, 0) и (i, height[i]).
Найдите две линии, которые вместе с осью X образуют контейнер,
содержащий больше всего воды.
Верните максимальное количество воды, которое может хранить контейнер.
Обратите внимание, что контейнер нельзя наклонять.

Пример 1:
https://s3-lc-upload.s3.amazonaws.com/uploads/2018/07/17/question_11.jpg
Вход: height = [1,8,6,2,5,4,8,3,7]
Выход: 49
Пояснение: вертикальные линии представлены массивом [1,8,6,2,5,4,8,3,7].
В этом случае максимальная площадь воды (синяя секция),
которую может содержать контейнер, равна 49.

Пример 2:
Вход: height = [1,1]
Выход: 1

Ограничения:
n == height.length
2 <= n <= 10^5
0 <= height[i] <= 10^4
*/

// maxArea ищет наибольшую площадь между стенками двумя указателями.
// Удаляем меньшую стенку: при меньшей ширине она не улучшит текущую пару.
// Время O(n), n = len(height); рабочая память и скалярный ответ O(1).
// height не изменяется.
func maxArea(height []int) int {
	maxResult := 0
	l, r := 0, len(height)-1
	for l < r {
		// Площадь = ширина * меньшая высота; обе границы в массиве.
		// По условию площадь меньше 10^9, безопасна для 32-битного int.
		maxResult = max(maxResult, min(height[l], height[r])*(r-l))
		// Более высокую границу сохраняем для следующей пары.
		// При равных высотах допустима любая сторона; здесь отбрасываем правую.
		if height[l] < height[r] {
			l++
		} else {
			r--
		}
	}
	return maxResult
}
