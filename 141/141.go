package main

/*
Дана голова связного списка.
Определите, есть ли в списке цикл.
В списке существует цикл, если есть некоторый узел,
к которому можно снова добраться, непрерывно следуя по указателю next.
Внутри pos обозначает индекс узла, к которому подключён указатель next хвоста.
Обратите внимание, что pos не передаётся в качестве параметра.
Возвращайте true, если в связанном списке есть цикл.
В противном случае верните false.

Пример 1:
https://assets.leetcode.com/uploads/2018/12/07/circularlinkedlist.png
Вход: head = [3,2,0,-4], pos = 1
Выход: true
Пояснение: в списке есть цикл, хвост соединяется с узлом с индексом 1
при индексации с нуля.

Пример 2:
https://assets.leetcode.com/uploads/2018/12/07/circularlinkedlist_test2.png
Вход: head = [1,2], pos = 0
Выход: true
Пояснение: В связанном списке есть цикл, хвост которого соединяется с 0-м узлом.

Пример 3:
https://assets.leetcode.com/uploads/2018/12/07/circularlinkedlist_test3.png
Вход: head = [1], pos = -1
Выход: false
Объяснение: В связанном списке нет цикла.

Ограничения:
Количество узлов в списке находится в диапазоне [0, 10^4].
-10^5 <= Node.val <= 10^5
pos имеет значение -1 или допустимый индекс в связанном списке.
*/

type ListNode struct {
    Val int
    Next *ListNode
}

// hasCycle использует указатели Флойда со скоростями один и два узла.
// В цикле fast догоняет slow, уменьшая расстояние по модулю длины цикла.
// Время O(n), n — число разных достижимых узлов; рабочая память
// и скалярный результат O(1). Связи исходного списка не изменяются.
func hasCycle(head *ListNode) bool {
    slow, fast := head, head
	// Два nil-условия защищают fast.Next.Next. Если цикла нет,
	// быстрый указатель достигнет конца, в том числе для пустого списка.
	for fast != nil && fast.Next != nil {
		slow = slow.Next
		fast = fast.Next.Next
		// Сравниваем после движения: исходное равенство head само по себе
		// не доказывает цикл. Встреча означает повторное посещение узла.
		if slow == fast {
			return true
		}
	}
	return false
}
