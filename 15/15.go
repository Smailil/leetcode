package main

import "sort"

/*
Дан целочисленный массив nums.
Верните все тройки [nums[i], nums[j], nums[k]], для которых
i != j, i != k, j != k и nums[i] + nums[j] + nums[k] == 0.
Набор решений не должен содержать повторяющихся троек.

Пример 1:
Вход: nums = [-1,0,1,2,-1,-4]
Выход: [[-1,-1,2],[-1,0,1]]
Пояснение:
nums[0] + nums[1] + nums[2] = (-1) + 0 + 1 = 0.
nums[1] + nums[2] + nums[4] = 0 + 1 + (-1) = 0.
nums[0] + nums[3] + nums[4] = (-1) + 2 + (-1) = 0.
Отдельные тройки — это [-1,0,1] и [-1,-1,2].
Порядок вывода и порядок троек не имеют значения.

Пример 2:
Вход: nums = [0,1,1]
Выход: []
Пояснение: единственная возможная тройка не даёт в сумме 0.

Пример 3:
Вход: nums = [0,0,0]
Выход: [[0,0,0]]
Пояснение: сумма единственной возможной тройки равна 0.
*/

// threeSum сортирует nums и ищет пару двумя указателями для каждого i.
// n = len(nums), t — число различных троек в результате.
// Время O(n^2), рабочая память O(log n) для стека сортировки;
// сами два указателя требуют O(1), результат занимает O(t).
// Побочный эффект: nums сортируется на месте при n >= 3.
func threeSum(nums []int) [][]int {
    if len(nums) < 3 {
        return [][]int{}
    }
    
    // Сортировка делает сумму монотонной по каждому из двух указателей.
    sort.Ints(nums)
    result := make([][]int, 0)
    
    for i := 0; i < len(nums)-2; i++ {
        // Повтор первого значения породил бы те же тройки.
        if i > 0 && nums[i] == nums[i-1] {
            continue
        }
        
        // Все последующие значения не меньше nums[i]: три положительных
        // числа уже не дадут ноль, поэтому следующие i не нужны.
		if nums[i] > 0 {
            break
        }
        
        // Индексы i < l < r различны; сужаем ещё не исключённый диапазон.
        l, r := i+1, len(nums)-1
        for l < r {
            // Малую сумму можно увеличить лишь сдвигом l вправо,
            // большую — уменьшить сдвигом r влево; пары вне диапазона
            // уже исключены монотонностью отсортированного массива.
            // Для произвольных int сумма может переполниться: защиты нет.
            sum := nums[i] + nums[l] + nums[r]
            if sum < 0 {
                l++
            } else if sum > 0 {
                r--
            } else {
                result = append(result, []int{nums[i], nums[l], nums[r]})

                // После ответа пропускаем равные значения с обоих краёв,
                // затем оба указателя уходят к следующей возможной паре.
                // l < r защищает обращения l+1 и r-1.
                for l < r && nums[l] == nums[l+1] {
                    l++
                }
                for l < r && nums[r] == nums[r-1] {
                    r--
                }
                l++
                r--
            }
        }
    }
    
    return result
}
