package main

/*
Дан массив различных целых чисел-кандидатов candidates
и целевое целочисленное значение target.
Верните список всех уникальных комбинаций кандидатов,
в которых сумма выбранных чисел равна целевому значению.
Вы можете возвращать комбинации в любом порядке.
Одно и то же число может быть выбрано из candidates неограниченное число раз.
Две комбинации уникальны, если частота хотя бы одного из выбранных чисел
различна.
Тестовые примеры генерируются таким образом, чтобы количество уникальных
комбинаций с суммой target было меньше 150 для данного входа.

Пример 1:
Вход: candidates = [2,3,6,7], target = 7
Выход: [[2,2,3],[7]]
Объяснение:
2 и 3 являются кандидатами, а 2 + 2 + 3 = 7.
Обратите внимание, что 2 можно использовать несколько раз.
7 — кандидат, а 7 = 7.
Это единственные две комбинации.

Пример 2:
Вход: candidates = [2,3,5], target = 8
Выход: [[2,2,2,2],[2,3,3],[3,5]]

Пример 3:
Вход: candidates = [2], target = 1
Выход: []

Ограничения:
1 <= candidates.length <= 30
2 <= candidates[i] <= 40
Все элементы candidates различны.
1 <= target <= 40
*/

// combinationSum перебирает количество копий каждого кандидата.
// m = len(candidates), a — минимум кандидатов, d = target/a + 1.
// T — число вызовов dfs, L — суммарная длина найденных комбинаций.
// Время O(d*T + L): верхняя оценка учитывает копирование при append;
// T может быть экспоненциальным, глубина не больше m+d.
// Рабочая память O(m+d), память результата O(L); вход не меняется.
func combinationSum(candidates []int, target int) [][]int {
    res := make([][]int, 0)
	var dfs func(int, []int, int)
	// dfs выбирает кандидатов начиная с i, total — сумма текущего cur.
	// Индексы выбранных кандидатов не убывают: перестановки не дублируются.
	// Для этого поддерева T — число вызовов, S — длина новых ответов.
	// Время O(d*T+S), рабочая память O(m+d) для пути и рекурсии.
	// Рабочий буфер cur меняется, ответы копируются в захваченный res.
	dfs = func(i int, cur []int, total int) {
		if total == target {
			// Копия изолирует ответ от следующих append и откатов cur.
			r := make([]int, len(cur))
			copy(r, cur)
			res = append(res, r)
			return 
		}
		// Все кандидаты положительны: превышение уже нельзя исправить.
		// Проверка i также защищает обращение candidates[i] ниже.
		if i >= len(candidates) || total > target {
			return 
		}

		// Взять кандидата: оставляем i, разрешая повтор этого же числа.
		cur = append(cur, candidates[i])
		dfs(i, cur, total + candidates[i])
		// Пропустить кандидата: откатываем путь и переходим к i+1.
		// Две ветки разделяют решения по наличию очередной копии числа.
		cur = cur[:len(cur)-1]
		dfs(i + 1, cur, total)
	}
	dfs(0, make([]int, 0), 0)
	return res
}
