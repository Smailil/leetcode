package main

/*
Вам даны два массива положительных целых чисел arr1 и arr2.

Префикс положительного целого числа — это целое число, образованное одной
или несколькими его цифрами, начиная с самой левой.
Например, 123 — префикс числа 12345, а 234 — нет.

Общий префикс двух целых чисел a и b — это целое число c, которое является
префиксом и a, и b.
Например, у чисел 5655359 и 56554 есть общие префиксы 565 и 5655,
а у чисел 1223 и 43456 общего префикса нет.

Найдите длину самого длинного общего префикса среди всех пар (x, y),
где x принадлежит arr1, а y принадлежит arr2.

Верните длину самого длинного общего префикса среди всех пар.
Если ни у одной пары нет общего префикса, верните 0.

Пример 1:
Вход: arr1 = [1,10,100], arr2 = [1000]
Выход: 3
Пояснение: есть 3 пары (arr1[i], arr2[j]):
- Самый длинный общий префикс пары (1, 1000) — 1.
- Самый длинный общий префикс пары (10, 1000) — 10.
- Самый длинный общий префикс пары (100, 1000) — 100.
Самый длинный общий префикс — 100, его длина равна 3.

Пример 2:
Вход: arr1 = [1,2,3], arr2 = [4,4,4]
Выход: 0
Пояснение: ни у одной пары (arr1[i], arr2[j]) нет общего префикса,
поэтому возвращаем 0.
Обратите внимание: общие префиксы элементов одного массива не учитываются.

Ограничения:
1 <= arr1.length, arr2.length <= 5 * 10^4
1 <= arr1[i], arr2[i] <= 10^8
*/

// longestCommonPrefix находит максимальную длину общего префикса пары
// из одного числа arr1 и одного числа arr2.
// Собирает префиксы arr1 и ищет самый длинный совпавший для каждого arr2.
// Время: в среднем O((m + n) * d), где d — максимум цифр в числе.
// m = len(arr1), n = len(arr2); d <= 9 по условию, поэтому O(m + n).
// Дополнительная память: O(k), где k — число разных префиксов arr1.
// k <= m*d; при фиксированном d худшая память O(m).
// Входные массивы не изменяются.
func longestCommonPrefix(arr1, arr2 []int) int {
	// Множество: p есть в prefixes, если p — префикс хотя бы одного
	// числа из arr1. Повторы не увеличивают размер множества.
	prefixes := make(map[int]bool)

	for _, num := range arr1 {
		// num — копия элемента, поэтому деление не изменяет arr1.
		// Например, из 123 получаем 123, 12 и 1; 0 не добавляем.
		for num > 0 {
			prefixes[num] = true
			// Для положительного числа /10 удаляет последнюю цифру.
			num /= 10
		}
	}

	// answer — максимум для уже рассмотренных чисел arr2.
	// Ноль означает, что общий префикс пока не найден.
	answer := 0

	for _, num := range arr2 {
		// Проверяем число целиком, затем укорачиваем его справа.
		// Первая найденная запись — самый длинный общий префикс этого num.
		prefix := num

		// Отсутствующий ключ map даёт false. Ноль завершает поиск:
		// он не считается префиксом положительного числа.
		for prefix > 0 && !prefixes[prefix] {
			// Для arr1 = [1,10,100] и num = 1000: 1000 отсутствует,
			// а 100 уже есть в prefixes, поэтому останавливаемся на нём.
			prefix /= 10
		}

		// Если совпадения нет, prefix = 0 и length остаётся 0.
		// Иначе считаем цифры: 100 -> 10 -> 1 -> 0 даёт длину 3.
		// При этом prefix расходуется; результат сохраняется в length.
		length := 0
		for prefix > 0 {
			length++
			prefix /= 10
		}

		// Оба цикла вместе удаляют не больше d цифр исходного num:
		// сначала до совпадения, затем у совпавшей части. Это O(d), не O(d^2).
		// Обновляем максимум для всех уже обработанных чисел arr2.
		answer = max(answer, length)
	}

	return answer
}