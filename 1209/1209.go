package main

import "strings"

/*
Даны строка s и целое число k.
Операция удаления k одинаковых букв состоит в выборе k соседних одинаковых
букв в s и их удалении.
При этом части строки слева и справа от удалённой подстроки соединяются.

Повторяйте такие удаления в s, пока их больше нельзя выполнить.

Верните итоговую строку после выполнения всех таких удалений.
Гарантируется, что ответ единственен.

Пример 1:
Вход: s = "abcd", k = 2
Выход: "abcd"
Пояснение: Удалять нечего.

Пример 2:
Вход: s = "deeedbbcccbdaa", k = 3
Выход: "aa"
Пояснение:
Сначала удалите "eee" и "ccc": получится "ddbbbdaa".
Затем удалите "bbb": получится "dddaa".
Наконец, удалите "ddd": получится "aa".

Пример 3:
Вход: s = "pbbcggttciiippooaais", k = 2
Выход: "ps"

Ограничения:
1 <= s.length <= 10^5
2 <= k <= 10^4
s содержит только строчные английские буквы.

*/

// removeDuplicates удаляет группы из k соседних одинаковых букв.
// Стек хранит группы остатка строки после обработки текущего префикса.
// Время: O(n) амортизированно, где n = len(s).
// Рабочая память без результата: O(n); память результата: O(r),
// где r — длина итоговой строки; исходная строка s не изменяется.
func removeDuplicates(s string, k int) string {
    // В записи [char, count] хранятся код буквы и число её повторений.
    // Группы идут в порядке строки; вершина стека — последняя группа.
    stack := [][]int{} // [char, count]

    // По условию буквы ASCII: каждый rune c соответствует одному байту s.
    for _, c := range s {
        // Новая буква либо продолжает последнюю группу, либо начинает новую.
        // Проверка len(stack) > 0 защищает обращение к вершине пустого стека.
        if len(stack) > 0 && stack[len(stack)-1][0] == int(c) {
            stack[len(stack)-1][1]++
        } else {
            stack = append(stack, []int{int(c), 1})
        }
        // После ветки выше стек непуст: группу обновили или добавили.
        // Как только набралось k букв, удаляем всю группу с вершины за O(1).
        if stack[len(stack)-1][1] == k {
            // Предыдущая группа снова становится концом оставшейся строки.
            // Следующие буквы могут продолжить её и вызвать новое удаление.
            // При k=2 в "abccba" исчезнут "cc", затем "bb", затем "aa".
            stack = stack[:len(stack)-1]
        }
    }

    // В оставшихся группах count < k, соседние группы различаются буквами.
    // Восстанавливаем строку в порядке стека: каждую букву пишем count раз.
    // Всего записывается r <= n байтов, поэтому сборка занимает O(r).
    var res strings.Builder
    for _, item := range stack {
        for i := 0; i < item[1]; i++ {
            res.WriteByte(byte(item[0]))
        }
    }

    // String() использует буфер Builder без копирования. Этот буфер входит
    // в память результата O(r), а не в дополнительную память стека O(n).
    return res.String()
}