package main

/*
Вам дан массив целых чисел nums, есть скользящее окно размера k,
которое движется из самого левого края массива в самый правый.
В окне вы можете увидеть только k чисел.
Каждый раз скользящее окно перемещается вправо на одну позицию.
Вернуть максимумы скользящих окон.

Пример 1:
Вход: nums = [1,3,-1,-3,5,3,6,7], k = 3
Выход: [3,3,5,5,6,7]
Объяснение:
Положение окна                 Максимум
---------------               -----
[1  3  -1] -3  5  3  6  7       3
 1 [3  -1  -3] 5  3  6  7       3
 1  3 [-1  -3  5] 3  6  7       5
 1  3  -1 [-3  5  3] 6  7       5
 1  3  -1  -3 [5  3  6] 7       6
 1  3  -1  -3  5 [3  6  7]      7

Пример 2:
Вход: nums = [1], k = 1
Выход: [1]

Ограничения:
1 <= nums.length <= 10^5
-10^4 <= nums[i] <= 10^4
1 <= k <= nums.length
*/

type deque struct {
	indexes []int
}

// func (d *deque) pushFirst(i int) {
// 	d.indexes = append([]int{i}, d.indexes...)
// }

// getFirst читает первый индекс за O(1) времени и памяти, не меняя deque.
// Требует непустой indexes; вызывающий алгоритм проверяет это своим порядком.
func (d *deque) getFirst() int {
	return d.indexes[0]
}

// popFirst снимает первый индекс с непустого deque, изменяя d.indexes.
// Время и новая рабочая память O(1); срез удерживает прежний общий буфер.
func (d *deque) popFirst() {
	d.indexes = d.indexes[1:]
}

// pushLast добавляет индекс в конец, изменяя d.indexes.
// Время O(1) амортизированно, но рост буфера может стоить O(t),
// t — текущая длина. Рабочие переменные O(1), новый буфер до O(t+1).
func (d *deque) pushLast(i int) {
	d.indexes = append(d.indexes, i)
}

// getLast читает последний индекс непустого deque без изменений.
// Время, рабочая память и скалярный результат O(1).
func (d *deque) getLast() int {
	return d.indexes[len(d.indexes)-1]
}

// popLast удаляет последний индекс непустого deque, меняя d.indexes.
// Время и новая рабочая память O(1); общий буфер среза остаётся выделенным.
func (d *deque) popLast() {
	d.indexes = d.indexes[:len(d.indexes)-1]
}

// empty проверяет логическую пустоту за O(1) времени и памяти.
// Состояние deque не изменяется; наличие буфера не означает наличие элементов.
func (d *deque) empty() bool {
	return len(d.indexes) == 0
}


// maxSlidingWindow хранит индексы кандидатов в монотонном deque.
// Для k > 1 время O(n) амортизированно, n = len(nums): каждый индекс
// добавляется и удаляется не более раза. Рабочая память O(k),
// новый результат O(n-k+1). Исходный nums не изменяется.
// При k == 1 время/новая память O(1): возвращается сам срез nums,
// поэтому ответ разделяет весь его существующий буфер.
func maxSlidingWindow(nums []int, k int) []int {
    if k == 1 {
		return nums
	}
	res := make([]int, 0)
	dq := &deque{}
	l, r := 0, 0
	for ; r < len(nums); r++ {
		// Более слабый старый кандидат не нужен: новый индекс правее
		// и проживёт в окне дольше. Равные значения сохраняются,
		// поэтому высоты кандидатов не возрастают, индексы возрастают.
		for !dq.empty() && nums[dq.getLast()] < nums[r] {
			dq.popLast()
		}
		dq.pushLast(r)

		// После pushLast deque непустой, значит getFirst безопасен.
		// l сдвигается только на единицу: устареть мог лишь один
		// прежний первый индекс, остальные ещё принадлежат окну.
		if l > dq.getFirst() {
			dq.popFirst()
		}
		// Только после накопления k элементов окно полное.
		// Максимум находится спереди; затем сдвигаем левую границу.
		if r+1>=k {
			res = append(res, nums[dq.getFirst()])
			l++
		}
	}
	return res
}
