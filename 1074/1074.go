package main

/*
Даны матрица matrix и число target.
Верните количество непустых подматриц, сумма элементов которых равна target.

Подматрица (x1, y1, x2, y2) — это множество всех клеток matrix[x][y],
для которых x1 <= x <= x2 и y1 <= y <= y2.

Две подматрицы (x1, y1, x2, y2) и (x1', y1', x2', y2') различны,
если хотя бы одна их координата различается, например x1 != x1'.

Пример 1:
https://assets.leetcode.com/uploads/2020/09/02/mate1.jpg
Вход: matrix = [[0,1,0],[1,1,1],[0,1,0]], target = 0
Выход: 4
Пояснение: четыре подматрицы размера 1x1, содержащие только 0.

Пример 2:
Вход: matrix = [[1,-1],[-1,1]], target = 0
Выход: 5
Пояснение: две подматрицы 1x2, две подматрицы 2x1 и одна подматрица 2x2.

Пример 3:
Вход: matrix = [[904]], target = 0
Выход: 0

Ограничения:
1 <= matrix.length <= 100
1 <= matrix[0].length <= 100
-1000 <= matrix[i][j] <= 1000
-10^8 <= target <= 10^8
*/

// numSubmatrixSumTarget считает подматрицы с суммой target.
// Фиксирует пару столбцов и сжимает полосу в суммы по строкам.
// Время: в среднем O(R*C^2), R = len(matrix), C = len(matrix[0]).
// Память: O(R + k), k — число разных префиксных сумм для полосы.
// k <= R+1, поэтому дополнительная память O(R); matrix не изменяется.
func numSubmatrixSumTarget(matrix [][]int, target int) int {
    // Матрица непуста и прямоугольна, поэтому matrix[0] существует.
    ROWS, COLS := len(matrix), len(matrix[0])
    // Есть R*(R+1)/2 отрезков строк и C*(C+1)/2 отрезков столбцов.
    // При R=C=100 это 25 502 500 подматриц: res помещается в int32.
    res := 0

    for c1 := range COLS {
        // c1 — левая граница полосы; для новой границы суммы обнуляем.
        rowPrefix := make([]int, ROWS)
        for c2 := c1; c2 < COLS; c2++ {
            // Расширяем полосу вправо на один столбец.
            // После цикла rowPrefix[r] — сумма строки r на c1..c2.
            for r := range ROWS {
                rowPrefix[r] += matrix[r][c2]
            }

            // При фиксированных столбцах подматрица — отрезок строк.
            // Её сумма равна сумме соответствующего отрезка rowPrefix.
            // Для каждой пары столбцов частоты создаём заново.
            // 0:1 — пустой префикс до строки 0: он позволяет учитывать
            // подматрицы, начинающиеся с самой первой строки.
            count := map[int]int{0: 1}
            curSum := 0
            // В count хранятся только более ранние префиксы.
            for r := range ROWS {
                // |rowPrefix[r]| <= 10^5, |curSum| <= 10^7.
                // С |target| <= 10^8 разность curSum-target по модулю
                // не больше 110 000 000: даже int32 достаточно.
                curSum += rowPrefix[r]
                // P(t) — сумма первых t строк; сейчас curSum = P(r+1).
                // Сумма строк t..r: curSum-P(t)=target => P(t)=curSum-target.
                // Берём частоту: равные суммы могут иметь разные начала.
                // Для rowPrefix=[0,0] и target=0 получаем 1, затем 2 начала.
                // Это 3 подматрицы полной ширины во втором примере.
                // Две полосы ширины 1 дадут ещё по одной: итог примера 5.
                res += count[curSum-target]
                // Добавляем текущий префикс только после подсчёта.
                // Иначе при target=0 учли бы пустой отрезок P(r+1)-P(r+1).
                count[curSum]++
            }
        }
    }
    return res
}