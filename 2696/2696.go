package main

/*
Дана строка s, состоящая только из заглавных английских букв.

За одну операцию можно удалить из s любое вхождение "AB" или "CD".

Верните минимально возможную длину строки после таких операций.

После удаления оставшиеся части строки соединяются,
и на стыке могут появиться новые подстроки "AB" или "CD".

Пример 1:
Вход:
s := "ABFCACDB"
Выход: 2
Пояснение: Можно выполнить следующие операции:
- Из строки "ABFCACDB" удаляем "AB", получаем "FCACDB".
- Из строки "FCACDB" удаляем "CD", получаем "FCAB".
- Из строки "FCAB" удаляем "AB", получаем "FC".
Длина получившейся строки равна 2.
Можно показать, что это минимальная возможная длина.

Пример 2:
Вход:
s := "ACBBD"
Выход: 5
Пояснение: Ни одну операцию выполнить нельзя, поэтому длина не меняется.

Ограничения:
1 <= s.length <= 100
Строка s состоит только из заглавных английских букв.
*/

// minLength возвращает минимальную длину после удаления пар AB и CD.
// Стек хранит остаток прочитанного префикса, в котором таких пар уже нет.
// Время O(m), дополнительная память O(m), где m = len(s).
func minLength(s string) int {
	stack := make([]byte, 0, len(s))
	for i := 0; i < len(s); i++ {
		// По условию буквы однобайтовые, поэтому s[i] — одна буква.
		c, n := s[i], len(stack)
		// В стеке удаляемых пар уже нет. Новая пара возможна только на
		// стыке вершины и c; n > 0 защищает обращение к stack[n-1].
		if n > 0 && ((stack[n-1] == 'A' && c == 'B') || (stack[n-1] == 'C' && c == 'D')) {
			// Снимаем вершину и не кладём c: исчезают обе буквы пары.
			// Например, в ACDB удаление CD оставляет A на вершине.
			// Следующая буква B образует с ней AB, и стек пустеет.
			stack = stack[:n-1]
		} else {
			// Пары на стыке нет, поэтому добавление c сохраняет инвариант.
			stack = append(stack, c)
		}
	}

	// Любые две доступные пары не перекрываются: B и D не могут начинать
	// пару. Их удаление в любом порядке даёт одну и ту же строку.
	// Отсюда по индукции по длине все цепочки удалений до упора дают один
	// остаток. Поэтому длина остатка в стеке минимальна.
	return len(stack)
}
