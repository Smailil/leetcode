package main

/*
Даны две строки s и t. Определите, являются ли они изоморфными.

Строки s и t изоморфны, если символы в s можно заменить так,
чтобы получить t.

Все вхождения одного символа должны заменяться другим символом
с сохранением порядка. Никакие два символа не могут отображаться
в один и тот же символ, но символ может отображаться сам в себя.

Пример 1:
Вход: s = "egg", t = "add"
Выход: true
Пояснение: строки s и t можно сделать одинаковыми:
символ 'e' отображается в 'a';
символ 'g' отображается в 'd'.

Пример 2:
Вход: s = "f11", t = "b23"
Выход: false
Пояснение: строки s и t нельзя сделать одинаковыми, поскольку символ '1'
должен одновременно отображаться в символы '2' и '3'.

Пример 3:
Вход: s = "paper", t = "title"
Выход: true

Ограничения:
1 <= s.length <= 5 * 10^4
t.length == s.length
s и t состоят из любых допустимых символов ASCII.
*/

// isIsomorphic проверяет, задают ли строки взаимно однозначное
// соответствие между символами на одинаковых позициях.
// Время: O(n). Дополнительная память: O(1), поскольку алфавит ASCII
// содержит не более 256 различных байтов.
func isIsomorphic(s string, t string) bool {
    // Прямое отображение фиксирует замену символа из s на символ из t.
    // Обратное не позволяет двум разным символам s перейти в один символ t.
    mapST := make(map[byte]byte)
    mapTS := make(map[byte]byte)

    // Рассматриваем символы попарно: каждая позиция задаёт требуемую замену.
    for i := 0; i < len(s); i++ {
        c1, c2 := s[i], t[i]

        // Уже назначенную замену символа из s нельзя изменить позднее.
        if val, ok := mapST[c1]; ok && val != c2 {
            return false
        }
        // Обратная проверка сохраняет взаимную однозначность соответствия.
        if val, ok := mapTS[c2]; ok && val != c1 {
            return false
        }

        // Первое появление фиксирует пару; повторная запись той же пары
        // ничего не меняет и поддерживает единый инвариант цикла.
        mapST[c1] = c2
        mapTS[c2] = c1
    }

    // Все пары согласованы в обоих направлениях, значит строки изоморфны.
    return true
}
