package main

/*
В очереди стоят n человек, пронумерованных от 0 до n - 1
слева направо.
Дан массив heights из различных целых чисел,
где heights[i] — рост человека с индексом i.

Человек может видеть другого человека справа от себя в очереди,
если все стоящие между ними люди ниже обоих этих людей.
Формально, человек i видит человека j, если i < j и
min(heights[i], heights[j]) >
max(heights[i+1], heights[i+2], ..., heights[j-1]).

Верните массив answer длины n, где answer[i] — число людей,
которых человек с индексом i видит справа от себя в очереди.

Пример 1:
https://assets.leetcode.com/uploads/2021/05/29/queue-plane.jpg
Вход: heights = [10,6,8,5,11,9]
Выход: [3,1,2,1,1,0]
Пояснение:
Человек 0 видит людей 1, 2 и 4.
Человек 1 видит человека 2.
Человек 2 видит людей 3 и 4.
Человек 3 видит человека 4.
Человек 4 видит человека 5.
Человек 5 никого не видит, поскольку справа от него никого нет.

Пример 2:
Вход: heights = [5,1,2,3,10]
Выход: [4,1,1,1,0]

Ограничения:
n == heights.length
1 <= n <= 10^5
1 <= heights[i] <= 10^5
Все значения heights уникальны.

*/

// canSeePersonsCount считает для каждого человека видимых людей справа.
// Проходим слева направо с монотонно убывающим стеком индексов: текущий
// человек увеличивает ответы тех людей слева, которые могут его увидеть.
// Срез heights не изменяется.
//
// Время: O(n), где n = len(heights). Каждый индекс добавляется в стек один
// раз и удаляется не более одного раза, поэтому все проходы внутреннего
// цикла вместе занимают O(n), а не O(n^2).
// Рабочая память: O(n) для стека; при убывающем росте он хранит все индексы.
// Память результата: O(n) для отдельного среза res.
func canSeePersonsCount(heights []int) []int {
    n := len(heights)
    res := make([]int, n)
    // В стеке остаются люди, для которых в просмотренной части очереди
    // ещё не встретился более высокий человек справа. Индексы возрастают,
    // а рост строго убывает от основания к вершине: все значения различны.
    // Храним индексы, чтобы увеличивать соответствующие счётчики в res.
    stack := []int{}

    // Ответ для i сейчас ещё неизвестен: он накопится, когда мы дойдём
    // до людей справа от него. На текущем шаге обновляем ответы людей слева.
    for i := range n {
        h := heights[i]
        // Человек на вершине ниже h и видит i: все между ними ниже него,
        // иначе более высокий человек уже удалил бы его из стека раньше.
        // Считаем i видимым и удаляем вершину: теперь h закрывает этому
        // человеку обзор на любого будущего, поскольку выше его самого.
        for len(stack) > 0 && heights[stack[len(stack)-1]] < h {
            res[stack[len(stack)-1]]++
            stack = stack[:len(stack)-1]
        }
        // Если стек не пуст, вершина — ближайший слева человек выше h.
        // Он тоже видит i: все между ними ниже h. Но он сам закрывает i
        // от остальных людей в стеке, поэтому увеличиваем лишь его ответ.
        // Например, при приходе 8 в [10,6,8] сначала считаем видимость
        // для человека ростом 6 и удаляем его, затем — для человека ростом 10.
        if len(stack) > 0 {
            res[stack[len(stack)-1]]++
        }
        // Все меньшие роста уже удалены, так что добавление i сохраняет
        // убывание роста в стеке. Сам i будет ждать видимых людей справа.
        stack = append(stack, i)
    }
    return res
}