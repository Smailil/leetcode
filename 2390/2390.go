package main

/*
Дана строка s, содержащая звёздочки *.

За одну операцию можно:
- Выбрать звёздочку в строке s.
- Удалить её вместе с ближайшей буквой слева.

Верните строку после удаления всех звёздочек.

Примечание:
Входные данные гарантируют, что операцию всегда можно выполнить.
Можно доказать, что итоговая строка всегда единственна.

Пример 1:
Вход: s = "leet**cod*e"
Выход: "lecoe"
Пояснение: Выполняем удаления слева направо:
- Для первой звёздочки ближайший символ слева — 't' в "leet**cod*e".
  Строка s становится "lee*cod*e".
- Для второй звёздочки ближайший символ слева — 'e' в "lee*cod*e".
  Строка s становится "lecod*e".
- Для третьей звёздочки ближайший символ слева — 'd' в "lecod*e".
  Строка s становится "lecoe".
Звёздочек больше нет, поэтому возвращаем "lecoe".

Пример 2:
Вход: s = "erase*****"
Выход: ""
Пояснение: Вся строка удаляется, поэтому возвращаем пустую строку.

Ограничения:
1 <= s.length <= 10^5
Строка s состоит из строчных английских букв и звёздочек *.
Описанную операцию можно выполнить для s.
*/

// removeStars удаляет звёздочки вместе с ближайшими оставшимися буквами слева.
// Стек хранит оставшиеся буквы уже обработанного префикса в исходном порядке.
// Время: O(n), n = len(s): один проход и преобразование стека в строку.
// Память в худшем случае: O(n) для стека и отдельно O(n) для результата.
func removeStars(s string) string {
	stack := []byte{}
	// По условию буквы английские, поэтому каждый символ занимает один байт.
	for i := 0; i < len(s); i++ {
		if s[i] == '*' {
			// Вершина стека — ближайшая неудалённая буква слева от звёздочки.
			// В "abc**d" первая звёздочка снимает c, вторая — уже b.
			// На допустимом входе стек здесь непуст; проверка защищает срез.
			if len(stack) > 0 {
				stack = stack[:len(stack)-1]
			}
		} else {
			// Буква остаётся в префиксе и становится вершиной стека.
			stack = append(stack, s[i])
		}
	}
	return string(stack)
}
