package main

import "sort"

/*
Изначально у вас есть запас силы power, 0 очков и набор жетонов.
Целочисленный массив tokens задаёт их значения: tokens[i] — значение
жетона с индексом i.

Ваша цель — набрать как можно больше очков, разыгрывая жетоны.
За один ход можно разыграть неиспользованный жетон одним из двух способов,
но нельзя применить оба способа к одному жетону.

Лицевой стороной вверх: если текущая сила не меньше tokens[i], можно
разыграть жетон с индексом i, потратив tokens[i] силы и получив 1 очко.
Лицевой стороной вниз: если у вас есть хотя бы 1 очко, можно разыграть
жетон с индексом i, получив tokens[i] силы и потеряв 1 очко.

Верните наибольшее число очков, которое можно набрать, разыграв любое
количество жетонов.

Пример 1:
Вход: tokens = [100], power = 50
Выход: 0
Пояснение:
Изначально у вас 0 очков, поэтому разыграть жетон лицевой стороной вниз
нельзя.
Лицевой стороной вверх его тоже разыграть нельзя: сила (50) меньше
tokens[0] (100).

Пример 2:
Вход: tokens = [200,100], power = 150
Выход: 1
Пояснение:
Разыграйте жетон с индексом 1 (100) лицевой стороной вверх.
Сила снизится до 50, а число очков вырастет до 1.
Жетон с индексом 0 разыгрывать не нужно: его нельзя разыграть лицевой
стороной вверх и получить очко.
Максимальное число очков — 1.

Пример 3:
Вход: tokens = [100,200,300,400], power = 200
Выход: 2
Пояснение:
Чтобы получить 2 очка, разыграйте жетоны в следующем порядке:
Разыграйте жетон с индексом 0 (100) лицевой стороной вверх.
Сила снизится до 100, а число очков вырастет до 1.
Разыграйте жетон с индексом 3 (400) лицевой стороной вниз.
Сила вырастет до 500, а число очков снизится до 0.
Разыграйте жетон с индексом 1 (200) лицевой стороной вверх.
Сила снизится до 300, а число очков вырастет до 1.
Разыграйте жетон с индексом 2 (300) лицевой стороной вверх.
Сила снизится до 0, а число очков вырастет до 2.
Максимальное число очков — 2.

Ограничения:
0 <= tokens.length <= 1000
0 <= tokens[i], power < 10^4
*/

// bagOfTokensScore возвращает наибольшее число очков за игру.
// Покупает очко за самый дешёвый жетон, а при нехватке силы продаёт
// самый дорогой жетон за одно очко, если оно есть.
// Сортирует входной срез tokens на месте, не создавая копии.
// Время: O(n log n), где n = len(tokens): сортировка и проход O(n).
// Дополнительная память: O(log n) для стека сортировки; проход — O(1).
func bagOfTokensScore(tokens []int, power int) int {
	sort.Ints(tokens)
	// [l, r] — включительный диапазон ещё не сыгранных жетонов.
	// score — текущие очки, res — максимум очков за все прошлые ходы.
	res, score, l, r := 0, 0, 0, len(tokens)-1

	// При l <= r оба индекса валидны, каждый ход сужает диапазон.
	// При пустом tokens сразу r = -1, поэтому обращения к срезу нет.
	for l <= r {
		if power >= tokens[l] {
			// Любая покупка даёт ровно одно очко; минимальная цена
			// оставляет не меньше силы, чем покупка другого жетона.
			power -= tokens[l]
			l++
			score++
			// Продажа может уменьшить score, но уже набранный
			// максимум нужно сохранить: можно закончить игру раньше.
			if score > res {
				res = score
			}
		} else if score > 0 {
			// Если не хватает силы даже на дешёвый жетон, купить очко
			// сейчас нельзя. Продажа стоит одно очко; правый жетон
			// даёт больше всего силы и оставляет дешёвые для покупок.
			// Например, при power = 100 и score = 1 продажа за 400
			// даёт power = 500 и score = 0, а res остаётся равным 1.
			// Начальная сила и каждый жетон меньше 10^4, n <= 1000:
			// power < (n+1)*10^4, поэтому даже int32 не переполнится.
			power += tokens[r]
			r--
			score--
		} else {
			// Самый дешёвый жетон недоступен, очков на продажу нет:
			// ни один из двух ходов сейчас невозможен.
			break
		}
	}

	return res
}
