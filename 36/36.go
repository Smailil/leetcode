package main

/*
Дана доска для игры в судоку размером 9 х 9.
Доска для игры в судоку считается действительной,
если соблюдаются следующие правила:
Каждая строка должна содержать цифры от 1 до 9 без повторений.
Каждый столбец должен содержать цифры от 1 до 9 без повторений.
Каждый из девяти блоков таблицы размером 3 x 3
должен содержать цифры от 1 до 9 без повторений.
Верните true, если таблица судоку действительна,
в противном случае верните false.

Примечание: Доска не обязательно должна быть полной или разрешимой,
чтобы быть действительной.

Пример 1:
Вход: board =
[["1","2",".",".","3",".",".",".","."],
 ["4",".",".","5",".",".",".",".","."],
 [".","9","8",".",".",".",".",".","3"],
 ["5",".",".",".","6",".",".",".","4"],
 [".",".",".","8",".","3",".",".","5"],
 ["7",".",".",".","2",".",".",".","6"],
 [".",".",".",".",".",".","2",".","."],
 [".",".",".","4","1","9",".",".","8"],
 [".",".",".",".","8",".",".","7","9"]]
Выход: true

Пример 2:
Вход: board =
[["1","2",".",".","3",".",".",".","."],
 ["4",".",".","5",".",".",".",".","."],
 [".","9","1",".",".",".",".",".","3"],
 ["5",".",".",".","6",".",".",".","4"],
 [".",".",".","8",".","3",".",".","5"],
 ["7",".",".",".","2",".",".",".","6"],
 [".",".",".",".",".",".","2",".","."],
 [".",".",".","4","1","9",".",".","8"],
 [".",".",".",".","8",".",".","7","9"]]
Выход: false
Пояснение: В верхнем левом поле размером 3х3 есть две цифры "1".

Ограничения:
board.length == 9
board[i].length == 9
board[i][j] - это цифры 1-9 или '.'.
*/

// isValidSudoku проверяет повторы цифр в строках, столбцах и блоках.
// Доска не меняется; заполнение пустых ячеек или поиск решения не выполняется.
// Среднее время: O(N + G), N=81 ячейка, G=27 множеств групп.
// Рабочая память: O(G * D), D=9 допустимых цифр в группе.
// Поиск в map по ключу byte в среднем O(1), включая хеширование ключа.
// При фиксированной доске 9x9 время и память составляют O(1).
func isValidSudoku(board [][]byte) bool {
	// Каждая строка, столбец и блок получают независимое множество цифр.
	// Значения struct{} не несут данных: важен только факт наличия ключа.
	rowHms := make([]map[byte]struct{}, 9)
    colHms := make([]map[byte]struct{}, 9)
	boxHms := make([]map[byte]struct{}, 9)

	for i := range rowHms {
        rowHms[i] = make(map[byte]struct{})
        colHms[i] = make(map[byte]struct{})
        boxHms[i] = make(map[byte]struct{})
    }

	// Множества содержат только цифры из уже обработанных ячеек.
	for i, row := range board {
		for j, sym := range row {
			// Пустые клетки не участвуют в проверке и не заносятся в множества.
			if sym == '.' {
				continue
			}
			// i/3 — полоса блоков, j/3 — номер блока в этой полосе.
			// По три блока в полосе: индекс равен 3*(i/3) + j/3.
			// При i,j в 0..8 индекс блока лежит в 0..8, делитель 3 ненулевой.
			boxNum := i / 3 * 3 + j / 3
			// Проверяем ДО вставки, иначе текущая цифра совпала бы сама с собой.
			_, rowOk := rowHms[i][sym]
			_, colOk := colHms[j][sym]
			_, boxOk := boxHms[boxNum][sym]
			if rowOk || colOk || boxOk {
				return false
			}
			rowHms[i][sym], colHms[j][sym], boxHms[boxNum][sym] = struct{}{}, struct{}{}, struct{}{}
		}
	}
	// Все заполненные ячейки проверены; это не утверждение о разрешимости.
	return true
}