package main

import "math"

/*
Дан массив nums из n целых чисел.
Шаблон 132 — это подпоследовательность из трёх элементов nums[i], nums[j]
и nums[k], для которых i < j < k и nums[i] < nums[k] < nums[j].

Верните true, если в nums есть шаблон 132, иначе верните false.

Пример 1:
Вход: nums = [1,2,3,4]
Выход: false
Пояснение: В последовательности нет шаблона 132.

Пример 2:
Вход: nums = [3,1,4,2]
Выход: true
Пояснение: В последовательности есть шаблон 132: [1, 4, 2].

Пример 3:
Вход: nums = [-1,3,2,0]
Выход: true
Пояснение: В последовательности есть три шаблона 132:
[-1, 3, 2], [-1, 3, 0] и [-1, 2, 0].

Ограничения:
n == nums.length
1 <= n <= 2 * 10^5
-10^9 <= nums[i] <= 10^9
*/

// find132pattern проверяет, есть ли в nums подпоследовательность 132.
// Идём справа налево и используем обработанный суффикс nums как стек.
// Время: O(n), где n = len(nums): каждый элемент кладём и снимаем
// не более одного раза. Дополнительная память: O(1).
// Функция перезаписывает элементы nums, используя его для хранения стека.
func find132pattern(nums []int) bool {
	n := len(nums)
	// Стек пуст; заполняем его от правого края массива влево.
	stkTop := n
	// k — наибольшее найденное значение «2», а не индекс.
	// До первой пары k меньше любого допустимого значения nums[i].
	k := math.MinInt32

	for i := n - 1; i >= 0; i-- {
		// Если nums[i] < k, справа уже есть пара «3», «2», а текущий
		// элемент подходит на роль «1».
		// В [3,1,4,2] число 4 снимает 2 со стека, и затем 1 < 2.
		if nums[i] < k {
			return true
		}

		// С вершины вглубь стека значения не убывают.
		// Когда nums[i] больше вершины, это «3» для снятого значения «2».
		// Оставшиеся значения и новый элемент не меньше снятого,
		// поэтому k не уменьшается при последующих снятиях.
		for stkTop < n && nums[i] > nums[stkTop] {
			k = nums[stkTop]
			stkTop++
		}

		// До итерации в стеке не больше n - 1 - i элементов, то есть
		// stkTop >= i + 1. Снятия лишь увеличивают stkTop, поэтому
		// запись после -- не затронет ещё не прочитанные индексы левее i.
		stkTop--
		nums[stkTop] = nums[i]
	}

	return false
}