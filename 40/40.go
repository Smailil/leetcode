package main

import "sort"

/*
Дан набор чисел-кандидатов candidates и целевое число target.
Найдите все уникальные комбинации среди кандидатов,
в которых сумма чисел кандидатов равна целевому значению.
Каждый элемент candidates можно использовать в комбинации только один раз.
Примечание: Набор решений не должен содержать повторяющихся комбинаций.

Пример 1:
Вход: candidates = [10,1,2,7,6,1,5], target = 8
Выход:
[
[1,1,6],
[1,2,5],
[1,7],
[2,6]
]

Пример 2:
Вход: candidates = [2,5,2,1,2], target = 5
Выход:
[
[1,2,2],
[5]
]

Ограничения:
1 <= candidates.length <= 100
1 <= candidates[i] <= 50
1 <= target <= 30
*/

// combinationSum2 перебирает включение/исключение отсортированных элементов.
// При исключении пропускает блок дублей, оставляя уникальные решения.
// Пусть n = len(candidates), L — суммарное число элементов ответа.
// Верхняя оценка времени O(n*log n + n*2^n + L), включая копирование.
// Рабочая память O(n): рекурсия и путь; память результата O(L).
// Сортировка изменяет candidates; каждый ответ получает отдельный срез.
func combinationSum2(candidates []int, target int) [][]int {
    res := make([][]int, 0)
	// Равные значения станут соседними для отсечения повторных ветвей.
	sort.Ints(candidates)
	var dfs func(int, []int, int)
	// dfs продолжает cur с суммой total на суффиксе candidates[i:].
	// Время поддерева O(n*2^(n-i)+Lsub), Lsub — элементы новых ответов.
	// Рабочая память O(n); новые результаты занимают O(Lsub).
	// Добавляет копии путей в общий res, сам candidates здесь не меняется.
	dfs = func(i int, cur []int, total int) {
		// Путь готов; копия защищает ответ от следующих append и откатов.
		if total == target {
			copyCur := make([]int, len(cur))
			copy(copyCur, cur)
			res = append(res, copyCur)
			return 
		}
		// Положительные числа не исправят превышение суммы.
		// Проверка конца предшествует обращению candidates[i].
		if total > target || i == len(candidates) {
			return
		}
		// Включаем позицию один раз и продолжаем с i+1.
		// Перед шагом total<=30, число<=50: новая сумма не больше 80.
		cur = append(cur, candidates[i])
		dfs(i + 1, cur, total+candidates[i])
		// Откат длины исключает выбранный элемент из следующей ветви.
		cur = cur[:len(cur)-1]
		// Исключив значение, пропускаем все его равные копии на этом уровне.
		// Включение поздней копии после пропуска первой повторило бы комбинацию.
		for i + 1 < len(candidates) && candidates[i] == candidates[i+1] {
			i++
		}
		dfs(i+1, cur, total)
	}
	dfs(0, make([]int, 0), 0)
	return res
}
