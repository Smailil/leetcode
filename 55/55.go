package main

/*
Дан целочисленный массив nums.
Изначально вы находитесь на первом индексе массива, и каждый элемент
представляет максимальную длину прыжка из этой позиции.
Верните true, если можно достичь последнего индекса, иначе верните false.

Пример 1:
Вход: nums = [2,3,1,1,4]
Выход: true
Пояснение: прыгните на 1 шаг с индекса 0 на 1,
затем на 3 шага до последнего индекса.

Пример 2:
Вход: nums = [3,2,1,0,4]
Выход: false
Пояснение: как ни выбирать прыжки, перейти дальше индекса 3 нельзя.
Его максимальная длина прыжка равна 0, поэтому достичь последнего индекса
невозможно.

Ограничения:
1 <= nums.length <= 10^4
0 <= nums[i] <= 10^5
*/

// canJump ищет достижимый до конца индекс справа налево.
// n = len(nums); время O(n), рабочая память O(1), ответ — bool.
// Вход не изменяется; контракт гарантирует непустой массив.
func canJump(nums []int) bool {
    // goal — самый левый уже обработанный индекс, из которого доступен
    // последний элемент. Сам последний элемент является базовым случаем.
    goal := len(nums) - 1

    for i := len(nums) - 2; i >= 0; i-- {
        // Достаточно достичь goal, а не прыгать на всю nums[i]: разрешён
        // любой прыжок короче максимума. Из goal уже есть путь к концу.
        // По границам задачи i+nums[i] <= 109998, переполнения int нет.
        if i + nums[i] >= goal {
            goal = i
        }
    }
    // Дойти из начала можно ровно тогда, когда оно вошло в цепочку goal.
    return goal == 0
}
