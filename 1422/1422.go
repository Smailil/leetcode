package main

/*
Дана строка s, состоящая из нулей и единиц. Верните максимальный результат,
который можно получить, разделив строку на две непустые подстроки: левую и
правую.

Результат разбиения равен количеству нулей в левой подстроке плюс количеству
единиц в правой подстроке.

Пример 1:
Вход: s = "011101"
Выход: 5
Пояснение:
Все возможные способы разделить s на две непустые подстроки:
левая = "0", правая = "11101", результат = 1 + 4 = 5
левая = "01", правая = "1101", результат = 1 + 3 = 4
левая = "011", правая = "101", результат = 1 + 2 = 3
левая = "0111", правая = "01", результат = 1 + 1 = 2
левая = "01110", правая = "1", результат = 2 + 1 = 3

Пример 2:
Вход: s = "00111"
Выход: 5
Пояснение: при левой подстроке "00" и правой подстроке "111" максимальный
результат равен:
2 + 3 = 5.

Пример 3:
Вход: s = "1111"
Выход: 3

Ограничения:
2 <= s.length <= 500
Строка s состоит только из символов '0' и '1'.
*/

// maxScore находит лучший результат разбиения строки на две непустые части.
// Для каждой границы результат равен общему числу единиц плюс разность между
// числом нулей и единиц в левой части.
//
// Время: O(n), где n = len(s), поскольку строка просматривается один раз.
// Дополнительная память: O(1), используются только несколько счётчиков.
func maxScore(s string) int {
    // zeros и ones описывают уже включённый левый префикс, а res хранит
    // максимальную разность zeros - ones среди допустимых границ.
    zeros, ones := 0, 0
    // Значение -2^31 меньше любой возможной разности при длине не более 500,
    // поэтому первая допустимая граница обязательно обновит res.
    res := -1 << 31

    // Первый символ заранее относится к левой части, поэтому она не бывает
    // пустой при проверке первой границы разбиения.
    if s[0] == '0' {
        zeros++
    } else {
        ones++
    }

    for i := 1; i < len(s); i++ {
        // Сначала оцениваем границу перед s[i]: слева уже есть хотя бы один
        // символ, а справа остаётся непустой суффикс, начинающийся с s[i].
        if zeros-ones > res {
            res = zeros - ones
        }
        // После проверки переносим текущий символ в левый префикс. К концу
        // цикла ones станет общим числом единиц во всей строке.
        if s[i] == '0' {
            zeros++
        } else {
            ones++
        }
    }

    // Прибавляем общее число единиц к лучшей разности левого префикса:
    // totalOnes + zerosLeft - onesLeft = zerosLeft + onesRight.
    return res + ones
}