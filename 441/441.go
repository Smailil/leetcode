package main

import "math"

/*
У вас есть n монет, и вы хотите построить из них лестницу.
Лестница состоит из k рядов, причём i-й ряд содержит ровно i монет.
Последний ряд лестницы может быть неполным.

Дано целое число n.
Верните количество полностью заполненных рядов построенной лестницы.

Пример 1:
https://assets.leetcode.com/uploads/2021/04/09/arrangecoins1-grid.jpg
Вход: n = 5
Выход: 2
Пояснение: 3-й ряд неполный, поэтому возвращаем 2.

Пример 2:
https://assets.leetcode.com/uploads/2021/04/09/arrangecoins2-grid.jpg
Вход: n = 8
Выход: 3
Пояснение: 4-й ряд неполный, поэтому возвращаем 3.

Ограничения:
1 <= n <= 2^31 - 1
*/

// arrangeCoins возвращает число полных рядов, на которые хватает n монет.
// Для k рядов нужно 1 + ... + k = k*(k+1)/2 монет.
// Из k*(k+1)/2 <= n следует (k+0.5)^2 <= 2*n+0.25.
// Значит, ответ равен floor(sqrt(2*n+0.25) - 0.5).
// Время: O(1). Дополнительная память: O(1).
// Входной n не изменяется.
func arrangeCoins(n int) int {
    // Сначала переводим n в float64: вычисление 2*n в int могло бы
    // переполнить 32-битный int. После преобразования умножение вещественное.
    // При n <= 2^31 - 1 аргумент 2*n+0.25 точно представим в float64.

    // math.Sqrt берёт неотрицательный корень: число рядов k неотрицательно.
    // Вычитание 0.5 даёт верхнюю границу k из неравенства над функцией.
    // Если монет ровно на k рядов, корень равен k+0.5 и представим точно.
    // Для остальных n расстояние до целой границы намного больше ошибки
    // float64 при данном ограничении, поэтому округление не меняет ответ.

    // При n >= 1 выражение перед int не меньше 1. Преобразование к int
    // отбрасывает дробную часть; для неотрицательного числа это floor.
    // Например, n=8: sqrt(16.25) - 0.5 примерно равно 3.531, получаем 3 ряда.
    return int(math.Sqrt(2*float64(n)+0.25) - 0.5)
}