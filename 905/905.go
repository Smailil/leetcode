package main

/*
Дан целочисленный массив nums.
Переместите все чётные числа в начало массива,
а все нечётные расположите после них.

Верните любой массив, удовлетворяющий этому условию.

Пример 1:
Вход: nums = [3,1,2,4]
Выход: [2,4,3,1]
Пояснение: Результаты [4,2,3,1], [2,4,1,3] и [4,2,1,3]
также принимаются.

Пример 2:
Вход: nums = [0]
Выход: [0]

Ограничения:
1 <= nums.length <= 5000
0 <= nums[i] <= 5000
*/

// sortArrayByParity группирует nums: чётные числа идут перед нечётными.
// Один проход: каждый найденный чётный элемент переносится к границе l.
// Изменяет nums на месте и возвращает срез того же массива, без новой копии.
// Время O(n), где n = len(nums): каждая позиция просматривается один раз.
// Дополнительная рабочая память O(1).
// Результат использует исходный буфер O(n), не выделяя ещё один такой буфер.
func sortArrayByParity(nums []int) []int {
    // l — число уже найденных чётных элементов и место для следующего.
    // Изначально чётная часть пуста, поэтому её правая граница равна 0.
    l := 0
    // Перед итерацией [0, l) содержит чётные, [l, r) — нечётные числа.
    // Суффикс [r, n) ещё не обработан; range даёт 0 <= r < n, а 0 <= l <= r.
    for r := range nums {
        // Нечётный элемент остаётся в обработанной нечётной части.
        // Чётный нужно поставить на границу l, расширив чётную часть.
        if nums[r] % 2 == 0 {
            // При l < r на позиции l стоит нечётное число: переносим его в r.
            // Уже проверенный чётный nums[r] занимает освобождённое место l.
            // Будущие позиции не затронуты: обмен остаётся в [0, r].
            // Поэтому ещё не обработанные элементы не пропускаются.
            // При l == r обмен с собой корректен: элемент уже на нужном месте.
            // Пример: [3,1,2,4] при l=0, r=2 превращается в [2,1,3,4].
            nums[l], nums[r] = nums[r], nums[l]
            // После обмена в чётной части на один элемент больше.
            // В примере l станет 1, и следующий чётный 4 попадёт на позицию 1.
            l++
        }
    }
    // Теперь [0, l) — все чётные, [l, n) — все нечётные; значения сохранены.
    // Порядок внутри групп не требуется; обмены могут менять порядок нечётных.
    return nums
}