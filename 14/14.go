package main

/*
Напишите функцию для нахождения наидлиннейшего общего префикса
среди массива строк.

Если общего префикса нет, верните пустую строку "".

Пример 1:
Вход: strs = ["flower","flow","flight"]
Выход: "fl"

Пример 2:
Вход: strs = ["dog","racecar","car"]
Выход: ""
Пояснение: Среди входных строк нет общего префикса.

Ограничения:
1 <= strs.length <= 200
0 <= strs[i].length <= 200
strs[i] состоит только из строчных букв английского алфавита, если непуста.
*/

// longestCommonPrefix сравнивает строки посимвольно, столбец за столбцом.
// Первый конец строки или несовпадение завершает общий префикс.
// Время: O(n * m + 1), где n = len(strs), m = len(strs[0]).
// Рабочая память: O(1). Результат не копирует байты исходной строки.
// Новый заголовок занимает O(1), удерживаемый общий буфер — O(B).
// B — размер исходного буфера, не обязательно длина короткого префикса.
func longestCommonPrefix(strs []string) string {
    // strs непуст по условию, поэтому strs[0] существует.
    // До позиции i все строки имеют общий префикс strs[0][:i].
    // Если первая строка пуста, цикл не выполняется.
    for i := range len(strs[0]) {
        for _, s := range strs {
            // На прошлых позициях отказа не было: i не больше len(s).
            // При i == len(s) короткое замыкание не даёт прочитать s[i].
            // Иначе сравнение проверяет следующий символ общего префикса.
            if i == len(s) || s[i] != strs[0][i] {
                // Первые i символов уже совпали во всех строках.
                // Продлить префикс нельзя из-за конца или несовпадения.
                return s[:i]
            }
        }
    }
    // Все символы первой строки проверены: она целиком входит в префикс.
    return strs[0]
}
