package main

/*
Даны массив пар переменных equations и массив вещественных чисел values,
где equations[i] = [A_i, B_i],
а values[i] задает уравнение A_i / B_i = values[i].
Каждая A_i или B_i - строка, представляющая одну переменную.

Также дан массив запросов queries,
где queries[j] = [C_j, D_j] представляет j-й запрос,
для которого нужно найти ответ на C_j / D_j = ?.

Верните ответы для всех запросов.
Если отдельный ответ определить невозможно, верните -1.0.

Примечание: входные данные всегда корректны.
Можно считать, что вычисление запросов не приведет к делению на ноль
и что противоречий нет.

Примечание: переменные, которые не встречаются в списке уравнений,
не определены,
поэтому ответ для них определить невозможно.

Пример 1:
Вход:
equations = [["a","b"],["b","c"]], values = [2.0,3.0],
queries = [["a","c"],["b","a"],["a","e"],["a","a"],["x","x"]]
Выход: [6.00000,0.50000,-1.00000,1.00000,-1.00000]
Пояснение:
Дано: a / b = 2.0, b / c = 3.0
Запросы: a / c = ?, b / a = ?, a / e = ?, a / a = ?, x / x = ?
Вернуть: [6.0, 0.5, -1.0, 1.0, -1.0]
Примечание: x не определена => -1.0

Пример 2:
Вход:
equations = [["a","b"],["b","c"],["bc","cd"]], values = [1.5,2.5,5.0],
queries = [["a","c"],["c","b"],["bc","cd"],["cd","bc"]]
Выход: [3.75000,0.40000,5.00000,0.20000]

Пример 3:
Вход:
equations = [["a","b"]], values = [0.5],
queries = [["a","b"],["b","a"],["a","c"],["x","y"]]
Выход: [0.50000,2.00000,-1.00000,-1.00000]

Ограничения:
1 <= equations.length <= 20
equations[i].length == 2
1 <= A_i.length, B_i.length <= 5
values.length == equations.length
0.0 < values[i] <= 20.0
1 <= queries.length <= 20
queries[i].length == 2
1 <= C_j.length, D_j.length <= 5
A_i, B_i, C_j, D_j состоят из строчных английских букв и цифр.
*/

// calcEquation строит граф отношений и отвечает на каждый запрос отдельным BFS.
// M = len(equations), Q = len(queries), V — число разных переменных графа.
// При ключах до 5 байт среднее время O(M + Q * (V + M)).
// Рабочая память O(V + M): граф и один BFS; результат занимает O(Q).
// Входы не меняет; граф, очередь и visited остаются локальными.
func calcEquation(equations [][]string, values []float64, queries [][]string) []float64 {
    // В adj[u] храним пары [v, u/v]. Каждое уравнение даёт два ребра.
    // Строковые ключи имеют до 5 ASCII-байт: хеш и сравнение стоят O(1).
    // Оценка map-поиска средняя, а добавления в срезы — амортизированная.
    adj := make(map[string][][2]any)

    // У каждой пары два имени, а values выровнен с equations по контракту.
    for i, eq := range equations {
        a, b := eq[0], eq[1]
        // Если a / b = values[i], то добавляем направленное ребро от a к b с
        // весом values[i].
        adj[a] = append(adj[a], [2]any{b, values[i]})
        // Обратный вес b/a = 1/(a/b); values[i] > 0, делитель ненулевой.
        // Типы элементов [2]any: string и float64; проверки типов безопасны.
        adj[b] = append(adj[b], [2]any{a, 1.0 / values[i]})
    }

    // bfs ищет отношение src/target через любой путь в графе.
    // Среднее время O(V + M), рабочая память O(V), скалярный ответ O(1).
    // Читает общий adj без изменений; очередь и visited создаёт для запроса.
    // Общий граф O(V + M) уже учтён выше, его не копируем для каждого BFS.
    bfs := func(src, target string) float64 {
        // Даже x/x неизвестно, если x не было в equations: существование
        // проверяем раньше равенства имён, которое дало бы единичный путь.
        if _, ok := adj[src]; !ok {
            return -1.0
        }
        if _, ok := adj[target]; !ok {
            return -1.0
        }

        // Элемент очереди — [узел u, отношение src/u]. Для src это 1.
        // Пока путь не найден, произведение рёбер поддерживает этот инвариант
        // в точной арифметике; float64 допускает округление и переполнение.
        queue := [][2]any{{src, 1.0}}
        
        // Отмечаем при добавлении в очередь: каждый узел попадёт туда один раз.
        // Это разрывает циклы, включая взаимные и повторные рёбра.
        visited := make(map[string]bool)
        visited[src] = true

        // Без противоречий точные отношения путей совпадают; BFS не ищет
        // максимальное произведение, а возвращает первое достижение цели.
        for len(queue) > 0 {
            // Извлекаем первый элемент из очереди (принцип FIFO).
            node := queue[0][0].(string)
            weight := queue[0][1].(float64)
            // Сдвиг среза стоит O(1), но не освобождает начало общего буфера.
            // Удержанная ёмкость очереди — O(V), не только её текущая длина.
            queue = queue[1:] // Удаляем обработанный элемент из очереди.

            // Если мы достигли целевой переменной, возвращаем накопленный
            // множитель.
            if node == target {
                return weight
            }

            // Перебираем всех соседей текущей переменной.
            for _, nei := range adj[node] {
                neiNode := nei[0].(string)
                neiWeight := nei[1].(float64)
                
                // Если сосед еще не был посещен, добавляем его в очередь.
                if !visited[neiNode] {
                    visited[neiNode] = true
                    // (src/u) * (u/v) = src/v: например, 2 * 3 даёт a/c = 6.
                    // Пометка до append исключает повторное добавление v.
                    queue = append(queue, [2]any{neiNode, weight * neiWeight})
                }
            }
        }

        // Оба имени известны, но находятся в разных компонентах связности.
        return -1.0
    }

    // Массив для хранения ответов на все запросы.
    res := make([]float64, len(queries))
    
    // Пары запросов имеют длину 2. Между запросами граф общий, но visited
    // создаётся заново: прошлый обход не должен блокировать следующий.
    for i, q := range queries {
        res[i] = bfs(q[0], q[1])
    }

    return res
}