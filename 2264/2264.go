package main

import "strings"

/*
Дана строка num, представляющая большое целое число. Целое число считается
хорошим, если оно удовлетворяет следующим условиям:

Оно является подстрокой num длины 3.
Оно состоит только из одной уникальной цифры.

Верните максимальное хорошее целое число в виде строки или пустую строку "",
если такого числа не существует.

Примечание:
Подстрока — это непрерывная последовательность символов внутри строки.
В num или хорошем целом числе могут присутствовать ведущие нули.

Пример 1:
Вход: num = "6777133339"
Выход: "777"
Пояснение: существуют два различных хороших целых числа: "777" и "333".
Число "777" больше, поэтому возвращаем "777".

Пример 2:
Вход: num = "2300019"
Выход: "000"
Пояснение: "000" — единственное хорошее целое число.

Пример 3:
Вход: num = "42352338"
Выход: ""
Пояснение: ни одна подстрока длины 3 не состоит из одной уникальной цифры.
Следовательно, хороших целых чисел нет.

Ограничения:
3 <= num.length <= 1000
num состоит только из цифр.
*/

// largestGoodInteger находит наибольшую цифру, образующую подстроку длины 3.
// Для этого функция проверяет каждое возможное окно и запоминает лучший ответ.
// Время: O(n), где n = len(num).
// Дополнительная рабочая память: O(1); длина результата равна 0 или 3.
func largestGoodInteger(num string) string {
    // Значение -1 не совпадает ни с одной цифрой и одновременно показывает,
    // что подходящее окно пока не найдено.
    res := -1

    // Последнее окно начинается в позиции len(num)-3, поэтому len(num)-2
    // итераций гарантируют допустимость обращений i+1 и i+2.
    for i := range len(num)-2 {
        // Равенство всех трёх символов означает, что окно содержит одну цифру.
        if num[i] == num[i+1] && num[i] == num[i+2] {
            digit := int(num[i] - '0')

            // Сравнивать достаточно одну цифру: для строк вида "ddd" их порядок
            // полностью определяется значением d.
            if digit > res {
                res = digit
            }
        }
    }

    // Неизменившийся маркер означает, что ни одного хорошего числа не было.
    if res == -1 {
        return ""
    }

    // Преобразуем лучшую цифру обратно в символ и повторяем её ровно три раза.
    return strings.Repeat(string(rune(res+'0')), 3)
}