package main

/*
Изначально множество целых чисел s содержит все числа от 1 до n.
К сожалению, из-за ошибки одно из чисел в s продублировалось. Поэтому одно
число теперь встречается дважды, а другое число отсутствует.

Вам дан массив целых чисел nums, описывающий состояние множества после ошибки.

Найдите число, которое встречается дважды, и пропущенное число. Верните их
в виде массива.

Пример 1:
Вход: nums = [1,2,2,4]
Выход: [2,3]

Пример 2:
Вход: nums = [1,1]
Выход: [1,2]

Ограничения:
2 <= nums.length <= 10^4
1 <= nums[i] <= 10^4
*/

// findErrorNums вычисляет повторяющееся и пропущенное числа через разности
// фактических и ожидаемых сумм чисел и их квадратов.
// Время: O(n), где n = len(nums), поскольку массив обходится один раз.
// Дополнительная память: O(1).
func findErrorNums(nums []int) []int {
    N := len(nums)

    // После обработки любой части массива x равен разности обычных сумм,
    // а y — разности сумм квадратов на этой части.
    // В конце x = duplicate - missing, а
    // y = duplicate^2 - missing^2.
    x := 0
    y := 0

    // Одновременно вычитаем ожидаемые числа от 1 до N из элементов nums.
    // При ограничении 10^4 промежуточные суммы квадратов помещаются
    // в 64-битный int, который используется средой LeetCode.
    for i := 1; i <= N; i++ {
        x += nums[i-1] - i
        y += nums[i-1]*nums[i-1] - i*i
    }

    // Так как y = x * (duplicate + missing), выражение ниже получается
    // из равенства y - x^2 = 2 * x * missing. Деление безопасно: повторённое
    // и пропущенное числа различны, поэтому x != 0.
    missing := (y - x*x) / (2 * x)

    // Из x = duplicate - missing восстанавливаем повторённое число.
    duplicate := missing + x

    // По условию сначала возвращаем повторённое, затем пропущенное число.
    return []int{duplicate, missing}
}