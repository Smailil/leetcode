package main

/*
Дан массив целых чисел asteroids, представляющих астероиды в ряд.
Индексы астероидов в массиве отражают их относительное положение в пространстве.

Абсолютное значение каждого астероида означает его размер,
а знак — направление движения (положительный — вправо, отрицательный — влево).
Все астероиды движутся с одинаковой скоростью.

Определите состояние астероидов после всех столкновений.
При встрече двух астероидов меньший взрывается.
Если оба одинакового размера — оба взрываются.
Два астероида, движущихся в одном направлении, никогда не встретятся.

Пример 1:
Вход: asteroids = [5,10,-5]
Выход: [5,10]
Пояснение: 10 и -5 сталкиваются, побеждает 10.
5 и 10 не встречаются.

Пример 2:
Вход: asteroids = [8,-8]
Выход: []
Пояснение: 8 и -8 сталкиваются и взрывают друг друга.

Пример 3:
Вход: asteroids = [10,2,-5]
Выход: [10]
Пояснение: 2 и -5 сталкиваются, побеждает -5.
10 и -5 сталкиваются, побеждает 10.

Пример 4:
Вход: asteroids = [3,5,-6,2,-1,4]​​​​​​​
Выход: [-6,2,4]
Пояснение: Астероид -6 уничтожает астероиды 3 и 5 и продолжает лететь влево.
С другой стороны, астероид 2 уничтожает астероид -1 и продолжает лететь вправо,
не достигая астероида 4.

Ограничения:
2 <= asteroids.length <= 10^4
-1000 <= asteroids[i] <= 1000
asteroids[i] != 0
*/

// asteroidCollision моделирует столкновения стеком уцелевших астероидов.
// n — число элементов asteroids. Время O(n) амортизированно:
// каждый астероид кладётся в стек и удаляется не более одного раза.
// Стек становится результатом, его общий буфер занимает O(n).
// Кроме этого буфера рабочая память O(1), отдельной копии результата нет.
// Результат может удерживать capacity после удалений, даже при малой длине.
// Входной массив не меняется; буфер stack с ним не разделяется.
func asteroidCollision(asteroids []int) []int {
    stack := []int{}
    // В stack уже нет встречных пар; a — следующий справа астероид.
    for _, a := range asteroids {
        // Встречаются только положительный слева и отрицательный справа.
        // len проверяется первым, поэтому обращение к вершине безопасно.
        for len(stack) > 0 && a < 0 && stack[len(stack)-1] > 0 {
            // При a < 0 сумма равна размеру вершины минус размер a.
            // Ограничения размеров исключают переполнение int.
            diff := a + stack[len(stack)-1]
            // a крупнее: удаляем вершину и проверяем следующую встречу.
            if diff < 0 {
                stack = stack[:len(stack)-1]
            } else if diff > 0 {
                // Вершина крупнее: 0 отмечает уничтоженный текущий астероид.
                a = 0
            } else {
                // Размеры равны: оба уничтожаются, продолжать встречу нечем.
                a = 0
                stack = stack[:len(stack)-1]
            }
        }
        // Ноль — только служебная метка: исходные значения ненулевые.
        // Сохранившийся a добавляется в стабильный стек.
        if a != 0 {
            stack = append(stack, a)
        }
    }
    return stack
}
