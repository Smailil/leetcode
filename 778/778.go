package main

/*
Дана целочисленная матрица grid размера n x n,
где grid[i][j] — высота в точке (i, j).

Начинается дождь, и со временем вода постепенно поднимается.
В момент времени t уровень воды равен t, 
что означает, что любая ячейка с высотой не более t находится под водой или
достижима.
Можно переплыть в соседнюю по одной из четырёх сторон ячейку
тогда и только тогда, когда высота каждой из двух ячеек не превышает t.
Вы можете проплыть бесконечные расстояния за нулевое время.
Конечно, во время плавания вы должны оставаться в пределах сетки.

Верните минимальное время достижения нижней правой ячейки (n - 1, n - 1),
если начать из верхней левой ячейки (0, 0).

Пример 1:
https://assets.leetcode.com/uploads/2021/06/29/swim1-grid.jpg
Вход: grid = [[0,2],[1,3]]
Выход: 3
Объяснение:
В момент времени 0 вы находитесь в координатной сетке (0, 0).
Нельзя перейти в другую ячейку, потому что все соседи по четырём сторонам
имеют высоту больше t = 0.
Вы не сможете достичь точки (1, 1) до момента 3.
Когда глубина воды равна 3, мы можем плыть в любом месте сетки.

Пример 2:
https://assets.leetcode.com/uploads/2021/06/29/swim2-grid-1.jpg
Вход: grid = [[0,1,2,3,4],[24,23,22,21,5],[12,13,14,15,16],[11,17,18,19,20],[10,
9,8,7,6]]
Выход: 16
Пояснение: Показан конечный маршрут.
Нам нужно дождаться момента 16, чтобы (0, 0) и (4, 4) соединились.

Ограничения:
n == grid.length
n == grid[i].length
1 <= n <= 50
0 <= grid[i][j] < n^2
Каждое значение grid[i][j] уникально.
*/

import (
	"container/heap"
)

// Структура для элемента кучи
type Node struct {
	t int // время/максимальная высота
	r int // строка
	c int // столбец
}

// Реализация интерфейса heap.Interface для MinHeap
type MinHeap []*Node

// Len читает размер за O(1) времени и памяти, не меняя очередь.
func (h MinHeap) Len() int           { return len(h) }
// Less сравнивает пороги min-heap за O(1) времени и памяти.
// Индексы и ненулевые узлы гарантирует вызывающий heap.
func (h MinHeap) Less(i, j int) bool { return h[i].t < h[j].t } // Мин-куча по
// времени
// Swap меняет два элемента общего среза; время и рабочая память O(1).
func (h MinHeap) Swap(i, j int)      { h[i], h[j] = h[j], h[i] }

// Push добавляет *Node: время O(1) амортизированно, O(q) при росте буфера.
// Рабочая память при росте O(q), q — размер кучи; очередь меняется.
func (h *MinHeap) Push(x any) {
	*h = append(*h, x.(*Node))
}

// Pop снимает последний узел после перестановки heap в непустой очереди.
// Время, рабочая память и возвращаемая ссылка O(1); очередь укорачивается.
// Старый слот не обнулён, backing-массив может удерживать снятые узлы.
func (h *MinHeap) Pop() any {
	old := *h
	n := len(old)
	x := old[n-1]
	*h = old[0 : n-1]
	return x
}

// swimInWater ищет путь с минимальным максимумом высоты, снимая из кучи
// клетку с наименьшим порогом; переход берёт max(порог, высота соседа).
// Время O(V*log(V+1)), V=N²; рабочая память O(V), результат int O(1).
// Каждая клетка добавляется один раз; grid не меняется, N>=1 по условию.
func swimInWater(grid [][]int) int {
	N := len(grid)
	
	// Массив посещенных клеток
	visited := make([][]bool, N)
	for i := range visited {
		visited[i] = make([]bool, N)
	}

	// Инициализация кучи
	h := &MinHeap{}
	heap.Init(h)
	
	// Добавляем стартовую точку
	heap.Push(h, &Node{grid[0][0], 0, 0})
	// visited означает добавление в кучу, а не завершённое извлечение.
	visited[0][0] = true

	// Направления: вправо, влево, вниз, вверх
	directions := [][2]int{{0, 1}, {0, -1}, {1, 0}, {-1, 0}}

	for h.Len() > 0 {
		node := heap.Pop(h).(*Node)
		t, r, c := node.t, node.r, node.c

		// Если достигли правого нижнего угла
		if r == N-1 && c == N-1 {
			return t
		}

		// Перебор соседей
		for _, d := range directions {
			nr, nc := r+d[0], c+d[1]

			// Проверка границ и посещенности
			if nr >= 0 && nr < N && nc >= 0 && nc < N && !visited[nr][nc] {
				// Отметка при добавлении корректна именно для этого minimax:
				// будущие предшественники имеют порог не меньше t, а высота
				// назначения одинакова для всех входов: улучшить max нельзя.
				visited[nr][nc] = true
				// Доступны должны быть и прежний путь, и новая клетка.
				heap.Push(h, &Node{max(t, grid[nr][nc]), nr, nc})
			}
		}
	}

	// После подъёма воды связная квадратная сетка вся достижима:
	// для корректного входа цель вернётся из цикла, включая N=1.
	return 0
}
