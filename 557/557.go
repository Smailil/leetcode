package main

/*
Дана строка s.
Разверните порядок символов в каждом слове предложения,
сохранив пробелы и исходный порядок слов.

Пример 1:
Вход: s = "Let's take LeetCode contest"
Выход: "s'teL ekat edoCteeL tsetnoc"

Пример 2:
Вход: s = "Mr Ding"
Выход: "rM gniD"

Ограничения:
1 <= s.length <= 5 * 10^4
s содержит печатные символы ASCII.
В начале и конце s нет пробелов.
В s есть хотя бы одно слово.
Все слова в s разделены одним пробелом.
*/

// reverseWords разворачивает символы каждого слова, сохраняя пробелы
// и порядок слов. Границы слов ищутся слева направо, а символы внутри
// каждого найденного слова меняются местами двумя встречными указателями.
// Время: O(n), n = len(s): проход по строке и все обмены суммарно линейны.
// Рабочая память: O(n) для chars; память результата: O(n).
// Суммарная дополнительная память: O(n); исходная строка s не изменяется.
func reverseWords(s string) string {
	// Строки Go неизменяемы, поэтому для обменов нужен байтовый буфер.
	// По условию символы ASCII однобайтовые: разворот байтов не повредит
	// символы. Для произвольного UTF-8 такой подход уже не подходит.
	chars := []byte(s)
	// l — начало текущего слова. Все предыдущие слова уже развёрнуты,
	// а пробелы остаются на своих исходных позициях.
	l := 0
	// r ищет правую границу слова: пробел или позицию за концом строки.
	// Дополнительный шаг r == len(chars) обрабатывает последнее слово,
	// после которого по условию нет пробела.
	for r := 0; r <= len(chars); r++ {
		// При r == len(chars) правая часть || не вычисляется:
		// обращения chars[len(chars)] не будет. В остальных случаях
		// 0 <= r < len(chars), поэтому индекс chars[r] допустим.
		if r == len(chars) || chars[r] == ' ' {
			// Слово занимает [l, r), его последний байт имеет индекс r-1.
			// Например, для "ab cd" первая граница r = 2 даёт [0, 2):
			// меняем "ab" на "ba", не затрагивая пробел с индексом 2.
			tempL, tempR := l, r-1
			// Переставляем крайние ещё не обработанные байты слова.
			// После каждого обмена оба края уже стоят на нужных местах;
			// при встрече указателей центральный байт менять не нужно.
			for tempL < tempR {
				chars[tempL], chars[tempR] = chars[tempR], chars[tempL]
				tempL++
				tempR--
			}
			// Пропускаем пробел: следующее слово начинается с r+1.
			// После последнего слова l больше не используется.
			l = r + 1
		}
	}
	// Из изменённого буфера формируем строку-результат длины n.
	return string(chars)
}