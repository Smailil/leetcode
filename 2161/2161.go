package main

/*
Даны массив целых чисел nums с индексацией с 0 и целое число pivot.
Переставьте элементы nums так, чтобы выполнялись следующие условия:

Каждый элемент меньше pivot расположен перед каждым элементом больше pivot.
Элементы, равные pivot, находятся между элементами меньше и больше pivot.
Относительный порядок сохраняется внутри группы элементов меньше pivot
и отдельно внутри группы элементов больше pivot.
Формально, пусть p_i и p_j — новые позиции элементов
с исходными индексами i и j соответственно.
Если i < j и оба элемента меньше pivot (либо оба больше pivot), то p_i < p_j.
Верните nums после перестановки элементов.

Пример 1:
Вход: nums = [9,12,5,10,14,3,10], pivot = 10
Выход: [9,5,3,10,10,12,14]
Пояснение:
Элементы 9, 5 и 3 меньше pivot, поэтому находятся в левой части массива.
Элементы 12 и 14 больше pivot, поэтому находятся в правой части массива.
Относительный порядок внутри групп также сохранён:
[9, 5, 3] и [12, 14] соответственно.

Пример 2:
Вход: nums = [-3,4,3,2], pivot = 2
Выход: [-3,2,4,3]
Пояснение:
Элемент -3 меньше pivot, поэтому находится в левой части массива.
Элементы 4 и 3 больше pivot, поэтому находятся в правой части массива.
Относительный порядок внутри групп также сохранён:
[-3] и [4, 3] соответственно.

Ограничения:
1 <= nums.length <= 10^5
-10^6 <= nums[i] <= 10^6
pivot равен одному из элементов nums.
*/

// pivotArray стабильно разделяет nums относительно pivot в новом срезе.
// Три прохода добавляют группы: сначала x < pivot, затем x == pivot,
// после них x > pivot, сохраняя исходный порядок внутри каждой группы.
// Исходный nums не изменяется.
// Время: O(n), где n = len(nums), поскольку три прохода последовательные.
// Дополнительная рабочая память без результата: O(1).
// Память результата: O(n); всего дополнительной памяти: O(n).
func pivotArray(nums []int, pivot int) []int {
	// Срез создаётся с длиной 0, но ёмкостью n: заполняем его через append.
	// Каждый элемент удовлетворяет ровно одному из условий <, == или >.
	// Всего добавлений будет n, поэтому буферу не потребуется расширение.
	answer := make([]int, 0, len(nums))
	// Меньшие pivot элементы добавляются в порядке обхода nums слева направо.
	// Уже выбранные элементы не переставляются: это и даёт стабильность.
	// В примере 1 после этого прохода answer = [9,5,3].
	for _, x := range nums {
		if x < pivot {
			answer = append(answer, x)
		}
	}
	// Равные pivot дописываем после всех меньших.
	// Заполненный префикс не трогаем: только добавляем элементы справа.
	// Продолжение примера: answer = [9,5,3,10,10].
	for _, x := range nums {
		if x == pivot {
			answer = append(answer, x)
		}
	}
	// Последними добавляем большие pivot, снова обходя nums слева направо.
	// Поэтому 12 остаётся перед 14, как в nums: группа не сортируется.
	// Итог примера: [9,5,3,10,10,12,14].
	for _, x := range nums {
		if x > pivot {
			answer = append(answer, x)
		}
	}
	return answer
}

