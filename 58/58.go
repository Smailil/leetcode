package main

/*
Дана строка s, состоящая из слов и пробелов. Верните длину последнего слова
в строке.

Слово — это максимальная подстрока, состоящая только из непробельных
символов.

Пример 1:
Ввод: s = "Hello World"
Вывод: 5
Пояснение: последнее слово — "World", его длина равна 5.

Пример 2:
Ввод: s = "   fly me   to   the moon  "
Вывод: 4
Пояснение: последнее слово — "moon", его длина равна 4.

Пример 3:
Ввод: s = "luffy is still joyboy"
Вывод: 6
Пояснение: последнее слово — "joyboy", его длина равна 6.

Ограничения:
1 <= s.length <= 10^4
Строка s состоит только из английских букв и пробелов ' '.
В строке s есть хотя бы одно слово.
*/

// lengthOfLastWord идёт с конца строки, поэтому не обрабатывает слова,
// расположенные перед последним. Время работы — O(len(s)), память — O(1).
func lengthOfLastWord(s string) int {
    // i начинает с последнего символа, а length хранит найденную длину слова.
    i, length := len(s)-1, 0

    // Конечные пробелы не принадлежат слову, поэтому пропускаем их и находим
    // последний непробельный символ.
    for i >= 0 && s[i] == ' ' {
        i--
    }

    // Двигаемся влево по последнему слову до пробела или начала строки.
    // Каждый посещённый символ увеличивает его длину на единицу.
    for i >= 0 && s[i] != ' ' {
        i--
        length++
    }

    // После второго прохода length равна длине всего последнего слова.
    return length
}
