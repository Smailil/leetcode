package main

/*
Дана строка s, верните количество палиндромных подстрок в ней.
Строка является палиндромом, если она читается
как в прямом, так и в обратном направлении.
Подстрока — это непрерывная последовательность символов внутри строки.

Пример 1:
Вход: s = "abc"
Выход: 3
Пояснение: Три палиндромные строки: «a», «b», «c».

Пример 2:
Вход: s = "aaa"
Выход: 6
Пояснение: Шесть палиндромных строк: «a», «a», «a», «aa», «aa», «aaa».

Ограничения:
1 <= s.length <= 1000
s состоит из строчных английских букв.
*/

// countSubstrings считает палиндромы расширением вокруг всех центров.
// n — число байтов s; по условию это строчные ASCII-буквы.
// В худшем случае время O(n^2), рабочая память O(1).
// Результат int занимает O(1); строка не изменяется и не копируется.
func countSubstrings(s string) int {
    res := 0
    // У каждого палиндрома единственный центр: буква либо зазор.
    // Одинаковый текст в разных позициях считается отдельно.
    for i := 0; i < len(s); i++ {
        // Совпавшие границы начинают палиндром нечётной длины.
        res += countPals(s, i, i)
        // Соседние границы начинают палиндром чётной длины.
        res += countPals(s, i, i+1)
    }
    return res
}

// countPals считает палиндромы с заданными начальными границами.
// Вызовы выше дают 0 <= l < n и l <= r <= n, n — число байтов s.
// Для k успешных расширений время O(k+1), рабочая память O(1).
// Результат int занимает O(1); меняются только локальные l, r и res.
func countPals(s string, l, r int) int {
    res := 0
    // Проверки границ идут до индексации; при несовпадении
    // дальнейшее расширение этого центра уже не даст палиндром.
    for l >= 0 && r < len(s) && s[l] == s[r] {
        // Каждая успешная пара добавляет один новый палиндром.
        res++
        l--
        r++
    }
    return res
}
