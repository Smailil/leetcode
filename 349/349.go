package main

/*
Даны два массива целых чисел nums1 и nums2. Верните массив их пересечения.
Каждый элемент результата должен быть уникальным. Результат можно вернуть
в любом порядке.

Пример 1:
Вход: nums1 = [1,2,2,1], nums2 = [2,2]
Выход: [2]

Пример 2:
Вход: nums1 = [4,9,5], nums2 = [9,4,9,8,4]
Выход: [9,4]
Пояснение: ответ [4,9] также считается правильным.

Ограничения:
1 <= nums1.length, nums2.length <= 1000
0 <= nums1[i], nums2[i] <= 1000
*/

// intersection строит множество значений nums1 и проверяет по нему каждый
// элемент nums2, удаляя уже добавленные в результат значения.
// Время: в среднем O(n + m), где n = len(nums1), m = len(nums2), поскольку
// операции с map в среднем выполняются за O(1).
// Дополнительная рабочая память без результата: O(k), где k — число различных
// значений в nums1 и k <= n.
// По ограничениям k <= 1001, поэтому в рамках задачи эта память — O(1).
// Память результата: O(r), где r — размер пересечения и r <= min(n, m).
func intersection(nums1 []int, nums2 []int) []int {
    // Сохраняем только факт присутствия значения в nums1. Повторения в nums1
    // не меняют множество и не могут создать дубликаты в ответе.
    seen := make(map[int]bool)
    for _, num := range nums1 {
        seen[num] = true
    }

    // Порядок результата определяется первым появлением подходящих значений
    // в nums2, что допустимо по условию задачи.
    res := []int{}
    for _, num := range nums2 {
        if seen[num] {
            res = append(res, num)

            // После добавления удаляем значение из seen. Поэтому последующие
            // повторы num в nums2 уже не попадут в результат.
            delete(seen, num)
        }
    }
    return res
}