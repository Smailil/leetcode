package main

/*
Вам даны n шариков, пронумерованных от 0 до n - 1.
На каждом шарике нарисован номер, представленный массивом nums.
Вас просят лопнуть все шарики.
Если вы лопнете i-й шарик,
вы получите nums[i - 1] * nums[i] * nums[i + 1] монет.
Если i - 1 или i + 1 выходит за пределы массива, относитесь к нему так,
как будто на нем нарисован воздушный шар с цифрой 1.
Верните как можно больше монет, которые сможете собрать,
разумно лопая воздушные шары.

Пример 1:
Вход: nums = [3,1,5,8]
Выход: 167
nums = [3,1,5,8] --> [3,5,8] --> [3,8] --> [8] --> []
coins = 3*1*5 + 3*5*8 + 1*3*8 + 1*8*1 = 167

Пример 2:
Вход: nums = [1,5]
Выход: 10

Ограничения:
n == nums.length
1 <= n <= 300
0 <= nums[i] <= 100
*/

// maxCoins выбирает последний лопнувший шарик каждого подинтервала.
// Тогда внешние соседи ещё целы, а левый и правый интервалы независимы.
// При положительных nums время O(m³), m=len(nums), за счёт мемоизации.
// Допустимые нули не узнаются в кэше: худшее время O(3^m), код не исправлен.
// Рабочая память O(m²) для dp и рекурсии; результат int O(1).
// nums копируется в arr и не изменяется.
func maxCoins(nums []int) int {
    n := len(nums)
    arr := make([]int, n+2)
    arr[0] = 1
    arr[n+1] = 1
    copy(arr[1:], nums)

	// Теперь n — длина arr с двумя служебными единицами, то есть m+2.
	n = len(arr)
    dp := make([][]int, n)
    for i := range dp {
        dp[i] = make([]int, n)
    }

    var dfs func(l, r int) int
    // dfs возвращает максимум для включённого [l,r].
    // Худшее время O(3^k), k=r-l+1; рабочая память стека O(k).
    // Общая dp занимает O(m²); результат вызова O(1).
    dfs = func(l, r int) int {
        // Пустой интервал приносит 0 и завершает вызов до обращения к dp.
        if l > r {
            return 0
        }
        // Исходный дефект: оптимум 0 допустим, но этот тест не узнаёт его.
        // На одних нулях T(0)=1, T(k)=1+2*сумма T(j), j от 0 до k-1.
        // Отсюда T(k)=3*T(k-1)=3^k: одни и те же интервалы вычисляются снова.
        if dp[l][r] > 0 {
            return dp[l][r]
        }

        for i := l; i <= r; i++ {
            // i лопается последним: его соседи в этот момент l-1 и r+1.
            // Начальный [1,n-2] и рекурсивные границы защищают оба индекса.
            // До 300 произведений не выше 10^6 дают сумму до 3*10^8.
            coins := arr[l-1] * arr[i] * arr[r+1]
            coins += dfs(l, i-1) + dfs(i+1, r)
            if dp[l][r] < coins {
                dp[l][r] = coins
            }
        }
        return dp[l][r]
    }

    return dfs(1, n-2)
}