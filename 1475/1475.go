package main

/*
Дан целочисленный массив prices, где prices[i] — цена i-го товара
в магазине.

В магазине действует специальная скидка.
Если вы покупаете i-й товар, то получите скидку, равную prices[j],
где j — наименьший индекс, для которого j > i и prices[j] <= prices[i].
Если такого индекса нет, скидки не будет.

Верните целочисленный массив answer, где answer[i] — итоговая цена,
которую вы заплатите за i-й товар с учётом специальной скидки.

Пример 1:
Вход: prices = [8,4,6,2,3]
Выход: [4,2,4,2,3]
Пояснение:
Товар 0 стоит 8, скидка равна prices[1]=4, итоговая цена: 8 - 4 = 4.
Товар 1 стоит 4, скидка равна prices[3]=2, итоговая цена: 4 - 2 = 2.
Товар 2 стоит 6, скидка равна prices[3]=2, итоговая цена: 6 - 2 = 4.
Для товаров 3 и 4 скидки нет.

Пример 2:
Вход: prices = [1,2,3,4,5]
Выход: [1,2,3,4,5]
Пояснение: в этом случае ни для одного товара скидки нет.

Пример 3:
Вход: prices = [10,1,1,6]
Выход: [9,0,1,6]

Ограничения:
1 <= prices.length <= 500
1 <= prices[i] <= 1000
*/

// finalPrices возвращает цены после вычета первой подходящей скидки справа.
// Монотонный стек хранит индексы товаров, для которых скидка ещё не найдена.
// Время: O(n), n = len(prices): каждый индекс кладём и снимаем не более раза.
// Память: O(n) для стека в худшем случае и O(n) для возвращаемой копии цен.
func finalPrices(prices []int) []int {
	// В answer записываем итоговые цены, а в prices оставляем исходные.
	// Если скидка не найдётся, в answer уже стоит цена без скидки.
	answer := append([]int(nil), prices...)
	stack := []int{}
	for i, price := range prices {
		// Цены товаров в стеке строго возрастают от дна к вершине.
		// Поэтому снимаем подходящие индексы с вершины, пока там цена >= price.
		// Если цена на вершине меньше price, ниже подходящих цен тоже нет.
		// Например, цена 2 закроет сразу 6 и 4, если обе ещё ждут скидки.
		for len(stack) > 0 && prices[stack[len(stack)-1]] >= price {
			// Это первая подходящая цена справа: более ранние уже проверены.
			// Равная цена тоже даёт скидку, поэтому итог может стать нулём.
			answer[stack[len(stack)-1]] -= price
			stack = stack[:len(stack)-1]
		}
		// Добавляем i только теперь: скидку для него ищем среди следующих цен.
		stack = append(stack, i)
	}
	return answer
}
