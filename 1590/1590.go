package main

/*
Дан массив положительных целых чисел nums. Удалите из него наименьший
подмассив, который может быть пустым, так, чтобы сумма оставшихся элементов
делилась на p. Удалять весь массив нельзя.

Верните длину наименьшего подмассива, который нужно удалить, или -1, если это
невозможно.

Подмассив — это непрерывный блок элементов массива.

Пример 1:
Вход: nums = [3,1,4,2], p = 6
Выход: 1
Пояснение: Сумма элементов nums равна 10 и не делится на 6.
Можно удалить подмассив [4]. Тогда сумма оставшихся элементов будет равна 6 и
будет делиться на 6.

Пример 2:
Вход: nums = [6,3,5,2], p = 9
Выход: 2
Пояснение: Нельзя удалить один элемент и получить сумму, которая делится на 9.
Лучший вариант — удалить подмассив [5,2], оставив [6,3] с суммой 9.

Пример 3:
Вход: nums = [1,2,3], p = 3
Выход: 0
Пояснение: Сумма уже равна 6 и делится на 3, поэтому ничего удалять не нужно.

Ограничения:
1 <= nums.length <= 10^5
1 <= nums[i] <= 10^9
1 <= p <= 10^9
*/

// minSubarray возвращает длину кратчайшего подмассива, удаление которого
// делает сумму оставшихся элементов кратной p. Если total % p = remain, сумма
// удаляемого подмассива также должна иметь остаток remain. Такой подмассив
// ищется по остаткам префиксных сумм.
// Среднее время работы — O(n), где n = len(nums): оба обхода линейны, а
// операции с map в среднем занимают O(1). Дополнительная память — O(k), где k
// — число сохранённых остатков и k <= min(n + 1, p). Срез nums не изменяется.
func minSubarray(nums []int, p int) int {
    // По ограничениям total может достигать 10^14, поэтому реализация
    // предполагает 64-разрядный int, используемый средой LeetCode для Go.
    total := 0
    for _, num := range nums {
        total += num
    }

    // Из суммы массива нужно убрать именно её остаток по модулю p.
    remain := total % p
    if remain == 0 {
        // Исходная сумма уже кратна p, поэтому допустим пустой подмассив.
        return 0
    }

    // Значение len(nums) служит признаком того, что допустимый подмассив
    // короче всего массива пока не найден.
    res := len(nums)
    curSum := 0

    // m[r] хранит последний индекс j, на котором префикс nums[0..j] имеет
    // остаток r. Последний, то есть наибольший, индекс даёт кратчайший отрезок
    // для любого будущего правого конца i.
    m := make(map[int]int)

    // Виртуальный пустой префикс S_-1 = 0 позволяет находить подмассивы,
    // начинающиеся с nums[0].
    m[0] = -1

    for i, num := range nums {
        // curSum = S_i % p — остаток префиксной суммы через индекс i.
        curSum = (curSum + num) % p

        // Для nums[j+1..i] требуется
        // (S_i - S_j) % p = remain. Следовательно,
        // S_j % p = (curSum - remain + p) % p. Добавление p не меняет класс
        // остатка, но не даёт результату стать отрицательным.
        prefix := (curSum - remain + p) % p
        if idx, ok := m[prefix]; ok {
            // Найденный idx задаёт подмассив nums[idx+1..i]. Например, для
            // [6,3,5,2] и p = 9 при i = 3 искомый остаток равен 0; индекс 1
            // задаёт удаляемый подмассив [5,2] длины 2.
            if i-idx < res {
                res = i - idx
            }
        }

        // Перезаписываем индекс остатка более поздним: при следующих i он
        // образует более короткий подмассив, чем любой прежний такой индекс.
        m[curSum] = i
    }

    // Кандидат длины len(nums) означает удаление всего массива, что запрещено
    // условием задачи. Другого подходящего подмассива в этом случае нет.
    if res == len(nums) {
        return -1
    }
    return res
}