package main

/*
Скобочная строка правильна тогда и только тогда, когда выполняется
хотя бы одно из условий:
- Строка пуста.
- Строка имеет вид AB (конкатенация A и B), где A и B — правильные строки.
- Строка имеет вид (A), где A — правильная строка.

Дана скобочная строка s.
За один ход можно вставить скобку в любую позицию строки.

Например, если s = "()))", можно вставить открывающую скобку и получить
"(()))" либо вставить закрывающую скобку и получить "())))".
Верните минимальное число ходов, необходимое, чтобы сделать s правильной.

Пример 1:
Вход:
s := "())"
Выход: 1

Пример 2:
Вход:
s := "((("
Выход: 3

Ограничения:
1 <= s.length <= 1000
s[i] — либо '(', либо ')'.
*/

// minAddToMakeValid возвращает минимальное число вставок скобок.
// Сопоставляем пары слева направо и считаем скобки, которым пары не хватило.
// Время: O(n), где n = len(s). Дополнительная память: O(1).
func minAddToMakeValid(s string) int {
	// opens — открывающие скобки без пары в пройденной части строки.
	// additions — вставки открывающих для закрывающих без пары.
	opens, additions := 0, 0
	for _, c := range s {
		if c == '(' {
			opens++
		} else if opens > 0 {
			// Закрывающая образует пару с одной из предыдущих открывающих.
			opens--
		} else {
			// В префиксе нет свободной открывающей. Нужна вставка до c:
			// открывающая из остатка строки не может закрыть этот дефицит.
			additions++
		}
	}
	// Для каждой оставшейся открывающей нужна закрывающая. Эти вставки
	// можно сделать в конце: они не устраняют дефицит ранних префиксов.
	// Например, для ")(()" additions = 1 и opens = 1: ответ 2.
	return additions + opens
}
