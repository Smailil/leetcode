package main

/*
Вам дана сетка размером m x n,
инициализированная этими тремя возможными значениями:
	-1 Стена или препятствие.
	0 Ворота.
	INF Бесконечность означает пустую комнату.
	Мы используем значение 2^31 - 1 = 2147483647
	для представления INF, поскольку можно предположить,
	что расстояние до ворот меньше 2147483647.
Заполните каждую пустую комнату расстоянием до ближайших ворот.
Если из комнаты невозможно добраться до ворот, оставьте в ней INF.

Пример 1:
Вход: rooms = [[2147483647,-1,0,2147483647],
	[2147483647,2147483647,2147483647,-1],
	[2147483647,-1,2147483647,-1],[0,-1,2147483647,2147483647]]
Выход: [[3,-1,0,1],[2,2,1,-1],[1,-1,2,-1],[0,-1,3,4]]

Пример 2:
Вход: rooms = [[-1]]
Выход: [[-1]]

Ограничения:
m == rooms.length
n == rooms[i].length
1 <= m, n <= 250
rooms[i][j] имеет значение -1, 0 или 2^31 - 1.
*/

type cell struct {
	row int
	col int
}

// islandsAndTreasure заполняет комнаты многоточечным BFS от всех ворот.
// R=len(grid), C=len(grid[0]), N=R*C: среднее время O(N).
// K — число достигнутых ячеек: map и буферы очереди занимают O(K+1),
// не более O(N). Отдельного результата нет, значения grid меняются.
// По условию R>=1, C>=1, строки прямоугольны.
func islandsAndTreasure(grid [][]int) {
    rows, cols := len(grid), len(grid[0])
	visited := make(map[cell]struct{})
	queue := []cell{}

	// addCell ставит непосещённую проходимую ячейку в очередь.
	// Среднее амортизированное время O(1); рост map/queue может быть дороже.
	// Буферы уже учтены в O(K+1); новая память при их росте до O(K+1).
	// Меняет visited/queue, не grid. Ключ cell имеет фиксированный размер.
	addCell := func(r, c int) {
		// Вызов из допустимой ячейки сдвигает координату только на 1.
		// Сверху возможны ровно rows/cols; границы проверяются до grid[r][c].
		if (r < 0 || r == rows || c < 0 || c == cols) {
			return
		}
		room := cell{r, c}
		if _, ok := visited[room]; ok {
			return
		}
		if grid[r][c] == -1 {
			return
		}
		// Помечаем при постановке, не при извлечении: одна ячейка не попадёт
		// в очередь от разных родителей. Первое достижение BFS — кратчайшее.
		visited[room] = struct{}{}
		queue = append(queue, room)
	}

	// Все ворота — источники слоя 0. Их заранее отмечаем, чтобы соседние
	// пути не поставили ворота в более поздний слой.
	for r := range(rows) {
		for c := range(cols) {
			if grid[r][c] == 0 {
				treasure := cell{r, c}
				visited[treasure] = struct{}{}
				queue = append(queue, treasure)
			}
		}
	}
	distance := 0
	for len(queue) > 0 {
		// Фиксируем текущий слой. Новые соседи получат distance+1
		// и обрабатываются только после всех levelSize старых элементов.
		levelSize := len(queue)
		for range(levelSize) {
			current := queue[0]
			queue = queue[1:]
			// Ячейка извлечена из минимального слоя: записываем итоговое расстояние.
			// INF не участвует в сложении; distance не выше N, int32 безопасен.
			grid[current.row][current.col] = distance
			addCell(current.row+1, current.col)
			addCell(current.row-1, current.col)
			addCell(current.row, current.col+1)
			addCell(current.row, current.col-1)
		}
		// Недостижимые комнаты не попадают в queue, поэтому сохраняют INF.
		// Стены не добавлялись вообще и остаются -1.
		distance++
	}
}
