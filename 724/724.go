package main

/*
Дан массив целых чисел nums. Найдите его опорный индекс.

Опорный индекс — это индекс, для которого сумма всех элементов строго слева
равна сумме всех элементов строго справа.

Если индекс находится на левом краю массива, сумма слева равна 0, поскольку
слева нет элементов. То же правило применяется к правому краю массива.

Верните крайний левый опорный индекс. Если такого индекса нет, верните -1.

Пример 1:
Вход: nums = [1,7,3,6,5,6]
Выход: 3
Пояснение:
Опорный индекс равен 3.
Сумма слева = nums[0] + nums[1] + nums[2] = 1 + 7 + 3 = 11
Сумма справа = nums[4] + nums[5] = 5 + 6 = 11

Пример 2:
Вход: nums = [1,2,3]
Выход: -1
Пояснение:
Ни один индекс не удовлетворяет условиям задачи.

Пример 3:
Вход: nums = [2,1,-1]
Выход: 0
Пояснение:
Опорный индекс равен 0.
Сумма слева = 0 (слева от индекса 0 нет элементов)
Сумма справа = nums[1] + nums[2] = 1 + -1 = 0

Ограничения:
1 <= nums.length <= 10^4
-1000 <= nums[i] <= 1000
*/

// pivotIndex возвращает крайний левый индекс, у которого суммы элементов
// слева и справа совпадают, либо -1, если такого индекса нет.
// Алгоритм заранее вычисляет сумму массива, чтобы для каждой позиции
// получать правую сумму за O(1) без повторного прохода по суффиксу.
// Время: O(n), где n = len(nums). Дополнительная память: O(1).
func pivotIndex(nums []int) int {
    // Сначала вычисляем сумму всего массива: из неё затем получаем правую
    // часть, исключая левую сумму и текущий элемент.
    total := 0
    for _, num := range nums {
        total += num
    }

    // Перед проверкой позиции i переменная leftSum хранит сумму элементов
    // строго слева от i — это основной инвариант обхода.
    leftSum := 0
    for i := range nums {
        // Правая сумма равна общей сумме без левой части и nums[i].
        rightSum := total - leftSum - nums[i]

        // Поскольку индексы проверяются слева направо, первое совпадение
        // является требуемым крайним левым опорным индексом.
        if leftSum == rightSum {
            return i
        }

        // Добавляем nums[i] только после сравнения, чтобы на следующей
        // итерации инвариант leftSum оставался верным.
        leftSum += nums[i]
    }
    return -1
}