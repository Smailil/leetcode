package main

/*
Строится таблица из n строк, нумерация которых начинается с 1.
В первой строке записывается 0.
В каждой следующей строке каждый 0 из предыдущей строки заменяется на 01,
а каждая 1 — на 10.

Например, при n = 3 первая строка — 0, вторая — 01, а третья — 0110.
Даны два целых числа n и k.
Верните k-й символ в n-й строке таблицы, считая позиции с 1.

Пример 1:
Вход: n = 1, k = 1
Выход: 0
Пояснение:
строка 1: 0

Пример 2:
Вход: n = 2, k = 1
Выход: 0
Пояснение:
строка 1: 0
строка 2: 01

Пример 3:
Вход: n = 2, k = 2
Выход: 1
Пояснение:
строка 1: 0
строка 2: 01

Ограничения:
1 <= n <= 30
1 <= k <= 2^(n-1)
*/

// kthGrammar возвращает k-й символ n-й строки с нумерацией позиций от 1.
// Вместо построения строк спускается по дереву подстановок от корня к k.
// Время: O(n) — n-1 переходов между строками, каждый за O(1).
// Дополнительная память: O(1) — хранятся только границы и текущий символ.
func kthGrammar(n int, k int) int {
	// Корень дерева — символ 0 из первой строки.
	cur := 0
	// Каждая подстановка удваивает длину; у корня 2^(n-1) потомков в строке n.
	// При 1 <= n <= 30 сдвиг от 0 до 29, длина помещается даже в int32.
	left, right := 1, 1<<(n-1)

	// Перед шагом i cur — символ строки i+1. Его потомки в строке n
	// занимают [left, right] длины 2^(n-1-i); позиция k внутри отрезка.
	for i := 0; i < n-1; i++ {
		// Длина отрезка чётная, mid — последняя позиция левой половины.
		// Обе границы не больше 2^29, поэтому их сумма не больше 2^30.
		mid := (left + right) / 2
		if k <= mid {
			// Первый ребёнок совпадает с родителем: 0 -> 01, 1 -> 10.
			right = mid
		} else {
			// Правая половина начинается с mid+1; второй ребёнок
			// противоположен родителю, поэтому переключаем cur.
			left = mid + 1
			cur ^= 1
		}
	}

	// Например, n=3, k=3: [1,4] -> [3,4] -> [3,3], cur: 0 -> 1 -> 1.
	// После n-1 делений остаётся [k, k], а cur — искомый символ.
	// При n=1 цикл не нужен: k=1 и cur=0 уже в начале.
	return cur
}
