package main

/*
Дана строка s, представляющая выражение.
Вычислите значение этого выражения и верните его.

При целочисленном делении результат нужно усекать в сторону нуля.

Можно считать, что заданное выражение всегда корректно.
Все промежуточные результаты находятся в диапазоне [-2^31, 2^31 - 1].

Примечание: запрещено использовать встроенные функции, которые вычисляют
значение строк как математических выражений, например eval().

Пример 1:
Вход: s = "3+2*2"
Выход: 7

Пример 2:
Вход: s = " 3/2 "
Выход: 1

Пример 3:
Вход: s = " 3+5 / 2 "
Выход: 5

Ограничения:
1 <= s.length <= 3 * 10^5
s состоит из целых чисел и операторов ('+', '-', '*', '/'),
между которыми могут быть пробелы.
s задаёт корректное выражение.
Все целые числа в выражении неотрицательны
и лежат в диапазоне [0, 2^31 - 1].
Гарантируется, что ответ помещается в 32-битное целое число.

*/

// calculate вычисляет выражение с приоритетом * и / над + и -.
// Цепочки * и / сворачиваются в prev, завершённые слагаемые — в total.
// Время: O(n), где n = len(s). Дополнительная память: O(1).
func calculate(s string) int {
    // total — сумма завершённых слагаемых; prev — текущее слагаемое
    // с уже учтённым знаком, но возможным продолжением через * или /.
    // num собирает очередное число, op хранит оператор перед ним.
    total, prev, num := 0, 0, 0
    // Начальный '+' позволяет обработать первое число как положительное.
    op := byte('+')
    n := len(s)
    i := 0

    // i == n — дополнительная итерация с искусственным '+'.
    // Она применяет op к последнему num; s[n] не читается.
    for i <= n {
        var ch byte
        if i < n {
            ch = s[i]
        } else {
            ch = '+'
        }
        // Пробелы не завершают число и не меняют ожидающий оператор.
        if ch == ' ' {
            i++
            continue
        }
        if ch >= '0' && ch <= '9' {
            // Собираем десятичное число: для "12" получаем 1*10+2.
            // По условию num <= 2^31 - 1, поэтому накопление безопасно.
            num = num*10 + int(ch-'0')
        } else {
            // num закончено. Выполняем op, стоящий перед этим числом;
            // ch сохраняем ниже как оператор для следующего числа.
            switch op {
            case '+':
                // Сложение завершает прежнее слагаемое: переносим prev
                // в total, а num становится новым слагаемым.
                total += prev
                prev = num
            case '-':
                // Вычитание тоже завершает прежнее слагаемое.
                // Храним новое как -num, чтобы затем складывать слагаемые.
                total += prev
                prev = -num
            case '*':
                // Умножение продолжает текущее слагаемое, не меняя total.
                // В 3+2*2 значение prev превращается из 2 в 4.
                prev = prev * num
            default:
                // Из четырёх допустимых операторов здесь остаётся '/'.
                // Корректность выражения гарантирует num != 0 при делении.
                // Go усекает частное к нулю, в том числе при prev < 0.
                prev = prev / num
            }
            // Следующее число будет обрабатываться с оператором ch.
            // Сбрасываем num, чтобы не склеить соседние числа.
            op = ch
            num = 0
        }
        i++
    }
    // Последнее слагаемое ещё находится в prev: добавляем его к total.
    total += prev
    return total
}