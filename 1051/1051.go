package main

/*
Школа хочет сделать ежегодную фотографию всех учеников. Учеников просят
выстроиться в один ряд в порядке неубывания роста. Представим этот порядок
целочисленным массивом expected, где expected[i] — ожидаемый рост i-го
ученика в ряду.

Дан целочисленный массив heights, представляющий текущий порядок учеников.
Каждый элемент heights[i] — рост i-го ученика в ряду при нумерации с нуля.

Верните количество индексов, для которых heights[i] != expected[i].

Пример 1:
Вход: heights = [1,1,4,2,1,3]
Выход: 3
Пояснение:
heights:  [1,1,4,2,1,3]
expected: [1,1,1,2,3,4]
Индексы 2, 4 и 5 не совпадают.

Пример 2:
Вход: heights = [5,1,2,3,4]
Выход: 5
Пояснение:
heights:  [5,1,2,3,4]
expected: [1,2,3,4,5]
Ни один индекс не совпадает.

Пример 3:
Вход: heights = [1,2,3,4,5]
Выход: 0
Пояснение:
heights:  [1,2,3,4,5]
expected: [1,2,3,4,5]
Все индексы совпадают.

Ограничения:
1 <= heights.length <= 100
1 <= heights[i] <= 100

*/

// heightChecker подсчитывает позиции, в которых текущий порядок учеников
// отличается от порядка по неубыванию роста. Функция восстанавливает этот
// порядок по частотам и сразу сравнивает его с heights, не сохраняя отдельный
// массив expected.
//
// Время: O(n + k), где n = len(heights), k = 100 — диапазон роста.
// Поскольку k фиксировано условием, асимптотически это также O(n).
// Дополнительная память: O(k) для массива частот. Поскольку k = 100,
// по условиям задачи это O(1).
func heightChecker(heights []int) int {
	// Ограничение heights[i] <= 100 позволяет использовать сам рост как индекс.
	// После этого прохода count[h] точно равен числу учеников роста h, поэтому
	// частот достаточно для восстановления отсортированного порядка.
	var count [101]int
	for _, h := range heights {
		count[h]++
	}

	// Значения h перебираются по возрастанию, а каждое повторяется count[h] раз.
	// Это последовательно создаёт те же значения, что находились бы в
	// отсортированной копии heights, но без выделения памяти под эту копию.
	res := 0
	index := 0
	for h := 1; h <= 100; h++ {
		for count[h] > 0 {
			// index указывает на позицию очередного ожидаемого роста. Сравнение
			// непосредственно с heights[index] сразу фиксирует несовпадение.
			if heights[index] != h {
				res++
			}

			// Обработанную позицию и одну копию роста h исключаем из дальнейшего
			// рассмотрения. Сумма всех частот равна len(heights), поэтому будет
			// выполнено ровно n сравнений и index не выйдет за границы массива.
			index++
			count[h]--
		}
	}

	return res
}
