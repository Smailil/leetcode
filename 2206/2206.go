package main

/*
Дан массив целых чисел nums, состоящий из 2 * n элементов.

Нужно разделить nums на n пар так, чтобы:
Каждый элемент входил ровно в одну пару.
Элементы в каждой паре были равны.
Верните true, если nums можно разделить на n таких пар, иначе false.

Пример 1:
Вход: nums = [3,2,3,2,2,2]
Выход: true
Пояснение:
В массиве nums 6 элементов, поэтому его нужно разделить на 6 / 2 = 3 пары.
Если разделить nums на пары (2, 2), (3, 3) и (2, 2), все условия будут
выполнены.

Пример 2:
Вход: nums = [1,2,3,4]
Выход: false
Пояснение:
Невозможно разделить nums на 4 / 2 = 2 пары так, чтобы каждая пара
соответствовала всем условиям.

Ограничения:
nums.length == 2 * n
1 <= n <= 500
1 <= nums[i] <= 500
*/

// divideArray проверяет, что каждое значение встречается чётное число раз:
// это необходимое и достаточное условие для разбиения массива на равные пары.
// Вместо хранения полных частот алгоритм отслеживает только их чётность.
// Время: O(m), где m = len(nums). Дополнительная память: O(1), поскольку
// ограничения допускают не более 500 различных значений nums[i].
func divideArray(nums []int) bool {
    // oddSet содержит значения с нечётной частотой в уже обработанном префиксе.
    oddSet := make(map[int]bool)

    for _, num := range nums {
        // Каждое вхождение меняет чётность: нечётную частоту превращаем в
        // чётную удалением из множества, а чётную — в нечётную добавлением.
        if oddSet[num] {
            delete(oddSet, num)
        } else {
            oddSet[num] = true
        }
    }

    // Пустое множество означает, что для каждого значения можно составить
    // пары без оставшегося одиночного элемента.
    return len(oddSet) == 0
}