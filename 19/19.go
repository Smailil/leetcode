package main

/*
Дана голова связного списка head.
Удалите n-й узел с конца списка и верните голову списка.

Пример 1:
Вход: head = [1,2,3,4,5], n = 2
Выход: [1,2,3,5]

Пример 2:
Вход: head = [1], n = 1
Выход: []

Пример 3:
Вход: head = [1,2], n = 1
Выход: [1]

Ограничения:
Количество узлов в списке равно sz.
1 <= sz <= 30
0 <= Node.val <= 100
1 <= n <= sz
*/

type ListNode struct {
	Val  int
	Next *ListNode
}

// removeNthFromEnd удаляет n-й узел с конца через зазор указателей.
// Время O(sz), sz — длина head; рабочая память O(1).
// Ответ удерживает sz-1 старых узлов, новых узлов ответа не создаётся.
// Меняет связь Next исходного списка и может вернуть другую голову.
func removeNthFromEnd(head *ListNode, n int) *ListNode {
	// Dummy позволяет удалить голову тем же оператором, что и другой узел.
	dummy := &ListNode{Next: head}
	l, r := dummy, head
	// l стоит перед head; после n шагов r опережает l на n+1 связей.
	// 1<=n<=sz гарантирует допустимость каждого обращения r.Next.
	for ; n > 0; n-- {
		r = r.Next
	}
	// Сохраняем зазор до конца списка; l станет предшественником цели.
	// При n=sz r уже nil, и l остаётся фиктивной головой.
	for r != nil {
		r = r.Next
		l = l.Next
	}
	// l.Next существует при допустимом n; исключаем этот узел из цепочки.
	l.Next = l.Next.Next
	return dummy.Next
}
