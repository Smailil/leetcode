package main

/*
Дан массив целых чисел nums. Верните длину самого длинного подмассива nums,
который является либо строго возрастающим, либо строго убывающим.

Пример 1:
Вход: nums = [1,4,3,3,2]
Выход: 2
Пояснение:
Строго возрастающие подмассивы nums: [1], [2], [3], [3], [4] и
[1,4].
Строго убывающие подмассивы nums: [1], [2], [3], [3], [4], [3,2] и
[4,3].
Поэтому возвращаем 2.

Пример 2:
Вход: nums = [3,3,3,3]
Выход: 1
Пояснение:
Строго возрастающие подмассивы nums: [3], [3], [3] и [3].
Строго убывающие подмассивы nums: [3], [3], [3] и [3].
Поэтому возвращаем 1.

Пример 3:
Вход: nums = [3,2,1]
Выход: 3
Пояснение:
Строго возрастающие подмассивы nums: [3], [2] и [1].
Строго убывающие подмассивы nums: [3], [2], [1], [3,2], [2,1] и
[3,2,1].
Поэтому возвращаем 3.

Ограничения:
1 <= nums.length <= 50
1 <= nums[i] <= 50
*/

// longestMonotonicSubarray возвращает длину самого длинного строго
// возрастающего или строго убывающего непрерывного подмассива.
// За один проход алгоритм хранит длину текущего участка и определяет его
// направление по соседним элементам.
//
// Пусть n = len(nums). Время работы — O(n), дополнительная память — O(1).
func longestMonotonicSubarray(nums []int) int {
    // По условию nums непуст. curLen — длина текущего монотонного участка,
    // заканчивающегося на предыдущем элементе, res — лучший результат.
    curLen, res := 1, 1

    for i := 1; i < len(nums); i++ {
        // Текущий участок начинается в i-curLen и заканчивается в i-1.
        // Равенство нарушает строгость, а несовпадение направлений его первой
        // и новой пар означает переход от роста к убыванию или обратно.
        if nums[i] == nums[i-1] ||
            ((nums[i-curLen] < nums[i-curLen+1]) != (nums[i-1] < nums[i])) {
            // После равенства новый участок содержит только nums[i]. При смене
            // направления последние два разных элемента начинают новый
            // участок длины 2.
            if nums[i] == nums[i-1] {
                curLen = 1
            } else {
                curLen = 2
            }
            // Такой сброс не улучшает res: прежний участок уже имел длину
            // не меньше 2, а после равенства текущая длина равна 1.
            continue
        }

        // Новая пара сохраняет прежнее строгое направление, поэтому текущий
        // участок можно продлить и учесть при обновлении максимума.
        curLen++
        if curLen > res {
            res = curLen
        }
    }

    return res
}