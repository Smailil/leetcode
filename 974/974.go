package main

/*
Даны целочисленный массив nums и целое число k. Верните количество непустых
подмассивов, сумма элементов которых делится на k.

Подмассив — это непрерывная часть массива.

Пример 1:
Вход: nums = [4,5,0,-2,-3,1], k = 5
Выход: 7
Пояснение: Существует 7 подмассивов, сумма которых делится на k = 5:
[4, 5, 0, -2, -3, 1], [5], [5, 0], [5, 0, -2, -3], [0],
[0, -2, -3], [-2, -3]

Пример 2:
Вход: nums = [5], k = 9
Выход: 0

Ограничения:
1 <= nums.length <= 3 * 10^4
-10^4 <= nums[i] <= 10^4
2 <= k <= 10^4
*/

// subarraysDivByK подсчитывает непустые подмассивы с суммой, кратной k.
// Обозначим сумму nums[0..i] как prefixSum_i. Тогда
// sum(nums[j+1..i]) = prefixSum_i - prefixSum_j.
// Искомая сумма делится на k, если
// prefixSum_i - prefixSum_j ≡ 0 (mod k), что эквивалентно равенству
// prefixSum_i % k == prefixSum_j % k. Поэтому для текущей префиксной суммы
// достаточно узнать число предыдущих сумм с тем же остатком.
// Среднее время работы — O(n), где n = len(nums), поскольку операции с map в
// среднем занимают O(1). Дополнительная память — O(d), где d — число разных
// встреченных остатков и d <= min(n + 1, k). Срез nums не изменяется.
func subarraysDivByK(nums []int, k int) int {
    prefixSum, res := 0, 0
    prefixCnt := make(map[int]int)

    // prefixCnt[r] хранит количество уже встреченных префиксных сумм с
    // остатком r. Например, для [4,5] при k = 5 суммы 4 и 9 дают один остаток
    // 4, а их разность 9 - 4 = 5 — это сумма подходящего подмассива [5].

    // До первого элемента префиксная сумма равна 0. Её запись позволяет
    // учитывать nums[0..i], когда prefixSum_i сама делится на k.
    prefixCnt[0] = 1

    // Инвариант: перед добавлением текущего остатка prefixCnt содержит только
    // префиксные суммы, которые закончились раньше текущего элемента.
    for _, n := range nums {
        // По ограничениям |prefixSum| <= 3 * 10^8, что помещается в int.
        prefixSum += n

        // В Go отрицательная сумма может дать отрицательный остаток.
        // Добавление k приводит его к каноническому диапазону [0, k), чтобы
        // один класс остатков всегда соответствовал одному ключу map.
        // Делитель ненулевой: по условию k >= 2.
        remain := prefixSum % k
        if remain < 0 {
            remain += k
        }

        // prefixCnt[remain] — число предыдущих префиксных сумм с тем же
        // остатком. Каждая из них задаёт один подходящий подмассив, который
        // заканчивается на текущем элементе.
        res += prefixCnt[remain]

        // Текущую префиксную сумму записываем только после подсчёта, чтобы она
        // не образовала сама с собой подмассив нулевой длины.
        prefixCnt[remain]++
    }

    return res
}
