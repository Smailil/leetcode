package main

/*
Дан целочисленный массив nums, верните массив answer таким образом, 
чтобы answer[i] был равен произведению всех элементов nums, кроме nums[i].

Произведение любого префикса или суффикса nums гарантированно укладывается
в 32-битное целое число.

Вы должны написать алгоритм, который выполняется за O(n) времени
и без использования операции деления.

Пример 1:
Вход: nums = [1,2,3,4]
Выход: [24,12,8,6]

Пример 2:
Вход: nums = [-1,1,0,-3,3]
Выход: [0,0,9,0,0]

Ограничения:
2 <= nums.length <= 10^5
-30 <= nums[i] <= 30
Входные данные генерируются таким образом,
что answer[i] гарантированно укладывается в 32-битное целое число.
*/

// productExceptSelf соединяет произведения слева и справа от каждой позиции.
// n=len(nums): время O(n), рабочая память O(1), память результата O(n).
// nums не меняется; output — отдельный буфер, не срез исходного массива.
// Префиксы, суффиксы и ответ по условию помещаются в int32, значит и в int.
func productExceptSelf(nums []int) []int {
    output := make([]int, len(nums))

	// Пустое произведение равно 1. Перед шагом i pref равен произведению
	// элементов nums[0:i].
	// Сначала записываем его, лишь затем включаем nums[i] для следующего шага.
	pref := 1
	for i, num := range nums {
		output[i] = pref
		pref *= num
	}
	// Перед шагом i suf равен произведению nums[i+1:n]. Умножаем префикс
	// на этот суффикс: собственный nums[i] отсутствует в обоих множителях.
	// suf обновляется после ответа, чтобы не включить текущий элемент раньше.
	suf := 1
	for i := len(nums) - 1; i >= 0; i-- {
		output[i] *= suf
		suf *= nums[i]
	}
	// Деление не используется: нули и отрицательные значения не требуют
	// отдельной ветки; два нуля дают нули во всех произведениях без себя.
	return output
}