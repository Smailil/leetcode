package main

/*
Дан целочисленный массив nums с индексацией с нуля.

Пусть nums[i..j] — подмассив с элементами от i до j включительно,
где 0 <= i <= j < nums.length.
Для каждого подмассива посчитайте, сколько в нём различных значений.
Верните сумму квадратов этих количеств по всем подмассивам nums.

Подмассив — непустая непрерывная последовательность элементов массива.

Пример 1:
Вход: nums := []int{1, 2, 1}
Выход: 15
Пояснение: есть шесть подмассивов:
[1]: 1 различное значение
[2]: 1 различное значение
[1]: 1 различное значение
[1,2]: 2 различных значения
[2,1]: 2 различных значения
[1,2,1]: 2 различных значения
Сумма квадратов: 1^2 + 1^2 + 1^2 + 2^2 + 2^2 + 2^2 = 15.

Пример 2:
Вход: nums := []int{1, 1}
Выход: 3
Пояснение: есть три подмассива:
[1]: 1 различное значение
[1]: 1 различное значение
[1,1]: 1 различное значение
Сумма квадратов: 1^2 + 1^2 + 1^2 = 3.

Ограничения:
1 <= nums.length <= 100
1 <= nums[i] <= 100
*/

// sumCounts суммирует квадраты числа различных значений во всех подмассивах.
// Для каждой левой границы расширяем подмассив вправо и обновляем множество.
// Время: в среднем O(n²), где n = len(nums), при вставке в map за O(1).
// Дополнительная память: O(k), где k — число различных значений в nums.
// По условию k <= min(n, 100), то есть при фиксированном диапазоне это O(1).
func sumCounts(nums []int) int {
	n := len(nums)
	res := 0
	for i := range n {
		// Новая левая граница: значения прежнего подмассива не переносим.
		seen := map[int]bool{}
		for j := i; j < n; j++ {
			// После вставки seen содержит ровно значения из nums[i..j].
			// Повтор обновляет существующий ключ, не увеличивая len(seen).
			seen[nums[j]] = true
			// Пара (i, j) задаёт отдельный подмассив, даже если размер
			// множества не изменился. Например, при i = 0 в [1,2,1]
			// подмассивы [1,2] и [1,2,1] оба добавляют 2² = 4.
			res += len(seen) * len(seen)
		}
	}
	return res
}