package main

/*
Вам дан целочисленный массив coins, представляющий монеты разного номинала,
и целое число amount, представляющее общую сумму денег.
Верните наименьшее количество монет, необходимое для составления этой суммы.
Если эту сумму денег нельзя составить ни одной комбинацией монет,
верните -1.
Вы можете предположить, что у вас есть бесконечное количество монет
каждого вида.

Пример 1:
Вход: coins = [1,2,5], amount = 11
Выход: 3
Пояснение: 11 = 5 + 5 + 1

Пример 2:
Вход: coins = [2], amount = 3
Выход: -1

Пример 3:
Вход: coins = [1], amount = 0
Выход: 0

Ограничения:
1 <= coins.length <= 12
1 <= coins[i] <= 2^31 - 1
0 <= amount <= 10^4
*/

// coinChange строит минимум числа монет для каждой суммы снизу вверх.
// A=amount, m=len(coins): время O(A+1+A*m), рабочая память O(A+1).
// Ответ int O(1); coins не меняется, каждая монета доступна многократно.
func coinChange(coins []int, amount int) int {
    dp := make([]int, amount+1)
    // A+1 — признак недостижимости: при номиналах >=1 любой возможный ответ
    // не больше A. Для amount=0 таблица из одного элемента корректна.
    for i := range dp {
        dp[i] = amount + 1 // значение выше любого допустимого числа монет
    }
    // Нулевая сумма требует 0 монет, это база для достижимых переходов.
    dp[0] = 0
    // Для суммы a пробуем выбрать последней монету c. Положительность c
    // даёт a-c<a, поэтому минимум для остатка уже полностью вычислен.
    for a := 1; a <= amount; a++ {
        for _, c := range coins {
            // c может быть до int32 max, но a-c всё равно помещается в int.
            // При a-c>=0 индекс также меньше a, а значит внутри dp.
            // dp[a-c] ещё не включает добавляемую монету c: её учитывает +1.
            // Например, с coins=[3], a=6, c=3: dp[3]=1, кандидат 1+1=2.
            // Если остаток недостижим, кандидат A+2 не улучшит прежнее A+1.
            if a-c >= 0 {
                dp[a] = min(dp[a], 1+dp[a-c])
            }
        }
    }
    // Значения dp не выше A+1, кандидаты не выше A+2<=10002: int безопасен.
    // Только оставшийся признак недостижимости преобразуем в -1.
    if dp[amount] > amount {
        return -1
    }
    return dp[amount]
}