package main

/*
В этой задаче дерево представляет собой неориентированный граф,
связный и не имеющий циклов.
Вам дан граф, который начинался как дерево с n узлами,
помеченными от 1 до n, и добавленным одним дополнительным ребром.
Добавленное ребро имеет две разные вершины, выбранные от 1 до n,
и не является уже существующим ребром.
Граф представлен как массив рёбер длины n, где edges[i] = [a_i, b_i]
означает наличие ребра между узлами a_i и b_i.
Верните ребро, которое можно удалить,
чтобы полученный граф представлял собой дерево из n узлов.
Если существует несколько ответов, верните ответ,
который встречается последним во входных данных.

Пример 1:
Вход: edges = [[1,2],[1,3],[2,3]]
Выход: [2,3]

Пример 2:
Вход: edges = [[1,2],[2,3],[3,4],[1,4],[1,5]]
Выход: [1,4]

Ограничения:
n == edges.length
3 <= n <= 1000
edges[i].length == 2
1 <= a_i < b_i <= edges.length
a_i != b_i
Повторяющихся ребер нет.
Данный граф связен.
*/

// findRedundantConnection выбирает последнее ребро единственного цикла.
// Сначала DFS отмечает вершины цикла, затем рёбра проверяются с конца.
// n — число рёбер и вершин по условию; среднее время O(n),
// при среднем O(1) поиске int-ключей map; рабочая память O(n).
// Результат — новый срез из двух int, память O(1); edges не меняется.
func findRedundantConnection(edges [][]int) []int {
    n := len(edges)
    // Метки лежат в [1,n], поэтому слот 0 оставляем неиспользованным.
    // Для каждого неориентированного ребра храним оба направления.
    adj := make([][]int, n+1)
    for _, edge := range edges {
        u, v := edge[0], edge[1]
        adj[u] = append(adj[u], v)
        adj[v] = append(adj[v], u)
    }

    visit := make([]bool, n+1)
    cycle := make(map[int]struct{})
    // cycleStart хранит вход в цикл; -1 закрывает сбор его вершин.
    cycleStart := -1

    var dfs func(node, par int) bool
    // dfs сигнализирует найденный цикл и заполняет visit/cycle/cycleStart.
    // Один обход занимает O(n) времени и O(h) памяти стека, h <= n.
    // Захваченные массивы/карта общие, bool результата занимает O(1).
    dfs = func(node, par int) bool {
        // Повторный узел не является родителем: найдено замыкание цикла.
        if visit[node] {
            cycleStart = node
            return true
        }

        visit[node] = true
        for _, nei := range adj[node] {
            // Обратное направление ребра к родителю не образует цикл.
            if nei == par {
                continue
            }
            // true поднимается по стеку до выхода из всего поиска.
            if dfs(nei, node) {
                // Пока вход в цикл не достигнут, узлы пути входят в цикл.
                if cycleStart != -1 {
                    cycle[node] = struct{}{}
                }
                // Сам вход уже добавлен; его предки в cycle не попадут.
                if node == cycleStart {
                    cycleStart = -1
                }
                return true
            }
        }
        return false
    }

    // Граф связен, поэтому одного старта достаточно; других циклов нет.
    dfs(1, -1)

    // В графе дерево + одно ребро нет хорд между вершинами цикла.
    // Значит, оба конца в cycle точно выделяют удаляемые рёбра.
    // Обратный порядок реализует выбор последнего ребра во входе.
    for i := len(edges) - 1; i >= 0; i-- {
        u, v := edges[i][0], edges[i][1]
		if _, ok := cycle[u]; ok {
			if _, ok := cycle[v]; ok {
				// Значения копируются: результат не ссылается на edges[i].
				return []int{u, v}
			}
		}
    }
    // По контракту цикл существует; это резервный пустой результат.
    return []int{}
}
