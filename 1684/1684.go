package main

/*
Даны строка allowed, состоящая из различных символов,
и массив строк words.
Строка считается допустимой, если каждый её символ встречается в allowed.

Верните количество допустимых строк в массиве words.

Пример 1:
Вход: allowed = "ab", words = ["ad","bd","aaab","baa","badab"]
Выход: 2
Пояснение: строки "aaab" и "baa" являются допустимыми,
поскольку содержат только символы 'a' и 'b'.

Пример 2:
Вход: allowed = "abc", words = ["a","b","c","ab","ac","bc","abc"]
Выход: 7
Пояснение: все строки являются допустимыми.

Пример 3:
Вход: allowed = "cad", words = ["cc","acd","b","ba","bac","bad","ac","d"]
Выход: 4
Пояснение: строки "cc", "acd", "ac" и "d" являются допустимыми.

Ограничения:
1 <= words.length <= 10^4
1 <= allowed.length <= 26
1 <= words[i].length <= 10
Все символы в allowed различны.
words[i] и allowed содержат только строчные английские буквы.
*/

// countConsistentStrings подсчитывает слова, состоящие только из символов
// allowed, представляя множество разрешённых букв битовой маской.
// Время: O(a + s), где a = len(allowed), а s — суммарная длина всех слов.
// Дополнительная память: O(1), поскольку маска и счётчики имеют фиксированный
// размер и не зависят от количества слов.
func countConsistentStrings(allowed string, words []string) int {
    // Каждой строчной букве соответствует один бит. По условию c находится
    // в диапазоне 'a'..'z', поэтому индекс сдвига всегда лежит в пределах 0..25.
    bitMask := 0
    for _, c := range allowed {
        bitMask |= 1 << (c - 'a')
    }

    // Сначала считаем все слова допустимыми, а затем вычитаем каждое слово,
    // в котором обнаружится хотя бы один запрещённый символ.
    res := len(words)
    for _, w := range words {
        for _, c := range w {
            bit := 1 << (c - 'a')
            // Нулевое пересечение означает, что бит буквы отсутствует в маске.
            // После первого такого символа слово уже нельзя сделать допустимым.
            if bit&bitMask == 0 {
                res--
                break
            }
        }
    }

    return res
}