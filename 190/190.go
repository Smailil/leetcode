package main

/*
Обратите биты заданного 32-битного целого числа со знаком.

Пример 1:
Вход: n = 43261596
Выход: 964176192
Объяснение:
целое двоичное_число
43261596 00000010100101000001111010011100
964176192 00111001011110000010100101000000

Пример 2:
Вход: n = 2147483644
Выход: 1073741822
Объяснение:
целое двоичное_число
2147483644	01111111111111111111111111111100
1073741822	00111111111111111111111111111110

Ограничения:
0 <= n <= 2^31 - 2
n четное.
*/

// reverseBits разворачивает все 32 бита через извлечение младшего бита.
// Ровно 32 итерации: время O(1), рабочая память O(1), ответ int O(1).
// Внешнее состояние не меняется; uint32 задаёт точную ширину сдвигов.
func reverseBits(n int) int {
    // По условию n неотрицателен и помещается в 31 бит: приведение точное.
    // num — беззнаковый, поэтому >> заполняет старшие позиции нулями.
    var num uint32 = uint32(n)
    var res uint32 = 0
    
    // После i шагов res содержит обратный порядок младших i битов n,
    // а num равен n, сдвинутому вправо на i. Обрабатываем и ведущие нули.
    for range 32 {
        // Освобождаем младшую позицию и дописываем num&1 (0 либо 1).
        // После <<1 младший бит равен 0, поэтому += не вызывает переноса.
        res = res << 1
        res += (num & 1)
        num = num >> 1
    }
    
    // n чётен: его младший бит 0 станет старшим битом res.
    // Значит res помещается в знаковый int32, а int(res) безопасен.
    return int(res)
}