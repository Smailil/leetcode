package main

/*
Дана строка s, найдите длину самой длинной подстроки без повторяющихся символов.

Пример 1:
Вход: s = "abcabcbb"
Выход: 3
Пояснение: ответ — "abc" длиной 3.
Обратите внимание, что "bca" и "cab" также являются правильными ответами.

Пример 2:
Вход: s = "bbbbb"
Выход: 1
Пояснение: ответ — "b" длиной 1.

Пример 3:
Вход: s = "pwwkew"
Выход: 3
Пояснение: ответ — "wke" длиной 3.
Обратите внимание, что ответ должен быть подстрокой.
"pwke" — это подпоследовательность, а не подстрока.

Ограничения:
0 <= s.length <= 5 * 10^4
s состоит из английских букв, цифр, символов и пробелов.
*/

// lengthOfLongestSubstring ищет максимальное окно без повторов.
// n = len(s), k — число разных байтов в окне.
// Время O(n) в среднем: каждый указатель сдвигается не более n раз.
// Поиск в map с байтовым ключом в среднем O(1).
// Рабочая память O(k), k <= 256, то есть O(1) при байтовом алфавите.
// Результат — одно число; вход не изменяется.
func lengthOfLongestSubstring(s string) int {
	maxCount := 0
    l, r := 0, 0
	// hash содержит ровно разные байты полуинтервала s[l:r].
	// Индексация побайтовая; для ASCII это также индексация символов.
	hash := make(map[byte]struct{}, 0)
	for r < len(s) {
		if _, ok := hash[s[r]]; ok {
			// Новый байт уже есть в окне: убираем левый край до удаления
			// его предыдущего вхождения, не двигая r преждевременно.
			delete(hash, s[l])
			l++
		} else {
			// Расширение сохраняет уникальность, поэтому длина r-l+1
			// допустима для ответа; затем r снова исключён из окна.
			hash[s[r]] = struct{}{}
			maxCount = max(maxCount, r - l + 1)
			r++
		}
	}
	return maxCount
}
