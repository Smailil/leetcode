package main

/*
Вам дан массив prices, где prices[i] — это цена данной акции на i-й день.
Вы хотите максимизировать свою прибыль, выбрав один день для покупки одной
акции и выбрав другой день в будущем для продажи этой акции.
Верните максимальную прибыль, которую вы можете получить от этой сделки.
Если вы не можете получить прибыль, верните 0.

Пример 1:
Вход: prices = [7,1,5,3,6,4]
Выход: 5
Пояснение: Покупайте в день 2 (цена = 1) и продавайте в день 5 (цена = 6),
прибыль = 6-1 = 5.
Обратите внимание, что покупка во второй день и продажа в первый день
не разрешены, поскольку вы должны купить, прежде чем продавать.

Пример 2:
Вход: prices = [7,6,4,3,1]
Выход: 0
Объяснение: В этом случае транзакции не выполняются, а максимальная прибыль = 0.

Ограничения:
1 <= prices.length <= 10^5
0 <= prices[i] <= 10^4
*/

// maxProfit хранит минимальную прошлую цену и лучший доход одной сделки.
// n = len(prices); время O(n), рабочая память и результат O(1).
// prices не изменяется; контракт гарантирует хотя бы один день.
func maxProfit(prices []int) int {
	maxRes := 0
    l, r := 0, 1
	// Перед шагом l<r и prices[l] — минимум дней до r.
	// maxRes — лучшая уже рассмотренная прибыль, не меньше нуля.
	for r < len(prices) {
		// Новый минимум выгоднее для будущих продаж; сегодня после
		// смены l продажу не считаем, чтобы покупка предшествовала продаже.
		if prices[l] > prices[r] {
			l = r
		} else {
			// При продаже сегодня лучшая покупка — на прежнем минимуме.
			// Разность цен не больше 10^4, переполнение int исключено.
			maxRes = max(maxRes, prices[r]-prices[l])
		}
		r++
	}
	return maxRes
}