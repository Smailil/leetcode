package main

/*
Даны массив строк words и строка chars.

Строка считается хорошей, если её можно составить из символов chars.
Каждый символ можно использовать не более одного раза для каждой строки words.

Верните сумму длин всех хороших строк из массива words.

Пример 1:
Вход: words = ["cat","bt","hat","tree"], chars = "atach"
Выход: 6
Пояснение: можно составить строки "cat" и "hat",
поэтому ответ равен 3 + 3 = 6.

Пример 2:
Вход: words = ["hello","world","leetcode"],
chars = "welldonehoneyr"
Выход: 10
Пояснение: можно составить строки "hello" и "world",
поэтому ответ равен 5 + 5 = 10.

Ограничения:
1 <= words.length <= 1000
1 <= words[i].length, chars.length <= 100
words[i] и chars состоят из строчных английских букв.
*/

// countCharacters возвращает сумму длин слов, которые можно составить
// из символов chars с учётом количества каждого символа.
// Время: O(m + s), где m = len(chars), а s — суммарная длина всех слов.
// Дополнительная память: O(k), где k — число различных строчных букв;
// поскольку k <= 26, в условиях задачи это O(1).
func countCharacters(words []string, chars string) int {
    // Один раз подсчитываем запас каждого символа, доступный для любого слова.
    count := make(map[rune]int)
    for _, c := range chars {
        count[c]++
    }
    res := 0
    for _, w := range words {
        // Каждое слово проверяется независимо: символы chars можно заново
        // использовать для следующего слова, поэтому счётчик создаётся снова.
        curWord := make(map[rune]int)
        good := true
        for _, c := range w {
            curWord[c]++
            // Как только слово требует больше копий символа, чем есть в chars,
            // дальнейшая проверка этого слова уже не изменит результат.
            if curWord[c] > count[c] {
                good = false
                break
            }
        }
        // В ответ входит полная длина только тех слов, для которых хватило
        // каждого требуемого символа.
        if good {
            res += len(w)
        }
    }
    return res
}