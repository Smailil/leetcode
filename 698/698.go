package main

import "sort"

/*
Дан целочисленный массив nums и целое число k.
Верните true, если этот массив можно разбить на k непустых подмножеств,
суммы которых все равны.

Пример 1:
Вход: nums = [4,3,2,3,5,2,1], k = 4
Выход: true
Пояснение: массив можно разбить на 4 подмножества
(5), (1, 4), (2,3), (2,3) с равными суммами.

Пример 2:
Вход: nums = [1,2,3,4], k = 3
Выход: false

Ограничения:
1 <= k <= nums.length <= 16
1 <= nums[i] <= 10^4
Частота каждого элемента находится в диапазоне [1, 4].
*/

// canPartitionKSubsets строит равносуммовые группы поиском с возвратом.
// n — число элементов nums. Верхняя оценка времени O(n*n!) без отсечений:
// выборы дают не более O(n!) префиксов перестановок, каждый сканирует n.
// Сортировка O(n*log n) включена в эту оценку; рабочая память O(n).
// Результат bool занимает O(1). После проверки делимости функция
// сортирует nums на месте, меняя порядок элементов общего буфера.
func canPartitionKSubsets(nums []int, k int) bool {
    // 1. Считаем общую сумму всех элементов массива.
    // Положительные числа и k >= 1 исключают нулевую цель и деление на 0.
    // Сумма не превосходит 16*10000, поэтому помещается в int.
    sum := 0
    for _, num := range nums {
        sum += num
    }
    
    // Если общая сумма не делится на k без остатка, 
    // то разбить массив на k подмножеств с равной суммой
    // математически невозможно
    if sum%k != 0 {
        return false
    }

    // Целевая сумма, которую должно иметь каждое из k подмножеств
    target := sum / k
    
    // 2. Сортируем исходный массив по убыванию, без создания копии.
    // Крупные числа проверяются раньше: это может раньше отсечь ветку,
    // но не устраняет экспоненциальный перебор в худшем случае.
    sort.Sort(sort.Reverse(sort.IntSlice(nums)))
    
    // Оптимизация: если самый большой элемент
    // в отсортированном массиве больше target,
    // он никуда не поместится, поэтому решение невозможно.
    if len(nums) > 0 && nums[0] > target {
        return false
    }
    
    // Слайс для отметок: использован ли элемент в каком-либо подмножестве
    used := make([]bool, len(nums))

    // 3. Вспомогательная рекурсивная функция (поиск с возвратом / бэктрекинг)
    // i: индекс, с которого начинаем перебор элементов
    // для текущего подмножества (чтобы не дублировать комбинации)
    // k: количество оставшихся подмножеств, которые нужно собрать
    // subsetSum: текущая сумма формируемого подмножества.
    // Индексы внутри группы растут, used отделяет уже выбранные позиции.
    var backtrack func(i, k, subsetSum int) bool
    // backtrack дополняет текущую группу и затем строит оставшиеся.
    // При r неиспользованных позициях верхняя оценка времени O(n*r!).
    // Рабочий стек O(r+k), общий used не копируется; результат bool O(1).
    // Замыкание меняет used и откатывает неудачный выбор, но не nums.
    backtrack = func(i, k, subsetSum int) bool {
        // Базовый случай: если осталось собрать 0 подмножеств,
        // значит все группы имеют target. Их общая сумма равна sum,
        // поэтому положительных неиспользованных чисел уже не осталось.
        if k == 0 {
            return true
        }
        
        // Если текущее подмножество собрано (сумма достигла target), 
        // переходим к сбору следующего.
        // Начинаем перебор заново с индекса 0; used сохраняет прошлые группы.
        // Положительная цель гарантирует, что собранная группа непустая.
        if subsetSum == target {
            return backtrack(0, k-1, 0)
        }
        
        // Перебираем доступные элементы, начиная с индекса i
        for j := i; j < len(nums); j++ {
            // Пропускаем позицию, взятую в любую группу, в том числе текущую,
            // либо число, которое превысит target. Все числа положительны,
            // поэтому превышенную сумму дальше уменьшить нельзя.
            if used[j] || subsetSum+nums[j] > target {
                continue
            }
            
            // Делаем выбор: берем элемент в текущее подмножество
            used[j] = true
            
            // Рекурсивно пытаемся завершить текущее подмножество
            // с оставшимися числами
            if backtrack(j+1, k, subsetSum+nums[j]) {
                // При успехе откат не нужен: used локален и больше не читается.
                return true // Найдено решение: возвращаем true
            }
            
            // Откатываем действие (бэктрекинг),
            // если текущий путь не привел к решению
            used[j] = false
            
            // В пустой группе первым берётся первый неиспользованный индекс.
            // В любом разбиении он входит в какую-то группу; группы можно
            // переставить и строить эту группу первой. Её остальные индексы
            // больше первого, поэтому текущий перебор уже покрывает её.
            // Неудача всех таких ветвей позволяет пропустить иные старты.
            if subsetSum == 0 {
                break
            }
        }
        
        // Если перебор закончился и собрать подмножество не удалось
        return false
    }

    // Стартуем процесс поиска с первого элемента (индекс 0),
    // собирая k подмножеств с начальной суммой 0
    return backtrack(0, k, 0)
}
