package main

/*
Даны индексируемый с нуля массив строк words и двумерный массив целых чисел
queries.

Каждый запрос queries[i] = [l_i, r_i] требует найти количество строк words
с индексами от l_i до r_i включительно, которые начинаются и заканчиваются
гласной буквой.

Верните массив ans длины queries.length, где ans[i] — ответ на i-й запрос.

Гласными считаются буквы 'a', 'e', 'i', 'o' и 'u'.

Пример 1:
Вход: words = ["aba","bcb","ece","aa","e"],
queries = [[0,2],[1,4],[1,1]]
Выход: [2,3,0]
Пояснение: строки "aba", "ece", "aa" и "e" начинаются и заканчиваются
гласной буквой.
Ответ на запрос [0,2] равен 2: это строки "aba" и "ece".
Ответ на запрос [1,4] равен 3: это строки "ece", "aa" и "e".
Ответ на запрос [1,1] равен 0.
Возвращаем [2,3,0].

Пример 2:
Вход: words = ["a","e","i"], queries = [[0,2],[0,1],[2,2]]
Выход: [3,2,1]
Пояснение: каждая строка удовлетворяет условиям, поэтому возвращаем
[3,2,1].

Ограничения:
1 <= words.length <= 10^5
1 <= words[i].length <= 40
words[i] состоит только из строчных английских букв.
sum(words[i].length) <= 3 * 10^5
1 <= queries.length <= 10^5
0 <= l_i <= r_i < words.length
*/

// vowelStrings отвечает на запросы о числе подходящих строк в диапазоне.
// Префиксные суммы позволяют вычислять каждый ответ вычитанием двух значений.
// Среднее время: O(n + q), где n = len(words), q = len(queries).
// Рабочая память: O(n). Возвращаемый массив занимает O(q).
func vowelStrings(words []string, queries [][]int) []int {
    // Поиск в map в среднем занимает O(1). Фиксированный набор из пяти
    // гласных использует O(1) памяти.
    vowels := map[byte]bool{'a': true, 'e': true, 'i': true, 'o': true, 'u': true}
    n := len(words)

    // prefixCnt[i] хранит число подходящих строк среди первых i элементов.
    // Нулевой элемент служит пустым префиксом и упрощает формулу диапазона.
    prefixCnt := make([]int, n+1)

    for i := range n {
        w := words[i]
        prefixCnt[i+1] = prefixCnt[i]

        // По условию строки непустые, поэтому первый и последний индексы
        // существуют. Увеличиваем префикс, только если обе буквы — гласные.
        if vowels[w[0]] && vowels[w[len(w)-1]] {
            prefixCnt[i+1]++
        }
    }

    // Размер результата совпадает с количеством независимых запросов.
    res := make([]int, len(queries))
    for i, q := range queries {
        l, r := q[0], q[1]

        // prefixCnt[r+1] учитывает правую границу, а prefixCnt[l]
        // исключает все строки, расположенные левее диапазона.
        res[i] = prefixCnt[r+1] - prefixCnt[l]
    }

    return res
}