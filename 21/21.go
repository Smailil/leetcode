package main

/*
Даны головы двух отсортированных связных списков list1 и list2.
Объедините их в один отсортированный связный список и верните его голову.
Новый список должен состоять из узлов списков list1 и list2.

Пример 1:
Вход: list1 = [1,2,4], list2 = [1,3,5]
Выход: [1,1,2,3,4,5]

Пример 2:
Вход: list1 = [], list2 = [1,2]
Выход: [1,2]

Пример 3:
Вход: list1 = [], list2 = []
Выход: []

Ограничения:
0 <= длина каждого списка <= 100
-100 <= Node.val <= 100
*/

type ListNode struct {
    Val int
    Next *ListNode
}

// mergeTwoLists сливает списки, выбирая меньшую текущую голову.
// Время O(m+n), m и n — длины list1/list2; рабочая память O(1).
// Ответ удерживает m+n исходных узлов; новые узлы ответа не выделяются.
// Связи Next входных узлов меняются, сами узлы не копируются.
func mergeTwoLists(list1 *ListNode, list2 *ListNode) *ListNode {
    // Фиктивный узел задаёт общий способ добавлять первую и следующие головы.
    dummy := &ListNode{}
	tail := dummy
	// tail — конец готового отсортированного префикса.
	// Обе головы существуют; меньшая не больше ещё не взятых узлов.
	for list1 != nil && list2 != nil {
		// При равенстве выбираем list1; продвигаем только выбранную голову.
		// Следующая запись tail.Next может изменить исходную связь.
		if list1.Val <= list2.Val {
			tail.Next = list1
			list1 = list1.Next
		} else {
			tail.Next = list2
			list2 = list2.Next
		}
		tail = tail.Next

	}
	// Одна цепочка закончилась; остаток другой уже отсортирован.
	// Присоединяем его одним указателем, без поузлового обхода.
	if list1 != nil {
		tail.Next = list1
	} else if list2 != nil {
		tail.Next = list2
	}
	// Dummy не входит в ответ: возвращаем первый исходный узел.
	return dummy.Next
}
