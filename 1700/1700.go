package main

/*
В школьной столовой на обед предлагают круглые и квадратные бутерброды,
обозначенные числами 0 и 1 соответственно. Все ученики стоят в очереди.
Каждый ученик предпочитает либо квадратные, либо круглые бутерброды.

Количество бутербродов в столовой равно количеству учеников. Бутерброды
сложены в стопку. На каждом шаге происходит следующее:

- Если ученик в начале очереди предпочитает верхний бутерброд из стопки,
  он забирает его и покидает очередь.
- В противном случае ученик оставляет бутерброд и переходит в конец очереди.

Процесс продолжается, пока никто из учеников в очереди не захочет взять
верхний бутерброд и поэтому не сможет поесть.

Даны два целочисленных массива students и sandwiches, где sandwiches[i] —
тип i-го бутерброда в стопке (i = 0 соответствует вершине стопки), а
students[j] — предпочтение j-го ученика в исходной очереди
(j = 0 соответствует началу очереди). Верните количество учеников,
которые не смогут поесть.

Пример 1:
Вход: students = [1,1,0,0], sandwiches = [0,1,0,1]
Выход: 0
Пояснение:
- Первый ученик оставляет верхний бутерброд и переходит в конец очереди:
  students = [1,0,0,1].
- Первый ученик снова оставляет бутерброд и переходит в конец очереди:
  students = [0,0,1,1].
- Первый ученик забирает бутерброд и покидает очередь:
  students = [0,1,1], sandwiches = [1,0,1].
- Первый ученик оставляет бутерброд и переходит в конец очереди:
  students = [1,1,0].
- Первый ученик забирает бутерброд и покидает очередь:
  students = [1,0], sandwiches = [0,1].
- Первый ученик оставляет бутерброд и переходит в конец очереди:
  students = [0,1].
- Первый ученик забирает бутерброд и покидает очередь:
  students = [1], sandwiches = [1].
- Первый ученик забирает бутерброд и покидает очередь:
  students = [], sandwiches = [].
Таким образом, все ученики смогут поесть.

Пример 2:
Вход: students = [1,1,1,0,0,1], sandwiches = [1,0,0,0,1,1]
Выход: 3

Ограничения:
1 <= students.length, sandwiches.length <= 100
students.length == sandwiches.length
sandwiches[i] равно 0 или 1.
students[i] равно 0 или 1.
*/

// countStudents возвращает количество учеников, которым не достанется еда.
// Вместо моделирования перестановок очереди функция считает предпочтения:
// пока верхний бутерброд кому-то нужен, очередь может довести этого ученика
// до начала, после чего он заберёт бутерброд.
//
// Время: O(n), где n = len(students) = len(sandwiches).
// Дополнительная память: O(1), поскольку типов бутербродов ровно два.
func countStudents(students []int, sandwiches []int) int {
    // res хранит число оставшихся учеников, а cnt[t] — сколько из них
    // предпочитают бутерброд типа t.
    res := len(students)
    cnt := make([]int, 2)
    for _, student := range students {
        cnt[student]++
    }

    // Бутерброды рассматриваются от вершины стопки. Если подходящий ученик
    // есть, перестановки очереди рано или поздно приведут его в начало.
    for _, s := range sandwiches {
        if cnt[s] > 0 {
            cnt[s]--
            res--
        } else {
            // Никому не нужен верхний бутерброд, поэтому он блокирует стопку,
            // а все res оставшихся учеников уже не смогут поесть.
            break
        }
    }
    return res
}