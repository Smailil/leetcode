package main

/*
Дан корень двоичного дерева.
Узел X называется хорошим, если на пути от корня до X нет узлов
со значением, большим, чем значение X.
Возвращает количество хороших узлов в бинарном дереве.

Пример 1:
https://assets.leetcode.com/uploads/2020/04/02/test_sample_1.png
Вход: root = [3,1,4,3,null,1,5]
Выход: 4
Пояснение: Узлы, выделенные синим цветом, являются хорошими.
Корневой узел (3) всегда является хорошим узлом.
Узел 4 -> (3,4) — максимальное значение на пути, начиная с корня.
Узел 5 -> (3,4,5) — максимальное значение на пути.
Узел 3 -> (3,1,3) — максимальное значение на пути.

Пример 2:
https://assets.leetcode.com/uploads/2020/04/02/test_sample_2.png
Вход: root = [3,3,null,4,2]
Выход: 3
Пояснение: Узел 2 -> (3, 3, 2) не является хорошим,
поскольку значение 3 на пути больше значения 2.

Пример 3:
Вход: root = [1]
Выход: 1
Пояснение: Корень считается хорошим.

Ограничения:
Количество узлов в бинарном дереве находится в диапазоне [1, 10^5].
Значение каждого узла находится в диапазоне [-10^4, 10^4].
*/

type TreeNode struct {
    Val int
    Left *TreeNode
    Right *TreeNode
}

// goodNodes считает узлы, не меньшие всех их предков, через DFS с максимумом.
// Время O(N), N — число узлов; рабочая память O(h) на стеке при высоте h.
// Результат int O(1); дерево только читается, узлы и ссылки не меняются.
// По условию root непуст, поэтому чтение root.Val при старте допустимо.
func goodNodes(root *TreeNode) int {
	var dfs func(node *TreeNode, prevMax int) int
	// dfs получает максимум пути до node, включает node и суммирует детей.
	// Для поддерева время O(Ns), стек O(hs); результат int O(1).
	// Изменяется лишь локальная копия prevMax, не дерево и не состояние соседа.
	dfs = func(node *TreeNode, prevMax int) int {
		if node == nil {
			return 0
		}
		res := 0
		if prevMax <= node.Val {
			res = 1
			prevMax = node.Val
		}
		return res + dfs(node.Left, prevMax) + dfs(node.Right, prevMax)
	}
	return dfs(root, root.Val)
}
