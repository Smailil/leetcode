package main

import "sort"

/*
Дан массив целых чисел nums. Отсортируйте его по возрастанию частоты
значений. Если несколько значений встречаются одинаково часто, расположите
их по убыванию самих значений.

Верните отсортированный массив.

Пример 1:
Вход: nums = [1,1,2,2,2,3]
Выход: [3,1,1,2,2,2]
Пояснение: число 3 встречается 1 раз, число 1 — 2 раза, а число 2 — 3 раза.

Пример 2:
Вход: nums = [2,3,1,3,2]
Выход: [1,3,3,2,2]
Пояснение: числа 2 и 3 встречаются по 2 раза, поэтому они расположены
по убыванию.

Пример 3:
Вход: nums = [-1,1,-6,4,5,-6,1,4,1]
Выход: [5,-1,4,4,-6,-6,1,1,1]

Ограничения:
1 <= nums.length <= 100
-100 <= nums[i] <= 100
*/

// frequencySort переупорядочивает nums на месте: сначала по возрастанию
// частоты значений, а при равной частоте — по убыванию самих значений.
// Среднее время работы — O(n log n), где n = len(nums): обращения к map
// занимают в среднем O(1), а сортировка выполняет O(n log n) сравнений.
// Дополнительная рабочая память — O(k + log n), где k — число различных
// значений: O(k) занимает map, O(log n) — стек сортировки. По ограничениям
// k <= 201. Отдельный результирующий срез не создаётся: возвращается nums.
func frequencySort(nums []int) []int {
    count := make(map[int]int)

    // Заранее считаем частоты, чтобы компаратор получал их за среднее O(1),
    // а не пересчитывал количество вхождений при каждом сравнении.
    for _, num := range nums {
        count[num]++
    }

    // Сортируем сам nums: элемент с меньшей частотой должен оказаться раньше.
    sort.Slice(nums, func(i, j int) bool {
        // Разные частоты задают основной порядок — по их возрастанию.
        if count[nums[i]] != count[nums[j]] {
            return count[nums[i]] < count[nums[j]]
        }

        // При равных частотах большее значение ставим раньше.
        return nums[i] > nums[j]
    })

    // Возвращаем тот же срез, который был переупорядочен на месте.
    return nums
}