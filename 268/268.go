package main

/*
Дан массив nums, содержащий n различных чисел в диапазоне [0, n],
верните единственное число в диапазоне, которое отсутствует в массиве.

Пример 1:
Вход: nums = [3,0,1]
Выход: 2
Объяснение:
n = 3, поскольку чисел 3, поэтому все числа находятся в диапазоне [0,3].
2 — это недостающее число в диапазоне, поскольку его нет в nums.

Пример 2:
Вход: nums = [0,1]
Выход: 2
Объяснение:
n = 2, поскольку чисел 2, поэтому все числа находятся в диапазоне [0,2].
2 — это недостающее число в диапазоне, поскольку его нет в nums.

Пример 3:
Вход: nums = [9,6,4,2,3,5,7,0,1]
Выход: 8
Объяснение:
n = 9, поскольку чисел 9, поэтому все числа находятся в диапазоне [0,9].
8 — это недостающее число в диапазоне, поскольку его нет в nums.

Ограничения:
n == nums.length
1 <= n <= 10^4
0 <= nums[i] <= n
Все числа nums уникальны.
*/

// missingNumber находит пропуск взаимным уничтожением одинаковых чисел XOR.
// Время O(n), n=len(nums); рабочая память и результат O(1).
// Вход не изменяется; XOR не создаёт арифметического переполнения.
func missingNumber(nums []int) int {
    // Индексы дадут XOR 0..n-1; недостающее n включаем заранее.
    xorr := len(nums)
    // XOR ассоциативен и коммутативен; одинаковые x^x=0 взаимно уничтожаются.
    // Останется единственное число диапазона, которого нет во входе.
    for i := range len(nums) {
        xorr ^= i ^ nums[i]
    }
    return xorr
}
