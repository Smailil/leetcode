package main

/*
Даны два массива строк words1 и words2.

Строка b является подмножеством строки a, если каждая буква из b
встречается в a не реже, чем в b.

Например, "wrr" — подмножество "warrior", но не "world".

Строка a из words1 является универсальной, если для каждой строки b
из words2 строка b является подмножеством a.

Верните массив всех универсальных строк из words1.
Ответ можно вернуть в любом порядке.

Пример 1:
Вход: words1 = ["amazon","apple","facebook","google","leetcode"],
words2 = ["e","o"]
Выход: ["facebook","google","leetcode"]

Пример 2:
Вход: words1 = ["amazon","apple","facebook","google","leetcode"],
words2 = ["lc","eo"]
Выход: ["leetcode"]

Пример 3:
Вход: words1 = ["acaac","cccbb","aacbb","caacc","bcbbb"],
words2 = ["c","cc","b"]
Выход: ["cccbb"]

Ограничения:
1 <= words1.length, words2.length <= 10^4
1 <= words1[i].length, words2[i].length <= 10
words1[i] и words2[i] состоят только из строчных английских букв.
Все строки words1 уникальны.

*/

// wordSubsets возвращает слова из words1, содержащие все требования words2.
// Порядок букв не важен: сравниваются только их количества в каждом слове.
// Для каждой буквы объединяем требования максимумом её частоты в words2,
// затем проверяем каждого кандидата по этому общему набору требований.
// Входные срезы и строки не изменяются.
//
// Время: O(L1 + L2 + A * (n + m)), где n = len(words1), m = len(words2),
// L1 и L2 — суммарные длины слов в words1 и words2, A = 26 — размер алфавита.
// При A = 26 и длине каждого слова не более 10 это O(n + m).
// Рабочая память: O(A), то есть O(1) для фиксированного алфавита.
// Результат: O(r) заголовков строк, где r — число подходящих слов.
// Символы не копируются: строки результата ссылаются на строки words1.
func wordSubsets(words1 []string, words2 []string) []string {
    // count2[i] — минимальное число вхождений i-й буквы для универсального
    // слова. После обработки части words2 здесь лежат максимумы её частот
    // среди уже просмотренных слов.
    count2 := [26]int{}
    for _, w := range words2 {
        // Частоты считаем отдельно для каждого слова: повторные буквы
        // тоже являются требованиями, например "bb" требует две буквы b.
        countW := [26]int{}
        for _, c := range w {
            // По условию c находится в 'a'..'z', поэтому индекс равен 0..25.
            countW[c-'a']++
        }
        // Кандидат должен удовлетворять каждому слову независимо.
        // Для одной буквы это count >= f1, count >= f2, ...,
        // что равносильно count >= max(f1, f2, ...).
        // Например, ["ab", "bb"] требует одну a и две b, а не три b:
        // одна и та же буква кандидата может покрывать разные слова words2.
        for i := range 26 {
            if countW[i] > count2[i] {
                count2[i] = countW[i]
            }
        }
    }

    res := []string{}
    for _, w := range words1 {
        // Считаем запас каждой буквы в кандидате. Новый нулевой массив
        // не позволяет частотам предыдущего кандидата повлиять на проверку.
        countW := [26]int{}
        for _, c := range w {
            countW[c-'a']++
        }

        // Проверяем общий набор требований вместо перебора всех words2.
        // flag остаётся true, пока для всех проверенных букв хватает запаса.
        flag := true
        for i := range 26 {
            if countW[i] < count2[i] {
                // Одной недостающей буквы достаточно для отказа:
                // в words2 есть слово, чьё требование кандидат не выполняет.
                flag = false
                break
            }
        }

        // Если дефицита нет, кандидат содержит каждое слово из words2.
        // Добавляем исходную строку, сохраняя порядок подходящих слов words1.
        if flag {
            res = append(res, w)
        }
    }

    return res
}
