package main

/*
Вам дана целочисленная матрица размера m x n со следующими двумя свойствами:
Каждая строка отсортирована в порядке неубывания.
Первое целое число каждой строки больше последнего целого числа
предыдущей строки.
Дано целое число target.
Верните true, если target находится в матрице, или false в противном случае.

Вы должны написать решение с временной сложностью O(log(m *n)).

Пример 1:
https://assets.leetcode.com/uploads/2020/10/05/mat.jpg
Вход: matrix = [[1,3,5,7],[10,11,16,20],[23,30,34,60]], target = 3
Выход: true

Пример 2:
https://assets.leetcode.com/uploads/2020/10/05/mat2.jpg
Вход: matrix = [[1,3,5,7],[10,11,16,20],[23,30,34,60]], target = 13
Выход: false

Ограничения:
m == matrix.length
n == matrix[i].length
1 <= m, n <= 100
-10^4 <= matrix[i][j], target <= 10^4
*/

// searchMatrix ищет target двоичным поиском по виртуально плоской матрице.
// R = len(matrix), C = len(matrix[0]): время O(log(R*C)), память O(1).
// Матрица не меняется; R >= 1, C >= 1, все строки имеют длину C.
func searchMatrix(matrix [][]int, target int) bool {
    // Порядок внутри строк и между ними делает весь диапазон отсортированным.
    // R*C <= 10000, поэтому произведение и l+r безопасны.
    l, r := 0, len(matrix)*len(matrix[0]) - 1
	for l <= r {
		mid := (l+r)/2
		// Здесь m и n — индексы строки и столбца, а не размеры матрицы.
		// mid = m*C+n, 0 <= n < C. При C >= 1 деление допустимо;
		// mid находится в 0..R*C-1, поэтому оба индекса корректны.
		m, n := mid/len(matrix[0]), mid%len(matrix[0])
		// Сравнение исключает mid и ненужную половину диапазона.
		if target > matrix[m][n] {
			l = mid + 1
		} else if target < matrix[m][n] {
			r = mid - 1
		} else {
			return true
		}
	}
	// Диапазон кандидатов пуст: target не встретился.
	return false
}
