package main

import "slices"

/*
Коко любит есть бананы.
Имеется n стопок бананов, в i-й стопке находится piles[i] бананов.
Охранники ушли и вернутся через h часов.
Коко может решить, что ее скорость поедания бананов в час равна k.
Каждый час она выбирает какую-то стопку бананов и съедает k бананов из этой
стопки.
Если в куче меньше k бананов, она съедает их все и больше не будет есть бананов
в течение этого часа.
Коко любит есть медленно, но все равно хочет съесть все бананы до того, как
вернутся охранники.
Верните минимальное целое число k, при котором она сможет съесть все бананы за h
часов.

Пример 1:
Вход: piles = [3,6,7,11], h = 8
Выход: 4

Пример 2:
Вход: piles = [30,11,23,4,20], h = 5
Выход: 30

Пример 3:
Вход: piles = [30,11,23,4,20], h = 6
Выход: 23

Ограничения:
1 <= piles.length <= 10^4
piles.length <= h <= 10^9
1 <= piles[i] <= 10^9
*/

// minEatingSpeed ищет первую допустимую скорость двоичным поиском.
// n = len(piles), M = max(piles): время O(n log(M + 1)), память O(1).
// Результат O(1); piles не изменяется. Проверка скорости линейна.
func minEatingSpeed(piles []int, h int) int {
    // При скорости M каждая стопка требует один час; n <= h даёт решение.
    l, r := 1, slices.Max(piles)
	res := r
	// Минимальная скорость лежит в [l, r] либо уже сохранена в res.
	// Увеличение скорости не увеличивает нужное число часов.
	for l <= r {
		// l >= 1, mid положителен; l+r <= 2*10^9 не переполняет int32.
		mid := (l+r)/2
		hours := 0
		// Для положительных p и mid: ceil(p/mid) = (p+mid-1)/mid.
		// Например, p=7, mid=3: (7+3-1)/3 = 3 часа, а не 2.
		// Числитель не выше 2*10^9-1. Сумма hours может быть 10^13:
		// она безопасна при 64-битном int, но может переполниться при int32.
		for _, p := range piles {
			hours += (p + mid - 1) / mid // Округление вверх.
			// math.Ceil(float64(p)/float64(mid))
		}
		// Допустимую скорость запоминаем и ищем меньшую слева.
		// При нехватке времени все скорости до mid также недопустимы.
		if hours <= h {
			res = min(res, mid)
			r = mid - 1
		} else {
			l = mid + 1
		}
	}
	// Непроверенный диапазон пуст; res — минимальный допустимый кандидат.
	return res
}
