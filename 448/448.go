package main

/*
Дан массив nums из n целых чисел, где nums[i] находится в диапазоне [1, n].
Верните массив всех целых чисел из диапазона [1, n], которые не встречаются
в nums.

Пример 1:
Вход: nums = [4,3,2,7,8,2,3,1]
Выход: [5,6]

Пример 2:
Вход: nums = [1,1]
Выход: [2]

Ограничения:
n == nums.length
1 <= n <= 10^5
1 <= nums[i] <= n
*/

// findDisappearedNumbers возвращает числа из [1, n], отсутствующие в nums.
// Алгоритм отмечает встреченное значение v знаком элемента nums[v-1],
// поэтому отдельное множество не требуется. Функция изменяет nums на месте.
// Время: O(n), где n = len(nums). Дополнительная память: O(1) без учёта
// возвращаемого среза.
func findDisappearedNumbers(nums []int) []int {
    for _, num := range nums {
        // Модуль восстанавливает значение, если текущий элемент уже помечен.
        // Вычитание 1 переводит число из [1, n] в индекс [0, n-1].
        i := abs(num) - 1

        // -abs сохраняет отрицательную метку и при повторном появлении числа.
        nums[i] = -abs(nums[i])
    }

    res := []int{}
    for i, num := range nums {
        // Положительный nums[i] означает, что значение i+1 не встречалось:
        // соответствующую позицию никто не отметил отрицательным знаком.
        if num > 0 {
            res = append(res, i+1)
        }
    }
    return res
}

// abs возвращает модуль x. Он позволяет читать исходные значения после
// изменения знаков в nums.
func abs(x int) int {
    if x < 0 {
        return -x
    }
    return x
}