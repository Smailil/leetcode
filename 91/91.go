package main

/*
Вы перехватили секретное сообщение, закодированное в виде строки цифр.
Сообщение декодируется с помощью следующего сопоставления:
"1" -> 'A'
"2" -> 'B'
...
"25" -> 'Y'
"26" -> 'Z'

Однако при декодировании сообщения вы понимаете,
что существует много разных способов декодирования сообщения,
поскольку некоторые коды содержатся в других кодах («2» и «5» против «25»).
Например, «11106» можно декодировать как:
«AAJF» с группировкой (1, 1, 10, 6)
«KJF» с группировкой (11, 10, 6)
Группировка (1, 11, 06) недействительна,
поскольку «06» не является допустимым кодом (действителен только «6»).
Примечание: могут существовать строки, которые невозможно декодировать.
Дана строка s, содержащая только цифры,
верните количество способов ее декодирования.
Если всю строку невозможно декодировать каким-либо допустимым способом,
верните 0.
Тестовые случаи генерируются таким образом,
чтобы ответ умещался в 32-битное целое число.

Пример 1:
Вход: s = "12"
Выход: 2
Объяснение:
«12» можно расшифровать как «AB» (1 2) или «L» (12).

Пример 2:
Вход: s = "226"
Выход: 3
Объяснение:
«226» можно декодировать как «BZ» (2 26), «VF» (22 6) или «BBF» (2 2 6).

Пример 3:
Вход: s = "06"
Выход: 0
Объяснение:
«06» нельзя сопоставить с «F» из-за лидирующего нуля («6» отличается от «06»).
В этом случае строка не является допустимой кодировкой, поэтому верните 0.

Ограничения:
1 <= s.length <= 100
s содержит только цифры и может содержать ведущие нули.
*/

// numDecodings считает допустимые разбиения строки на коды от 1 до 26.
// Динамика идёт справа налево: берёт один символ или допустимую пару.
// Время O(n), где n=len(s); рабочая память и память результата O(1).
// Вход неизменен, побочных эффектов нет; ответ помещается в int по условию.
func numDecodings(s string) int {
    // Пустой суффикс имеет один вариант; за ним служебное значение 0.
    // Перед итерацией i: dp1=ways(i+1), dp2=ways(i+2).
    dp1, dp2 := 1, 0
    dp := 0 // ways(i): сумма вариантов допустимых кодов.
    for i := len(s) - 1; i >= 0; i-- {
        // Ноль не является самостоятельным кодом; другие цифры дают dp1.
        if s[i] == '0' {
            dp = 0
        } else {
            dp = dp1
        }
        // Проверка границы защищает s[i+1]. Допустимы 10..19 и 20..26,
        // включая пары с нулём; ведущий ноль сюда попасть не может.
        if i+1 < len(s) && (s[i] == '1' ||
           s[i] == '2' && s[i+1] <= '6') {
            dp += dp2
        }
        // Сдвигаем два сохранённых суффикса для следующего индекса слева.
        dp2 = dp1
        dp1 = dp
        dp = 0
    }
    return dp1
}
