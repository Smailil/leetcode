package main

/*
Дан целочисленный массив cost, где cost[i] — стоимость i-й ступеньки лестницы.
После оплаты можно подняться на одну или две ступеньки.
Можно начать либо со ступеньки с индексом 0, либо со ступеньки с индексом 1.
Верните минимальную стоимость достижения вершины лестницы.

Пример 1:
Вход: cost = [10,15,20]
Выход: 15
Пояснение: Вы начнете с индекса 1.
-Заплатите 15 и поднимитесь на две ступеньки, чтобы достичь вершины.
Общая стоимость 15.

Пример 2:
Вход: cost = [1,100,1,1,1,100,1,1,100,1]
Выход: 6
Объяснение: Вы начнете с индекса 0.
-Заплатите 1 и поднимитесь на две ступеньки, чтобы достичь индекса 2.
-Заплатите 1 и поднимитесь на две ступеньки, чтобы достичь индекса 4.
-Заплатите 1 и поднимитесь на две ступеньки, чтобы достичь индекса 6.
-Заплатите 1 и поднимитесь на одну ступень, чтобы достичь индекса 7.
-Заплатите 1 и поднимитесь на две ступеньки, чтобы достичь индекса 9.
-Заплатите 1 и поднимитесь на одну ступеньку, чтобы достичь вершины.
Общая стоимость 6.

Ограничения:
2 <= cost.length <= 1000
0 <= cost[i] <= 999
*/

// minCostClimbingStairs считает цену пути от каждой ступеньки до вершины.
// n = len(cost): время O(n), рабочая память и результат O(1).
// Меняет cost: элементы до последних двух становятся ценами путей.
func minCostClimbingStairs(cost []int) int {
    //cost = append(cost, 0)
	// С последних двух ступенек можно сразу выйти наверх, заплатив их цену.
	// Обратный порядок даёт готовую динамику для i+1 и i+2.
	for i := len(cost) - 3; i >= 0; i-- {
		// Платим исходную цену i и выбираем дешевле из шагов на 1 или 2.
		// n <= 1000 и цена <= 999: сумма не выше 999000, int безопасен.
		cost[i] += min(cost[i+1], cost[i+2])
	}
	// Начинать можно с 0 или 1; n >= 2 защищает оба индекса.
	return min(cost[0], cost[1])
}
