package main

/*
Даны массив целых чисел nums и целое число k.
Верните длину кратчайшего непустого подмассива nums с суммой не менее k.
Если такого подмассива нет, верните -1.

Подмассив — непрерывная часть массива.

Пример 1:
Ввод:
nums := []int{1}
k := 1
Вывод: 1

Пример 2:
Ввод:
nums := []int{1, 2}
k := 4
Вывод: -1

Пример 3:
Ввод:
nums := []int{2, -1, 2}
k := 3
Вывод: 3

Ограничения:
1 <= nums.length <= 10^5
-10^5 <= nums[i] <= 10^5
1 <= k <= 10^9
*/

// shortestSubarray ищет длину кратчайшего подмассива с суммой не менее k.
// Префиксные суммы и монотонная очередь помогают отбрасывать лишние начала.
// Время: O(n), каждый индекс добавляется и удаляется не более одного раза.
// Дополнительная память: O(n) для сумм и очереди, где n = len(nums).
func shortestSubarray(nums []int, k int) int {
	n := len(nums)
	// prefix[i] — сумма первых i чисел. Сумма nums[j:i] равна
	// prefix[i] - prefix[j], где i — правая граница, не входящая в срез.
	// Модуль префиксной суммы может достигать 10^10: нужен int64.
	prefix := make([]int64, n+1)
	for i, x := range nums {
		prefix[i+1] = prefix[i] + int64(x)
	}
	// В queue[head:tail] — кандидаты j по возрастанию индексов и сумм.
	// Каждый из n+1 индексов добавляем один раз, поэтому места хватает.
	queue := make([]int, n+1)
	// n+1 — длина, невозможная для подмассива: ответа пока нет.
	head, tail, answer := 0, 0, n+1
	for i := 0; i <= n; i++ {
		// Если для головы сумма меньше k, для остальных она ещё меньше.
		// Если k достигнуто, учитываем длину и удаляем начало: любой
		// более поздний конец с этим же началом даст большую длину.
		for head < tail && prefix[i]-prefix[queue[head]] >= int64(k) {
			answer = min(answer, i-queue[head])
			head++
		}
		// Для любого будущего конца новый индекс i даёт не меньшую сумму
		// и меньшую длину, чем индекс в хвосте с prefix[j] >= prefix[i].
		// В [2,-1,2] начало 2 с суммой 1 вытесняет начало 1 с суммой 2.
		for head < tail && prefix[i] <= prefix[queue[tail-1]] {
			tail--
		}
		queue[tail] = i
		tail++
	}
	if answer <= n {
		return answer
	}
	return -1
}
