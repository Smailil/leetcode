package main

/*
Дан массив nums различных целых чисел с индексацией с 0.
Переставьте его элементы так, чтобы каждый элемент полученного массива
не был равен среднему арифметическому своих соседей.

Формально, для каждого i в диапазоне 1 <= i < nums.length - 1
значение (nums[i-1] + nums[i+1]) / 2 не должно равняться nums[i].

Верните любую перестановку nums, удовлетворяющую требованиям.

Пример 1:
Вход: nums = [1,2,3,4,5]
Выход: [1,2,4,5,3]
Пояснение:
При i=1: nums[i] = 2, среднее арифметическое соседей — (1+4) / 2 = 2.5.
При i=2: nums[i] = 4, среднее арифметическое соседей — (2+5) / 2 = 3.5.
При i=3: nums[i] = 5, среднее арифметическое соседей — (4+3) / 2 = 3.5.

Пример 2:
Вход: nums = [6,2,0,9,7]
Выход: [9,7,6,2,0]
Пояснение:
При i=1: nums[i] = 7, среднее арифметическое соседей — (9+6) / 2 = 7.5.
При i=2: nums[i] = 6, среднее арифметическое соседей — (7+2) / 2 = 4.5.
При i=3: nums[i] = 2, среднее арифметическое соседей — (6+0) / 2 = 3.
Обратите внимание: исходный массив [6,2,0,9,7] тоже удовлетворяет условиям.

Ограничения:
3 <= nums.length <= 10^5
0 <= nums[i] <= 10^5
*/

// rearrangeArray проверяет соседние тройки слева направо и обратно,
// меняя середину с соседом, когда она равна среднему соседей.
// Изменяет nums на месте и возвращает тот же срез.
// Время: O(n), где n = len(nums), два последовательных прохода.
// Рабочая дополнительная память: O(1).
// Результат удерживает исходный буфер nums без копирования элементов.
// Новый буфер не выделяется; всего дополнительной памяти O(1).
func rearrangeArray(nums []int) []int {
	n := len(nums)

	// Проверяем только внутренние элементы: 1 <= i <= n-2.
	// Поэтому индексы обоих соседей i-1 и i+1 всегда допустимы.
	for i := 1; i < n-1; i++ {
		// Пусть a=nums[i-1], b=nums[i], c=nums[i+1].
		// b=(a+c)/2 проверяем как 2*b=a+c, не выполняя деление.
		// Для [1,2,4] среднее 2.5, а деление целых в Go дало бы 2.
		// Обе стороны не больше 2*10^5, поэтому int не переполняется.
		if 2*nums[i] == nums[i-1]+nums[i+1] {
			// Обмен b и c убирает равенство в текущей тройке:
			// a+c=2*b и a+b=2*c одновременно возможны лишь при a=b=c.
			// Все элементы различны, поэтому такой случай исключён.
			nums[i], nums[i+1] = nums[i+1], nums[i]
		}
	}

	// Правый обмен может создать равенство в уже проверенной тройке слева.
	// Например, [1,3,4,5] -> [1,3,5,4], где 3=(1+5)/2.
	// Второй проход проверяет изменённый массив в обратном порядке.
	for i := n - 2; i > 0; i-- {
		if 2*nums[i] == nums[i-1]+nums[i+1] {
			// Зеркальный обмен тоже исправляет середину текущей тройки.
			// В примере выше получаем [3,1,5,4].
			nums[i], nums[i-1] = nums[i-1], nums[i]
		}
	}

	return nums
}