package main

/*
Даны два целых числа m и n, задающие сетку размера m x n
с индексацией с 0.
Также даны два двумерных целочисленных массива guards и walls,
где guards[i] = [row_i, col_i] и walls[j] = [row_j, col_j] задают
положения i-го охранника и j-й стены соответственно.

Охранник видит каждую клетку в четырёх основных направлениях
(на север, восток, юг или запад) от своей позиции, если обзор не перекрыт
стеной или другим охранником.
Клетка считается охраняемой, если её видит хотя бы один охранник.

Верните количество незанятых клеток, которые не охраняются.

Пример 1:
https://assets.leetcode.com/uploads/2022/03/10/example1drawio2.png
Вход: m = 4, n = 6, guards = [[0,0],[1,1],[2,3]], walls = [[0,1],[2,2],[1,4]]
Выход: 7
Пояснение: на схеме выше охраняемые и неохраняемые клетки показаны
красным и зелёным цветом соответственно.
Всего есть 7 неохраняемых клеток, поэтому возвращаем 7.

Пример 2:
https://assets.leetcode.com/uploads/2022/03/10/example2drawio.png
Вход: m = 3, n = 3, guards = [[1,1]], walls = [[0,1],[1,0],[2,1],[1,2]]
Выход: 4
Пояснение: на схеме выше неохраняемые клетки показаны зелёным цветом.
Всего есть 4 неохраняемые клетки, поэтому возвращаем 4.

Ограничения:
1 <= m, n <= 10^5
2 <= m * n <= 10^5
1 <= guards.length, walls.length <= 5 * 10^4
2 <= guards.length + walls.length <= m * n
guards[i].length == walls[j].length == 2
0 <= row_i, row_j < m
0 <= col_i, col_j < n
Все позиции в массивах guards и walls попарно различны.
*/

// countUnguarded считает незанятые клетки вне обзора всех охранников.
// Строит сетку состояний и выпускает четыре луча от каждого охранника.
// Время: O(m*n + g + w), g = len(guards), w = len(walls).
// По условию g+w <= m*n, поэтому время O(m*n).
// Дополнительная память: O(m*n); входные guards и walls не изменяются.
func countUnguarded(m, n int, guards, walls [][]int) int {
	// empty — свободная клетка без отметки обзора; guarded — с отметкой.
	// blocked объединяет стены и охранников: оба вида закрывают обзор.
	const (
		empty   byte = 0
		blocked byte = 1
		guarded byte = 2
	)

	// Новые byte-срезы заполнены нулями: в начале все клетки — empty.
	grid := make([][]byte, m)
	for i := range grid {
		grid[i] = make([]byte, n)
	}

	// До запуска любого луча отмечаем всех охранников и стены.
	// Иначе обзор мог бы пройти сквозь ещё не обработанную преграду.
	// По условию каждая pos содержит два индекса в пределах сетки.
	for _, pos := range guards {
		grid[pos[0]][pos[1]] = blocked
	}

	for _, pos := range walls {
		grid[pos[0]][pos[1]] = blocked
	}

	// Смещения (строка, столбец): вниз, вверх, вправо и влево.
	directions := [4][2]int{
		{1, 0},
		{-1, 0},
		{0, 1},
		{0, -1},
	}

	// Свободную клетку лучи посещают не более 4 раз:
	// с каждой стороны дальнему охраннику перекроет обзор ближний.
	// Поэтому все лучи вместе работают за O(m*n).
	for _, guard := range guards {
		for _, dir := range directions {
			// Начинаем с соседней клетки: сам охранник помечен blocked.
			r := guard[0] + dir[0]
			c := guard[1] + dir[1]

			// && проверяет условия слева направо: grid[r][c] читается,
			// только когда r и c находятся внутри сетки.
			// Только blocked прерывает обзор; guarded не является преградой.
			// Например, луч вправо из (1,0) уже отметил свободную (1,1).
			// Луч вниз из (0,1) всё равно идёт через неё к свободной (2,1).
			for r >= 0 && r < m && c >= 0 && c < n && grid[r][c] != blocked {
				grid[r][c] = guarded
				r += dir[0]
				c += dir[1]
			}
		}
	}

	// После всех лучей empty — ровно те клетки, которые свободны
	// и не видны ни одному охраннику. blocked и guarded не считаем.
	// answer <= m*n <= 10^5, поэтому результат помещается в int.
	answer := 0
	for _, row := range grid {
		for _, cell := range row {
			if cell == empty {
				answer++
			}
		}
	}

	return answer
}
