/*
Дана двумерная матрица размера n x n, представляющая изображение.
Поверните изображение на 90 градусов по часовой стрелке.
Поворот должен выполняться на месте, изменяя входную двумерную матрицу.
Не выделяйте дополнительную двумерную матрицу для поворота.

Пример 1:
https://assets.leetcode.com/uploads/2020/08/28/mat1.jpg
Вход: matrix = [[1,2,3],[4,5,6],[7,8,9]]
Выход: [[7,4,1],[8,5,2],[9,6,3]]

Пример 2:
https://assets.leetcode.com/uploads/2020/08/28/mat2.jpg
Вход: matrix = [[5,1,9,11],[2,4,8,10],[13,3,6,7],[15,14,12,16]]
Выход: [[15,13,2,5],[14,3,4,1],[12,6,8,9],[16,7,10,11]]

Ограничения:
n == matrix.length == matrix[i].length
1 <= n <= 20
-1000 <= matrix[i][j] <= 1000
*/

// rotate поворачивает квадратную матрицу на 90 градусов по часовой стрелке.
// Обрабатывает внешние слои к центру, циклически меняя четыре клетки сторон.
// Время O(n²): каждая клетка слоя участвует в одном цикле переноса.
// Рабочая память O(1); новый результат не выделяется.
// Входная matrix изменяется на месте; центральная клетка нечётного n остаётся.
func rotate(matrix [][]int) {
	// l и r ограничивают текущий слой; внешние слои уже повёрнуты.
	l, r := 0, len(matrix)-1
	for l < r {
		// Обходим сторону без конечного угла: он участвует в другом переносе.
		// При i=0 переносим углы, при остальных i — клетки между углами.
		for i := 0; i < r-l; i++ {
			top, bottom := l, r

			// Сохраняем клетку верхней стороны перед её перезаписью.
			topLeft := matrix[top][l+i]

			// Клетку левой стороны переносим на верхнюю сторону.
            matrix[top][l+i] = matrix[bottom-i][l]

            // Клетку нижней стороны переносим на левую сторону.
            matrix[bottom-i][l] = matrix[bottom][r-i]

            // Клетку правой стороны переносим на нижнюю сторону.
            matrix[bottom][r-i] = matrix[top+i][r]

            // Сохранённую клетку верхней стороны переносим на правую.
            matrix[top+i][r] = topLeft
		}
		// Переходим к следующему внутреннему слою.
		r--
		l++
	}
}
