package main

/*
Дан массив целых чисел размера n.
Найдите все элементы, которые встречаются более ⌊ n/3 ⌋ раз.

Пример 1:
Вход: nums = [3,2,3]
Выход: [3]

Пример 2:
Вход: nums = [1]
Выход: [1]

Пример 3:
Вход: nums = [1,2]
Выход: [1,2]

Ограничения:
1 <= nums.length <= 5 * 10^4
-10^9 <= nums[i] <= 10^9
*/

// majorityElement: модифицированный Бойер-Мур и проверка частот кандидатов.
// n=len(nums): среднее время O(n), int-key map имеет средний поиск O(1).
// k — максимум ключей count: рабочая память O(k); здесь k<=3, то есть O(1).
// Результат содержит не более двух чисел, O(1); nums не меняется.
// Порядок найденных чисел зависит от обхода map.
func majorityElement(nums []int) []int {
	// Этап 1: отбор потенциальных кандидатов (не более 2)
	count := make(map[int]int)

	for _, num := range nums {
		count[num]++

		if len(count) <= 2 {
			continue
		}

		// Третий различный ключ позволяет удалить тройку разных значений:
		// уменьшаем каждый счётчик на 1, остатки 0 не переносим в newCount.
		// Новый ключ пришёл с частотой 1, поэтому после удаления ключей <=2.
		// Если удалено d троек, d<=floor(n/3). Значение с частотой
		// f>floor(n/3) теряет не более d копий, f-d>0: оно останется кандидатом.
		// Обычные кандидаты тоже могут остаться, поэтому нужен второй проход.
		newCount := make(map[int]int)
		for num, c := range count {
			if c > 1 {
				newCount[num] = c - 1
			}
		}
		count = newCount
	}

	// Этап 2: верификация кандидатов за проход по массиву
	// Вместо вложенного цикла считаем частоты всех кандидатов параллельно
	// Три разных ответа невозможны: их суммарная частота превысила бы n.
	// Частоты после удаления троек не равны исходным; считаем их заново.
	threshold := len(nums) / 3
	candidateFreq := make(map[int]int)

	for _, num := range nums {
		// Проверяем, является ли текущий элемент кандидатом
		if _, isCandidate := count[num]; isCandidate {
			candidateFreq[num]++
		}
	}

	// Формируем результат: только элементы, превысившие порог
	result := []int{}
	for candidate, freq := range candidateFreq {
		if freq > threshold {
			result = append(result, candidate)
		}
	}

	return result
}
