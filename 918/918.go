package main

/*
Дан кольцевой целочисленный массив nums длины n.
Верните максимально возможную сумму непустого подмассива nums.

Кольцевой массив означает, что конец массива соединяется с началом массива.
Формально следующий элемент после nums[i] - это nums[(i + 1) % n],
а предыдущий элемент перед nums[i] - это nums[(i - 1 + n) % n].

Подмассив может включать каждый элемент фиксированного массива nums
не более одного раза.
Формально для подмассива nums[i], nums[i + 1], ..., nums[j]
не существует двух разных индексов k1 и k2 в диапазоне [i, j],
для которых k1 % n == k2 % n.

Пример 1:
Вход: nums = [1,-2,3,-2]
Выход: 3
Пояснение: подмассив [3] имеет максимальную сумму 3.

Пример 2:
Вход: nums = [5,-3,5]
Выход: 10
Пояснение: подмассив [5,5] имеет максимальную сумму 5 + 5 = 10.

Пример 3:
Вход: nums = [-3,-2,-3]
Выход: -2
Пояснение: подмассив [-2] имеет максимальную сумму -2.

Ограничения:
n == nums.length
1 <= n <= 3 * 10^4
-3 * 10^4 <= nums[i] <= 3 * 10^4
*/

// maxSubarraySumCircular сравнивает обычный максимум Кадане с дополнением
// минимального линейного отрезка: оставшиеся края образуют кольцевой отрезок.
// Время O(n), n=len(nums); рабочая память и результат int O(1).
// nums не меняется, непуст по условию; суммы до9*10^8 безопасны для int32.
func maxSubarraySumCircular(nums []int) int {
    // globMax и globMin хранят итоговые суммы максимального и минимального
    // подмассивов.
    // Инициализируем их первым элементом массива.
    globMax, globMin := nums[0], nums[0]
    
    // curMax и curMin — текущие промежуточные суммы (используются в алгоритме
    // Кадане).
    // total — сумма всех элементов массива.
    curMax, curMin, total := 0, 0, 0

    for _, num := range nums {
        // Обновляем текущий максимум: либо продлеваем предыдущий подмассив, 
        // либо начинаем новый с текущего числа (классический алгоритм Кадане).
        curMax = max(curMax+num, num)
        
        // Обновляем текущий минимум по тому же принципу.
        curMin = min(curMin+num, num)
        
        // Суммируем все элементы массива.
        total += num
        
        // Обновляем глобальные рекорды.
        globMax = max(globMax, curMax)
        globMin = min(globMin, curMin)
    }

    // globMax <= 0 означает, что все числа неположительные, включая нули.
    // Тогда минимум равен total; дополнение даёт0 и может быть пустым.
    // При одних отрицательных числах0 недопустим: нужен максимум элементов.
    // Возврат globMax покрывает и этот случай, и допустимый ответ0 при нулях.
    if globMax > 0 {
        // Если в массиве есть хотя бы одно положительное число, максимальный
        // подмассив может быть:
        // 1. Обычным непрерывным (globMax).
        // 2. "Зацикленным" (переходящим с конца массива в начало).
        //    Сумма такого зацикленного подмассива равна: 
        //    [Сумма всех элементов] - [Минимальный непрерывный подмассив в
        // середине].
        return max(globMax, total-globMin)
    }
    
    return globMax
}