package main

/*
Последовательность ДНК состоит из нуклеотидов, обозначаемых буквами 'A',
'C', 'G' и 'T'.

Например, "ACGAATTCCG" — последовательность ДНК.
При изучении ДНК полезно находить повторяющиеся фрагменты.

Дана строка s, представляющая последовательность ДНК.
Верните все подстроки длиной 10 символов, которые встречаются в молекуле ДНК
более одного раза.
Ответ можно вернуть в любом порядке.

Пример 1:
Вход: s = "AAAAACCCCCAAAAACCCCCCAAAAAGGGTTT"
Выход: ["AAAAACCCCC","CCCCCAAAAA"]

Пример 2:
Вход: s = "AAAAAAAAAAAAA"
Выход: ["AAAAAAAAAA"]

Ограничения:
1 <= s.length <= 10^5
s[i] имеет значение 'A', 'C', 'G' или 'T'.
*/

// findRepeatedDnaSequences возвращает уникальные фрагменты ДНК длиной 10,
// которые встречаются в s более одного раза; порядок ответа произвольный.
// Время в среднем O(n*10+r) = O(n), n = len(s), r — число повторов:
// хеширование и сравнение ключей стоят O(10), а r <= n.
// Рабочая память O(k) для map, k — число разных окон длиной 10, r <= k.
// k <= min(max(n-9, 0), 4^10); при фиксированных 10 и алфавите это O(1).
// Срез результата хранит O(r) заголовков строк. При непустом ответе они
// удерживают весь исходный буфер s: O(n) байтов, а не только r*10.
// Это общий буфер ключей и ответа, считаем его один раз; s не изменяется.
func findRepeatedDnaSequences(s string) []string {
    // seen отмечает уже встреченные окна, а res хранит только повторы.
    // Ключи map уникальны, поэтому один фрагмент попадёт в ответ лишь раз.
    seen := make(map[string]bool)
    res := make(map[string]bool)

    // Перебираем все начала окна длиной 10, включая перекрывающиеся окна.
    // При len(s) < 10 граница len(s)-9 неположительна и цикл не выполняется.
    for l := 0; l < len(s)-9; l++ {
        // l < len(s)-9 гарантирует l+10 <= len(s). cur — строковый
        // срез без копирования байтов; map сравнивает сами ключи,
        // поэтому коллизии хеша не создают ложных совпадений.
        cur := s[l : l+10]
        // Проверяем seen до отметки текущего окна: первое появление
        // ещё не является повтором, а каждое следующее добавляет cur в res.
        if seen[cur] {
            res[cur] = true
        }
        seen[cur] = true
    }

    // Обход res переносит уникальные повторы в срез в произвольном порядке.
    // Условие задачи разрешает вернуть их в любом порядке.
    result := []string{}
    for k := range res {
        result = append(result, k)
    }
    return result
}