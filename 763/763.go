package main

/*
Вам дана строка s.
Мы хотим разделить строку на как можно большее количество частей, чтобы каждая
буква появлялась не более чем в одной части.
Например, строка "ababcc" может быть разделена на ["abab", "cc"], но такие
разделы, как ["aba", "bcc"] или ["ab", "ab", "cc"] недействительны.
Обратите внимание, что разбиение выполнено так, что после объединения всех
частей по порядку результирующая строка должна быть s.
Верните список целых чисел, представляющих размер этих частей.

Пример 1:
Вход: s = "ababcbacadefegdehijhklij"
Выход: [9,7,8]
Объяснение:
Раздел — «ababcbaca», «defegde», «hijhklij».
Это раздел, в котором каждая буква встречается не более чем в одной части.
Раздел типа «ababcbacadefegde», «hijhklij» неверен, поскольку он разбивает s на
меньшее количество частей.

Пример 2:
Вход: s = "eccbbbbdec"
Выход: [10]

Ограничения:
1 <= s.length <= 500
s состоит из строчных английских букв.
*/

// partitionLabels жадно завершает часть на последнем появлении её букв.
// n — число байтов s, A = 26 — размер алфавита; время O(n+A).
// Рабочая память O(A), при фиксированном A это O(1), а время — O(n).
// Для k частей новый результат занимает O(k), отдельно от рабочей памяти.
// k <= min(n,A): каждая часть содержит свою букву, не встречающуюся в других.
// s не меняется и не копируется; результат хранит длины, а не срезы строки.
func partitionLabels(s string) []int {
    // Защитный ответ для пустой строки, хотя условие требует n >= 1.
    if len(s) == 0 {
        return []int{}
    }

    // ASCII-буквы 'a'..'z' дают индексы 0..25.
    // Повторная запись оставляет именно последнее появление каждой буквы.
    lastIndex := make([]int, 26)
    for i := 0; i < len(s); i++ {
        lastIndex[s[i]-'a'] = i
    }

    res := make([]int, 0)
    // currentLen — уже просмотренная длина текущей части.
    // partitionEnd — самый дальний последний индекс всех её встреченных букв.
    currentLen, partitionEnd := 0, 0

    for i := 0; i < len(s); i++ {
        currentLen++
        
        // Каждая новая буква может продлить обязательный конец части.
        if lastIndex[s[i]-'a'] > partitionEnd {
            partitionEnd = lastIndex[s[i]-'a']
        }

        // Если обязательный конец — конец строки, остаток уже нельзя делить.
        // К просмотренной длине прибавляем ещё partitionEnd-i байтов.
        // Например, для "abca" при i=0: 1+(3-0)=4, дальнейший обход не нужен.
        if partitionEnd == len(s)-1 {
            res = append(res, currentLen + (partitionEnd - i))
            break
        }

        // Все буквы текущей части закончились: это первый допустимый разрез.
        // Самый ранний разрез оставляет максимум возможностей для новых частей.
        if i == partitionEnd {
            res = append(res, currentLen)
            // partitionEnd можно не сбрасывать: следующая буква имеет
            // последний индекс правее завершённой части и обновит его сама.
            currentLen = 0
        }
    }

    return res
}
