package main

/*
Дана строка s чётной длины n с индексацией от 0. Строка содержит ровно
n / 2 открывающих скобок '[' и n / 2 закрывающих скобок ']'.

Строка называется сбалансированной тогда и только тогда, когда выполняется
одно из условий:
- это пустая строка;
- её можно записать как AB, где A и B — сбалансированные строки;
- её можно записать как [C], где C — сбалансированная строка.

Можно сколько угодно раз менять местами скобки в любых двух позициях.

Верните минимальное количество перестановок, необходимое для получения
сбалансированной строки s.

Пример 1:
Ввод: s = "][]["
Вывод: 1
Пояснение: строку можно сделать сбалансированной, поменяв местами скобки
с индексами 0 и 3.
В результате получится строка "[[]]".

Пример 2:
Ввод: s = "]]][[["
Вывод: 2
Пояснение: строку можно сделать сбалансированной следующим образом:
- Поменять местами скобки с индексами 0 и 4. s = "[]][][".
- Поменять местами скобки с индексами 1 и 5. s = "[[][]]".
В результате получится строка "[[][]]".

Пример 3:
Ввод: s = "[]"
Вывод: 0
Пояснение: строка уже сбалансирована.

Ограничения:
n == s.length
2 <= n <= 10^6
n — чётное число.
s[i] равен '[' или ']'.
Количество открывающих скобок '[' равно n / 2, и количество закрывающих
скобок ']' также равно n / 2.
*/

// minSwaps находит максимальный избыток закрывающих скобок в префиксе
// и вычисляет, сколько перестановок нужно для устранения этого дисбаланса.
// Время: O(n), где n = len(s). Дополнительная память: O(1).
func minSwaps(s string) int {
    // close равен разности между количеством ']' и '[' в текущем префиксе,
    // а maxClose хранит наибольшее значение этой разности.
    close, maxClose := 0, 0
    for _, c := range s {
        // Открывающая скобка уменьшает избыток закрывающих, а закрывающая
        // увеличивает его.
        if c == '[' {
            close--
        } else {
            close++
        }

        // Для сбалансированности каждый префикс должен иметь close <= 0,
        // поэтому достаточно запомнить его максимальное положительное значение.
        if close > maxClose {
            maxClose = close
        }
    }

    // Перестановка проблемной ']' с более поздней '[' уменьшает дисбаланс
    // на 2. Равное число скобок гарантирует наличие такой '[', а добавление
    // единицы реализует округление maxClose / 2 вверх.
    return (maxClose + 1) / 2
}