package main

/*
На сетке m x n находится робот.
Изначально робот расположен в верхнем левом углу, в клетке сетка[0][0].
Робот пытается переместиться в правый нижний угол,
то есть в клетку сетка[m - 1][n - 1].
В любой момент робот может двигаться только вниз или вправо.

По двум целым числам m и n верните количество возможных уникальных путей,
по которым робот может добраться до правого нижнего угла.

Тестовые случаи генерируются так, что ответ будет меньше или равен 2 *10^9.

Пример 1:
https://assets.leetcode.com/uploads/2018/10/22/robot_maze.png
Вход: m = 3, n = 7
Выход: 28

Пример 2:
Вход: m = 3, n = 2
Выход: 3
Пояснение: из верхнего левого угла можно попасть в правый нижний угол
тремя способами:
1. Вправо -> Вниз -> Вниз.
2. Вниз -> Вниз -> Вправо.
3. Вниз -> Вправо -> Вниз.

Ограничения:
1 <= m, n <= 100
*/

// uniquePaths считает маршруты как выбор позиций шагов вниз или вправо.
// Время O(min(m,n)), рабочая память и скалярный результат O(1).
// Параметры переставляются только локально, внешних изменений нет.
// Математическое решение через комбинаторику:
// Всего шагов: (m-1) + (n-1) = m+n-2
// Из них нужно выбрать: (m-1) шагов вниз (или (n-1) шагов вправо)
// Формула: C(m+n-2, m-1) = (m+n-2)! / ((m-1)! * (n-1)!)
func uniquePaths(m int, n int) int {
    // Базовый случай: если только одна строка или один столбец,
    // то путь только один (идти всё время прямо).
    if m == 1 || n == 1 {
        return 1
    }

    // Оптимизация: уменьшаем количество итераций цикла.
    // C(n, k) = C(n, n-k), поэтому выбираем минимальное из m и n.
    // Пример: C(8, 2) = C(8, 6), но 2 итерации быстрее, чем 6.
    if m < n {
        m, n = n, m
    }

    // Вычисляем биномиальный коэффициент итеративно:
    // C(m+n-2, n-1) = ∏(i=1..n-1) (m+n-2-i+1) / i
    //
    // res — накапливаемый результат
    // j   — знаменатель (1, 2, 3, ..., n-1)
    // i   — числитель (m, m+1, m+2, ..., m+n-2)
    res, j := 1, 1
    
    // В начале шага i = m+j-1 и res = C(m+j-2,j-1).
    // Тождество C(m+j-1,j) = C(m+j-2,j-1)*(m+j-1)/j
    // даёт res*i/j; деление точное, j начинается с 1.
    // При ограниченном ответе произведение меньше 4*10^11 и помещается
    // в 64-битный int, но на 32-битном int промежуточное переполнение
    // возможно ещё до деления. Сам код эту переносимость не защищает.
    // Выполняем (n-1) итераций
    // Диапазон: от m до (m + n - 2) включительно
    for i := m; i < m+n-1; i++ {
        res *= i  // Умножаем на следующий числитель
        res /= j  // Делим на следующий знаменатель
        j++
    }

    return res
}

