/*
Реализуйте функцию signFunc(x), которая возвращает:
1, если x положителен;
-1, если x отрицателен;
0, если x равен 0.

Дан массив целых чисел nums.
Пусть product — произведение всех элементов массива nums.
Верните signFunc(product).

Пример 1:
Вход: nums = [-1,-2,-3,-4,3,2,1]
Выход: 1
Пояснение: Произведение всех элементов массива равно 144,
поэтому signFunc(144) = 1.

Пример 2:
Вход: nums = [1,5,0,2,-3]
Выход: 0
Пояснение: Произведение всех элементов массива равно 0,
поэтому signFunc(0) = 0.

Пример 3:
Вход: nums = [-1,1,-1,1,-1]
Выход: -1
Пояснение: Произведение всех элементов массива равно -1,
поэтому signFunc(-1) = -1.

Ограничения:
1 <= nums.length <= 1000
-100 <= nums[i] <= 100
*/

// arraySign возвращает знак произведения nums, не вычисляя само произведение:
// ноль даёт 0, иначе знак зависит от чётности отрицательных множителей.
// Время O(n) в худшем случае, где n = len(nums); память O(1).
func arraySign(nums []int) int {
    // neg считает отрицательные числа среди уже просмотренных элементов.
    neg := 0
    for _, num := range nums {
        // Любой нулевой множитель обнуляет всё произведение.
        if num == 0 {
            return 0
        }
        // Каждый отрицательный множитель меняет знак произведения.
        if num < 0 {
            neg++
        }
    }
    // Чётное число смен знака даёт плюс, нечётное — минус.
    // Нулевые множители уже обработаны внутри цикла.
    if neg%2 == 0 {
        return 1
    }
    return -1
}