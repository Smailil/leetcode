package main

/*
Логическое выражение принимает значение true или false.
Допустимы следующие формы:
't' имеет значение true.
'f' имеет значение false.
'!(subExpr)' — логическое НЕ подвыражения subExpr.
'&(subExpr1, subExpr2, ..., subExprn)' — логическое И подвыражений
subExpr1, subExpr2, ..., subExprn, где n >= 1.
'|(subExpr1, subExpr2, ..., subExprn)' — логическое ИЛИ подвыражений
subExpr1, subExpr2, ..., subExprn, где n >= 1.

Дана строка expression, представляющая логическое выражение.
Верните значение этого выражения.

Гарантируется, что выражение корректно и соответствует указанным правилам.

Пример 1:
Ввод:
expression := "&(|(f))"
Вывод: false
Пояснение:
Сначала вычисляем |(f) --> f.
Теперь выражение имеет вид "&(f)".
Затем вычисляем &(f) --> f.
Теперь выражение имеет вид "f".
Возвращаем false.

Пример 2:
Ввод:
expression := "|(f,f,f,t)"
Вывод: true
Пояснение:
Значение выражения (false OR false OR false OR true) равно true.

Пример 3:
Ввод:
expression := "!(&(f,t))"
Вывод: true
Пояснение:
Сначала вычисляем &(f,t) --> (false AND true) --> false --> f.
Теперь выражение имеет вид "!(f)".
Затем вычисляем !(f) --> NOT false --> true.
Возвращаем true.

Ограничения:
1 <= expression.length <= 2 * 10^4
expression[i] — один из символов: '(', ')', '&', '|', '!', 't', 'f', ','.
*/

// parseBoolExpr вычисляет значение корректного логического выражения.
// Стек хранит открытые группы, а закрытые заменяем на 't' или 'f'.
// Время: O(n), каждый символ и результат группы проходят через стек
// не более раза. Дополнительная память: O(n), где n = len(expression).
func parseBoolExpr(expression string) bool {
	stack := []byte{}
	for i := 0; i < len(expression); i++ {
		c := expression[i]
		// Запятые только разделяют аргументы и не влияют на результат.
		if c == ',' {
			continue
		}
		if c != ')' {
			stack = append(stack, c)
			continue
		}
		// Встретили ')': над ближайшей '(' лежат только значения 't'/'f'.
		// Вложенные группы уже вычислены на своих закрывающих скобках.
		// yes отмечает наличие 't', no — наличие 'f'.
		yes, no := false, false
		for stack[len(stack)-1] != '(' {
			v := stack[len(stack)-1]
			stack = stack[:len(stack)-1]
			yes = yes || v == 't'
			no = no || v == 'f'
		}
		// Корректный вход гарантирует, что перед найденной '(' есть оператор.
		stack = stack[:len(stack)-1]
		op := stack[len(stack)-1]
		stack = stack[:len(stack)-1]
		// У '|' нет отдельной ветки: начальное value = yes уже даёт ответ.
		// Для '&' берём !no: ни одного 'f'.
		// У '!' один аргумент, поэтому инвертируем yes.
		value := yes
		switch op {
		case '!':
			value = !yes
		case '&':
			value = !no
		}
		v := byte('f')
		if value {
			v = 't'
		}
		// Заменяем группу её результатом для внешнего выражения.
		// В !(&(f,t)) сначала &(f,t) даёт 'f', затем !(f) даёт 't'.
		stack = append(stack, v)
	}
	// В корректном выражении в конце остаётся ровно одно значение.
	return stack[0] == 't'
}
