package main

import "sort"

/*
Дан целочисленный массив nums длины n, где n кратно 3,
и положительное целое число k.

Разделите nums на n / 3 массивов по 3 элемента так,
чтобы выполнялось следующее условие:
Разница между любыми двумя элементами одного массива не превышает k.
Верните двумерный массив, содержащий полученные массивы.
Если выполнить условия невозможно, верните пустой массив.
Если допустимых ответов несколько, верните любой из них.

Пример 1:
Вход: nums = [1,3,4,8,7,9,3,5,1], k = 2
Выход: [[1,1,3],[3,4,5],[7,8,9]]
Пояснение: разница между любыми двумя элементами каждого массива
не превышает 2.

Пример 2:
Вход: nums = [2,4,2,2,5,2], k = 2
Выход: []
Пояснение: nums можно разделить на 2 массива по 3 элемента так:
[[2,2,2],[2,4,5]] (и их перестановки)
[[2,2,4],[2,2,5]] (и их перестановки)
В nums четыре числа 2, поэтому при любом разбиении один из массивов
будет содержать одновременно 2 и 5.
Так как 5 - 2 = 3 > k, условие не выполняется,
и допустимого разбиения не существует.

Пример 3:
Вход: nums = [4,2,9,8,2,12,7,12,10,5,8,5,5,7,9,2,5,11], k = 14
Выход: [[2,2,2],[4,5,5],[5,5,7],[7,8,8],[9,9,10],[11,12,12]]
Пояснение: разница между любыми двумя элементами каждого массива
не превышает 14.

Ограничения:
n == nums.length
1 <= n <= 10^5
n кратно 3
1 <= nums[i] <= 10^5
1 <= k <= 10^5
*/

// divideArray разбивает nums на тройки с разницей любых двух чисел <= k.
// Сортирует nums на месте и жадно выбирает соседние тройки.
// Если разбиение невозможно, возвращает пустой двумерный массив.
// Время: O(n log n), где n = len(nums).
// При успехе: рабочая память O(log n) на стек sort; результат O(n).
// При отказе res отбрасывается; накопленный буфер может занимать O(n).
func divideArray(nums []int, k int) [][]int {
    // В любом допустимом разбиении можно собрать три наименьших в одну группу.
    // Меняем недостающие из них с числами из группы общего минимума.
    // Вытесненные значения не меньше минимумов принимающих групп,
    // но не больше общего минимума + k: ограничение k там сохраняется.
    // Повторяем этот выбор для остатка: перебор разбиений не требуется.
    sort.Ints(nums)
    res := [][]int{}

    // n кратно 3, а i идёт с шагом 3: последний i равен n-3.
    // Поэтому индексы i+1 и i+2 всегда остаются внутри nums.
    for i := 0; i < len(nums); i += 3 {
        // В отсортированной тройке nums[i] — минимум, nums[i+2] — максимум.
        // Разница любой пары не больше max-min, поэтому проверяем края.
        if nums[i+2]-nums[i] > k {
            // В остатке nums[i:] у тройки с его минимумом nums[i]
            // максимум не может быть меньше nums[i+2].
            // Если даже он слишком далёк, этому минимуму не найти тройку.
            // Жадный выбор выше не теряет решений: разбиение невозможно.
            return [][]int{}
        }

        // Создаём отдельный срез из трёх значений, а не представление nums.
        // Изменение чисел в этой строке результата не изменит входной массив.
        res = append(res, []int{nums[i], nums[i+1], nums[i+2]})
    }

    // Все n/3 троек проверены; каждый элемент nums использован ровно один раз.
    return res
}