package main

import "strings"

/*
Даны строки sentence1 и sentence2, каждая из которых задаёт предложение.
Предложение — список слов, разделённых одиночными пробелами,
без пробелов в начале и конце.
Каждое слово состоит только из прописных и строчных английских букв.

Два предложения s1 и s2 считаются похожими, если в одно из них можно
вставить произвольное предложение (возможно пустое), чтобы они совпали.
Вставленное предложение должно отделяться от существующих слов пробелами.

Например:
s1 = "Hello Jane" и s2 = "Hello my name is Jane" можно сделать одинаковыми,
вставив "my name is" между "Hello" и "Jane" в s1.
s1 = "Frog cool" и s2 = "Frogs are cool" не похожи: вставленный в s1
фрагмент "s are" не отделён от "Frog" пробелом.

Даны два предложения sentence1 и sentence2.
Верните true, если они похожи, иначе верните false.

Пример 1:
Вход: sentence1 = "My name is Haley", sentence2 = "My Haley"
Выход: true
Пояснение:
sentence2 можно превратить в sentence1, вставив "name is"
между "My" и "Haley".

Пример 2:
Вход: sentence1 = "of", sentence2 = "A lot of words"
Выход: false
Пояснение:
Нельзя одной вставкой предложения в одно из исходных предложений
сделать его равным другому.

Пример 3:
Вход: sentence1 = "Eating right now", sentence2 = "Eating"
Выход: true
Пояснение:
sentence2 можно превратить в sentence1, вставив "right now" в конец.

Ограничения:
1 <= sentence1.length, sentence2.length <= 100
Строки sentence1 и sentence2 состоят из строчных и прописных английских букв
и пробелов.
Слова в sentence1 и sentence2 разделены одиночными пробелами.
*/

// areSentencesSimilar проверяет, достаточно ли одной вставки слов,
// чтобы сделать предложения одинаковыми; вставка может быть пустой.
// Ищет общий префикс и суффикс, покрывающие все слова короткого предложения.
// Время: O(m + n), где m = len(sentence1), n = len(sentence2):
// разбиение и сравнение слов учитываются по числу символов.
// Дополнительная память: O(p + q) для срезов, где p и q — числа слов.
// Слова ссылаются на входной текст, сами строки не копируются.
func areSentencesSimilar(sentence1 string, sentence2 string) bool {
	// Сравниваем целые слова, а не части слов: "Frog" не равно "Frogs".
	// Fields разбивает предложения по пробелам, регистр букв сохраняется.
	a, b := strings.Fields(sentence1), strings.Fields(sentence2)
	// После обмена a всегда короче или равно b по числу слов.
	// Это локальная перестановка срезов: входные строки не меняются.
	if len(a) > len(b) {
		a, b = b, a
	}
	left, right := 0, 0
	// left — число общих слов с начала. Так как len(a) <= len(b),
	// проверка left < len(a) защищает оба обращения по индексу.
	for left < len(a) && a[left] == b[left] {
		left++
	}
	// right — число общих слов с конца, без повторного учёта префикса a.
	// Граница len(a)-left не даёт префиксу и суффиксу пересечься,
	// а также сохраняет неотрицательность обоих индексов с конца.
	for right < len(a)-left && a[len(a)-1-right] == b[len(b)-1-right] {
		right++
	}
	// Одна вставка даёт a = префикс + суффикс,
	// b = префикс + вставленные слова + суффикс.
	// Поэтому все слова a должны попасть в найденные совпадающие части.
	// Для ["My","Haley"] и ["My","name","is","Haley"] left=1, right=1:
	// покрыты оба слова a, между ними вставляется "name is".
	// Нулевой префикс или суффикс допускает вставку в начале или конце.
	// При одинаковых предложениях left == len(a): вставлять ничего не надо.
	return left+right == len(a)
}
