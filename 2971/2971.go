package main

import "sort"

/*
Дан массив положительных целых чисел nums длины n.

Многоугольник — замкнутая плоская фигура, у которой не менее 3 сторон.
Длина самой длинной стороны многоугольника меньше суммы длин остальных сторон.

И наоборот, если даны k (k >= 3) положительных действительных чисел
a_1, a_2, a_3, ..., a_k, для которых
a_1 <= a_2 <= a_3 <= ... <= a_k и
a_1 + a_2 + a_3 + ... + a_{k-1} > a_k,
то всегда существует многоугольник с k сторонами длиной
a_1, a_2, a_3, ..., a_k.

Периметр многоугольника — сумма длин его сторон.

Верните максимально возможный периметр многоугольника, длины сторон
которого можно выбрать из nums, или -1, если такой многоугольник построить
невозможно.

Пример 1:
Вход: nums = [5,5,5]
Выход: 15
Пояснение:
Единственный многоугольник, который можно построить из nums, имеет 3 стороны:
5, 5 и 5.
Его периметр равен 5 + 5 + 5 = 15.

Пример 2:
Вход: nums = [1,12,1,2,5,50,3]
Выход: 12
Пояснение:
Многоугольник с наибольшим периметром, который можно построить из nums,
имеет 5 сторон: 1, 1, 2, 3 и 5.
Его периметр равен 1 + 1 + 2 + 3 + 5 = 12.
Нельзя построить многоугольник с самой длинной стороной 12 или 50:
невозможно выбрать хотя бы две более короткие стороны с суммой длин,
превышающей длину выбранной самой длинной стороны.
Можно показать, что максимально возможный периметр равен 12.

Пример 3:
Вход: nums = [5,5,50]
Выход: -1
Пояснение:
Многоугольник построить невозможно: у него должно быть не менее 3 сторон,
а 50 > 5 + 5.

Ограничения:
3 <= n <= 10^5
1 <= nums[i] <= 10^9
*/

// largestPerimeter возвращает наибольший периметр многоугольника или -1.
// После сортировки проверяет префиксы: их последняя сторона — наибольшая.
// Изменяет nums, сортируя его на месте по неубыванию.
// Время: O(n log n), где n = len(nums); после сортировки обход занимает O(n).
// Дополнительная память: O(log n) на стек сортировки; сам обход — O(1).
func largestPerimeter(nums []int) int64 {
    // Для фиксированной наибольшей стороны выгодно взять все предыдущие:
    // они не длиннее неё, а их положительные длины увеличивают и периметр,
    // и сумму остальных сторон. Поэтому достаточно проверять префиксы.
    sort.Ints(nums)
    // Пока допустимый префикс не найден, сохраняем ответ «невозможно».
    var res int64 = -1
    // total — сумма уже пройденных сторон, пока без текущего num.
    // По ограничениям сумма <= 10^5 * 10^9 = 10^14: нужен int64.
    var total int64 = 0

    for _, num := range nums {
        // num — наибольшая сторона, total — сумма всех остальных.
        // Многоугольник существует, только если total > num.
        // При total <= num подмножество предыдущих сторон не поможет:
        // их удаление лишь уменьшит сумму при той же наибольшей стороне.
        // Отдельная проверка числа сторон не нужна: без предыдущих сторон
        // total = 0, а с одной total <= num из-за сортировки.
        if total > int64(num) {
            // Все длины положительны, поэтому сумма префикса растёт.
            // Новый допустимый периметр больше прежнего: max не нужен.
            res = total + int64(num)
        }
        // Добавляем num после проверки, чтобы не учесть его по обе стороны
        // неравенства. Слагаемое приводится к int64 до вычисления суммы.
        // Даже неудачный префикс может стать частью будущего многоугольника:
        // у [1,1,2] сумма 1+1 = 2, но у [1,1,2,3] уже 1+1+2 > 3.
        total += int64(num)
    }

    return res
}