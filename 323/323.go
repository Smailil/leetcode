package main

/*
У вас есть граф из n узлов.
Вам задано целое число n и массив ребер,
где edges[i] = [aᵢ, bᵢ] указывает на то,
что между aᵢ и bᵢ в графе есть ребро.
Возвращайте количество связных компонентов в графе.

Пример 1:
Вход:
n = 5, edges = [[0,1],[1,2],[3,4]]
Выход: 2

Пример 2:
Вход:
n = 5, edges = [[0,1],[1,2],[2,3],[3,4]]
Выход: 1

Ограничения:
1 <= n <= 2000
1 <= edges.length <= 5000
edges[i].length == 2
0 <= aᵢ <= bᵢ < n
aᵢ != bᵢ
Повторяющихся ребер нет.
*/

// countComponents считает запуски DFS из ещё не посещённых вершин.
// E=len(edges): время O(n+E), рабочая память O(n+E) для списков,
// visit и стека; ответ int O(1). edges не меняется.
func countComponents(n int, edges [][]int) int {
    adj := make([][]int, n)
	visit := make([]bool, n)
	// Неориентированное ребро добавляется в оба списка. Индексы валидны
	// по условию, суммарно обходим не более 2*E записей соседей.
	for _, edge := range edges {
		u, v := edge[0], edge[1]
		adj[u] = append(adj[u], v)
		adj[v] = append(adj[v], u)
	}

	var dfs func(int)
	// dfs обходит компоненту; node уже помечен вызывающим кодом.
	// За все вызовы время O(n+E), дополнительный стек O(n).
	// Меняет общий visit, читает adj; исходные edges не меняет.
	dfs = func(node int) {
		for _, nei := range adj[node] {
			// Помечаем соседа до рекурсии: цикл или обратное ребро не вызовут
			// второй обход его списка. Каждую вершину раскрываем один раз.
			if !visit[nei] {
				visit[nei] = true
				dfs(nei)
			}
		}
	}

	res := 0
	for node := 0; node < n; node++ {
		// Непосещённая вершина начинает новую компоненту, включая изолированную.
		// DFS отметит всю компоненту, поэтому другие её вершины res не увеличат.
		if !visit[node] {
			visit[node] = true
			dfs(node)
			res++
		}
	}
	return res
}

