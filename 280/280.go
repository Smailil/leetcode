package main

/*
Дан целочисленный массив nums. Измените порядок его элементов так, чтобы
выполнялось условие:
nums[0] <= nums[1] >= nums[2] <= nums[3]...

Можно считать, что для входного массива всегда существует допустимый ответ.

Пример 1:
Вход: nums = [3,5,2,1,6,4]
Выход: [3,5,1,6,2,4]
Пояснение: ответ [1,6,2,5,3,4] также будет принят.

Пример 2:
Вход: nums = [6,6,5,6,3,8]
Выход: [6,6,5,6,3,8]

Ограничения:
1 <= nums.length <= 5 * 10^4
0 <= nums[i] <= 10^4
Гарантируется, что для заданного входного массива nums существует ответ.
*/

// wiggleSort переставляет элементы среза nums на месте так, чтобы знаки
// между соседями чередовались: <=, >=, <= и так далее.
// Время: O(n), где n = len(nums); дополнительная память: O(1).
func wiggleSort(nums []int) {
    // Перед обработкой i префикс nums[:i] уже удовлетворяет условию.
    // После проверки пары (i-1, i) это будет верно и для nums[:i+1].
    for i := 1; i < len(nums); i++ {
        // На нечётной позиции нужен подъём: nums[i-1] <= nums[i].
        // На чётной нужен спуск: nums[i-1] >= nums[i].
        // Условие ниже проверяет нарушение нужного нестрогого знака.
        if (i%2 == 1 && nums[i] < nums[i-1]) ||
            (i%2 == 0 && nums[i] > nums[i-1]) {
            // Обмен исправляет текущую пару. Если предыдущая пара есть,
            // при нечётном i её правый элемент уменьшается, сохраняя >=;
            // при чётном i увеличивается, сохраняя <=.
            nums[i], nums[i-1] = nums[i-1], nums[i]
        }
    }
}