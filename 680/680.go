package main

/*
Дана строка s.
Верните true, если из строки s можно получить палиндром,
удалив не более одного символа.

Пример 1:
Вход: s = "aba"
Выход: true

Пример 2:
Вход: s = "abca"
Выход: true
Пояснение: можно удалить символ 'c'.

Пример 3:
Вход: s = "abc"
Выход: false

Ограничения:
1 <= s.length <= 10^5
s состоит из строчных букв английского алфавита.
*/

// validPalindrome при первом различии проверяет два остатка без одного края.
// n = len(s): время O(n), рабочая память и результат O(1).
// Два дополнительных прохода остаются линейными; s не изменяется.
func validPalindrome(s string) bool {
	// isPalindrome сверяет замкнутый диапазон [l, r] без новых удалений.
	// Время O(t), t — длина диапазона, рабочая память O(1); читает s.
	// l >= r сразу даёт true, включая пустой остаток.
	isPalindrome := func(l, r int) bool {
		for l < r {
			if s[l] != s[r] {
				return false
			}
			l++
			r--
		}
		return true
	}

	// По контракту байт соответствует английской букве, не части UTF-8.
	// Сравнения l < r гарантируют допустимые индексы внутри строки.
	l, r := 0, len(s)-1

	for l < r {
		// Если символы не совпадают, у нас есть только один шанс исправить строку:
		// удалить либо символ слева, либо символ справа.
		// Пробуем оба варианта через вспомогательную функцию:
		// 1. isPalindrome(l+1, r)  → пропускаем левый символ
		// 2. isPalindrome(l, r-1)  → пропускаем правый символ
		if s[l] != s[r] {
			return isPalindrome(l+1, r) || isPalindrome(l, r-1)
		}
		l++
		r--
	}

	// Если цикл завершился без несовпадений, строка уже является палиндромом.
	return true
}
