package main

/*
Дана строка s из строчных английских букв и двумерный массив целых чисел shifts,
где shifts[i] = [start_i, end_i, direction_i].
Для каждого i сдвиньте символы s с индекса start_i до end_i включительно
вперёд, если direction_i = 1, или назад, если direction_i = 0.

Сдвиг символа вперёд означает замену на следующую букву алфавита
(после 'z' идёт 'a').
Аналогично, сдвиг символа назад означает замену на предыдущую букву алфавита
(перед 'a' идёт 'z').

Верните итоговую строку после применения всех этих сдвигов к s.

Пример 1:
Вход: s = "abc", shifts = [[0,1,0],[1,2,1],[0,2,1]]
Выход: "ace"
Пояснение: Сначала сдвиньте символы с индекса 0 до индекса 1 назад.
Теперь s = "zac".
Затем сдвиньте символы с индекса 1 до индекса 2 вперёд.
Теперь s = "zbd".
Наконец, сдвиньте символы с индекса 0 до индекса 2 вперёд.
Теперь s = "ace".

Пример 2:
Вход: s = "dztz", shifts = [[0,0,0],[1,1,1]]
Выход: "catz"
Пояснение: Сначала сдвиньте символы с индекса 0 до индекса 0 назад.
Теперь s = "cztz".
Наконец, сдвиньте символы с индекса 1 до индекса 1 вперёд.
Теперь s = "catz".

Ограничения:
1 <= s.length, shifts.length <= 5 * 10^4
shifts[i].length == 3
0 <= start_i <= end_i < s.length
0 <= direction_i <= 1
s состоит из строчных английских букв.

*/

// shiftingLetters применяет сдвиги диапазонов через разностный массив.
// Накопленная сумма его элементов даёт общий сдвиг текущего символа.
// Время: O(n + m), где n = len(s), m = len(shifts).
// Рабочая память без результата: O(n); память возвращаемой строки: O(n).
func shiftingLetters(s string, shifts [][]int) string {
    n := len(s)
    // prefixDiff хранит изменения суммарного сдвига на границах диапазонов.
    // Ячейка n нужна для отметки right+1, когда диапазон заканчивается на n-1.
    prefixDiff := make([]int, n+1)

    for _, shift := range shifts {
        left, right, d := shift[0], shift[1], shift[2]
        // По условию d=1 означает сдвиг вперёд, а d=0 — назад.
        val := 1
        if d == 0 {
            val = -1
        }
        // При накоплении суммы val действует с left по right включительно:
        // отметка +val включает сдвиг,
        // а -val после правой границы отменяет его.
        // 0 <= left <= right < n,
        // поэтому оба индекса лежат в массиве длины n+1.
        prefixDiff[left] += val
        prefixDiff[right+1] -= val
    }

    diff := 0
    res := make([]int, n)
    // Строчные английские буквы занимают по одному байту, поэтому len(s)
    // совпадает с числом символов. Представляем буквы номерами от 0 до 25.
    for i := range n {
        res[i] = int(s[i] - 'a')
    }

    // До итерации diff содержит сумму отметок левее i.
    // Сначала учитываем отметки на i: включаем начинающиеся здесь диапазоны
    // и исключаем те, которые закончились на i-1.
    for i := range n {
        diff += prefixDiff[i]
        // Теперь diff — общий сдвиг символа i. В Go (-1)%26 равен -1.
        // diff%26 лежит в [-25,25], а исходный res[i] — в [0,25].
        // Прибавление 26 делает сумму неотрицательной; итоговый %26 даёт 0..25.
        // Например, 'a' со сдвигом -1: (-1 + 0 + 26) % 26 = 25, то есть 'z'.
        res[i] = ((diff%26 + res[i]) + 26) % 26
    }

    // Возвращаем номера 0..25 к ASCII-кодам букв 'a'..'z'.
    // result — отдельный байтовый буфер; исходная строка s не меняется.
    result := make([]byte, n)
    for i := range n {
        result[i] = byte(res[i] + 'a')
    }

    return string(result)
}