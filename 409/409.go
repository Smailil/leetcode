package main

/*
Дана строка s, состоящая из строчных или заглавных букв.
Верните длину самого длинного палиндрома, который можно
составить из этих букв.

Регистр букв имеет значение: например, "Aa" не считается
палиндромом.

Пример 1:
Вход: s = "abccccdd"
Выход: 7
Пояснение: Один из самых длинных палиндромов, которые
можно составить, — "dccaccd" длиной 7.

Пример 2:
Вход: s = "a"
Выход: 1
Пояснение: Самый длинный палиндром, который можно
составить, — "a" длиной 1.

Ограничения:
1 <= s.length <= 2000
s состоит только из строчных и/или заглавных
английских букв.
*/

// longestPalindrome вычисляет максимальную длину палиндрома.
// Битовые маски хранят чётность частот, а каждая готовая
// пара сразу добавляет два символа к ответу.
// Время: O(n), где n = len(s). Дополнительная память: O(1).
func longestPalindrome(s string) int {
    // Регистры учитываются отдельно, но каждая маска занимает
    // лишь 26 битов и помещается в int на всех платформах Go.
    mask1 := 0 // [a - z]
    mask2 := 0 // [A - Z]
    res := 0

    // Установленный бит означает, что буква встретилась нечётное
    // число раз. Повторное появление закрывает пару.
    for _, c := range s {
        if c >= 'a' && c <= 'z' {
            bit := 1 << (c - 'a')
            if mask1&bit != 0 {
                res += 2
            }
            // XOR переключает чётность частоты текущей буквы.
            mask1 ^= bit
        } else {
            bit := 1 << (c - 'A')
            if mask2&bit != 0 {
                res += 2
            }
            mask2 ^= bit
        }
    }

    // Любую оставшуюся непарную букву можно поместить в центр,
    // но для палиндрома подходит только один такой символ.
    if mask1 != 0 || mask2 != 0 {
        return res + 1
    }
    return res
}