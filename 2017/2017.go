package main

/*
Дана двумерная матрица grid размера 2 x n с индексацией с нуля, где
grid[r][c] — количество очков в ячейке (r, c). На этой матрице играют два
робота.

Оба робота начинают в ячейке (0, 0) и стремятся попасть в (1, n-1).
Каждый робот может двигаться только вправо — из (r, c) в (r, c + 1) —
или вниз — из (r, c) в (r + 1, c).

Сначала первый робот проходит путь от (0, 0) до (1, n-1), собирая очки
со всех посещённых ячеек. После его прохода значения grid[r][c] во всех
посещённых им ячейках становятся равны 0. Затем второй робот тоже проходит
от (0, 0) до (1, n-1), собирая очки на своём пути. Пути роботов могут
пересекаться.

Первый робот стремится уменьшить количество очков, которое соберёт второй,
а второй — увеличить его. Если оба играют оптимально, верните количество
очков, собранных вторым роботом.

Пример 1:
https://assets.leetcode.com/uploads/2021/09/08/a1.png
Вход: grid = [[2,5,4],[1,5,1]]
Выход: 4
Пояснение: оптимальный путь первого робота показан красным, а второго — синим.
Значения посещённых первым роботом ячеек становятся равны 0.
Второй робот соберёт 0 + 0 + 4 + 0 = 4 очка.

Пример 2:
https://assets.leetcode.com/uploads/2021/09/08/a2.png
Вход: grid = [[3,3,1],[8,5,2]]
Выход: 4
Пояснение: оптимальный путь первого робота показан красным, а второго — синим.
Значения посещённых первым роботом ячеек становятся равны 0.
Второй робот соберёт 0 + 3 + 1 + 0 = 4 очка.

Пример 3:
https://assets.leetcode.com/uploads/2021/09/08/a3.png
Вход: grid = [[1,3,1,15],[1,3,3,1]]
Выход: 7
Пояснение: оптимальный путь первого робота показан красным, а второго — синим.
Значения посещённых первым роботом ячеек становятся равны 0.
Второй робот соберёт 0 + 1 + 3 + 3 + 0 = 7 очков.

Ограничения:
grid.length == 2
n == grid[r].length
1 <= n <= 5 * 10^4
1 <= grid[r][c] <= 10^5
*/

// gridGame возвращает очки второго робота при оптимальной игре обоих.
// Каждый путь спускается с верхней строки на нижнюю ровно один раз, поэтому
// достаточно перебрать столбец спуска первого робота.
// Время O(n), где n = len(grid[0]); дополнительная память O(1).
func gridGame(grid [][]int) int64 {
	// topSum сначала равна сумме верхней строки. При переборе в ней останутся
	// только клетки справа от столбца спуска первого робота.
	// Сумма может достичь 5 * 10^9, поэтому храним её в int64.
	var topSum int64
	for _, value := range grid[0] {
		topSum += int64(value)
	}

	// bottomSum хранит сумму нижних клеток строго слева от текущего столбца.
	// Исходная сумма верхней строки — верхняя граница для первого кандидата:
	// после вычитания первой клетки он не может быть больше этой суммы.
	var bottomSum int64
	result := topSum

	for col := range grid[0] {
		// Первый робот обнулит верхнюю клетку col, поэтому исключаем её
		// до оценки оставшегося верхнего суффикса.
		topSum -= int64(grid[0][col])

		// Второй робот может собрать либо верхний суффикс, либо нижний
		// префикс, но не оба сразу. Он выбирает максимум, а первый робот
		// минимизирует этот максимум выбором столбца спуска.
		secondScore := max(bottomSum, topSum)
		if secondScore < result {
			result = secondScore
		}

		// Нижняя клетка col войдёт в доступный префикс только при
		// рассмотрении следующего столбца спуска первого робота.
		bottomSum += int64(grid[1][col])
	}

	return result
}
