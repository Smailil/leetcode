package main

/*
Даны два массива строк word1 и word2.
Верните true, если они представляют одну и ту же строку, иначе — false.

Массив представляет строку, если конкатенация его элементов по порядку
образует эту строку.

Пример 1:
Вход: word1 = ["ab", "c"], word2 = ["a", "bc"]
Выход: true
Пояснение:
word1 представляет строку "ab" + "c" -> "abc".
word2 представляет строку "a" + "bc" -> "abc".
Строки совпадают, поэтому возвращаем true.

Пример 2:
Вход: word1 = ["a", "cb"], word2 = ["ab", "c"]
Выход: false

Пример 3:
Вход: word1  = ["abc", "d", "defg"], word2 = ["abcddefg"]
Выход: true

Ограничения:
1 <= word1.length, word2.length <= 10^3
1 <= word1[i].length, word2[i].length <= 10^3
1 <= sum(word1[i].length), sum(word2[i].length) <= 10^3
word1[i] и word2[i] состоят из строчных букв.
*/

// arrayStringsAreEqual сравнивает конкатенации, не создавая общих строк.
// Два указателя проходят фрагменты независимо от мест их разбиения.
// Пусть n и m — суммарные длины строк в word1 и word2 в байтах.
// Время — O(min(n, m)), дополнительная память — O(1).
// Входные массивы и строки не изменяются.
func arrayStringsAreEqual(word1 []string, word2 []string) bool {
	// w1 и w2 выбирают фрагменты, i и j — байты внутри них.
	// По условию все фрагменты непусты, поэтому начальные индексы допустимы.
	w1, w2 := 0, 0
	i, j := 0, 0

	for w1 < len(word1) && w2 < len(word2) {
		// Перед сравнением уже пройденные префиксы равны по длине и содержимому.
		// Индексы указывают на следующие байты: переходы ниже сбрасывают их
		// при исчерпании фрагмента, а условие цикла проверяет границы массивов.
		// Первое несовпадение байтов доказывает различие конкатенаций.
		if word1[w1][i] != word2[w2][j] {
			return false
		}

		i++
		j++

		// Совпавшие байты пройдены; исчерпанные фрагменты сменяем независимо.
		// Для ["ab", "c"] и ["a", "bc"] после первого байта меняется только
		// w2, после второго — только w1, но следующими сравниваются два 'c'.
		if i == len(word1[w1]) {
			w1++
			i = 0
		}
		if j == len(word2[w2]) {
			w2++
			j = 0
		}
	}
	// Равенства просмотренных префиксов недостаточно: остаток в одном массиве
	// означает разную длину строк. Равенство требует исчерпания обоих массивов.
	return w1 == len(word1) && w2 == len(word2)
}