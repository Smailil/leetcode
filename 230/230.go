package main

/*
Дан корень двоичного дерева поиска и целое число k.
Верните k-е наименьшее значение среди значений всех узлов дерева
(нумерация с 1).

Пример 1:
https://assets.leetcode.com/uploads/2021/01/28/kthtree1.jpg
Вход: root = [3,1,4,null,2], k = 1
Выход: 1

Пример 2:
https://assets.leetcode.com/uploads/2021/01/28/kthtree2.jpg
Вход: root = [5,3,6,2,4,null,null,1], k = 3
Выход: 3

Ограничения:
Число узлов в дереве равно n.
1 <= k <= n <= 10^4
0 <= Node.val <= 10^4
*/

type TreeNode struct {
    Val int
    Left *TreeNode
    Right *TreeNode
}

// kthSmallest находит k-й узел симметричного обхода BST итеративным стеком.
// N — число узлов, h — высота: время O(h+k), в худшем O(N).
// Рабочая память O(h), ответ int O(1); дерево не меняется.
// По условию 1<=k<=N, root не nil; k нумерует узлы, не разные значения.
func kthSmallest(root *TreeNode, k int) int {
    stack := make([]*TreeNode, 0)
	// Локальный n считает уже посещённые узлы, а не размер дерева.
	n := 0
	curr := root
	for curr != nil || len(stack) != 0 {
		// Сохраняем путь влево. На вершине окажется следующий по порядку узел;
		// его предки ещё ждут посещения после своих левых поддеревьев.
		for curr != nil {
			stack = append(stack, curr)
			curr = curr.Left
		}
		// Стек непуст: либо внутренний цикл добавил узел, либо внешний цикл
		// был продолжен именно из-за непустого stack при curr=nil.
		curr = stack[len(stack)-1]
		stack = stack[:len(stack)-1]
		n += 1 
		// Inorder дерева поиска перечисляет значения по неубыванию.
		// Поэтому текущий узел после k извлечений содержит нужное значение.
		if n == k {
			return curr.Val
		}
		// Левое поддерево и сам curr пройдены: теперь посещаем правое.
		curr = curr.Right
	}
	// При допустимом k этот путь недостижим: ответ найден до конца обхода.
	return 0
}
