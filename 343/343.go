package main

/*
Дано целое число n.
Разбейте его на сумму k положительных целых чисел,
где k >= 2, и максимизируйте произведение этих чисел.

Верните максимальное произведение, которое можно получить.

Пример 1:
Вход: n = 2
Выход: 1
Пояснение: 2 = 1 + 1, 1 × 1 = 1.

Пример 2:
Вход: n = 10
Выход: 36
Пояснение: 10 = 3 + 3 + 4, 3 × 3 × 4 = 36.

Ограничения:
2 <= n <= 58
*/

import "math"

// integerBreak максимизирует произведение разбиения через двойки и тройки.
// При фиксированном n<=58 время и рабочая память O(1), ответ int O(1).
// Максимальный ответ 4*3^18=1549681956 помещается в int32; n не меняется.
func integerBreak(n int) int {
    // Базовые случаи для малых чисел.
    // По условию задачи число `n` нужно разбить как минимум на 2 положительных
    // целых числа.
    // Для n = 2 лучшее разбиение: 1 + 1, произведение = 1 * 1 = 1.
    // Для n = 3 лучшее разбиение: 1 + 2, произведение = 1 * 2 = 2.
    // В обоих случаях максимальное произведение равно `n - 1`.
    if n <= 3 {
        return n - 1
    }

    // Для n>=4 единицы невыгодны: 1+1 можно объединить в 2, 1+2 — в 3.
    // При x>=3 заменяем 1+x на 2+(x-1): сумма та же, 2*(x-1)>x.
    // Любая часть x>=5 делится на 3+(x-3): сумма x, а 3*(x-3)>x.
    // 4=2+2 без потери, три двойки меняем на две тройки: сумма 6, 9>8.
    // Поэтому остаются тройки и не более двух двоек; n=2/3 уже исключены.
    // count — начальное число троек; при остатке 1 одну позже заменим.
    count := n / 3

    // count<=19, поэтому стоимость math.Pow здесь ограничена константой.
    // math.Pow возвращает float64, а int усечёт его без округления.
    // Точная представимость ответа сама по себе ещё не доказывает точность.
    // В текущей stdlib Go на amd64 целая степень вычисляется умножениями,
    // без Exp/Log. Нормализованные степени 3 до 3^32 имеют числители <2^53,
    // поэтому промежуточные умножения и результат здесь точно представимы.
    // Полученное целое 3^count<=3^19 безопасно переводится в int32.
    res := int(math.Pow(3, float64(count)))

    // Теперь нужно правильно обработать остаток от деления `n` на 3.

    // 1. Если остаток равен 1 (например, n = 4, 7, 10...):
    // Умножать результат на 1 бессмысленно, это не увеличит итоговое значение.
    // Математически выгоднее "забрать" одну тройку из `res` и объединить её с
    // остатком 1,
    // чтобы получить 4.
    // А 4 оптимально разбивать на 2 * 2 (произведение 4).
    // Поэтому мы "откатываем" умножение на одну тройку (делим на 3) и умножаем
    // на 4.
    // 3+1=2+2 сохраняет сумму 4 и улучшает произведение с 3 до 4.
    // count>=1 при n>=4: res кратно 3, целочисленное деление точное.
    if n%3 == 1 {
        return (res / 3) * 4
    }

    // 2. Если остаток равен 0 (n делится на 3 без остатка):
    // Мы уже собрали идеальное произведение, состоящее только из троек, просто
    // возвращаем его.
    if n%3 == 0 {
        return res
    }
    
    // 3. Если остаток равен 2 (например, n = 5, 8, 11...):
    // Двойку разбивать не нужно.
    // Просто умножаем наше произведение троек на оставшуюся двойку.
    // (В этой точке n % 3 гарантированно равно 2).
    return res * 2
}

