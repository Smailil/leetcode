package main

/*
Дана индексируемая с нуля двумерная целочисленная матрица grid размера
n * n со значениями в диапазоне [1, n^2]. Каждое целое число встречается
ровно один раз, за исключением a, которое встречается дважды, и b, которое
отсутствует. Требуется найти повторяющееся и отсутствующее числа a и b.

Верните индексируемый с нуля целочисленный массив ans размера 2, где ans[0]
равно a, а ans[1] равно b.

Пример 1:
Вход: grid = [[1,3],[2,2]]
Выход: [2,4]
Пояснение: число 2 повторяется, а число 4 отсутствует, поэтому ответ — [2,4].

Пример 2:
Вход: grid = [[9,1,7],[8,9,2],[3,4,6]]
Выход: [9,5]
Пояснение: число 9 повторяется, а число 5 отсутствует, поэтому ответ — [9,5].

Ограничения:
2 <= n == grid.length == grid[i].length <= 50
1 <= grid[i][j] <= n * n
Среди всех x, для которых 1 <= x <= n * n, существует ровно одно x,
не равное ни одному элементу grid.
Среди всех x, для которых 1 <= x <= n * n, существует ровно одно x,
которому равны ровно два элемента grid.
Для всех x, для которых 1 <= x <= n * n, кроме двух из них, существует
ровно одна пара i, j, для которой 0 <= i, j <= n - 1 и grid[i][j] == x.

*/

// findMissingAndRepeatedValues находит повторяющееся число a и отсутствующее b.
// Разности фактических и ожидаемых сумм дают две связи: a - b и a + b.
// Время: O(N^2), где N = len(grid); дополнительная память: O(1).
func findMissingAndRepeatedValues(grid [][]int) []int {
    N := len(grid)
    gridSum := 0
    gridSqSum := 0

    // Одновременно накапливаем сумму элементов и сумму их квадратов,
    // чтобы получить две независимые связи между искомыми числами.
    for i := range N {
        for j := range N {
            gridSum += grid[i][j]
            gridSqSum += grid[i][j] * grid[i][j]
        }
    }

    // Для полного набора 1..N^2 известна сумма арифметической прогрессии.
    // Лишнее a и отсутствующее b сдвигают фактическую сумму на a - b.
    totSum := N * N * (N*N + 1) / 2
    diff := gridSum - totSum

    // Разность сумм квадратов равна a^2 - b^2 = (a - b)(a + b).
    // Деление на найденное a - b восстанавливает вторую связь a + b.
    totSqSum := N * N * (N*N + 1) * (2*N*N + 1) / 6
    sqDiff := gridSqSum - totSqSum

    sum := sqDiff / diff

    // Решаем систему diff = a - b и sum = a + b.
    a := (sum + diff) / 2
    b := sum - a

    return []int{a, b}
}