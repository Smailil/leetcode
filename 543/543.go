package main

/*
Дан корень двоичного дерева, верните длину диаметра дерева.
Диаметр двоичного дерева — это длина самого длинного пути
между любыми двумя узлами дерева.
Этот путь может проходить через корень, а может и не проходить.
Длина пути между двумя узлами представлена количеством ребер между ними.

Пример 1:
Вход: root = [1,2,3,4,5]
Выход: 3
Пояснение: 3 — это длина пути [4,2,1,3] или [5,2,1,3].

Пример 2:
Вход: root = [1,2]
Выход: 1

Ограничения:
Количество узлов в дереве находится в диапазоне [1, 10^4].
-100 <= Node.val <= 100
*/

type TreeNode struct {
    Val int
    Left *TreeNode
    Right *TreeNode
}

// diameterOfBinaryTree находит максимальный путь в рёбрах среди всех узлов.
// DFS возвращает высоты ветвей, а отдельный res хранит лучший диаметр.
// Время O(n+1), n — число узлов; рабочая память O(h+1), h — высота дерева.
// Результат int O(1); дерево только читается, новые узлы не создаются.
func diameterOfBinaryTree(root *TreeNode) int {
    res := 0
    var dfs func(*TreeNode) int
    // dfs возвращает высоту поддерева в узлах и обновляет внешнюю res.
    // Для m узлов поддерева время O(m+1); стек O(h+1), результат int O(1).
    // h — высота исходного дерева; curr и его потомки не изменяются.
    dfs = func(curr *TreeNode) int {
        // Пустая ветвь имеет высоту 0; поля nil не разыменовываются.
        if curr == nil {
            return 0
        }
        // Получаем высоты после обработки потомков: их диаметры уже учтены.
        left := dfs(curr.Left)
        right := dfs(curr.Right)
		// left/right считают узлы ниже curr; расстояния от curr равны
		// этим высотам в рёбрах. Путь через curr имеет left+right рёбер.
		// Общий предок любого пути встречается в обходе: берём максимум
		// по всем узлам, а не только путь через исходный root.
		res = max(res, left+right)
        // Родителю нужна одна самая длинная ветвь плюс сам curr,
        // поэтому возвращаем высоту в узлах, а не сумму двух ветвей.
        // Высота не больше 10000, диаметр не больше 9999: int безопасен.
        return max(left, right) + 1
    }
    dfs(root)
    return res
}