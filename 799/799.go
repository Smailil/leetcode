package main

/*
Выкладываем бокалы пирамидой: в первом ряду 1 бокал, во втором — 2,
и так далее до 100-го ряда.
Каждый бокал вмещает одну чашку шампанского.

Затем в верхний бокал наливают шампанское.
Когда он заполняется, лишняя жидкость поровну переливается
в два бокала под ним — слева и справа.
Когда эти бокалы заполняются, избыток шампанского тоже поровну переливается
в бокалы под ними слева и справа, и так далее.
Из бокалов нижнего ряда избыток шампанского выливается на пол.

Например, после одной чашки шампанского верхний бокал полон.
После двух чашек оба бокала второго ряда заполнены наполовину.
После трёх чашек эти два бокала полны: всего теперь 3 полных бокала.
После четырёх чашек средний бокал третьего ряда заполнен наполовину,
а два крайних — на четверть, как показано на рисунке ниже.

https://s3-lc-upload.s3.amazonaws.com/uploads/2018/03/09/tower.png

Налив целое неотрицательное число чашек шампанского, верните
долю заполнения j-го бокала в i-м ряду.
Индексы i и j начинаются с 0.

Пример 1:
Вход: poured = 1, query_row = 1, query_glass = 1
Выход: 0.00000
Пояснение: Мы налили 1 чашку шампанского в верхний бокал пирамиды
(с индексами (0, 0)).
Лишней жидкости нет, поэтому все бокалы под верхним останутся пустыми.

Пример 2:
Вход: poured = 2, query_row = 1, query_glass = 1
Выход: 0.50000
Пояснение: Мы налили 2 чашки шампанского в верхний бокал пирамиды
(с индексами (0, 0)).
Остаётся одна лишняя чашка жидкости.
Бокалы с индексами (1, 0) и (1, 1) делят её поровну:
каждый получает половину чашки шампанского.

Пример 3:
Вход: poured = 100000009, query_row = 33, query_glass = 17
Выход: 1.00000

Ограничения:
0 <= poured <= 10^9
0 <= query_glass <= query_row < 100

*/

// champagneTower возвращает долю заполнения бокала (query_row, query_glass).
// Динамическое программирование: из объёмов одного ряда строим следующий,
// передавая каждому нижнему соседу половину перелива из верхнего бокала.
// Время: O((R + 1)^2), где R = query_row: обходим все бокалы до этого ряда.
// Дополнительная память: O(R + 1), одновременно используются два ряда.
// Память результата: O(1), возвращается одно число.
func champagneTower(poured int, query_row int, query_glass int) float64 {
    // prevRow хранит весь объём, дошедший до каждого бокала ряда,
    // а не только остающийся в нём: значения могут быть больше 1.
    // В верхний бокал поступают все poured чашек шампанского.
    prevRow := []float64{float64(poured)}

    // На входе итерации prevRow описывает ряд row-1, после неё — ряд row.
    // При query_row == 0 цикл не нужен: верхний ряд уже представлен в prevRow.
    for row := 1; row <= query_row; row++ {
        // В ряду row находятся row+1 бокалов; пока в каждый пришло 0 чашек.
        curRow := make([]float64, row+1)
        // В предыдущем ряду row бокалов, поэтому i принимает значения 0..row-1.
        // Оба нижних соседа i и i+1 помещаются в curRow длины row+1.
        for i := range row {
            // Бокал вмещает 1 чашку, поэтому возможный перелив равен
            // prevRow[i] - 1. При extra <= 0 ничего вниз не передаётся.
            extra := prevRow[i] - 1
            if extra > 0 {
                // Перелив делится поровну между левым и правым нижним соседом.
                // Нужен +=: внутренний бокал получает объём от двух родителей.
                // Например, из prevRow = [1.5, 1.5] выйдет [0.25, 0.5, 0.25]:
                // средний бокал получает по 0.25 от каждого родителя.
                curRow[i] += 0.5 * extra
                curRow[i+1] += 0.5 * extra
            }
        }
        // Заменяем ряд только после обработки всех его бокалов:
        // объёмы curRow не должны стать источниками перелива в этой итерации.
        prevRow = curRow
    }

    // prevRow теперь описывает query_row и содержит query_row+1 элементов.
    // По условию 0 <= query_glass <= query_row, поэтому индекс безопасен.
    // Пришедший объём может превышать 1, но доля заполнения — не более 1.
    // Возвращаем min(prevRow[query_glass], 1): неполный бокал или полный.
    if prevRow[query_glass] < 1.0 {
        return prevRow[query_glass]
    }
    return 1.0
}
