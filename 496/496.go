package main

/*
Следующий больший элемент для некоторого элемента x в массиве — это первый
больший элемент, расположенный справа от x в том же массиве.

Даны два целочисленных массива nums1 и nums2 с различными элементами и
индексацией с нуля. Массив nums1 является подмножеством nums2.

Для каждого 0 <= i < nums1.length найдите индекс j, при котором
nums1[i] == nums2[j], и определите следующий больший элемент для nums2[j]
в массиве nums2. Если такого элемента нет, ответом на запрос будет -1.

Верните массив ans длины nums1.length, в котором ans[i] содержит следующий
больший элемент, описанный выше.

Пример 1:
Вход: nums1 = [4,1,2], nums2 = [1,3,4,2]
Выход: [-1,3,-1]
Пояснение: следующие большие элементы для значений nums1:
- Для 4 в nums2 = [1,3,4,2] большего элемента справа нет, поэтому ответ -1.
- Для 1 в nums2 = [1,3,4,2] следующим большим элементом является 3.
- Для 2 в nums2 = [1,3,4,2] большего элемента справа нет, поэтому ответ -1.

Пример 2:
Вход: nums1 = [2,4], nums2 = [1,2,3,4]
Выход: [3,-1]
Пояснение: следующие большие элементы для значений nums1:
- Для 2 в nums2 = [1,2,3,4] следующим большим элементом является 3.
- Для 4 в nums2 = [1,2,3,4] большего элемента справа нет, поэтому ответ -1.

Ограничения:
1 <= nums1.length <= nums2.length <= 1000
0 <= nums1[i], nums2[i] <= 10^4
Все целые числа в nums1 и nums2 различны.
Все целые числа из nums1 также присутствуют в nums2.
*/

// nextGreaterElement возвращает для каждого элемента nums1 первый больший
// элемент справа в nums2 либо -1, если такого элемента нет. Для поиска
// используется один проход по nums2 с монотонно убывающим стеком.
//
// Пусть m = len(nums1), n = len(nums2). Время работы — O(m + n),
// дополнительная память — O(m).
func nextGreaterElement(nums1 []int, nums2 []int) []int {
    // Сопоставляем каждому интересующему значению его позицию в ответе,
    // чтобы при просмотре nums2 сразу записывать найденный больший элемент.
    nums1Idx := make(map[int]int)
    for i, num := range nums1 {
        nums1Idx[num] = i
    }

    // Значение -1 является ответом по умолчанию и сохранится для элементов,
    // справа от которых не встретится ничего большего.
    res := make([]int, len(nums1))
    for i := range res {
        res[i] = -1
    }

    // В стеке лежат уже встреченные значения из nums1, для которых ответ
    // ещё не найден. От основания к вершине они идут в убывающем порядке.
    stack := []int{}
    for _, num := range nums2 {
        // При движении слева направо num становится первым большим элементом
        // справа для всех меньших значений на вершине стека.
        for len(stack) > 0 && num > stack[len(stack)-1] {
            val := stack[len(stack)-1]
            stack = stack[:len(stack)-1]
            idx := nums1Idx[val]
            res[idx] = num
        }
        // В стек добавляем только элементы из nums1: остальные нужны лишь
        // как возможные следующие большие значения.
        if _, ok := nums1Idx[num]; ok {
            stack = append(stack, num)
        }
    }

    return res
}