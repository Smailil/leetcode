package main

/*
Дана строка s.
Разбейте s так, чтобы каждая подстрока разбиения была палиндромом.
Верните все возможные палиндромные разбиения s.

Пример 1:
Вход: s = "aab"
Выход: [["a","a","b"],["aa","b"]]

Пример 2:
Вход: s = "a"
Выход: [["a"]]

Ограничения:
1 <= s.length <= 16
s содержит только строчные английские буквы.
*/

// isPal задумана как проверка палиндрома двумя указателями, но содержит
// исходный дефект: j=len(s), хотя последний индекс равен len(s)-1.
// Для непустого s первое s[j] вызывает panic; пустая строка даёт true.
// Фактически до возврата/panic: время O(1), память O(1); s не меняется.
func isPal(s string) bool {
	// j находится за концом строки. Эту ошибку комментарии не исправляют.
	i, j := 0, len(s)
	for i < j {
		if s[i] != s[j] {
			return false
		}
		i++
		j--
	}
	return true
}

// partition содержит каркас DFS палиндромных разбиений, но на любом
// допустимом входе n=len(s)>=1 вызывает panic в первом isPal(s[0:1]).
// До panic: время O(n) с учётом выделения part и рабочая память O(n);
// результат не возвращается. s не меняется. Пустой вход вне условия
// дошёл бы до базовой ветки и вернул одно пустое разбиение.
func partition(s string) [][]string {
    res := make([][]string, 0)
	// part предназначен для текущего разбиения; резервируем n заголовков строк.
	// На допустимом входе panic произойдёт до первого добавления в part.
	part := make([]string, 0, len(s))
	var dfs func(int)
	// dfs рассматривает суффикс с позиции i и использует общий part/res.
	// При i>=n, k=len(part): копирование занимает O(k) времени и O(k) ответа.
	// При фактическом i=0<n: до panic O(1) времени и O(1) стека.
	// Базовая ветка меняет res; до panic part не меняется.
	dfs = func(i int) {
		// Копия отделяет заголовки строк результата от изменяемого part.
		// Строки ссылаются на s; сама эта ветка на допустимом входе недостижима.
		if i >= len(s) {
			cPart := make([]string, len(part))
			copy(cPart, part)
			res = append(res, cPart)
			return 
		}
		// Каркас перебирает концы непустого фрагмента s[i:j+1].
		// При 0<=i<=j<n индекс j+1<=n допустим; сбой находится внутри isPal,
		// а не в этом срезе. До добавления/рекурсии/отката выполнение не дойдёт.
		for j := i; j < len(s); j++ {
			if p := s[i:j+1] ; isPal(p) {
				part = append(part, p)
				dfs(j+1)
				part = part[:len(part)-1]
			}
		}
	}
	dfs(0)
	return res
}
