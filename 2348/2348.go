package main

/*
Дан целочисленный массив nums.
Верните число подмассивов, состоящих только из 0.

Подмассив — это непустая непрерывная последовательность элементов массива.

Пример 1:
Вход: nums = [1,3,0,0,2,0,0,4]
Выход: 6
Пояснение:
Подмассив [0] встречается 4 раза.
Подмассив [0,0] встречается 2 раза.
Подмассивов длиной больше 2, состоящих только из 0, нет.
Поэтому возвращаем 6.

Пример 2:
Вход: nums = [0,0,0,2,0,0]
Выход: 9
Пояснение:
Подмассив [0] встречается 5 раз.
Подмассив [0,0] встречается 3 раза.
Подмассив [0,0,0] встречается 1 раз.
Подмассивов длиной больше 3, состоящих только из 0, нет.
Поэтому возвращаем 9.

Пример 3:
Вход: nums = [2,10,2019]
Выход: 0
Пояснение: Подмассивов, состоящих только из 0, нет.
Поэтому возвращаем 0.

Ограничения:
1 <= nums.length <= 10^5
-10^9 <= nums[i] <= 10^9

*/

// zeroFilledSubarray считает непустые подмассивы, состоящие только из нулей.
// За один проход суммирует их количество для каждого правого конца.
// Время: O(n), где n = len(nums). Дополнительная память: O(1).
func zeroFilledSubarray(nums []int) int64 {
    // res накапливает ответ. Для n нулей он равен n*(n+1)/2.
    // При n = 10^5 это 5 000 050 000: для ответа нужен int64.
    var res int64 = 0
    // count — длина нулевого суффикса уже просмотренной части nums.
    // Она не больше n <= 10^5, поэтому помещается даже в 32-битный int.
    count := 0

    for _, num := range nums {
        if num == 0 {
            // Текущий ноль продлевает нулевой суффикс на один элемент.
            count++
        } else {
            // Ненулевое значение разрывает серию: нулевой подмассив
            // не может заканчиваться здесь, поэтому вклад равен нулю.
            count = 0
        }
        // Если count = k, здесь заканчиваются k нулевых подмассивов:
        // их длины — от 1 до k, и каждому соответствует своё начало.
        // Для серии [0, 0, 0] прибавляем 1, затем 2, затем 3: всего 6.
        // У подмассива один правый конец, поэтому повторного подсчёта нет.
        // Приводим count к int64 перед накоплением большого ответа.
        res += int64(count)
    }

    return res
}
