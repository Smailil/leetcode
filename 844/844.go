package main

/*
Даны две строки s и t.
Верните true, если результаты их ввода в пустые текстовые редакторы совпадают.
Символ '#' означает удаление предыдущего символа (Backspace).

Удаление символа в пустом тексте оставляет текст пустым.

Пример 1:
Вход: s = "ab#c", t = "ad#c"
Выход: true
Пояснение: обе строки s и t превращаются в "ac".

Пример 2:
Вход: s = "ab##", t = "c#d#"
Выход: true
Пояснение: обе строки s и t превращаются в "".

Пример 3:
Вход: s = "a#c", t = "b"
Выход: false
Пояснение: s превращается в "c", а t — в "b".

Ограничения:
1 <= s.length, t.length <= 200
s и t содержат только строчные буквы и символы '#'.
*/

// backspaceCompare сравнивает результаты ввода s и t с учётом '#'.
// Обходит строки справа налево и сопоставляет только неудалённые байты,
// не создавая отредактированные строки.
// Время: O(n + m), n = len(s), m = len(t) — длины строк в байтах.
// Оба индекса только уменьшаются: вложенные циклы не обходят строки заново.
// Дополнительная память: O(1); исходные строки не изменяются.
func backspaceCompare(s string, t string) bool {
	// nextValidChar ищет справа следующий неудалённый байт str.
	// Возвращает его индекс либо отрицательное значение, если байтов нет.
	// Время: O(k + 1), k — число пропущенных байтов; память: O(1).
	nextValidChar := func(str string, index int) int {
		// backspace — сколько обычных байтов слева ещё нужно удалить.
		// Счётчик не больше числа '#' в str: по условию их не более 200.
		backspace := 0
		// index начинается не дальше конца str и только уменьшается.
		// Условие index >= 0 защищает чтение str[index].
		// В "ab##c" после сравнения 'c': '#' -> 1, '#' -> 2,
		// 'b' -> 1, 'a' -> 0; слева не остаётся символов.
		for index >= 0 {
			if str[index] == '#' {
				// Каждый '#' добавляет ещё одно незавершённое удаление.
				backspace++
			} else if backspace > 0 {
				// Этот байт удалён одним из '#' справа: не сравниваем его.
				backspace--
			} else {
				// Этот байт сохранился, а все удаления справа уже учтены.
				// Поэтому следующий вызов может начать счётчик с нуля.
				break
			}
			index--
		}
		// Если дошли за начало str, лишние '#' не меняют пустой текст.
		return index
	}

	// Для латинских букв байт соответствует символу. Такой побайтовый
	// обход не рассчитан на произвольные многобайтовые символы UTF-8.
	indexS, indexT := len(s)-1, len(t)-1

	// Нужен ||: остаток одной строки тоже проверяется. Иначе можно
	// пропустить лишнюю неудалённую букву после исчерпания другой строки.
	for indexS >= 0 || indexT >= 0 {
		indexS = nextValidChar(s, indexS)
		indexT = nextValidChar(t, indexT)

		// Байт 0 обозначает отсутствие следующего символа. Во входе его
		// нет: допустимы только буквы и '#'. Отрицательные индексы
		// не используются для чтения строк благодаря проверкам ниже.
		var charS, charT byte = 0, 0
		if indexS >= 0 {
			charS = s[indexS]
		}
		if indexT >= 0 {
			charT = t[indexT]
		}

		// Разные байты или символ только в одной строке означают неравенство.
		if charS != charT {
			return false
		}

		// Совпавшие байты обработаны; следующая проверка начнётся левее.
		// У исчерпанной строки индекс просто остаётся отрицательным.
		indexS--
		indexT--
	}

	// Обе строки исчерпаны с учётом удалений, все сохранённые байты совпали.
	return true
}