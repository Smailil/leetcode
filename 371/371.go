package main

/*
Даны два целых числа a и b.
Верните сумму двух целых чисел без использования операторов + и -.

Пример 1:
Вход: a = 1, b = 2
Выход: 3

Пример 2:
Вход: a = 2, b = 3
Выход: 5

Ограничения:
-1000 <= a, b <= 1000
*/

// getSum складывает числа XOR-суммой и переносами в 32-битном слове.
// На каждой итерации a — сумма без переноса, b — ещё не добавленные переносы.
// Время O(1): перенос смещается влево, итераций не больше фиксированных 32.
// Рабочая память и результат O(1); аргументы меняются только локально.
// Маска 0xFFFFFFFF в int требует 64-битного Go; на 32-битном не компилируется.
func getSum(a int, b int) int {
    mask := 0xFFFFFFFF   // Маска 32 бит:
    // Эмулирует переполнение 32-битного беззнакового слова по модулю 2^32.
    maxInt := 0x7FFFFFFF // Макс. положительное 32-битное знаковое число

    // Тождество a+b=(a XOR b)+2*(a AND b) отделяет сумму от переноса.
    // Маска отбрасывает биты выше 31; перенос не может вернуться вправо.
    for b != 0 {
        carry := (a & b) << 1  // Биты переноса
        a = (a ^ b) & mask     // Сумма без переноса, обрезка до 32 бит
        b = carry & mask       // Перенос, обрезка до 32 бит
    }

    if a <= maxInt {
        return a  // Неотрицательное: бит 31 = 0
    }
    // Здесь a — 32-битное слово с единицей знака, но положительный Go int.
    // a XOR mask = (2^32-1)-a; полный NOT даёт a-2^32 — нужное отрицательное.
    // Сумма исходных чисел в [-2000,2000], поэтому восстановление точное.
    return ^(a ^ mask)  // Отрицательное: конвертация
    // из 32-битного дополнительного кода в Go int
}