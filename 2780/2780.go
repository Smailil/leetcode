package main

/*
Элемент x целочисленного массива arr длины m называется доминирующим, если
более половины элементов arr равны x.

Дан целочисленный массив nums длины n с индексацией с нуля, содержащий ровно
один доминирующий элемент.

Массив nums можно разделить по индексу i на два массива nums[0, ..., i] и
nums[i + 1, ..., n - 1], но разделение считается допустимым, только если:

0 <= i < n - 1
nums[0, ..., i] и nums[i + 1, ..., n - 1] имеют один и тот же доминирующий
элемент.

Здесь nums[i, ..., j] обозначает подмассив nums, который начинается с индекса i
и заканчивается индексом j включительно. В частности, если j < i, то
nums[i, ..., j] обозначает пустой подмассив.

Верните минимальный индекс допустимого разделения. Если допустимого разделения
не существует, верните -1.

Пример 1:
Вход: nums = [1,2,2,2]
Выход: 2
Пояснение: Можно разделить массив по индексу 2 и получить массивы [1,2,2] и
[2].
В массиве [1,2,2] элемент 2 является доминирующим, поскольку встречается два
раза и 2 * 2 > 3.
В массиве [2] элемент 2 является доминирующим, поскольку встречается один раз
и 1 * 2 > 1.
Массивы [1,2,2] и [2] имеют тот же доминирующий элемент, что и nums, поэтому
такое разделение допустимо.
Можно показать, что индекс 2 — минимальный индекс допустимого разделения.

Пример 2:
Вход: nums = [2,1,3,1,1,1,7,1,2,1]
Выход: 4
Пояснение: Можно разделить массив по индексу 4 и получить массивы [2,1,3,1,1]
и [1,7,1,2,1].
В массиве [2,1,3,1,1] элемент 1 является доминирующим, поскольку встречается
три раза и 3 * 2 > 5.
В массиве [1,7,1,2,1] элемент 1 является доминирующим, поскольку встречается
три раза и 3 * 2 > 5.
Оба массива имеют тот же доминирующий элемент, что и nums, поэтому такое
разделение допустимо.
Можно показать, что индекс 4 — минимальный индекс допустимого разделения.

Пример 3:
Вход: nums = [3,3,3,3,7,2,2]
Выход: -1
Пояснение: Можно показать, что допустимого разделения не существует.

Ограничения:
1 <= nums.length <= 10^5
1 <= nums[i] <= 10^9
Массив nums содержит ровно один доминирующий элемент.
*/

// minimumIndex возвращает минимальную границу, по которой обе части nums
// сохраняют один и тот же доминирующий элемент, либо -1, если её нет.
// Голосование Бойера — Мура находит кандидата, а два следующих прохода
// проверяют его количество по обе стороны каждой границы.
// Время работы — O(n), где n = len(nums); дополнительная память — O(1).
// Срез nums не изменяется.
func minimumIndex(nums []int) int {
    // В голосовании одинаковые элементы усиливают кандидата, а остальные
    // взаимно сокращаются с ним. Гарантия задачи оставляет победителем
    // единственный доминирующий элемент.
    majority, count := 0, 0
    for _, num := range nums {
        if count == 0 {
            majority = num
        }
        if num == majority {
            count++
        } else {
            count--
        }
    }

    // До выбора границы весь массив считается правой частью. Подсчитываем в
    // ней кандидата, чтобы затем обновлять обе части за O(1) на каждом шаге.
    leftCnt, rightCnt := 0, 0
    for _, num := range nums {
        if num == majority {
            rightCnt++
        }
    }

    n := len(nums)
    for i := range n {
        // Переносим текущий элемент через границу из правой части в левую.
        if nums[i] == majority {
            leftCnt++
            rightCnt--
        }

        leftLen := i + 1
        rightLen := n - i - 1

        // Неравенство 2 * count > length проверяет строгое большинство без
        // деления. При n <= 10^5 удвоенные счётчики безопасны для int.
        // На последнем индексе правая часть пуста, поэтому условие для неё
        // автоматически ложно и недопустимая граница не будет возвращена.
        if 2*leftCnt > leftLen && 2*rightCnt > rightLen {
            return i
        }
    }

    // Ни одна граница не сохранила доминирование кандидата в обеих частях.
    return -1
}