package main

/*
Дана строка s. Верните длину самой длинной подстроки между
двумя одинаковыми символами, не включая эти два символа.
Если такой подстроки нет, верните -1.

Подстрока — это непрерывная последовательность символов в строке.

Пример 1:
Вход: s = "aa"
Выход: 0
Пояснение: Оптимальная подстрока — это пустая подстрока
между двумя символами 'a'.

Пример 2:
Вход: s = "abca"
Выход: 2
Пояснение: Оптимальная подстрока — "bc".

Пример 3:
Вход: s = "cbzxy"
Выход: -1
Пояснение: В строке s нет символов, которые встречаются дважды.

Ограничения:
1 <= s.length <= 300
s содержит только строчные английские буквы.
*/

// maxLengthBetweenEqualCharacters находит максимальное число
// символов между двумя одинаковыми буквами. Для каждой буквы
// хранится самая ранняя позиция, дающая наибольшее расстояние.
// Время: O(n), где n = len(s), при среднем O(1) для операции map.
// Память: O(k), где k — число разных букв; при k <= 26 это O(1).
func maxLengthBetweenEqualCharacters(s string) int {
    // Инвариант: charIndex хранит только первую позицию буквы,
    // а res остаётся -1, пока не найдена ни одна пара.
    charIndex := make(map[byte]int)
    res := -1

    // По условию s содержит только ASCII-буквы, поэтому байтовый
    // индекс i совпадает с позицией символа.
    for i := 0; i < len(s); i++ {
        c := s[i]
        if idx, ok := charIndex[c]; ok {
            // Вычитание 1 исключает из длины обе граничные буквы.
            // Первый idx даёт максимальную длину для текущего i.
            if i-idx-1 > res {
                res = i - idx - 1
            }
        } else {
            // Не перезаписываем индекс: будущие повторы должны
            // измеряться от самого раннего вхождения.
            charIndex[c] = i
        }
    }

    return res
}
