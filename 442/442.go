package main

/*
Дан целочисленный массив nums длины n, все элементы которого находятся
в диапазоне [1, n], а каждое число встречается не более двух раз.
Верните массив всех чисел, которые встречаются дважды.

Нужно написать алгоритм, который работает за время O(n) и использует
постоянную дополнительную память, не считая памяти для результата.

Пример 1:
Вход: nums = [4,3,2,7,8,2,3,1]
Выход: [2,3]

Пример 2:
Вход: nums = [1,1,2]
Выход: [1]

Пример 3:
Вход: nums = [1]
Выход: []

Ограничения:
n == nums.length
1 <= n <= 10^5
1 <= nums[i] <= n
Каждый элемент nums встречается один или два раза.
*/

// findDuplicates возвращает числа, встречающиеся в nums дважды.
// Отмечает встреченные значения знаками элементов исходного массива.
// Изменяет знаки в nums; исходные знаки перед возвратом не восстанавливает.
// Время: O(n), где n = len(nums); append учитывается амортизированно.
// Рабочая память: O(1) без результата; память результата: O(k).
// Здесь k — число различных дублей, k <= n/2.
func findDuplicates(nums []int) []int {
    // В res добавляем число при втором появлении, а не при первом.
    res := []int{}

    for _, num := range nums {
        // range читает текущее значение: ранее оно могло сменить знак.
        // Модуль восстанавливает исходное число x = abs(num).
        // 1 <= x <= n, поэтому индекс x-1 лежит в пределах [0, n-1].
        idx := abs(num) - 1
        // Знак nums[x-1] хранит историю x, не значения в этой ячейке.
        // Изначально все числа положительны; минус означает, что x
        // уже встретился один раз. Текущая встреча тогда вторая.
        if nums[idx] < 0 {
            // num мог стать отрицательным из-за отметки другого числа.
            // В результат добавляем исходное положительное значение.
            res = append(res, abs(num))
        }
        // При первом появлении x ставим минус, при втором возвращаем плюс.
        // Третьего появления по условию нет, поэтому дубль не теряется.
        // Для [2,2]: сначала nums = [2,-2]; затем num = -2, abs(num) = 2.
        // Добавляем 2 в res и возвращаем знак: nums снова равен [2,2].
        nums[idx] = -nums[idx]
    }

    return res
}

// abs возвращает |x| при условии, что x не равен минимальному int.
// При вызовах из findDuplicates |x| <= 10^5: отрицание безопасно.
// Время: O(1). Дополнительная память: O(1).
func abs(x int) int {
    if x < 0 {
        return -x
    }
    return x
}