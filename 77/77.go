package main

/*
Даны два целых числа n и k.
Верни все возможные комбинации из k чисел, выбранных из диапазона [1, n].

Ответ можно вернуть в любом порядке.

Пример 1:
Вход: n = 4, k = 2
Выход: [[1,2],[1,3],[1,4],[2,3],[2,4],[3,4]]
Пояснение: Из 4 выбрать 2 = 6 комбинаций всего.
Комбинации неупорядочены, то есть [1,2] и [2,1]
считаются одной и той же комбинацией.

Пример 2:
Вход: n = 1, k = 1
Выход: [[1]]
Пояснение: Из 1 выбрать 1 = 1 комбинация всего.

Ограничения:
1 <= n <= 20
1 <= k <= n
*/

// combine перечисляет возрастающие k-подмножества диапазона 1..n.
// R = C(n,k), T = сумма C(n,d) по d от 0 до k: время O(k*T + k*R).
// Это верхняя оценка с O(k) копирования при append и копированием ответов.
// Отсечения невозможных префиксов нет: при k=n обходится 2^n префиксов,
// хотя ответ один. Рабочая память O(k), результат O(k*R).
// Параметры n/k не меняются; каждую комбинацию копируем отдельно.
func combine(n int, k int) [][]int {
    // Инициализируем пустой срез для хранения всех найденных комбинаций
    res := [][]int{}

    var backtrack func(start int, comb []int)
    // backtrack достраивает возрастающий comb числами от start до n.
    // Для u = n-start+1, t = k-len(comb), R' = C(u,t):
    // время O(k*T' + k*R'), T' — сумма C(u,d) по d от 0 до t.
    // O(k) на шаг покрывает возможное выделение/копирование буфера append.
    // C(u,d)=0 при d>u. Рабочая память O(k), новые ответы O(k*R').
    // append меняет буфер comb, длина откатывается; res пополняется копиями.
    backtrack = func(start int, comb []int) {
        // Базовый случай: если длина комбинации достигла k,
        // сохраняем её в результат
        if len(comb) == k {
            // Создаем копию текущей комбинации, чтобы сохранить её состояние
            // Без копирования ответы могли бы разделять буфер comb,
            // который следующие append перезапишут при переборе других ветвей.
            temp := make([]int, len(comb))
            copy(temp, comb)
            res = append(res, temp)
            return
        }

        // Перебираем все числа от start до n, даже если оставшихся чисел
        // недостаточно для k позиций: такие ветви просто иссякнут.
        for i := start; i <= n; i++ {
            // Добавляем текущее число в комбинацию
            comb = append(comb, i)
            
            // Рекурсивно строим комбинацию дальше, начиная с числа i+1
            // Это гарантирует, что числа в комбинации не повторяются
            // и идут по возрастанию
            backtrack(i+1, comb)
            
            // Откат: удаляем последнее добавленное число,
            // чтобы попробовать другие варианты на этой позиции
            // После нашего append длина положительна: len(comb)-1 безопасно.
            comb = comb[:len(comb)-1]
        }
    }

    // Запускаем поиск с возвратом с начального числа 1 и пустой комбинации
    backtrack(1, []int{})
    
    // Возвращаем все найденные комбинации
    return res
}