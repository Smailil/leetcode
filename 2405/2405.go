package main

/*
Дана строка s.
Разбейте её на одну или несколько подстрок так, чтобы все символы
в каждой подстроке были уникальными.
То есть ни одна буква не должна встречаться в одной подстроке более одного раза.

Верните минимальное число подстрок в таком разбиении.

Каждый символ должен принадлежать ровно одной подстроке разбиения.

Пример 1:
Вход: s = "abacaba"
Выход: 4
Пояснение:
Два возможных разбиения: ("a","ba","cab","a") и ("ab","a","ca","ba").
Можно показать, что 4 — минимальное необходимое число подстрок.

Пример 2:
Вход: s = "ssssss"
Выход: 6
Пояснение:
Единственное допустимое разбиение: ("s","s","s","s","s","s").

Ограничения:
1 <= s.length <= 10^5
s состоит только из строчных букв английского алфавита.
*/

// partitionString возвращает минимальное число подстрок без повторов букв.
// Жадно продолжаем текущую подстроку до первого повтора; затем начинаем новую.
// Время: O(n), где n = len(s): каждый символ обрабатывается один раз.
// Дополнительная память: O(1): 26 букв помещаются в одну битовую маску.
func partitionString(s string) int {
    // По условию s непустая, поэтому нужна хотя бы одна подстрока.
    // res считает подстроки, включая текущую; mask хранит её набор букв.
    // Вначале ни одной буквы ещё не обработали, поэтому mask равна нулю.
    res, mask := 1, 0
    for _, c := range s {
        // Буквы 'a'..'z' соответствуют битам 0..25: 'a' -> 0, 'b' -> 1.
        // 1 << i создаёт маску только этой буквы: для 'b' это двоичное 10.
        // По ограничению i находится в пределах 0..25, сдвиг помещается в int.
        i := int(c - 'a')
        // Побитовое И ненулевое, если бит этой буквы уже установлен в mask.
        // Например, после "ab" mask = 11; новая 'a' даёт 11 & 01 = 01.
        if mask&(1<<i) != 0 {
            // Повтор нельзя добавить в текущую подстроку: нужен разрез.
            // Делаем его прямо перед повтором, а не раньше.
            // Если сдвинуть более ранний разрез сюда, подстроки остатка
            // только укоротятся или исчезнут: уникальность не нарушится,
            // а их число не увеличится. Поэтому ранний разрез не выгоднее.
            // Сбрасываем набор букв и учитываем новую подстроку.
            mask = 0
            res++
        }
        // Устанавливаем бит текущей буквы в выбранной подстроке.
        // После сброса она становится первой буквой новой подстроки;
        // без сброса добавляется к буквам, которые уже были в текущей.
        mask |= 1 << i
    }
    // Каждый повтор открыл новую подстроку; res уже учитывает и последнюю.
    return res
}