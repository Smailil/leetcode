package main

/*
Даны n неотрицательных целых чисел, представляющих карту высот,
где ширина каждой полосы равна 1.
Вычислите, сколько воды она может удержать после дождя.

Пример 1:
https://assets.leetcode.com/uploads/2018/10/22/rainwatertrap.png
Вход: height = [0,1,0,2,1,0,1,3,2,1,2,1]
Выход: 6
Пояснение: Приведённая выше карта высот (чёрная секция)
представлена массивом [0,1,0,2,1,0,1,3,2,1,2,1].
В данном случае задерживается 6 единиц дождевой воды (синяя секция).

Пример 2:
Вход: height = [4,2,0,3,2,5]
Выход: 9

Ограничения:
n == height.length
1 <= n <= 2 * 10^4
0 <= height[i] <= 10^5
*/

// trap считает воду двумя указателями и максимумами с пройденных краёв.
// Обрабатываем меньший максимум: другая сторона даёт достаточную стенку.
// Время O(n), n = len(height); рабочая память и скалярный ответ O(1).
// height не меняется; сумма<=n*10^5<=2*10^9 помещается в int.
func trap(height []int) int {
	res := 0
	// Проверка защищает доступ к крайним высотам даже при пустом входе.
	if len(height) != 0 {
    	l, r := 0, len(height) - 1
		maxL, maxR := height[l], height[r]
		// maxL/maxR — максимумы пройденных частей с двух концов.
		// На каждом шаге сдвигается граница до встречи указателей.
		for l < r {
			if maxL < maxR {
				l++
				// Для более низкой стенки вода равна maxL-height[l].
				// Более высокая даёт 0 и станет новым maxL ниже.
				res += max(0, maxL-height[l])
				maxL = max(maxL, height[l])
			} else {
				// Симметрично справа, включая случай равных максимумов.
				r--
				res += max(0, maxR-height[r])
				maxR = max(maxR, height[r])
			}
		}
	}
	return res
}
