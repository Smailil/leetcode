package main

/*
Дан массив непересекающихся интервалов, где intervals[i] = [start_i, end_i]
представляет начало и конец i-го интервала,
а интервалы отсортированы по start_i в порядке возрастания.
Также дан интервал newInterval = [start, end], представляющий начало и конец
другого интервала.
Вставьте newInterval в intervals так, чтобы интервалы оставались
отсортированными по начальным значениям в порядке возрастания,
а также непересекающимися (при необходимости объединяйте перекрывающиеся).
Верните интервалы после вставки.
Обратите внимание, что изменять intervals на месте не требуется.
Можно создать новый массив и вернуть его.

Пример 1:
Вход: intervals = [[1,3],[6,9]], newInterval = [2,5]
Выход: [[1,5],[6,9]]

Пример 2:
Вход: intervals = [[1,2],[3,5],[6,7],[8,10],[12,16]], newInterval = [4,8]
Выход: [[1,2],[3,10],[12,16]]
Пояснение: новый интервал [4,8] перекрывается с [3,5],[6,7],[8,10].

Ограничения:
0 <= intervals.length <= 10^4
intervals[i].length == 2
0 <= start_i <= end_i <= 10^5
intervals отсортирован по start_i в порядке возрастания.
newInterval.length == 2
0 <= start <= end <= 10^5
*/

// insert вставляет интервал в отсортированный непересекающийся список.
// До перекрытия копирует ссылки на старые интервалы, при перекрытии расширяет
// newInterval, а после него добавляет весь оставшийся суффикс.
// Время O(n), включая копирование заголовков срезов в результат.
// Рабочая память O(1); память результата O(n): внешний срез ёмкости n+1.
// Глубоких копий нет: res разделяет внутренние срезы с intervals/newInterval.
// Границы newInterval изменяются; это видно всем ссылкам на его общий массив.
func insert(intervals [][]int, newInterval []int) [][]int {
    res := make([][]int, 0, len(intervals)+1)

    // В res лежат интервалы слева; прошлые перекрытия включены в newInterval.
    for i := range intervals {
        // Строго левее текущего: оставшийся суффикс уже не пересечётся.
        // Равенство границ означает перекрытие и попадёт в последнюю ветку.
        if newInterval[1] < intervals[i][0] {
            res = append(res, newInterval)
            return append(res, intervals[i:]...)
        // Старый интервал строго слева и сохраняется без изменения границ.
        } else if newInterval[0] > intervals[i][1] {
            res = append(res, intervals[i])
        } else {
            // Пересечение или касание: расширяем объединённый интервал.
            // Ниже сохранена исходная альтернатива с созданием нового среза.
            // newInterval = []int{
            //     min(newInterval[0], intervals[i][0]),
            //     max(newInterval[1], intervals[i][1]),
            // }
			if intervals[i][0] < newInterval[0] {
			    newInterval[0] = intervals[i][0]
			}
			if intervals[i][1] > newInterval[1] {
    			newInterval[1] = intervals[i][1]
			}
        }
    }
    // Правого суффикса не встретили: объединение становится последним.
    res = append(res, newInterval)
    return res
}