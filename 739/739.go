package main

/*
Дан целочисленный массив temperatures с дневными температурами.
Верните массив answer, где answer[i] — количество дней после i-го дня,
которое нужно подождать до более высокой температуры.
Если такого будущего дня нет, answer[i] == 0.

Пример 1:
Вход: temperatures = [73,74,75,71,69,72,76,73]
Выход: [1,1,4,2,1,1,0,0]

Пример 2:
Вход: temperatures = [30,40,50,60]
Выход: [1,1,1,0]

Пример 3:
Вход: temperatures = [30,60,90]
Выход: [1,1,0]

Ограничения:
1 <= temperatures.length <= 10^5
30 <= temperatures[i] <= 100
*/

// dailyTemperatures хранит в стеке ещё не решённые дни с невозрастающей
// температурой; первый более тёплый день закрывает подходящие вершины.
// Время O(n), n=len(temperatures): каждый индекс добавляется и удаляется раз.
// Рабочая память O(n) для стека; независимый результат O(n), вход не меняется.
func dailyTemperatures(temperatures []int) []int {
	stack := make([]int, 0)
	// Нули останутся у дней без более тёплого будущего дня.
	answer := make([]int, len(temperatures))
	for i := range temperatures {
		for len(stack) != 0 {
			// Непустота проверена; top — корректный ранее добавленный индекс.
			top := stack[len(stack)-1]
			// Равная температура не закрывает день: нужна строго более высокая.
			if temperatures[i] > temperatures[top] {
				// Ранее тёплого дня не было, иначе top уже был бы удалён.
				answer[top] = i - top
				stack = stack[:len(stack)-1]
			} else {
				break
			}
		}
		// Индексы растут, температуры от дна к вершине не возрастают.
		stack = append(stack, i)
	}
	return answer
}