package main

import "strings"

/*
Даны шаблон pattern и строка s. Определите, соответствует ли строка s
этому шаблону.

Под соответствием понимается полное совпадение: между символами pattern
и непустыми словами строки s существует биекция. В частности:

Каждому символу pattern соответствует ровно одно уникальное слово из s.
Каждому уникальному слову из s соответствует ровно один символ pattern.
Два разных символа не могут соответствовать одному слову, а два разных
слова — одному символу.

Пример 1:
Вход: pattern = "abba", s = "dog cat cat dog"
Выход: true
Пояснение:
Биекцию можно задать следующим образом:
'a' соответствует "dog".
'b' соответствует "cat".

Пример 2:
Вход: pattern = "abba", s = "dog cat cat fish"
Выход: false

Пример 3:
Вход: pattern = "aaaa", s = "dog cat cat dog"
Выход: false

Ограничения:
1 <= pattern.length <= 300
pattern содержит только строчные английские буквы.
1 <= s.length <= 3000
s содержит только строчные английские буквы и пробелы ' '.
s не содержит пробелов в начале или конце.
Все слова в s разделены ровно одним пробелом.

*/

// wordPattern проверяет взаимно-однозначное соответствие между символами
// pattern и словами строки s. Для каждой стороны хранится одинаковый маркер
// последней позиции, на которой встретилась согласованная пара.
//
// Время: O(m + n) в среднем, где m = len(pattern), n = len(s).
// Дополнительная память: O(w), где w — количество слов в s.
func wordPattern(pattern string, s string) bool {
    // Два направления нужны для биекции: они запрещают как одному символу
    // соответствовать разным словам, так и разным символам — одному слову.
    charToWord := make(map[byte]int)
    wordToChar := make(map[string]int)

    // По условию слова разделены ровно одним пробелом, поэтому Split сразу
    // восстанавливает последовательность, сопоставляемую символам pattern.
    words := strings.Split(s, " ")

    // Биекция по позициям невозможна, если число символов и слов различается.
    if len(pattern) != len(words) {
        return false
    }

    for i := range words {
        c := pattern[i]
        word := words[i]

        // Равные маркеры означают, что символ и слово либо ещё не встречались
        // (оба значения равны нулю), либо ранее встречались только вместе.
        if charToWord[c] != wordToChar[word] {
            return false
        }

        // Храним i + 1, чтобы ноль оставался однозначным признаком отсутствия
        // ключа в map и не совпадал с маркером первой позиции.
        charToWord[c] = i + 1
        wordToChar[word] = i + 1
    }

    return true
}