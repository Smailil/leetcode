package main

/*
Существует целочисленный массив nums, отсортированный по возрастанию
(с разными значениями).
Перед передачей в функцию nums, возможно, поворачивается влево
по неизвестному индексу k (1 <= k < nums.length),
так что результирующий массив имеет вид
[nums[k], nums[k+1], ..., nums[n-1], nums[0], nums[1], ..., nums[k-1]]
(индексация с 0).
Например, [0,1,2,4,5,6,7] можно повернуть влево на 3 индекса
и превратить в [4,5,6,7,0,1,2].
Даны массив nums после возможного поворота и целое число target.
Верните индекс target, если оно находится в nums, или -1, если его нет в nums.
Вы должны написать алгоритм со сложностью выполнения O(log n).

Пример 1:
Вход: nums = [4,5,6,7,0,1,2], target = 0
Выход: 4

Пример 2:
Вход: nums = [4,5,6,7,0,1,2], target = 3
Выход: -1

Пример 3:
Вход: nums = [1], target = 0
Выход: -1

Ограничения:
1 <= nums.length <= 5000
-10^4 <= nums[i] <= 10^4
Все значения чисел уникальны.
nums — это возрастающий массив, который, возможно, повёрнут.
-10^4 <= target <= 10^4
*/

// search ищет target в повёрнутом массиве с уникальными значениями.
// Одна половина интервала отсортирована: проверяем её границы.
// Время O(log n), n = len(nums); рабочая память и ответ-индекс O(1).
// nums не изменяется.
func search(nums []int, target int) int {
    l, r := 0, len(nums) - 1
	for l <= r {
		// 0<=l<=r<n: mid — допустимый индекс.
		// n<=5000 исключает переполнение l+r даже для 32-битного int.
		mid := (l+r)/2
		if nums[mid] == target {
			return mid
		}
		// Левая половина отсортирована; уникальность исключает неоднозначность.
		if nums[l] <= nums[mid] {
			// Попадание в её диапазон сохраняет слева все возможные позиции.
			// Уже проверенный mid исключается при сужении интервала.
			if nums[l] <= target && target <= nums[mid] {
				r = mid - 1
			} else {
				l = mid + 1
			}
		// Иначе разрыв находится слева, а правая половина отсортирована.
		} else {
			if nums[mid] <= target && target <= nums[r] {
				l = mid + 1
			} else {
				r = mid - 1
			}
		}
	}
	// Пустой интервал означает отсутствие возможных позиций.
	return -1
}
