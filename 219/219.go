package main

/*
Дан массив целых чисел nums и целое число k.
Верните true, если существуют два различных индекса i и j такие,
что nums[i] == nums[j] и abs(i - j) <= k.

Пример 1:
Вход: nums = [1,2,3,1], k = 3
Выход: true

Пример 2:
Вход: nums = [1,0,1,1], k = 1
Выход: true

Пример 3:
Вход: nums = [1,2,3,1,2,3], k = 2
Выход: false

Ограничения:
1 <= nums.length <= 10^5
-10^9 <= nums[i] <= 10^9
0 <= k <= 10^5
*/

// containsNearbyDuplicate ищет повтор среди последних k позиций.
// n=len(nums): среднее время O(n) для map с int-ключами.
// d — максимум разных ключей window: рабочая память O(d),
// d<=min(n,k+1); ответ bool O(1). nums не меняется.
func containsNearbyDuplicate(nums []int, k int) bool {
    window := make(map[int]bool)
    L := 0

    for R := range nums {
        // После прошлого шага R-L не превышало k; R вырос только на 1.
        // Поэтому одного удаления хватает: перед проверкой окно [L,R)
        // содержит ровно допустимые предыдущие позиции. При k=0 оно пусто.
        // В этой ветке L<R, значит nums[L] существует.
        if R-L > k {
            delete(window, nums[L])
            L++
        }
        // До найденного повтора все значения окна различны, поэтому
        // удаление ключа не теряет другой ещё нужный экземпляр.
        // Проверяем до добавления: совпадение всегда относится к иному индексу.
        if window[nums[R]] {
            return true
        }
        // После добавления храним [L,R], не более k+1 значений.
        window[nums[R]] = true
    }

    return false
}
