package main

/*
У вас есть длинная клумба, на которой некоторые участки засажены,
а некоторые нет. При этом нельзя высаживать цветы на соседних участках.

Дан целочисленный массив flowerbed из 0 и 1: 0 означает пустой участок,
а 1 — занятый. Также дано целое число n. Верните true, если на клумбе
можно посадить n новых цветов, не нарушая запрет на соседние цветы,
и false в противном случае.

Пример 1:
Вход: flowerbed = [1,0,0,0,1], n = 1
Выход: true

Пример 2:
Вход: flowerbed = [1,0,0,0,1], n = 2
Выход: false

Ограничения:
1 <= flowerbed.length <= 2 * 10^4
flowerbed[i] равно 0 или 1.
В массиве flowerbed нет двух соседних участков с цветами.
0 <= n <= flowerbed.length
*/

// canPlaceFlowers считает вместимость каждой непрерывной серии нулей.
// Вместо изменения массива функция вычитает допустимые посадки из n.
// Время: O(len(flowerbed)), дополнительная память: O(1).
func canPlaceFlowers(flowerbed []int, n int) bool {
    // Виртуальный пустой участок слева унифицирует формулу для начальной
    // серии нулей, у которой нет занятого соседа слева.
    empty := 0
    if flowerbed[0] == 0 {
        empty = 1
    }

    // empty хранит длину текущей серии нулей с учётом граничной поправки.
    for _, f := range flowerbed {
        if f == 1 {
            // Цветок замыкает серию справа. Благодаря граничной поправке
            // формула одинакова для внутренней и начальной серии нулей.
            n -= (empty - 1) / 2
            empty = 0
        } else {
            // Свободный участок продолжает текущую непрерывную серию.
            empty++
        }
    }

    // У хвостовой серии нет цветка справа, поэтому она вмещает empty / 2
    // новых цветов; начальная поправка также учитывает полностью пустой массив.
    n -= empty / 2

    // Как только суммарной вместимости достаточно, остаток n становится <= 0.
    return n <= 0
}
