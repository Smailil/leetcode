/*
Даны два вектора целых чисел v1 и v2.
Реализуйте итератор, возвращающий их элементы поочерёдно.

Реализуйте класс ZigzagIterator:
ZigzagIterator(List<int> v1, List<int> v2)
инициализирует объект двумя векторами v1 и v2.
boolean hasNext() возвращает true, если у итератора ещё есть элементы,
и false в противном случае.
int next() возвращает текущий элемент итератора
и перемещает итератор к следующему элементу.

Пример 1:
Вход: v1 = [1,2], v2 = [3,4,5,6]
Выход: [1,3,2,4,5,6]
Пояснение: вызывайте next, пока hasNext не вернёт false.
Порядок элементов, возвращаемых next, должен быть: [1,3,2,4,5,6].

Пример 2:
Вход: v1 = [1], v2 = []
Выход: [1]

Пример 3:
Вход: v1 = [], v2 = [1]
Выход: [1]

Ограничения:
0 <= v1.length, v2.length <= 1000
1 <= v1.length + v2.length <= 2000
-2^31 <= v1[i], v2[i] <= 2^31 - 1
*/

// ZigzagIterator хранит две ссылки на входные векторы и индексы чтения.
// cur — выбранный вектор, size=2; indxs[v] — следующее значение из вектора v.
// Буферы входа разделяются: изменения их элементов извне будут видны.
type ZigzagIterator struct {
	cur   int
	size  int
	indxs []int
	vects [][]int
}

// Constructor создаёт итератор без копирования элементов векторов.
// Время и рабочая память O(1); новые данные результата O(1).
// Результат удерживает O(B) входных данных, B — размеры общих массивов,
// а не только длины срезов; один общий массив не учитывается дважды.
func Constructor(v1, v2 []int) *ZigzagIterator {
	return &ZigzagIterator{
		cur:   0,
		size:  2,
		indxs: []int{0, 0},
		vects: [][]int{v1, v2},
	}
}

// next читает элемент выбранного вектора и переключает очередь, меняя this.
// Время, рабочая память и скалярный результат O(1); векторы не меняются.
// Перед КАЖДЫМ next нужен успешный hasNext: сам next не пропускает
// исчерпанные векторы и без этого протокола может вызвать панику индекса.
func (this *ZigzagIterator) next() int {
	v := this.vects[this.cur]
	i := this.indxs[this.cur]
	res := v[i]
	this.indxs[this.cur]++
	// size=2 после Constructor, поэтому делитель не нулевой.
	this.cur = (this.cur + 1) % this.size
	return res
}

// hasNext выбирает непустой остаток вектора или обнаруживает конец обоих.
// Проверяет не больше size=2 векторов: время, рабочая память, результат O(1).
// Меняет this.cur, даже будучи проверкой; значения векторов не изменяет.
func (this *ZigzagIterator) hasNext() bool {
	startCur := this.cur
	// При корректном протоколе индексы не превышают длины векторов.
	// Полный оборот без найденного элемента означает завершение итератора.
	for this.indxs[this.cur] == len(this.vects[this.cur]) {
		this.cur = (this.cur + 1) % this.size
		if startCur == this.cur {
			return false
		}
	}
	return true
}

