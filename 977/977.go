package main

/*
Дан целочисленный массив nums, отсортированный в неубывающем порядке.
Верните массив квадратов всех его чисел, также отсортированный
в неубывающем порядке.

Пример 1:
Вход: nums = [-4,-1,0,3,10]
Выход: [0,1,9,16,100]
Пояснение: После возведения в квадрат массив станет [16,1,0,9,100].
После сортировки он станет [0,1,9,16,100].

Пример 2:
Вход: nums = [-7,-3,2,3,11]
Выход: [4,9,9,49,121]

Ограничения:
1 <= nums.length <= 10^4
-10^4 <= nums[i] <= 10^4
nums отсортирован в неубывающем порядке.

*/

// sortedSquares возвращает квадраты nums в неубывающем порядке.
// Два указателя выбирают максимальные квадраты с краёв исходного массива;
// они записываются в невозрастающем порядке, затем результат разворачивается.
// Время: O(n) амортизированно (из-за append), где n = len(nums).
// Рабочая память без результата: O(1); память результата: O(n).
// Исходный массив nums не изменяется.
func sortedSquares(nums []int) []int {
    // Включительный интервал [l, r] содержит ещё не обработанные числа.
    l, r := 0, len(nums)-1
    // res хранит уже выбранные квадраты в невозрастающем порядке.
    // append увеличивает его длину и при необходимости расширяет буфер.
    res := []int{}

    // В отсортированном интервале максимальный модуль находится на краю:
    // среди отрицательных чисел он слева, среди неотрицательных — справа.
    // Поэтому максимальный оставшийся квадрат — один из nums[l]^2, nums[r]^2.
    // Инвариант: все квадраты в res не меньше квадратов оставшихся чисел.
    // Условие l <= r позволяет обработать и последний элемент при l == r.
    for l <= r {
        // По условию |nums[i]| <= 10^4, поэтому квадрат <= 10^8:
        // умножение безопасно для int даже на 32-битной платформе.
        if nums[l]*nums[l] > nums[r]*nums[r] {
            // Левый квадрат больше: добавляем его и исключаем только nums[l].
            // Следующий выбранный квадрат не больше этого — порядок сохранён.
            res = append(res, nums[l]*nums[l])
            l++
        } else {
            // Иначе выбираем правый край. При равенстве квадратов разных
            // элементов можно брать любой край: порядок результата тот же.
            res = append(res, nums[r]*nums[r])
            r--
        }
    }

    // Сейчас res имеет невозрастающий порядок, а нужен неубывающий.
    // Например, для [-4,-1,0,3,10] получено [100,16,9,1,0].
    // Обмены с краёв к центру дают [0,1,9,16,100] без второго массива.
    // Условие i < j не даёт повторно обменять пару; центр менять не нужно.
    for i, j := 0, len(res)-1; i < j; i, j = i+1, j-1 {
        res[i], res[j] = res[j], res[i]
    }
    return res
}