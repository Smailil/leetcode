package main

/*
Фраза является палиндромом, если после преобразования всех прописных букв
в строчные и удаления всех небуквенно-цифровых
символов она читается одинаково и вперед, и назад.
Буквенно-цифровые символы включают буквы и цифры.

Дана строка s, верните true, если это палиндром, или false в противном случае.

Пример 1:
Вход: s = "A man, a plan, a canal: Panama"
Выход: true
Объяснение: "amanaplanacanalpanama" — палиндром.

Пример 2:
Вход: s = "race a car"
Выход: false
Объяснение: "raceacar" — не палиндром.

Пример 3:
Вход: s = " "
Выход: true
Объяснение: s — пустая строка "" после удаления небуквенно-цифровых символов.
Поскольку пустая строка читается одинаково и вперед, и назад,
она является палиндромом.

Ограничения:
1 <= s.length <= 2 * 10^5
s состоит только из печатных символов ASCII.
*/

// toLower приводит прописную ASCII-букву к строчной; остальные байты
// возвращает без изменения. Время и дополнительная память O(1).
func toLower(b byte) byte {
	if 'A' <= b && b <= 'Z' {
		return b - 'A' + 'a'
	}
	return b
}

// isLetter проверяет ASCII-букву или цифру, несмотря на имя функции.
// Время и дополнительная память O(1); внешнее состояние не меняется.
func isLetter(b byte) bool {
	return ('a' <= b && b <= 'z') || ('A' <= b && b <= 'Z') || ('0' <= b && b <= '9')
}

// isPalindrome сравнивает значимые символы с двух концов, игнорируя
// регистр ASCII-букв. Ограничение ASCII позволяет работать с байтами.
// Время O(n), n = len(s): каждый указатель проходит строку не более раза.
// Рабочая память и скалярный результат O(1); строка s не изменяется.
func isPalindrome(s string) bool {
    l := 0
	r := len(s)-1
	// Между l и r находится ещё не проверенная часть строки.
	// Пока l <= r, оба индекса допустимы; пустая строка цикл не запускает.
	for l <= r {
		// Пропускаем разделители отдельно с каждого конца:
		// они не участвуют в сравнении и не требуют копирования строки.
		if !isLetter(s[l]) {
			l++
			continue
		}
		if !isLetter(s[r]) {
			r--
			continue
		}
		// Совпавшая пара больше не влияет на ответ; несовпадение
		// опровергает палиндром независимо от оставшейся середины.
		if toLower(s[l]) == toLower(s[r]) {
			l++
			r--
		} else {
			return false
		}
	}
	return true
}