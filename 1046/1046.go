package main

import "container/heap"

/*
Вам дан массив целых чисел, где stones[i] — это вес i-го камня.
Мы играем в игру с камнями.
На каждом ходу мы выбираем два самых тяжелых камня и разбиваем их вместе.
Предположим, что два самых тяжелых камня имеют вес x и y, причем x <= y.
Результат этого удара:
Если x == y, оба камня уничтожаются.
Если x != y, камень веса x уничтожается,
а камень веса y приобретает новый вес y -x.
В конце игры остается не более одного камня.
Верните вес последнего оставшегося камня.
Если камней не осталось, верните 0.

Пример 1:
Вход: stones = [2,7,4,1,8,1]
Выход: 1
Объяснение:
Мы объединяем 7 и 8, чтобы получить 1,
поэтому массив преобразуется в [2,4,1,1,1], а затем:
мы объединяем 2 и 4, чтобы получить 2,
поэтому массив преобразуется в [2,1,1,1], затем
мы объединяем 2 и 1, чтобы получить 1,
поэтому массив преобразуется в [1,1,1], затем
мы объединяем 1 и 1, чтобы получить 0,
поэтому массив преобразуется в [1], тогда это значение последнего камня.

Пример 2:
Вход: stones = [1]
Выход: 1

Ограничения:
1 <= stones.length <= 30
1 <= stones[i] <= 1000
*/

type IntHeap []int

// Len читает длину за O(1) времени и памяти.
func (h IntHeap) Len() int {return len(h)}
// Less задаёт max-heap сравнением за O(1) времени и памяти.
func (h IntHeap) Less(i, j int) bool {return h[i] > h[j]}
// Swap меняет два элемента кучи за O(1) времени и памяти.
func (h IntHeap) Swap(i, j int) {h[i], h[j] = h[j], h[i]}
// Push — callback heap: добавляет int и меняет срез.
// k — длина кучи: время амортизированно O(1), при росте буфера O(k).
// Рабочая память O(1), кроме O(k) при росте буфера.
func (h *IntHeap) Push(x interface{}) {*h = append(*h, x.(int))}
// Pop — callback heap: снимает хвост непустого среза, меняя длину.
// Выбранный корень предварительно перенесён в хвост пакетом container/heap.
// Время и рабочая память O(1), результат — один int.
func (h *IntHeap) Pop() interface{} {
    n := len(*h)
    x := (*h)[n-1]
    *h = (*h)[0:n-1]
    return x
}

// lastStoneWeight моделирует удары, извлекая два максимума из кучи.
// n = len(stones): время O(n log(n + 1)), рабочая память и результат O(1).
// Меняет исходный буфер stones: преобразование к IntHeap не копирует его.
func lastStoneWeight(stones []int) int {
    // heap.Init строит max-heap за O(n) на том же массиве stones.
    ih := IntHeap(stones)
    heap.Init(&ih)
    // Каждый удар уменьшает число камней минимум на один: не более n-1.
    // После двух Pop возможный Push помещается в исходную ёмкость, без роста.
    for ih.Len() > 1 {
        // Len > 1 гарантирует оба извлечения. В коде x — первый максимум,
        // y — второй: x >= y, поэтому x-y неотрицателен и не больше 1000.
        x, y := heap.Pop(&ih).(int), heap.Pop(&ih).(int)
        // Равные камни исчезают; иначе возвращается один камень разности.
        if x != y {
            heap.Push(&ih, x-y)
        }
    }
    
    // Осталось 0 или 1 камень; проверка защищает последнее извлечение.
    if ih.Len() == 0 {
        return 0
    }
    
    return heap.Pop(&ih).(int)
}
