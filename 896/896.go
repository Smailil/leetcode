package main

/*
Массив является монотонным, если он либо монотонно не убывает, либо
монотонно не возрастает.

Массив nums монотонно не убывает, если для всех i <= j выполняется
nums[i] <= nums[j]. Массив nums монотонно не возрастает, если для всех
i <= j выполняется nums[i] >= nums[j].

Дан массив целых чисел nums. Верните true, если он монотонный, иначе false.

Пример 1:
Вход: nums = [1,2,2,3]
Выход: true

Пример 2:
Вход: nums = [6,5,4,4]
Выход: true

Пример 3:
Вход: nums = [1,3,2]
Выход: false

Ограничения:
1 <= nums.length <= 10^5
-10^5 <= nums[i] <= 10^5
*/

// isMonotonic проверяет, является ли nums неубывающим или
// невозрастающим массивом. За один проход поддерживаются оба возможных
// направления, пока очередная пара элементов не опровергнет одно из них.
// Время: O(n), где n = len(nums). Дополнительная память: O(1).
func isMonotonic(nums []int) bool {
    // До первого нарушения оба направления считаются возможными. Для массива
    // из одного элемента цикл не выполнится, поэтому результат останется true.
    increase, decrease := true, true

    // Проверок соседних пар достаточно: если каждая из них упорядочена в одном
    // направлении, то благодаря транзитивности так же упорядочен весь массив.
    for i := range len(nums)-1 {
        // Строгий спад исключает неубывание, а строгий рост — невозрастание.
        // Равные соседние элементы не нарушают ни одного направления.
        if !(nums[i] <= nums[i+1]) {
            increase = false
        }
        if !(nums[i] >= nums[i+1]) {
            decrease = false
        }
    }
    // Массив монотонен, пока после всех сравнений возможно хотя бы одно
    // из двух направлений.
    return increase || decrease
}