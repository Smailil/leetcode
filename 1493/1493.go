package main

import "fmt"

/*
Дан двоичный массив nums, из которого нужно удалить ровно один элемент.

Верните длину самого длинного непустого подмассива из одних единиц
в полученном массиве.
Если такого подмассива нет, верните 0.

Пример 1:
Вход: nums = [1,1,0,1]
Выход: 3
Пояснение: После удаления числа с индексом 2 массив [1,1,1]
содержит 3 числа со значением 1.

Пример 2:
Вход: nums = [0,1,1,1,0,1,1,0,1]
Выход: 5
Пояснение: После удаления числа с индексом 4 получаем [0,1,1,1,1,1,0,1].
Самый длинный подмассив из одних единиц — [1,1,1,1,1].

Пример 3:
Вход: nums = [1,1,1]
Выход: 2
Пояснение: Необходимо удалить один элемент.

Ограничения:
1 <= nums.length <= 10^5
nums[i] равно 0 или 1.
*/

// longestSubarray соединяет две соседние серии единиц удалением нуля.
// prev — длина серии слева от последнего нуля, curr — текущей справа.
// Время O(n), n=len(nums); рабочая память и результат int O(1).
// nums не меняется. Если нулей нет, ровно одно удаление даёт n-1, не n.
func longestSubarray(nums []int) int {
	prev, curr, maxSum := 0, 0, 0
	hasZero := false

	for _, num := range nums {
		if num == 1 {
			curr++
		} else {
			// На новом нуле оцениваем пару вокруг предыдущего и сдвигаем серии.
			// Два соседних нуля дают curr=0, объединение через оба недопустимо.
			hasZero = true
			maxSum = max(maxSum, prev+curr)
			prev = curr
			curr = 0
		}
	}

	// Последняя серия завершается концом массива, не новым нулём.
	maxSum = max(maxSum, prev+curr)

	if hasZero {
		return maxSum
	}

	// Непустой массив из единиц всё равно обязан потерять один элемент.
	return maxSum - 1
}

// main демонстрирует longestSubarray на [1,0] и печатает 1 с новой строкой.
// На фиксированном примере время и рабочая память O(1), результата нет.
// Побочный эффект — запись в stdout; запуск для комментирования не требуется.
func main() {
	a := longestSubarray([]int{1, 0})
	fmt.Println(a)
}
