package main

import (
	"strconv"
	"strings"
)

/*
Сериализация — это преобразование структуры данных или объекта
в последовательность битов, которую можно сохранить в файле
или буфере памяти либо передать по сетевому соединению,
чтобы позднее восстановить её в той же или другой компьютерной среде.

Разработайте алгоритм сериализации и десериализации двоичного дерева.
Ограничений на работу алгоритма сериализации/десериализации нет.
Нужно лишь обеспечить возможность сериализовать двоичное дерево в строку
и десериализовать эту строку в исходную структуру дерева.

Уточнение: Формат входа/выхода совпадает с форматом сериализации
двоичного дерева в LeetCode.
Следовать этому формату необязательно.
Проявите изобретательность и самостоятельно предложите различные подходы.

Пример 1:
https://assets.leetcode.com/uploads/2020/09/15/serdeser.jpg
Вход: root = [1,2,3,null,null,4,5]
Выход: [1,2,3,null,null,4,5]

Пример 2:
Вход: root = []
Выход: []

Ограничения:
Количество узлов в дереве находится в диапазоне [0, 10^4].
-1000 <= Node.val <= 1000
*/


type TreeNode struct {
    Val int
    Left *TreeNode
    Right *TreeNode
}

type Codec struct{}

// Constructor создаёт stateless Codec за O(1) времени и памяти.
// Каждая операция хранит состояние локально, отдельного общего буфера нет.
func Constructor() Codec {
    return Codec{}
}

// serialize кодирует preorder, сохраняя пустые дети маркером N.
// Время O(n+L+1), n — число узлов, L — длина выходной строки;
// при ограниченном Val это O(n+1). Рабочая память O(n+h+1)
// для res и стека, h — высота; строковый результат O(L).
// Дерево и this не изменяются; Join создаёт самостоятельную строку.
func (this *Codec) serialize(root *TreeNode) string {
    var res []string

    var dfs func(node *TreeNode)
    // dfs дописывает корень, левое и правое поддерево, включая nil.
    // Время O(t+1) амортизированно, t — число узлов текущего поддерева
    // при ограниченном Val; рабочий стек O(d+1), d — его высота.
    // Общий буфер res содержит O(n+1) токенов; итоговая строка O(L)
    // формируется после обхода. Меняет захваченный res, но не дерево.
    dfs = func(node *TreeNode) {
        // N отличает отсутствие ребёнка от настоящего узла, поэтому
        // последовательность значений однозначно задаёт также форму.
        if node == nil {
            res = append(res, "N")
            return
        }
        res = append(res, strconv.Itoa(node.Val))
        dfs(node.Left)
        dfs(node.Right)
    }

    // У n узлов n+1 пустых детей: всего 2*n+1 токенов.
    // Даже пустое дерево кодируется строкой N, не пустой строкой.
    dfs(root)
    return strings.Join(res, ",")
}

// deserialize восстанавливает дерево из собственного preorder-формата.
// Требует корректного data из serialize; чужой/усечённый ввод не проверяет.
// Время O(L+n), L = len(data), n — число кодированных узлов.
// Рабочая память O(n+h+1) для заголовков vals и стека; новые узлы O(n).
// vals разделяет буфер data только во время вызова; результат его не держит.
// this и data не изменяются, дерево результата создаётся заново.
func (this *Codec) deserialize(data string) *TreeNode {
    vals := strings.Split(data, ",")
    i := 0

    var dfs func() *TreeNode
    // dfs читает ровно одно поддерево, начиная с текущего токена i.
    // Время O(Lt+t+1), Lt — число его символов, t — число новых узлов.
    // Рабочий стек O(d+1), d — высота поддерева; результат O(t) узлов.
    // Использует общий vals O(n+1), меняет захваченный i, не data/this.
    dfs = func() *TreeNode {
        // Для data из serialize i всегда указывает на следующий токен.
        // Явной проверки границ для некорректного внешнего ввода здесь нет.
        if vals[i] == "N" {
            i++
            return nil
        }
        // Числовой токен от serialize гарантированно допустим;
        // код игнорирует Atoi error, а не обрабатывает произвольный текст.
        val, _ := strconv.Atoi(vals[i])
        node := &TreeNode{Val: val}
        i++
        // Сначала сдвигаем i за корень, затем полностью читаем левую
        // и правую ветви: после каждого dfs i стоит за его поддеревом.
        node.Left = dfs()
        node.Right = dfs()
        return node
    }

    return dfs()
}


/**
 * Объект Codec будет создан и вызван следующим образом:
 * ser := Constructor();
 * deser := Constructor();
 * data := ser.serialize(root);
 * ans := deser.deserialize(data);
 */