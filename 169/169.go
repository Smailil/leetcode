package main

/*
Дан массив nums размером n.
Верните мажоритарный элемент.

Мажоритарный элемент — это элемент, который встречается более ⌊n / 2⌋ раз.
Гарантируется, что мажоритарный элемент в массиве всегда существует.

Пример 1:
Вход: nums = [3,2,3]
Выход: 3

Пример 2:
Вход: nums = [2,2,1,1,1,2,2]
Выход: 2

Ограничения:
n == nums.length
1 <= n <= 5 * 10^4
-10^9 <= nums[i] <= 10^9
Входные данные гарантируют существование мажоритарного элемента в массиве.
*/

// majorityElement находит мажоритарный элемент голосованием Бойера-Мура.
// Попарное удаление разных значений сохраняет строгую долю большинства:
// каждый такой шаг убирает не более одного его вхождения.
// Время O(n), n = len(nums); рабочая память и результат O(1).
// Массив nums не изменяется. Существование большинства гарантирует условие.
func majorityElement(nums []int) int {
	// res — текущий кандидат на роль мажоритарного элемента
	// count — баланс "голосов": увеличивается при совпадении с кандидатом,
	// уменьшается при различии
	res, count := 0, 0

	// count считает остаток после отмены разных пар, а не частоту res
	// во всём массиве. Обнуление означает, что остаток префикса пуст.
	for _, num := range nums {
		// Если баланс голосов обнулился, "забываем" старого кандидата
		// и выбираем текущий элемент как нового претендента
		if count == 0 {
			res = num
		}
		// Если текущий элемент совпадает с кандидатом, увеличиваем баланс
		// иначе уменьшаем (отменяем один голос за кандидата)
		if num == res {
			count++
		} else {
			count--
		}
	}
	// После полного прохода по массиву в res гарантированно остаётся
	// мажоритарный элемент именно благодаря гарантии его существования.
	// Без неё кандидат потребовал бы отдельной проверки частоты.
	return res
}
