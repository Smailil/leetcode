package main

/*
Дана строка s.

Удалите все цифры, повторяя следующую операцию:
удалите первую слева цифру и ближайший к ней слева нецифровой символ.
Верните строку, которая останется после удаления всех цифр.

Операцию нельзя выполнить для цифры, слева от которой нет ни одного
символа, отличного от цифры.

Пример 1:
Вход:
s := "abc"
Выход: "abc"
Пояснение:
В строке нет цифр.

Пример 2:
Вход:
s := "cb34"
Выход: ""
Пояснение:
Сначала применяем операцию к s[2], и s становится равной "c4".
Затем применяем операцию к s[1], и s становится равной "".

Ограничения:
1 <= s.length <= 100
Строка s состоит только из строчных английских букв и цифр.
Входные данные гарантируют, что все цифры можно удалить.
*/

// clearDigits удаляет каждую цифру вместе с ближайшей оставшейся буквой
// слева. Стек хранит оставшиеся буквы обработанного префикса по порядку.
// Время O(n) и рабочая память O(n), где n = len(s).
// Память результата O(k), где k — длина оставшейся строки.
func clearDigits(s string) string {
	stack := make([]byte, 0, len(s))
	// Во входе только ASCII-буквы и цифры, поэтому один байт — один символ.
	for i := 0; i < len(s); i++ {
		if s[i] >= '0' && s[i] <= '9' {
			// Вершина стека — ближайшая оставшаяся буква слева от цифры.
			// Стек не пуст: иначе в префиксе до i включительно цифр было бы
			// больше, чем букв, что противоречит гарантии задачи.
			stack = stack[:len(stack)-1]
		} else {
			// Оставляем букву в исходном порядке для результата или
			// для удаления одной из следующих цифр.
			stack = append(stack, s[i])
		}
	}
	// Буквы уже в нужном порядке: достаточно преобразовать стек в строку.
	return string(stack)
}
