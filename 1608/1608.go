package main

/*
Дан массив nums из неотрицательных целых чисел. Массив nums считается
особым, если существует число x, для которого ровно x элементов nums
больше или равны x.

Обратите внимание: x не обязано быть элементом nums.

Верните x, если массив является особым; в противном случае верните -1.
Можно доказать, что для особого массива значение x единственно.

Пример 1:
Вход: nums = [3,5]
Выход: 2
Пояснение: существуют 2 значения (3 и 5), которые больше или равны 2.

Пример 2:
Вход: nums = [0,0]
Выход: -1
Пояснение: ни одно число x не соответствует условию.
Если x = 0, чисел, которые больше или равны x, должно быть 0, но их 2.
Если x = 1, чисел, которые больше или равны x, должно быть 1, но их 0.
Если x = 2, чисел, которые больше или равны x, должно быть 2, но их 0.
x не может быть больше, поскольку в nums всего 2 элемента.

Пример 3:
Вход: nums = [0,4,3,0,4]
Выход: 3
Пояснение: существуют 3 значения, которые больше или равны 3.

Ограничения:
1 <= nums.length <= 100
0 <= nums[i] <= 1000
*/

// specialArray возвращает число x, для которого ровно x элементов nums
// больше или равны x. Частоты значений позволяют проверить все кандидаты
// без повторного обхода исходного массива.
// Время: O(n), где n = len(nums). Дополнительная память: O(n).
func specialArray(nums []int) int {
    // Искомое x не может превышать n, поэтому достаточно n + 1 корзины.
    // count[i] хранит число элементов с ограниченным сверху значением i.
    count := make([]int, len(nums)+1)
    for _, num := range nums {
        // Для любого допустимого x значения больше n эквивалентны n:
        // каждое из них в любом случае не меньше x.
        index := min(num, len(nums))
        count[index]++
    }

    // Проверяем кандидатов справа налево и одновременно накапливаем
    // количество элементов, которые не меньше текущего i.
    totalRight := 0
    for i := len(nums); i >= 0; i-- {
        totalRight += count[i]
        if i == totalRight {
            // Ровно i элементов оказались не меньше i, поэтому условие
            // специального массива выполнено. Здесь totalRight равно i.
            return totalRight
        }
    }

    // Ни один кандидат от 0 до n не удовлетворяет условию задачи.
    return -1
}