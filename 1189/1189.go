package main

/*
Дана строка text. Требуется использовать её символы, чтобы составить как можно
больше экземпляров слова "balloon".

Каждый символ строки text можно использовать не более одного раза. Верните
максимальное число экземпляров, которые можно составить.

Пример 1:
https://assets.leetcode.com/uploads/2019/09/05/1536_ex1_upd.JPG
Вход: text = "nlaebolko"
Выход: 1

Пример 2:
https://assets.leetcode.com/uploads/2019/09/05/1536_ex2_upd.JPG
Вход: text = "loonbalxballpoon"
Выход: 2

Пример 3:
Вход: text = "leetcode"
Выход: 0

Ограничения:
1 <= text.length <= 10^4
text состоит только из строчных букв английского алфавита.

*/

// maxNumberOfBalloons определяет, сколько полных слов "balloon" можно
// одновременно составить из символов text. Для этого функция сравнивает
// доступное количество каждой нужной буквы с её расходом на одно слово.
//
// Время: O(n), где n = len(text), поскольку строка просматривается один раз.
// Дополнительная память: O(1), так как входной алфавит содержит лишь 26 букв.
func maxNumberOfBalloons(text string) int {
    // За один проход собираем точные частоты всех букв исходной строки.
    // После цикла countText[c] показывает общий запас символа c.
    countText := make(map[rune]int)
    for _, c := range text {
        countText[c]++
    }

    // В слове "balloon" буквы l и o нужны дважды, остальные — по одному разу.
    // Поэтому для каждой буквы важно не только наличие, но и расход на слово.
    balloon := map[rune]int{'b': 1, 'a': 1, 'l': 2, 'o': 2, 'n': 1}

    // Число слов заведомо не превосходит количества символов во входе, поэтому
    // len(text) служит безопасным начальным верхним пределом для минимума.
    res := len(text)
    for c, need := range balloon {
        // Частное countText[c]/need — число слов, обеспеченное буквой c.
        // Минимальное такое значение задаёт дефицитную букву и общий результат;
        // деление безопасно, поскольку все значения need положительны.
        if countText[c]/need < res {
            res = countText[c] / need
        }
    }
    return res
}