package main

/*
Дан двоичный массив nums.
Верните максимальную длину непрерывного подмассива с равным числом 0 и 1.

Пример 1:
Вход: nums = [0,1]
Выход: 2
Пояснение: [0, 1] — самый длинный непрерывный подмассив
с равным количеством 0 и 1.

Пример 2:
Вход: nums = [0,1,0]
Выход: 2
Пояснение: [0, 1] (или [1, 0]) — один из самых длинных непрерывных подмассивов
с равным количеством 0 и 1.

Пример 3:
Вход: nums = [0,1,1,1,1,1,0,0,0]
Выход: 6
Пояснение: [1,1,1,0,0,0] — самый длинный непрерывный подмассив
с равным количеством 0 и 1.

Ограничения:
1 <= nums.length <= 10^5
nums[i] равно 0 или 1.
*/

// findMaxLength возвращает наибольшую длину подмассива с равным числом 0 и 1.
// Сопоставляет баланс one-zero у префиксов с его самыми ранними индексами.
// Время: в среднем O(m), где m = len(nums); nums не изменяется.
// Дополнительная память: O(k) для k различных балансов, k <= m.
// В худшем случае память O(m); счётчики и результат занимают O(1).
func findMaxLength(nums []int) int {
    // zero и one — количества нулей и единиц в обработанном префиксе.
    // res хранит наибольшую найденную длину; 0 означает отсутствие ответа.
    zero, one, res := 0, 0, 0
    // Для каждого баланса сохраняем только индекс его первого появления.
    diffIndex := make(map[int]int)

    for i, n := range nums {
        // По условию n равен 0 или 1, поэтому ветка else считает единицы.
        if n == 0 {
            zero++
        } else {
            one++
        }

        // Баланс diff — разность количества единиц и нулей в префиксе.
        // Для подмассива j+1..i баланс равен diff(i)-diff(j),
        // где diff(j) — значение one-zero после обработки индекса j.
        // Равные балансы дают разность 0: на этом участке поровну 0 и 1.
        // one+zero = i+1 <= m <= 10^5: счётчики и diff помещаются в int.
        diff := one - zero
        // Не заменяем первый индекс: более поздний дал бы меньшую длину.
        if _, ok := diffIndex[diff]; !ok {
            diffIndex[diff] = i
        }

        if one == zero {
            // Сбалансирован весь префикс 0..i, его длина one+zero = i+1.
            // Он длиннее любого прежнего ответа, поэтому max не нужен.
            // Так учтён пустой префикс с индексом -1 без записи его в map.
            res = one + zero
        } else {
            // Здесь j = diffIndex[diff] — первый индекс текущего баланса.
            // Подмассив j+1..i сбалансирован, его длина i-j; улучшаем res.
            // Для [0,1,0] баланс -1 повторяется при i = 0 и i = 2: длина 2.
            // У нового баланса j = i, поэтому кандидат имеет длину 0.
            if res < i-diffIndex[diff] {
                res = i - diffIndex[diff]
            }
        }
    }

    return res
}