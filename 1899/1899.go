package main

/*
Тройка — это массив из трёх целых чисел.
Дан двумерный целочисленный массив triplets,
где triplets[i] = [a_i, b_i, c_i] описывает i-ю тройку.
Также дан целочисленный массив target = [x, y, z], описывающий целевую тройку.

Для получения target следующую операцию можно выполнять любое число раз,
в том числе ноль:
Выберите два различных индекса i и j (индексация с 0)
и замените triplets[j] на [max(a_i, a_j), max(b_i, b_j), max(c_i, c_j)].
Например, если triplets[i] = [2, 5, 3] и triplets[j] = [1, 7, 5],
то triplets[j] станет [max(2, 1), max(5, 7), max(3, 5)] = [2, 7, 5].

Верните true, если целевую тройку [x, y, z] можно получить как элемент triplets,
и false в противном случае.

Пример 1:
Вход: triplets = [[2,5,3],[1,8,4],[1,7,5]], target = [2,7,5]
Выход: true
Пояснение: выполните следующие операции:
- Выберите первую и последнюю тройки [[2,5,3],[1,8,4],[1,7,5]].
  Замените последнюю тройку на [max(2,1), max(5,7), max(3,5)] = [2,7,5].
  triplets = [[2,5,3],[1,8,4],[2,7,5]]
Целевая тройка [2,7,5] теперь является элементом triplets.

Пример 2:
Вход: triplets = [[3,4,5],[4,5,6]], target = [3,2,5]
Выход: false
Пояснение: невозможно получить [3,2,5] в качестве элемента,
поскольку ни в одной из троек нет числа 2.

Пример 3:
Вход: triplets = [[2,5,3],[2,3,4],[1,2,5],[5,2,3]], target = [5,5,5]
Выход: true
Пояснение: выполните следующие операции:
- Выберите первую и третью тройки [[2,5,3],[2,3,4],[1,2,5],[5,2,3]].
  Замените третью тройку на [max(2,1), max(5,2), max(3,5)] = [2,5,5].
  triplets = [[2,5,3],[2,3,4],[2,5,5],[5,2,3]].
- Выберите третью и четвёртую тройки [[2,5,3],[2,3,4],[2,5,5],[5,2,3]].
  Замените четвёртую тройку на [max(2,5), max(5,2), max(5,3)] = [5,5,5].
  triplets = [[2,5,3],[2,3,4],[2,5,5],[5,5,5]].
Целевая тройка [5,5,5] теперь является элементом triplets.

Ограничения:
1 <= triplets.length <= 10^5
triplets[i].length == target.length == 3
1 <= a_i, b_i, c_i, x, y, z <= 1000
*/

// mergeTriplets проверяет достижимость покоординатного максимума без слияний.
// Время O(n), n=len(triplets); рабочая память и результат bool O(1).
// Входы не меняются; у всех троек и target по три компоненты по условию.
func mergeTriplets(triplets [][]int, target []int) bool {
    x, y, z := false, false, false

    for _, t := range triplets {
        // Максимумы не уменьшаются: тройку с превышением target брать нельзя.
        // Каждый флаг означает, что безопасная тройка даёт нужную координату.
        x = x || (t[0] == target[0] && t[1] <= target[1] && t[2] <= target[2])
        y = y || (t[0] <= target[0] && t[1] == target[1] && t[2] <= target[2])
        z = z || (t[0] <= target[0] && t[1] <= target[1] && t[2] == target[2])

        // Максимум троек-свидетелей ровно target: все координаты не больше
        // цели, и для каждой есть равенство. Индексы могут совпасть:
        // уже имеющийся target достижим без единой операции.
        if x && y && z {
            return true
        }
    }
    return false
}
