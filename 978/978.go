package main

/*
Дан целочисленный массив arr.
Верните длину максимального по размеру турбулентного подмассива arr.

Подмассив называется турбулентным, если знак сравнения меняется
между каждой соседней парой его элементов.

Формально подмассив [arr[i], arr[i + 1], ..., arr[j]] массива arr
турбулентен тогда и только тогда, когда выполнено одно из условий:
Для i <= k < j:
arr[k] > arr[k + 1], когда k нечётно, и
arr[k] < arr[k + 1], когда k чётно.
Или для i <= k < j:
arr[k] > arr[k + 1], когда k чётно, и
arr[k] < arr[k + 1], когда k нечётно.

Пример 1:
Вход: arr = [9,4,2,10,7,8,8,1,9]
Выход: 5
Пояснение: arr[1] > arr[2] < arr[3] > arr[4] < arr[5]

Пример 2:
Вход: arr = [4,8,12,16]
Выход: 2

Пример 3:
Вход: arr = [100]
Выход: 1

Ограничения:
1 <= arr.length <= 4 * 10^4
0 <= arr[i] <= 10^9
*/

// maxTurbulenceSize расширяет окно с чередующимися строгими сравнениями.
// Повтор направления начинает окно с последней пары, равенство — с элемента.
// Время O(n), n=len(arr): каждый r проверяется не более двух раз.
// Рабочая память и результат int O(1); arr не меняется.
func maxTurbulenceSize(arr []int) int {
    // l и r — левая и правая границы скользящего окна.
    // res — максимальная найденная длина подмассива (минимум 1, так как один
    // элемент — это уже подмассив).
    l, r, res := 0, 1, 1
    
    // prev сохраняет знак предыдущего сравнения соседних элементов: 
    // ">" (убывание) или "<" (возрастание).
    // Это нужно для проверки чередования знаков.
    prev := ""

    // Итерируемся по массиву, пока правый указатель не выйдет за его пределы
    for r < len(arr) {
        // Случай 1: текущая пара элементов убывает (arr[r-1] > arr[r]), 
        // и предыдущее сравнение НЕ было убыванием (prev != ">")
        if arr[r-1] > arr[r] && prev != ">" {
            // Условие чередования выполнено — обновляем максимум длины текущего
            // окна
            if r-l+1 > res {
                res = r - l + 1
            }
            r++          // Сдвигаем правую границу, расширяя окно
            prev = ">"   // Фиксируем текущий знак сравнения для следующей
            // итерации

        // Случай 2: текущая пара элементов возрастает (arr[r-1] < arr[r]), 
        // и предыдущее сравнение НЕ было возрастанием (prev != "<")
        } else if arr[r-1] < arr[r] && prev != "<" {
            // Условие чередования выполнено — обновляем максимум длины текущего
            // окна
            if r-l+1 > res {
                res = r - l + 1
            }
            r++          // Сдвигаем правую границу
            prev = "<"   // Фиксируем текущий знак сравнения

        // Случай 3: условие турбулентности нарушено (знаки совпали или элементы
        // равны)
        } else {
            // Если соседние элементы равны, они не могут быть частью
            // турбулентного подмассива.
            // Пропускаем этот элемент, сдвигая правый указатель.
            if arr[r] == arr[r-1] {
                r++
            }
            
            // Сбрасываем левую границу окна. 
            // Новое потенциальное окно начинаем строить с элемента (r - 1).
            // Без равенства r не сдвинут: следующая итерация заново проверит
            // ту же пару с пустым prev и затем сдвинет r. При равенстве новый
            // старт — прежний правый элемент, сравнивать его с собой не нужно.
            l = r - 1
            
            // Сбрасываем сохраненный знак, так как новое окно только начинается
            prev = ""
        }
    }

    return res
}