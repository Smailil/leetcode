package main

/*
Всего вам нужно пройти numCourses курсов, помеченных от 0 до numCourses -1.
Дан массив предварительных требований, где prerequisites[i] = [a_i, b_i]
означает, что перед курсом a_i необходимо пройти курс b_i.
Например, пара [0, 1] указывает, что для прохождения курса 0 необходимо
сначала пройти курс 1.
Верните порядок курсов, которые нужно пройти, чтобы закончить все курсы.
Если правильных ответов много, верните любой из них.
Если пройти все курсы невозможно, верните пустой массив.

Пример 1:
Вход: numCourses = 2, prerequisites = [[1,0]]
Выход: [0,1]
Объяснение: Всего нужно пройти 2 курса.
Чтобы пройти курс 1, вы должны закончить курс 0.
Поэтому правильный порядок курсов — [0,1].

Пример 2:
Вход: numCourses = 4, prerequisites = [[1,0],[2,0],[3,1],[3,2]]
Выход: [0,2,1,3]
Пояснение: Всего необходимо пройти 4 курса.
Чтобы пройти курс 3, вам необходимо пройти оба курса 1 и 2.
Оба курса 1 и 2 следует пройти после окончания курса 0.
Таким образом, один правильный порядок курса — [0,1,2,3].
Другой правильный порядок — [0,2,1,3].

Пример 3:
Вход: numCourses = 1, prerequisites = []
Выход: [0]

Ограничения:
1 <= numCourses <= 2000
0 <= prerequisites.length <= numCourses * (numCourses - 1)
prerequisites[i].length == 2
0 <= a_i, b_i < numCourses
a_i != b_i
Все пары [a_i, b_i] различны.
*/

// findOrder выполняет DFS по зависимостям и выявляет цикл по активному пути.
// Время в среднем O(n+m), n = numCourses, m = len(prerequisites):
// ключи map — int, а каждый курс и его зависимости обрабатываются один раз.
// Рабочая память O(n+m) для графа, отметок и стека; результат O(n).
// Входные prerequisites не изменяются, порядок построен в локальном output.
func findOrder(numCourses int, prerequisites [][]int) []int {
    // Ребро идёт от курса к обязательному предшественнику: после
    // рекурсивного обхода предшественника можно сразу добавить сам курс.
    prereq := make(map[int][]int)
    for i := 0; i < numCourses; i++ {
        prereq[i] = []int{}
	}
	for _, pair := range prerequisites {
		crs, pre := pair[0], pair[1]
        prereq[crs] = append(prereq[crs], pre)
	}

	output := []int{}
    // visit содержит полностью проверенные курсы, cycle — только
    // текущий рекурсивный путь. Повтор из visit не означает цикл.
    visit := make(map[int]struct{})
    cycle := make(map[int]struct{})

    var dfs func(int) bool
    // dfs проверяет зависимости crs и дописывает курс после них.
    // Время в среднем O(n+m) для полного поиска, O(1) для visit-hit;
    // n и m определены выше. Рабочий стек и новые отметки O(n),
    // дописываемый output O(n). Меняет захваченные cycle, visit, output;
    // граф prereq и входные данные не изменяет.
    dfs = func(crs int) bool {
        // Возврат в ещё активную вершину замыкает направленный цикл.
        if _, ok := cycle[crs]; ok {
            return false
        }
        if _, ok := visit[crs]; ok {
            return true
        }

        cycle[crs] = struct{}{}
        for _, pre := range prereq[crs] {
            if !dfs(pre) {
                return false
            }
        }
        // Все зависимости успешно добавлены раньше crs. Удаляем его
        // из активного пути и отмечаем готовым, чтобы не обходить повторно.
        delete(cycle, crs)
        visit[crs] = struct{}{}
        output = append(output, crs)
        return true
    }

    // Запускаем поиск также из изолированных курсов и других компонент.
    // При цикле немедленно возвращаем пустой ответ: частичный не годится.
    for i := range numCourses {
        if !dfs(i) {
            return []int{}
        }
    }

    return output
}
