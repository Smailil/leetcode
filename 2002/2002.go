package main

/*
Дана строка s. Найдите две непересекающиеся палиндромные подпоследовательности
строки s так, чтобы произведение их длин было максимальным. Две
подпоследовательности не пересекаются, если они не содержат символ с одним и
тем же индексом.

Верните максимально возможное произведение длин двух палиндромных
подпоследовательностей.

Подпоследовательность — это строка, которую можно получить из другой строки,
удалив некоторые символы или не удаляя ни одного и не меняя порядок оставшихся
символов. Строка является палиндромом, если она одинаково читается слева
направо и справа налево.

Пример 1:
example-1
Вход: s = "leetcodecom"
Выход: 9
Пояснение: оптимальное решение — выбрать "ete" в качестве первой
подпоследовательности и "cdc" в качестве второй подпоследовательности.
Произведение их длин: 3 * 3 = 9.

Пример 2:
Вход: s = "bb"
Выход: 1
Пояснение: оптимальное решение — выбрать "b" (первый символ) в качестве первой
подпоследовательности и "b" (второй символ) в качестве второй
подпоследовательности.
Произведение их длин: 1 * 1 = 1.

Пример 3:
Вход: s = "accbcaxxcxx"
Выход: 25
Пояснение: оптимальное решение — выбрать "accca" в качестве первой
подпоследовательности и "xxcxx" в качестве второй подпоследовательности.
Произведение их длин: 5 * 5 = 25.

Ограничения:
2 <= s.length <= 12
Строка s состоит только из строчных английских букв.
*/

// maxProduct находит наибольшее произведение длин двух непересекающихся
// палиндромных подпоследовательностей. Маска задаёт первую, а для оставшихся
// символов динамическое программирование ищет самую длинную вторую.
// Время: O(2^n * n^2), где n = len(s): для каждой маски выполняется
// проход по парам индексов. Дополнительная память: O(n) для dp.
func maxProduct(s string) int {
    n := len(s)
    res := 0
    // Один и тот же массив dp используется для всех масок; перед каждым
    // новым поиском второй подпоследовательности он заполняется заново.
    dp := make([]int, n)

    // В mask единичные биты принадлежат первой подпоследовательности.
    // Здесь ищем длину наибольшей палиндромной подпоследовательности среди
    // позиций с нулевыми битами. Так они не пересекутся с первой.
    longestPalindromeSubseq := func(mask int) int {
        // После обработки i значение dp[j] описывает доступные позиции [i, j].
        // Если i уже занят первой подпоследовательностью, прежние значения
        // для диапазона [i+1, j] остаются верными и без обновления.
        for i := n - 1; i >= 0; i-- {
            if (mask & (1 << i)) != 0 {
                continue
            }

            // До обновления dp[j] хранит ответ для [i+1, j], а dp[j-1]
            // уже хранит ответ для [i, j-1]. prev — старое dp[j-1], то есть
            // ответ для внутреннего диапазона [i+1, j-1].
            prev := 0
            for j := i + 1; j < n; j++ {
                tmp := dp[j]
                // Совпавшие доступные края дополняют внутренний палиндром:
                // у "aba" два крайних "a" дают 2 + 1 за внутреннюю "b".
                if (mask&(1<<j)) == 0 && s[i] == s[j] {
                    dp[j] = 2 + prev
                } else {
                    // Если края не подходят, исключаем один из них и берём
                    // лучший из двух уже вычисленных вариантов.
                    dp[j] = max(dp[j-1], dp[j])
                }
                // На следующем j старое dp[j] станет ответом для внутреннего
                // диапазона, который потребуется при совпадении новых краёв.
                prev = tmp
            }
        }
        return dp[n-1]
    }

    // Проверяем, образуют ли выбранные mask позиции палиндром. Пропускаем
    // позиции с нулевыми битами с обоих концов и сравниваем выбранные буквы.
    // Ноль означает, что выбранная подпоследовательность не палиндромна.
    palsize := func(mask int) int {
        i, j := 0, n-1
        res := 0
        for i <= j {
            if (mask & (1 << i)) == 0 {
                i++
            } else if (mask & (1 << j)) == 0 {
                j--
            } else {
                if s[i] != s[j] {
                    return 0
                }
                // Средний символ учитывается один раз, остальные — парами.
                if i == j {
                    res += 1
                } else {
                    res += 2
                }
                i++
                j--
            }
        }
        return res
    }

    // Перебираем все непустые варианты первой подпоследовательности.
    // Непалиндромные маски отбрасываем до более дорогого поиска второй.
    for i := 1; i < (1 << n); i++ {
        m1 := palsize(i)
        if m1 == 0 {
            continue
        }

        // Для одного доступного символа ответ равен 1, для занятого — 0.
        // Так следующая маска не унаследует значения dp от предыдущей.
        for j := 0; j < n; j++ {
            if (i & (1 << j)) == 0 {
                dp[j] = 1
            } else {
                dp[j] = 0
            }
        }
        // Первая подпоследовательность имеет длину m1, а вторая выбирается
        // оптимально среди не занятых ею позиций.
        m2 := longestPalindromeSubseq(i)
        res = max(res, m1*m2)
    }

    return res
}
