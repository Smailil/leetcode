package main

import "sort"

/*
Даны массив целых чисел nums и целое число target.

Верните число непустых подпоследовательностей nums,
в которых сумма минимального и максимального элементов не превышает target.
Ответ может быть очень большим, поэтому верните его по модулю 10^9 + 7.

Пример 1:
Вход: nums = [3,5,6,7], target = 9
Выход: 4
Пояснение: условию удовлетворяют 4 подпоследовательности.
[3] -> Минимум + максимум <= target (3 + 3 <= 9)
[3,5] -> (3 + 5 <= 9)
[3,5,6] -> (3 + 6 <= 9)
[3,6] -> (3 + 6 <= 9)

Пример 2:
Вход: nums = [3,3,6,8], target = 10
Выход: 6
Пояснение: условию удовлетворяют 6 подпоследовательностей.
Массив nums может содержать повторяющиеся числа.
[3] , [3] , [3,3], [3,6] , [3,6] , [3,3,6]

Пример 3:
Вход: nums = [2,3,3,4,6,7], target = 12
Выход: 61
Пояснение: всего существует 63 непустые подпоследовательности.
Две из них не удовлетворяют условию: [6,7] и [7].
Число допустимых подпоследовательностей: 63 - 2 = 61.

Ограничения:
1 <= nums.length <= 10^5
1 <= nums[i] <= 10^6
1 <= target <= 10^6
*/

// numSubseq считает допустимые непустые подпоследовательности по модулю MOD.
// Использует сортировку, два указателя и подсчёт независимых выборов.
// Сортировка изменяет входной nums на месте.
// Время: O(n log n), где n = len(nums), включая сортировку и вызовы power.
// Дополнительная память: O(log n) на стек сортировки;
// остальные переменные и power используют O(1) памяти.
// Результат — скаляр int O(1), отдельный массив не создаётся.
func numSubseq(nums []int, target int) int {
    // Подпоследовательность задаётся выбором индексов исходного массива.
    // Условие зависит только от минимума и максимума, а не от порядка.
    // Сортировка сохраняет число выборов, включая разные копии одного числа.
    sort.Ints(nums)
    MOD := 1000000007
    res := 0

    // r — кандидат на правую границу; уточняем его для каждого nums[i].
    r := len(nums) - 1

    // power вычисляет base^exp % mod бинарным возведением в степень.
    // Для e = исходный exp время O(log(e + 1)), память O(1).
    // В этих вызовах exp >= 0 и mod = MOD > 0.
    // Результат int O(1); меняются локальные копии параметров, не nums.
    power := func(base, exp, mod int) int {
        // result накапливает степени для уже обработанных единичных битов.
        // b соответствует степени основания для текущего бита exp.
        result := 1
        b := base

        // В этих вызовах множители < MOD: произведение < MOD^2 < 2^63.
        // Умножения безопасны для 64-битного int, но не для 32-битного.
        for exp > 0 {
            // Младший бит 1 означает, что текущая степень b нужна в ответе.
            if exp&1 == 1 {
                result = (result * b) % mod
            }

            // Квадрат b отвечает следующему биту; сдвиг убирает текущий бит.
            b = (b * b) % mod
            exp >>= 1
        }
        return result
    }

    // При росте i минимум не уменьшается: отвергнутые максимумы не подходят.
    // Поэтому r движется только влево, суммарно не более n раз.
    for i := range nums {
        // Убираем слишком большие максимумы для текущего минимума nums[i].
        // && сначала проверяет i <= r: nums[r] не читается при r < i,
        // в том числе когда r становится равным -1.
        for i <= r && nums[i]+nums[r] > target {
            r--
        }

        // Если i > r, даже одиночное nums[i] не подходит: добавлять нечего.
        if i <= r {
            // Индекс i выбираем обязательно как первый выбранный индекс.
            // Каждую из r-i позиций от i+1 до r можно взять или пропустить.
            // Любой такой выбор допустим: его максимум не больше nums[r].
            // Значит, получаем 2^(r-i) вариантов без пустого набора.
            // Например, допустимый диапазон [3,5,6] даёт 2^2 = 4 варианта:
            // [3], [3,5], [3,6], [3,5,6].
            res = (res + power(2, r-i, MOD)) % MOD
        }
    }

    // Выборы разных итераций не пересекаются: первый выбранный индекс разный.
    return res
}