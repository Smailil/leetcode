package main

/*
Дан корень двоичного дерева, верните его максимальную глубину.
Максимальная глубина двоичного дерева — это количество узлов
на самом длинном пути от корневого узла до самого дальнего листового узла.

Пример 1:
Вход: root = [3,9,20,null,null,15,7]
Выход: 3

Пример 2:
Вход: root = [1,null,2]
Выход: 2

Ограничения:
Количество узлов в дереве находится в диапазоне [0, 10^4].
-100 <= Node.val <= 100
*/

type TreeNode struct {
	Val   int
	Left  *TreeNode
	Right *TreeNode
}

// maxDepth считает число узлов на самом длинном пути рекурсивно.
// n — число узлов, h — высота; время O(n+1), рабочая память O(h+1).
// У вырожденного дерева h=n; результат — число, дерево не изменяется.
func maxDepth(root *TreeNode) int {
	// Пустое дерево имеет глубину 0 и останавливает рекурсию.
	if root == nil {
		return 0
	}
	// Каждый непустой путь содержит корень и путь одного из детей.
	// Поэтому глубина равна 1 + максимум двух дочерних глубин.
	return 1 + max(maxDepth(root.Left), maxDepth(root.Right))
}
