package main

/*
Напишите функцию, которая переворачивает строку.
Входная строка передаётся в виде массива символов s.

Вы должны сделать это, изменяя входной массив на месте
с O(1) дополнительной памяти.

Пример 1:
Вход: s = ["h","e","l","l","o"]
Выход: ["o","l","l","e","h"]

Пример 2:
Вход: s = ["H","a","n","n","a","h"]
Выход: ["h","a","n","n","a","H"]

Ограничения:
1 <= s.length <= 10^5
s[i] — это печатный ASCII-символ.
*/

// reverseString разворачивает ASCII-байты встречными обменами.
// Время O(n), n=len(s); рабочая память O(1), новый результат не выделяется.
// Входной срез s изменяется на месте.
func reverseString(s []byte) {
    l, r := 0, len(s)-1
    // Снаружи [l,r] байты уже на финальных местах; внутри ещё не обработаны.
    // l меньше r гарантирует допустимые разные индексы; центр менять не надо.
    for l < r {
        s[l], s[r] = s[r], s[l]
        l++
        r--
    }
}
