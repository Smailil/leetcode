package main

import "fmt"

/*
Дана строка path, где каждый символ path[i] равен 'N', 'S', 'E' или 'W' и
означает перемещение на одну единицу соответственно на север, юг, восток или
запад. Вы начинаете путь в начале координат (0, 0) на двумерной плоскости и
двигаетесь по маршруту, заданному строкой path.

Верните true, если путь пересекает сам себя в какой-либо точке, то есть если
вы повторно оказываетесь в ранее посещённой позиции. В противном случае
верните false.

Пример 1:
https://assets.leetcode.com/uploads/2020/06/10/screen-shot-2020-06-10-at-123929-pm.png
Вход: path = "NES"
Выход: false
Пояснение: путь не проходит ни через одну точку более одного раза.

Пример 2:
Вход: path = "NESWW"
Выход: true
Пояснение: путь дважды проходит через начало координат.

Ограничения:
1 <= path.length <= 10^4
path[i] принимает одно из значений: 'N', 'S', 'E' или 'W'.
*/

// isPathCrossing проверяет, посещает ли маршрут одну координату более одного
// раза. Для этого функция запоминает каждую достигнутую позицию и ищет повтор
// сразу после очередного перемещения.
//
// Время: O(n), где n = len(path). Для целых чисел фиксированной разрядности
// формирование и проверка строкового ключа занимает O(1) на каждом шаге.
// Дополнительная память: O(n), поскольку map хранит не более n + 1 позиций.
func isPathCrossing(path string) bool {
    visit := make(map[string]bool)
    x, y := 0, 0
    // Начальная точка тоже считается посещённой, поэтому возвращение в (0, 0)
    // будет обнаружено так же, как повтор любой другой позиции.
    visit[fmt.Sprintf("%d,%d", x, y)] = true

    for _, c := range path {
        // Обновляем ровно одну координату в соответствии с текущим шагом.
        // По условию другие символы в path не встречаются.
        switch c {
		case 'N':
            y++
        case 'S':
            y--
        case 'E':
            x++
        case 'W':
            x--
        }

        // Запятая однозначно разделяет x и y в ключе даже для отрицательных
        // координат, поэтому разные точки не получают одинаковую строку.
        pos := fmt.Sprintf("%d,%d", x, y)
        // Проверяем позицию до добавления: наличие ключа означает пересечение.
        if visit[pos] {
            return true
        }
        // Новая точка становится частью истории для следующих шагов.
        visit[pos] = true
    }

    // Если повторов не найдено после всех шагов, путь себя не пересекает.
    return false
}