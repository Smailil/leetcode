package main

/*
Напишите алгоритм, определяющий, является ли число n счастливым.
Счастливое число — это число, определяемое следующим процессом:
Начиная с любого положительного целого числа,
замените число суммой квадратов его цифр.
Повторяйте процесс до тех пор, пока число не станет равным 1
(где оно и останется), или пока он не будет повторяться бесконечно в цикле,
который не включает 1.
Счастливыми являются те числа, для которых этот процесс заканчивается на 1.
Возвращайте true, если n — счастливое число, и false, если нет.

Пример 1:
Вход: n = 19
Выход: true
Объяснение:
1^2 + 9^2 = 82
8^2 + 2^2 = 68
6^2 + 8^2 = 100
1^2 + 0^2 + 0^2 = 1

Пример 2:
Вход: n = 2
Выход: false

Ограничения:
1 <= n <= 2^31 - 1
*/

// Алгоритм использует метод Флойда "черепаха и заяц"
// для обнаружения цикла без использования дополнительной памяти.
// isHappy проверяет, приводит ли цепочка сумм квадратов цифр к 1.
// Время O(T*d): T переходов до встречи, d — максимальное число цифр состояния.
// При данном 32-битном диапазоне это O(1): после первого шага число до 810,
// а множество дальнейших состояний конечно и ограничено постоянной.
// Рабочая память и результат O(1); вход передан по значению.
func isHappy(n int) bool {
    // Инициализируем два указателя:
    // slow ("черепаха") — делает один шаг за итерацию
    // fast ("заяц") — делает два шага за итерацию
    slow, fast := n, sumOfSquares(n)

    // Двигаем указатели, пока они не встретятся.
    // Если есть цикл — они обязательно встретятся внутри него.
    // Если число счастливое — оба указателя сойдутся на значении 1.
    for slow != fast {
        // "Заяц" делает два шага: применяем sumOfSquares дважды
        fast = sumOfSquares(fast)
        fast = sumOfSquares(fast)
        // "Черепаха" делает один шаг
        slow = sumOfSquares(slow)
    }

    // Если указатели сошлись на 1 — число счастливое.
    // Если сошлись на другом числе — значит, попали в цикл,
    // число не счастливое.
    return fast == 1
}

// sumOfSquares извлекает десятичные цифры и суммирует их квадраты.
// Время O(d), d — число цифр n; при фиксированной разрядности это O(1).
// Рабочая память и результат O(1); меняется только локальная копия n.
func sumOfSquares(n int) int {
    output := 0
    for n > 0 {
        // Остаток при делении на 10 даёт цифру в [0,9], делитель ненулевой.
        digit := n % 10
        output += digit * digit
        // Целочисленное деление убирает обработанную младшую цифру.
        n = n / 10
    }
    return output
}