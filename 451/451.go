package main

import "strings"

/*
Дана строка s.
Отсортируйте её символы по убыванию частоты.
Частота символа — количество его вхождений в строку.

Верните отсортированную строку.
Если возможны несколько ответов, верните любой из них.

Пример 1:
Вход: s = "tree"
Выход: "eert"
Пояснение: 'e' встречается дважды, а 'r' и 't' — по одному разу.
Поэтому 'e' должен стоять перед 'r' и 't'.
Таким образом, "eetr" — тоже допустимый ответ.

Пример 2:
Вход: s = "cccaaa"
Выход: "aaaccc"
Пояснение: 'c' и 'a' встречаются по три раза.
Поэтому и "cccaaa", и "aaaccc" — допустимые ответы.
Ответ "cacaca" неверен, поскольку одинаковые символы должны идти подряд.

Пример 3:
Вход: s = "Aabb"
Выход: "bbAa"
Пояснение: "bbaA" — тоже допустимый ответ, а "Aabb" — неверный.
Символы 'A' и 'a' считаются разными.

Ограничения:
1 <= s.length <= 5 * 10^5
s состоит из строчных и прописных английских букв и цифр.
*/

// frequencySort группирует символы s по убыванию числа их вхождений.
// Частоты хранятся в map, символы — в корзинах с индексом-частотой.
// n = len(s), k — количество разных символов; по условию k <= 62.
// Время: O(n + k) в среднем, то есть O(n); рост Builder амортизирован.
// Дополнительная рабочая память без результата: O(n + k) = O(n).
// Память результата: O(n), включая удерживаемый буфер Builder.
// Входная строка s не изменяется.
func frequencySort(s string) string {
    // range читает s по рунам. По условию все символы ASCII, поэтому
    // число рун совпадает с n; 'A' и 'a' — разные ключи.
    // В count будет k записей: O(k), при k <= 62 это O(1).
    count := make(map[rune]int)
    for _, c := range s {
        count[c]++
    }

    // buckets[f] хранит символы с частотой f. Частота не больше n,
    // поэтому для индексов от 0 до n требуется n+1 корзина.
    // Массив корзин и его инициализация требуют O(n), даже если k мало.
    buckets := make([][]rune, len(s)+1)
    for i := range buckets {
        buckets[i] = []rune{}
    }

    // Каждый символ кладём один раз в корзину с номером, равным его частоте.
    // Всего здесь k рун, не n: повторения появятся при сборке результата.
    // Для "tree" корзина 2 содержит 'e', корзина 1 — 'r' и 't'.
    for char, freq := range count {
        buckets[freq] = append(buckets[freq], char)
    }

    // Builder дописывает результат в общий буфер, а не склеивает строки.
    // Все записи суммарно занимают O(n) с учётом роста буфера.
    var res strings.Builder
    // Частые символы выводим первыми, спускаясь по частотам от n до 1.
    // Внутри одной частоты порядок произволен из-за обхода map.
    // Внешний цикл проверяет n корзин. Вложенные циклы всего обходят
    // k символов и записывают n рун: сумма всех их частот равна n.
    for i := len(s); i > 0; i-- {
        for _, c := range buckets[i] {
            // Выписываем все i копий c подряд, прежде чем перейдём
            // к другому символу: одинаковые символы не перемешиваются.
            for j := 0; j < i; j++ {
                res.WriteRune(c)
            }
        }
    }

    // String возвращает строку на том же буфере без копирования.
    // Его полная ёмкость удерживается результатом и уже учтена как O(n).
    return res.String()
}