package main

/*
Дано двоичное дерево поиска (BST),
найдите узел наименьшего общего предка (LCA) из двух заданных узлов в BST.
Согласно определению LCA в Википедии:
«Наименьший общий предок определяется между двумя узлами p и q
как самый нижний узел в T, который имеет как p, так и q в качестве потомков
(где мы позволяем узлу быть потомком самого себя)».

Пример 1:
Вход: root = [6,2,8,0,4,7,9,null,null,3,5], p = 2, q = 8
Выход: 6
Пояснение: LCA узлов 2 и 8 равен 6.

Пример 2:
Вход: root = [6,2,8,0,4,7,9,null,null,3,5], p = 2, q = 4
Выход: 2
Объяснение: LCA узлов 2 и 4 равен 2, поскольку согласно определению LCA
узел может быть потомком самого себя.

Пример 3:
Вход: root = [2,1], p = 2, q = 1
Выход: 2

Ограничения:
Количество узлов в дереве находится в диапазоне [2, 10^5].
-10^9 <= Node.val <= 10^9
Все Node.val уникальны.
p != q
p и q будут существовать в BST.
*/

type TreeNode struct {
    Val   int
    Left  *TreeNode
    Right *TreeNode
}


// lowestCommonAncestor спускается по BST до расхождения путей p и q.
// h — высота дерева: время O(h), рабочая память O(1).
// Новых узлов нет; ссылка результата O(1) удерживает исходное поддерево
// предка из S узлов, O(S). Дерево не меняется.
// По условию p/q существуют, не nil, значения всех узлов различны.
func lowestCommonAncestor(root, p, q *TreeNode) *TreeNode {
	cur := root
	// Инвариант: оба искомых узла принадлежат поддереву cur.
	// При переходе на общую сторону BST сохраняет этот инвариант.
	for cur != nil {
		if p.Val > cur.Val && q.Val > cur.Val {
			cur = cur.Right
		} else if p.Val < cur.Val && q.Val < cur.Val {
			cur = cur.Left
		// Пути расходятся либо cur совпадает с p/q. Ни один ребёнок
		// не содержит оба узла: cur — самый нижний общий предок.
		} else {
			return cur
		}
	}
	// Для допустимого входа найденный предок вернулся внутри цикла.
	// Этот возврат nil относится только к входу вне контрактных гарантий.
	return cur
}
