package main

import "math"

/*
Даны две строки s и t длиной m и n соответственно.
Верните подстроку s минимальной длины, содержащую каждый символ t,
включая дубликаты.
Если такой подстроки нет, верните пустую строку "".
Тестовые примеры будут сгенерированы таким образом, чтобы ответ был уникальным.

Пример 1:
Вход: s = "ADOBECODEBANC", t = "ABC"
Выход: "BANC"
Объяснение: Подстрока минимального окна "BANC"
включает "A", "B" и "C" из строки t.

Пример 2:
Вход: s = "a", t = "a"
Выход: "a"
Объяснение: Вся строка s представляет собой минимальное окно.

Пример 3:
Вход: s = "a", t = "aa"
Выход: ""
Объяснение: В окно должны быть включены обе буквы 'a' из t.
Поскольку самое большое окно s имеет только одну букву 'a',
верните пустую строку.

Ограничения:
m == s.length
n == t.length
1 <= m, n <= 10^5
s и t состоят из прописных и строчных английских букв.
*/
const GREATER = math.MaxInt32

// minWindow ищет кратчайшее окно s, покрывающее частоты символов t.
// Правая граница расширяет окно, левая сужает каждое допустимое окно.
// Среднее время O(m+n), где m=len(s), n=len(t), при O(1) операциях map.
// Обе границы идут только вперёд.
// Рабочая память O(A), где A — число разных байтов в s и t (до 52 здесь).
// Результат — заголовок строки O(1), без копирования выбранных байтов.
// Непустая подстрока может удерживать весь буфер s размера O(m).
// Строки не изменяются; побочных эффектов нет.
func minWindow(s string, t string) string {
    if len(t) < 1 || len(s) < len(t) {
		return ""
	}
	// countT хранит требуемые частоты, window — частоты окна [l,r].
	countT := make(map[byte]int)
	for i:=0;i<len(t);i++ {
		countT[t[i]]++
	}
	window := make(map[byte]int)
	// have считает покрытые РАЗНЫЕ байты, need — число требований.
	// Дубликаты t учитываются частотами, а не увеличением need.
	have, need := 0, len(countT)
	res, resLen := [2]int{-1, -1}, GREATER
	l, r := 0, 0
	for ;r < len(s); r++ {
		c := s[r]
		window[c]++

		// Требование становится покрытым только при достижении его частоты.
		if count, ok := countT[c]; ok && count == window[c]{
			have++
		}
		// Пока всё покрыто, сохраняем кандидат и пытаемся укоротить окно.
		for have == need {
			if resLen > r - l + 1 {
				res = [2]int{l, r}
				resLen = r - l + 1
			}
			// Удаление теряет покрытие только при переходе ниже нужной частоты.
			window[s[l]]--
			if count, ok := countT[s[l]]; ok && count - 1 == window[s[l]] {
				have--
			}
			l++
		}
	}
	// GREATER остаётся только если допустимых окон не было.
	if resLen == GREATER {
		return ""
	}
	// res хранит включённые границы, а правая граница среза исключается.
	return s[res[0]:res[1] + 1]
}
