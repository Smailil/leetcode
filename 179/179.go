package main

import (
	"sort"
	"strconv"
	"strings"
)

/*
Дан список неотрицательных целых чисел nums. Расположите их так, чтобы
они образовали наибольшее возможное число, и верните его.

Результат может быть очень большим, поэтому верните строку, а не целое число.

Пример 1:
Вход: nums = [10,2]
Выход: "210"

Пример 2:
Вход: nums = [3,30,34,5,9]
Выход: "9534330"

Ограничения:
1 <= nums.length <= 100
0 <= nums[i] <= 10^9
*/

// largestNumber возвращает строку с наибольшим числом, которое можно
// составить конкатенацией элементов nums.
// Сортируем элементы по выгодности порядка их конкатенации; nums не меняется.
// Время O(n k log n), где n = len(nums), k — максимум цифр в одном числе;
// при k <= 10 это O(n log n). Рабочая память O(nk), память результата O(nk).
func largestNumber(nums []int) string {
    // Преобразуем числа в строки один раз: далее сравниваем не их значения,
    // а варианты записи двух чисел подряд.
    arr := make([]string, len(nums))
    for i, num := range nums {
        arr[i] = strconv.Itoa(num)
    }

    // Для пары a, b порядок a,b выгоднее, когда a+b > b+a. Длины обеих
    // склеек равны, поэтому сравнение строк соответствует сравнению чисел.
    // Если b стоит перед a при a+b > b+a, обмен улучшит весь результат.
    sort.Slice(arr, func(i, j int) bool {
        return arr[i]+arr[j] > arr[j]+arr[i]
    })

    // После сортировки остаётся склеить элементы в найденном порядке.
    res := strings.Join(arr, "")
    // Если впереди "0", все элементы равны нулю: иначе ненулевой стоял бы
    // раньше. По условию nums не пуст, поэтому обращение к res[0] безопасно.
    if res[0] == '0' {
        return "0"
    }
    return res
}
