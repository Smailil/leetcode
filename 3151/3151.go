package main

/*
Массив считается особым, если у каждой пары соседних элементов различается
чётность. Иными словами, один элемент каждой пары должен быть чётным,
а другой — нечётным.

Дан массив целых чисел nums. Верните true, если nums является особым массивом,
иначе верните false.

Пример 1:
Вход: nums = [1]
Выход: true
Пояснение: в массиве только один элемент, поэтому ответ — true.

Пример 2:
Вход: nums = [2,1,4]
Выход: true
Пояснение: существуют только две пары: (2,1) и (1,4). Обе содержат числа
разной чётности, поэтому ответ — true.

Пример 3:
Вход: nums = [4,3,1,6]
Выход: false
Пояснение: nums[1] и nums[2] — нечётные, поэтому ответ — false.

Ограничения:
1 <= nums.length <= 100
1 <= nums[i] <= 100
*/

// isArraySpecial проверяет, чередуется ли чётность соседних элементов.
// Функция последовательно сравнивает соседние пары и сразу завершает проверку
// при первом совпадении чётности.
// Время: O(n), где n = len(nums). Дополнительная память: O(1).
func isArraySpecial(nums []int) bool {
    // На входе каждой итерации все пары до индекса i уже имеют разную
    // чётность; остаётся проверить пару nums[i-1] и nums[i].
    for i := 1; i < len(nums); i++ {
        // Младший бит равен 0 у чётного числа и 1 у нечётного. Равенство
        // битов означает, что текущая пара нарушает условие особого массива.
        if (nums[i-1] & 1) == (nums[i] & 1) {
            return false
        }
    }
    // Если нарушение не найдено, все соседние пары имеют разную чётность.
    // Для массива из одного элемента цикл не выполняется, что даёт true.
    return true
}