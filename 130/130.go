package main

/*
Дана матрица board размером m x n, содержащая буквы «X» и «O».
Захватите окружённые области:
Соединение: ячейка соединяется с соседними ячейками по горизонтали
или по вертикали.
Область: группа соединённых ячеек «O».
Окружение: область окружена, если ни одна её ячейка «O» не находится
на границе доски.
Такие области полностью окружены ячейками «X».
Чтобы захватить окружённую область, замените все буквы «O» на «X»
на исходной доске.
Ничего возвращать не требуется.

Пример 1:
Вход: board = [["X","X","X","X"],
				["X","O","O","X"],
				["X","X","O","X"],
				["X","O","X","X"]]
Выход: [["X","X","X","X"],
		 ["X","X","X","X"],
		 ["X","X","X","X"],
		 ["X","O","X","X"]]
Объяснение:
https://assets.leetcode.com/uploads/2021/02/19/xogrid.jpg
На приведенной выше диаграмме нижняя область не захвачена,
поскольку она находится на краю доски и не может быть окружена.

Пример 2:
Вход: board = [["X"]]
Выход: [["X"]]

Ограничения:
m == board.length
n == board[i].length
1 <= m, n <= 200
board[i][j] имеет значение «X» или «O».
*/

// solve сохраняет граничные области через временную метку 'L', остальные
// заменяет на 'X'. R = len(board), C = len(board[0]): время O(R*C),
// дополнительный стек O(R*C) в худшем случае; отдельного результата нет.
// board меняется на месте. По условию R >= 1, C >= 1, строки прямоугольны.
func solve(board [][]byte)  {
    rows, cols := len(board), len(board[0])
	var lockCell func(int, int)
	// lockCell помечает ещё не посещённую область 'O', достижимую из (r,c).
	// Для S новых ячеек: время O(S+1), стек O(S+1); меняет общий board.
	// При вызове вне доски или не на 'O' выполняется только проверка, O(1).
	lockCell = func(r, c int) {
		// Вызовы сдвигают допустимые координаты лишь на 1, поэтому за верхней
		// границей возможны ровно rows/cols. Короткое замыкание || не даёт
		// читать board[r][c] до проверки границ.
		if r < 0 || c < 0 || r == rows ||
           c == cols || board[r][c] != 'O' {
            return
        }
        // Помечаем до рекурсии: сосед не сможет вернуться в уже посещённую
        // ячейку. По условию 'L' не встречается в исходной доске.
        board[r][c] = 'L'
        lockCell(r+1, c)
        lockCell(r-1, c)
        lockCell(r, c+1)
        lockCell(r, c-1)
	}
	// Каждая неокружённая область имеет 'O' на границе. Сначала запускаем
	// DFS с левого и правого краёв, сохраняя все связанные с ними ячейки.
	for r := range rows {
        if board[r][0] == 'O' {
            lockCell(r, 0)
        }
        if board[r][cols-1] == 'O' {
            lockCell(r, cols-1)
        }
    }

    // Затем обрабатываем верхний и нижний края. Уже помеченные 'L' ячейки
    // не обходятся снова, в том числе углы при R=1 или C=1.
    for c := range cols {
        if board[0][c] == 'O' {
            lockCell(0, c)
        }
        if board[rows-1][c] == 'O' {
            lockCell(rows-1, c)
        }
    }

	// Остались только окружённые 'O': превращаем их в 'X'. Метки 'L'
	// восстанавливаем в 'O', завершая изменение доски без отдельного буфера.
	for r := range rows {
		for c := range cols {
			switch board[r][c] {
			case 'O':
				board[r][c] = 'X'
			case 'L':
				board[r][c] = 'O'
			}
		}
	}
}
