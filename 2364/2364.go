package main

/*
Дан целочисленный массив nums с индексацией с 0.
Пара индексов (i, j) называется плохой, если i < j и
j - i != nums[j] - nums[i].

Верните общее количество плохих пар в nums.

Пример 1:
Вход: nums = [4,1,3,3]
Выход: 5
Пояснение: пара (0, 1) плохая, поскольку 1 - 0 != 1 - 4.
Пара (0, 2) плохая, поскольку 2 - 0 != 3 - 4, 2 != -1.
Пара (0, 3) плохая, поскольку 3 - 0 != 3 - 4, 3 != -1.
Пара (1, 2) плохая, поскольку 2 - 1 != 3 - 1, 1 != 2.
Пара (2, 3) плохая, поскольку 3 - 2 != 3 - 3, 1 != 0.
Всего есть 5 плохих пар, поэтому возвращаем 5.

Пример 2:
Вход: nums = [1,2,3,4,5]
Выход: 0
Пояснение: плохих пар нет.

Ограничения:
1 <= nums.length <= 10^5
1 <= nums[i] <= 10^9
*/

// countBadPairs возвращает количество плохих пар индексов в nums.
// Считает все пары и вычитает хорошие, группируя индексы по nums[i]-i.
// Время: в среднем O(n), где n = len(nums); nums не изменяется.
// Дополнительная память: O(k) для k различных ключей, k <= n.
// В худшем случае память O(n); счётчики и результат занимают O(1).
func countBadPairs(nums []int) int64 {
    // Хорошая пара (a, b): b-a = nums[b]-nums[a], где a < b.
    // Перенос слагаемых даёт nums[b]-b = nums[a]-a.
    // В count храним частоты этих ключей только для пройденных индексов.
    count := make(map[int]int)
    // total — все пары пройденного префикса, good — хорошие среди них.
    // Максимум n*(n-1)/2 = 4 999 950 000 при n = 10^5: нужен int64.
    var total, good int64 = 0, 0
    for i := range nums {
        // Сейчас i — правый индекс; текущего элемента в count ещё нет.
        // 2-n <= key <= 10^9, а частота <= n <= 10^5: оба значения
        // помещаются даже в 32-битный int при заданных ограничениях.
        key := nums[i] - i
        // Каждый прежний индекс с таким ключом даёт одну хорошую пару с i.
        // Отсутствующий ключ даёт 0: подходящих левых индексов пока нет.
        // Для [4,1,3,3] ключи равны [4,0,1,0].
        // При i = 3 ключ 0 уже был у индекса 1: получаем хорошую пару (1,3).
        good += int64(count[key])
        // Добавляем i после подсчёта, чтобы не учесть недопустимую пару (i,i).
        count[key]++
        // Для правого индекса i есть ровно i левых индексов: 0..i-1.
        // Приведение к int64 выполняется до сложения с общим счётчиком.
        total += int64(i)
    }
    // Каждая пара учтена один раз, когда обработан её правый индекс.
    // Плохие пары — все, кроме хороших; в первом примере получаем 6-1 = 5.
    return total - good
}