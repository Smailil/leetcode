package main

/*
Дан массив nums. Верните true, если массив изначально был отсортирован в
неубывающем порядке, а затем циклически сдвинут на некоторое число позиций
(включая ноль). В противном случае верните false.

В исходном массиве могут быть повторяющиеся элементы.

Примечание: при циклическом сдвиге массива A на x позиций получается
массив B той же длины, для которого B[i] == A[(i+x) % A.length] для каждого
допустимого индекса i.

Пример 1:
Вход: nums = [3,4,5,1,2]
Выход: true
Пояснение: [1,2,3,4,5] — исходный отсортированный массив.
Его можно циклически сдвинуть на x = 2 позиции, чтобы он начинался с элемента
со значением 3: [3,4,5,1,2].

Пример 2:
Вход: nums = [2,1,3,4]
Выход: false
Пояснение: не существует отсортированного массива, циклический сдвиг которого
даёт nums.

Пример 3:
Вход: nums = [1,2,3]
Выход: true
Пояснение: [1,2,3] — исходный отсортированный массив.
Его можно циклически сдвинуть на x = 0 позиций (то есть не выполнять сдвиг),
чтобы получить nums.

Ограничения:
1 <= nums.length <= 100
1 <= nums[i] <= 100
*/

// check определяет, можно ли получить nums циклическим сдвигом массива,
// отсортированного в неубывающем порядке. Для этого дважды обходит nums
// как кольцо и ищет непрерывный неубывающий фрагмент длины n.
// Время: O(n), где n = len(nums). Дополнительная память: O(1).
func check(nums []int) bool {
    N := len(nums)
    // count хранит длину текущего неубывающего фрагмента в циклическом
    // обходе. Первый элемент уже образует фрагмент длины 1.
    count := 1

    // Два прохода охватывают каждую возможную точку начала отрезка длины N.
    // По условию N >= 1, поэтому % N безопасен и всегда даёт индекс массива.
    // При N <= 100 выражение 2*N также не может переполнить int.
    for i := 1; i < 2*N; i++ {
        // Продлеваем фрагмент только при сохранении неубывания. После нарушения
        // текущий элемент начинает новый возможный фрагмент длины 1.
        if nums[(i-1)%N] <= nums[i%N] {
            count++
        } else {
            count = 1
        }
        // N последовательных элементов образуют требуемую отсортированную
        // циклическую развёртку массива.
        if count == N {
            return true
        }
    }

    // Для N > 1 отсутствие фрагмента означает false. Одноэлементный массив
    // всегда подходит; отдельная проверка нужна, потому что в первой итерации
    // count сразу увеличивается с 1 до 2 и не бывает равен N.
    return N == 1
}
