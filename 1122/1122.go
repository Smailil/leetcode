package main

/*
Даны два массива arr1 и arr2. Элементы arr2 различны, и каждый из них
также присутствует в arr1.

Отсортируйте элементы arr1 так, чтобы их относительный порядок совпадал с
порядком элементов в arr2. Элементы, которых нет в arr2, должны находиться
в конце arr1 в порядке возрастания.

Пример 1:
Вход: arr1 = [2,3,1,3,2,4,6,7,9,2,19], arr2 = [2,1,4,3,9,6]
Выход: [2,2,2,1,4,3,3,9,6,7,19]

Пример 2:
Вход: arr1 = [28,6,22,8,44,17], arr2 = [22,28,8,6]
Выход: [22,28,8,6,17,44]

Ограничения:
1 <= arr1.length, arr2.length <= 1000
0 <= arr1[i], arr2[i] <= 1000
Все элементы arr2 различны.
Каждый элемент arr2[i] встречается в arr1.
*/

// relativeSortArray сначала размещает элементы по порядку arr2,
// а затем добавляет остальные значения по возрастанию.
// Время: O(n + m + V), где n = len(arr1), m = len(arr2), а
// V = max(arr1) + 1 — размер диапазона значений. Так как m <= n
// и V <= 1001, по ограничениям задачи время упрощается до O(n).
// Дополнительная рабочая память: O(V), то есть O(1) при V <= 1001;
// возвращаемый массив занимает O(n).
func relativeSortArray(arr1 []int, arr2 []int) []int {
    // Находим верхнюю границу, чтобы выделить счётчик точного размера.
    // arr1 непуст и содержит неотрицательные числа, поэтому maxVal
    // корректно начинается с нуля.
    maxVal := 0
    for _, num := range arr1 {
        if num > maxVal {
            maxVal = num
        }
    }

    // Индекс count совпадает со значением из arr1, а ячейка хранит
    // число его оставшихся вхождений. maxVal удерживает индексы
    // в границах счётчика.
    count := make([]int, maxVal+1)
    for _, num := range arr1 {
        count[num]++
    }

    var res []int
    // Для каждого значения arr2 переносим в результат все его вхождения.
    // По условию num присутствует в arr1, поэтому count[num] в границах.
    // Обнуление частоты не даст тому же значению попасть в хвост.
    for _, num := range arr2 {
        for count[num] > 0 {
            res = append(res, num)
            count[num]--
        }
    }

    // Остаток диапазона просматриваем по возрастанию, поэтому неиспользованные
    // значения сразу образуют отсортированный хвост без отдельной сортировки.
    for num := 0; num <= maxVal; num++ {
        for count[num] > 0 {
            res = append(res, num)
            count[num]--
        }
    }

    return res
}