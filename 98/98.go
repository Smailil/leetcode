package main

import "math"

/*
Дан корень двоичного дерева.
Определите, является ли оно допустимым двоичным деревом поиска (BST).
Действительный BST определяется следующим образом:
Левое поддерево узла содержит только узлы с ключами,
строго меньшими, чем ключ узла.
Правое поддерево узла содержит только узлы с ключами,
строго превышающими ключ узла.
И левое, и правое поддеревья также должны быть бинарными деревьями поиска.

Пример 1:
https://assets.leetcode.com/uploads/2020/12/01/tree1.jpg
Вход: root = [2,1,3]
Выход: true

Пример 2:
https://assets.leetcode.com/uploads/2020/12/01/tree2.jpg
Вход: root = [5,1,4,null,null,3,6]
Выход: false
Объяснение: Значение корневого узла равно 5,
а значение его правого дочернего узла равно 4.

Ограничения:
Количество узлов в дереве находится в диапазоне [1, 10^4].
-2^31 <= Node.val <= 2^31 - 1
*/

type TreeNode struct {
    Val int
    Left *TreeNode
    Right *TreeNode
}

// isValidBST проверяет строгие ограничения BST от всех предков узла.
// Рекурсия передаёт открытый интервал допустимых значений вниз по дереву.
// Время O(n), n — число узлов; рабочая память O(h), h — высота дерева.
// Результат bool занимает O(1); дерево не изменяется.
func isValidBST(root *TreeNode) bool {
    var valid func(node *TreeNode, left int, right int) bool
	// valid проверяет поддерево в интервале (left,right).
	// Время O(k), k — узлы поддерева; рабочая память O(h), результат O(1).
	valid = func(node *TreeNode, left, right int) bool {
		// Пустое поддерево не нарушает ограничений.
		if node == nil {
			return true
		}
		// Строгие границы исключают дубликаты и нарушения далёких предков.
		if !(left < node.Val && node.Val < right) {
			return false
		}
		// Для левого ребёнка сужаем верхнюю границу, для правого — нижнюю.
		// && прекращает проверку справа, если слева уже найдено нарушение.
		return valid(node.Left, left, node.Val) && valid(node.Right, node.Val, right)
	}
	// На 64-битном int границы шире всех допустимых 32-битных значений.
	// На 32-битном int крайние MinInt32/MaxInt32 ошибочно отвергаются:
	// исходная реализация использует строгие машинные пределы как границы.
	return valid(root, math.MinInt, math.MaxInt)
}
