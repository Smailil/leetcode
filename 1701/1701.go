package main

/*
В ресторане работает один повар. Дан массив customers, где
customers[i] = [arrival_i, time_i]:

arrival_i — время прибытия i-го посетителя. Значения времени прибытия
отсортированы в неубывающем порядке.
time_i — время, необходимое для приготовления заказа i-го посетителя.
Когда посетитель приходит, он передаёт повару заказ. Повар начинает готовить,
как только освобождается, а посетитель ждёт окончания приготовления. Повар
готовит не более одного заказа одновременно и обслуживает посетителей в том
порядке, в котором они указаны во входных данных.

Верните среднее время ожидания всех посетителей. Ответы, отличающиеся от
точного значения не более чем на 10^-5, считаются правильными.

Пример 1:
Вход: customers = [[1,2],[2,5],[4,3]]
Выход: 5.00000
Пояснение:
1) Первый посетитель приходит в момент 1. Повар сразу принимает заказ,
начинает готовить в момент 1 и заканчивает в момент 3. Время ожидания:
3 - 1 = 2.
2) Второй посетитель приходит в момент 2. Повар начинает готовить его заказ
в момент 3 и заканчивает в момент 8. Время ожидания: 8 - 2 = 6.
3) Третий посетитель приходит в момент 4. Повар начинает готовить его заказ
в момент 8 и заканчивает в момент 11. Время ожидания: 11 - 4 = 7.
Среднее время ожидания: (2 + 6 + 7) / 3 = 5.

Пример 2:
Вход: customers = [[5,2],[5,4],[10,3],[20,1]]
Выход: 3.25000
Пояснение:
1) Первый посетитель приходит в момент 5. Повар сразу принимает заказ,
начинает готовить в момент 5 и заканчивает в момент 7. Время ожидания:
7 - 5 = 2.
2) Второй посетитель приходит в момент 5. Повар начинает готовить его заказ
в момент 7 и заканчивает в момент 11. Время ожидания: 11 - 5 = 6.
3) Третий посетитель приходит в момент 10. Повар начинает готовить его заказ
в момент 11 и заканчивает в момент 14. Время ожидания: 14 - 10 = 4.
4) Четвёртый посетитель приходит в момент 20. Повар сразу принимает заказ,
начинает готовить в момент 20 и заканчивает в момент 21. Время ожидания:
21 - 20 = 1.
Среднее время ожидания: (2 + 6 + 4 + 1) / 4 = 3.25.

Ограничения:
1 <= customers.length <= 10^5
1 <= arrival_i, time_i <= 10^4
arrival_i <= arrival_{i+1}

*/

// averageWaitingTime вычисляет среднее время от прихода посетителя до
// завершения его заказа. Один проход поддерживает момент освобождения повара
// и суммарное время ожидания уже обработанных посетителей.
// Время: O(n), где n = len(customers). Дополнительная память: O(1).
func averageWaitingTime(customers [][]int) float64 {
    // t — момент завершения последнего заказа, total — сумма полного времени
    // ожидания, включая нахождение в очереди и приготовление. int64 защищает
    // накопленные значения от переполнения на больших входных данных.
    var t, total int64 = 0, 0

    // Посетители уже упорядочены по времени прихода, поэтому их можно
    // обслуживать последовательно, не создавая дополнительную очередь.
    for _, c := range customers {
        arrival, order := int64(c[0]), int64(c[1])

        // Если повар занят, посетитель ждёт t - arrival до начала готовки.
        // Иначе переводим часы к arrival, не добавляя время простоя в total.
        if t > arrival {
            total += t - arrival
        } else {
            t = arrival
        }

        // Приготовление тоже входит во время ожидания посетителя. После него
        // t становится моментом, когда повар сможет принять следующий заказ.
        total += order
        t += order
    }

    // По ограничениям customers непуст, поэтому деление на его длину безопасно.
    return float64(total) / float64(len(customers))
}