/*
Спроектируйте HashMap без использования встроенных библиотек хеш-таблиц.

Реализуйте класс MyHashMap:
MyHashMap() инициализирует объект с пустой картой.
void put(int key, int value) вставляет пару (ключ, значение) в HashMap.
    Если ключ уже существует, обновляет соответствующее значение.
int get(int key) возвращает значение, с которым сопоставлен указанный ключ,
    или -1, если карта не содержит сопоставления для этого ключа.
void remove(key) удаляет ключ и его значение, если карта содержит это
сопоставление.

Пример 1:
Вход
["MyHashMap", "put", "put", "get", "get", "put", "get", "remove", "get"]
[[], [1, 1], [2, 2], [1], [3], [2, 1], [2], [2], [2]]
Выход
[null, null, null, 1, -1, null, 1, null, -1]
Пояснение
MyHashMap myHashMap = new MyHashMap();
myHashMap.put(1, 1); // Карта теперь [[1,1]]
myHashMap.put(2, 2); // Карта теперь [[1,1], [2,2]]
myHashMap.get(1);    // возвращает 1, карта [[1,1], [2,2]]
myHashMap.get(3);    // возвращает -1 (не найдено), карта [[1,1], [2,2]]
myHashMap.put(2, 1); // Карта теперь [[1,1], [2,1]] (обновляет существующее
значение)
myHashMap.get(2);    // возвращает 1, карта [[1,1], [2,1]]
myHashMap.remove(2); // удаляет сопоставление для 2, карта теперь [[1,1]]
myHashMap.get(2);    // возвращает -1 (не найдено), карта [[1,1]]

Ограничения:
0 <= key, value <= 10^6
Не более 10^4 вызовов put, get и remove.
*/

// HashNode представляет узел связного списка, используемого для разрешения
// коллизий в хеш-таблице (метод цепочек).
type HashNode struct {
	key, val int
	next     *HashNode
}

// MyHashMap разрешает коллизии цепочками с фиктивными головами.
// B — число бакетов, K — число ключей: состояние O(B + K).
// При B = 1000 это O(K + 1); цепочки могут быть неравномерными.
type MyHashMap struct {
	data []*HashNode // Срез указателей на фиктивные головы каждого бакета
}

// Constructor выделяет B = 1000 бакетов с фиктивными узлами.
// Время O(B), рабочая память O(1), возвращаемое состояние O(B).
// При фиксированном B эти оценки постоянны.
func Constructor() MyHashMap {
	data := make([]*HashNode, 1000)
	for i := range data {
		data[i] = &HashNode{key: -1, val: -1} // Фиктивный узел для удобства операций
	}
	return MyHashMap{data: data}
}

// hash вычисляет key % B за O(1) времени и памяти, без изменений.
// key >= 0 по контракту, B = 1000 после Constructor: делитель ненулевой.
// Результат 0..B-1 — индекс бакета, не доказательство равных ключей.
func (this *MyHashMap) hash(key int) int {
	return key % len(this.data)
}

// Put ищет точный ключ в цепочке, обновляет его либо дописывает узел.
// b — длина цепочки: время O(b + 1), рабочая память O(1).
// Худшее время O(K + 1); равномерность хеша не гарантирована.
// Меняет состояние; для нового ключа добавляет O(1) памяти.
func (this *MyHashMap) Put(key int, value int) {
	// Получаем фиктивную голову соответствующего бакета
	cur := this.data[this.hash(key)]
	
	// Проходим по списку, проверяя следующий узел
	for cur.next != nil {
		if cur.next.key == key {
			// Ключ уже существует: обновляем значение и выходим
			cur.next.val = value
			return
		}
		cur = cur.next
	}
	
	// Ключ не найден в цепочке: добавляем новый узел в конец списка
	cur.next = &HashNode{key: key, val: value}
}

// Get сверяет реальные ключи и возвращает значение или -1.
// b — длина цепочки: время O(b + 1), в худшем O(K + 1).
// Рабочая память и результат O(1), состояние не меняет.
// Значения неотрицательны, поэтому -1 означает отсутствие.
func (this *MyHashMap) Get(key int) int {
	// Начинаем поиск сразу с первого реального элемента бакета (после фиктивной
	// головы)
	cur := this.data[this.hash(key)].next
	for cur != nil {
		if cur.key == key {
			return cur.val // Ключ найден, возвращаем значение
		}
		cur = cur.next
	}
	return -1 // Ключ не найден
}

// Remove ищет предшественника точного ключа и исключает следующий узел.
// b — длина цепочки: время O(b + 1), в худшем O(K + 1), память O(1).
// Меняет связи только при наличии ключа; фиктивная голова остаётся.
func (this *MyHashMap) Remove(key int) {
	cur := this.data[this.hash(key)]
	
	// Ищем узел, следующий за которым находится целевой ключ
	for cur.next != nil {
		if cur.next.key == key {
			// Ключ найден: исключаем следующий узел из цепочки, перенаправляя указатель
			cur.next = cur.next.next
			return
		}
		cur = cur.next
	}
}

