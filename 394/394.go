package main

/*
Дана закодированная строка — верните её декодированный вид.

Правило кодирования: k[encoded_string],
где encoded_string внутри квадратных скобок повторяется ровно k раз.
Гарантируется, что k — положительное целое число.

Можно считать, что входная строка всегда корректна:
лишних пробелов нет, квадратные скобки расставлены правильно и т.д.
Также можно считать, что исходные данные не содержат цифр —
цифры используются только для обозначения количества повторений k.
Например, входных данных вида 3a или 2[4] не будет.

Тесты составлены так, что длина результирующей строки не превысит 10^5.

Пример 1:
Вход: s = "3[a]2[bc]"
Выход: "aaabcbc"

Пример 2:
Вход: s = "3[a2[c]]"
Выход: "accaccacc"

Пример 3:
Вход: s = "2[abc]3[cd]ef"
Выход: "abcabccdcdcdef"

Ограничения:
1 <= s.length <= 30
s состоит из строчных латинских букв, цифр и квадратных скобок '[]'.
Гарантируется, что s — корректная входная строка.
Все целые числа в s находятся в диапазоне [1, 300].
*/

// decodeString рекурсивно раскрывает повторы, обходя s общим индексом.
// n = len(s), L — длина результата, d — число уровней вместе с внешним.
// При k ≤ 300 время O(n * (L + 1)): склейки копируют накопленные префиксы.
// Рабочая память без результата O(L + d), результат занимает O(L).
// Живые строковые буферы вместе с результатом — O(L), стек — O(d).
// Вход не меняется; общий i существует только внутри этого вызова.
func decodeString(s string) string {
	// i указывает на следующий байт для обработки. Контракт ASCII позволяет
	// считать длины и двигать индекс по байтам, а не по Unicode-символам.
	i := 0

	var helper func() string
	// helper возвращает строку текущего блока и сдвигает общий i до ']' либо EOF.
	// Закрывающую скобку оставляет родителю; вложенные блоки разбирает рекурсией.
	// b — длина входной ветви, r — её результат, h — уровни вместе с текущим.
	// При k ≤ 300 время O(b * (r + 1)); рабочая память O(r + h), результат O(r).
	// Буфер возвращённой строки и тот же буфер в дочернем вызове считаем один раз.
	helper = func() string {
		// res — уже раскрытый префикс уровня, k — число перед следующим '['.
		res := "" // Накопитель результата для текущего уровня
		k := 0    // Множитель повторений для следующей вложенной строки

		for i < len(s) {
			c := s[i]

			if c >= '0' && c <= '9' {
				// Приписываем цифру справа: для 12[a] k меняется 0 → 1 → 12.
				// c-'0' лежит в [0,9], накопленное число ≤ 300 по контракту.
				k = k*10 + int(c-'0')
			} else if c == '[' {
				i++ // Пропускаем открывающую скобку
				// Вложенный вызов начинает после '[' и останавливается на её парной ']'.
				subRes := helper()
				// Повторы дописываются к прежнему префиксу. Строки неизменяемы:
				// склейка может копировать весь res, а не только новую subRes.
				for j := 0; j < k; j++ {
					res += subRes
				}
				k = 0 // Сбрасываем множитель после применения
			} else if c == ']' {
				// Здесь i не увеличиваем: возврат оставляет его на закрывающей скобке.
				// Родитель поглотит её общим i++ в конце своей итерации.
				return res
			} else {
				// По корректному формату осталась латинская буква: string(c)
				// даёт тот же одиночный символ, который дописываем к res.
				res += string(c)
			}

			// После вложенного блока это переход за его ']', иначе — за текущий байт.
			i++
		}

		return res
	}

	// Верхний уровень завершится при i == len(s), а не на закрывающей скобке.
	// Время: O(n) посещений байтов и O(n) склеек при ограниченном k;
	// каждая склейка стоит до O(L). Пустой результат учтён слагаемым 1.
	// Префиксы активных уровней — разные части результата, не d копий по L.
	return helper()
}
