package main

/*
Алиса и Боб играют в игру с кучами камней.
Есть чётное число куч,
расположенных в ряд, и в каждой куче положительное целое число камней piles[i].

Цель игры — закончить с наибольшим числом камней.
Общее число камней во всех кучах нечётное,
поэтому ничьих не бывает.

Алиса и Боб ходят по очереди, первой ходит Алиса.
За один ход игрок забирает всю кучу камней
либо с начала, либо с конца ряда.
Игра продолжается, пока не останется куч;
после этого выигрывает тот, у кого больше камней.

Если Алиса и Боб играют оптимально, верните true, если Алиса выигрывает игру,
или false, если выигрывает Боб.

Пример 1:
Вход: piles = [5,3,4,5]
Выход: true
Пояснение:
Алиса ходит первой и может взять только первую 5 или последнюю 5.
Предположим, она берёт первую 5, тогда ряд становится [3, 4, 5].
Если Боб берёт 3, то поле становится [4, 5], и Алиса берёт 5,
чтобы выиграть с 10 очками.
Если Боб берёт последнюю 5, то поле становится [3, 4],
и Алиса берёт 4, чтобы выиграть с 9 очками.
Это показывает, что взять первую 5 было выигрышным ходом для Алисы,
поэтому возвращаем true.

Пример 2:
Вход: piles = [3,7,2,3]
Выход: true

Ограничения:
2 <= piles.length <= 500
piles.length — чётное.
1 <= piles[i] <= 500
sum(piles[i]) — нечётная.
*/

// stoneGame сравнивает интервальную DP-оценку с оставшейся суммой камней.
// n — число куч piles; время O(n^2), рабочая память O(n).
// Результат bool занимает O(1); piles не изменяется.
// DP максимизирует сумму куч, взятых на слоях с нечётной длиной интервала.
// Это не minimax-счёт Алисы: max применяется и на ходах другой стороны.
// Например, для [8,15,3,7] эта DP даёт 23, оптимальная Алиса получает 22.
// При чётном n и нечётной сумме победа Алисы всё равно гарантирована.
func stoneGame(piles []int) bool {
    n := len(piles)

    // D(l,r) — максимальная сумма выбранных куч только на нечётных слоях.
    // Перед обновлением dp[r] ещё хранит D(l+1,r), а dp[r-1] уже D(l,r-1).
    // Поэтому l идёт вниз, r вверх: обе зависимости читаются до потери.
    // После обновления dp[r] хранит D(l,r).
    dp := make([]int, n)

    // Перебираем все интервалы: l двигается справа налево,
    // а r — от l к концу массива.
    for l := n - 1; l >= 0; l-- {
        for r := l; r < n; r++ {
            // r-l чётно тогда и только тогда,
            // когда длина интервала r-l+1 нечётна.
            // Только на нечётном слое выбранная куча учитывается в сумме.
            // На чётном слое left/right остаются 0, но выбор тоже берёт max.
            even := (r-l)%2 == 0
            left, right := 0, 0
            if even {
                left = piles[l]
                right = piles[r]
            }

            if l == r {
                // База: интервал состоит из одной кучи,
                // это нечётный слой, и размер кучи становится базовой оценкой.
                dp[r] = left
            } else {
                // Два варианта перехода:
                // 1. dp[r] + left — удалить левый край и продолжить D(l+1,r);
                // 2. dp[r-1] + right — удалить правый край
                //    и продолжить D(l,r-1).
                // При нечётной длине край добавляется, при чётной — нет.
                // Всегда выбирается max, не противодействие соперника.
                dp[r] = max(dp[r]+left, dp[r-1]+right)
            }
        }
    }

    // Сумма всех камней нужна для сравнения оценки с её дополнением.
    // Это не восстановление оптимального счёта Боба по minimax.
    // Максимальная сумма 500*500 помещается в int по ограничениям.
    total := 0
    for _, pile := range piles {
        total += pile
    }

    // n >= 2 гарантирует доступность dp[n-1].
    // Имя aliceScore не делает значение оптимальным счётом Алисы.
    aliceScore := dp[n-1]

    // DP допускает учёт всех куч одной чётности исходных индексов.
    // Поэтому её итог не меньше большей из двух сумм чётности.
    // При нечётной total эта сумма строго больше половины.
    // Алиса тоже может обеспечить себе выбранную чётность, начиная первой,
    // так что boolean верен по контракту, хотя DP-счёт не является minimax.
    return aliceScore > total-aliceScore
}
