package main

/*
Вам дан индексируемый с нуля массив строк details. Каждый элемент details
содержит сведения о пассажире, сжатые в строку длины 15. Формат строки:

Первые десять символов содержат номер телефона пассажира.
Следующий символ обозначает пол пассажира.
Следующие два символа обозначают возраст пассажира.
Последние два символа определяют назначенное пассажиру место.

Верните количество пассажиров строго старше 60 лет.

Пример 1:
Ввод: details = ["7868190130M7522","5303914400F9211","9273338290F4010"]
Вывод: 2
Пояснение: пассажиры с индексами 0, 1 и 2 имеют возраст 75, 92 и 40 лет.
Таким образом, строго старше 60 лет находятся 2 пассажира.

Пример 2:
Ввод: details = ["1313579440F2036","2921522980M5644"]
Вывод: 0
Пояснение: ни один пассажир не старше 60 лет.

Ограничения:
1 <= details.length <= 100
details[i].length == 15
details[i] состоит только из цифр от '0' до '9'.
details[i][10] равен 'M', 'F' или 'O'.
Номера телефонов и мест пассажиров уникальны.
*/

// countSeniors извлекает возраст из каждой записи и считает пассажиров
// строго старше 60 лет. Время — O(len(details)), память — O(1).
func countSeniors(details []string) int {
    // res хранит количество уже найденных пожилых пассажиров.
    res := 0

    // Каждая строка имеет фиксированный формат и обрабатывается независимо.
    for _, d := range details {
        // Возраст записан в позициях 11 и 12. Вычитание '0' преобразует
        // ASCII-код каждой цифры в её числовое значение.
        ten := int(d[11] - '0')
        one := int(d[12] - '0')

        // Первая цифра задаёт десятки, а вторая — единицы возраста.
        age := one + 10*ten

        // Условие строгое: пассажир ровно 60 лет в ответ не входит.
        if age > 60 {
            res++
        }
    }

    // После обхода всех записей res содержит итоговое количество.
    return res
}
