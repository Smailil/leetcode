package main

/*
Дана голова связного списка head.
Разверните узлы списка группами по k и верните изменённый список.
k — целое положительное число, не превышающее длину связного списка.
Если количество узлов не кратно k, оставшиеся узлы в конце не меняются.
Нельзя изменять значения в узлах списка: можно изменять только сами узлы.

Пример 1:
Вход: head = [1,2,3,4,5], k = 2
Выход: [2,1,4,3,5]

Пример 2:
Вход: head = [1,2,3,4,5], k = 3
Выход: [3,2,1,4,5]

Ограничения:
Количество узлов в списке равно n.
1 <= k <= n <= 5000
0 <= Node.val <= 1000
*/

type ListNode struct {
	Val  int
	Next *ListNode
}

// getKthNode проходит k связей от curr и возвращает достигнутый узел.
// Если список закончился раньше, возвращает nil; время O(k), память O(1).
// Связи не меняются, возвращается ссылка на существующий узел.
func getKthNode(curr *ListNode, k int) *ListNode {
	for curr != nil && k > 0 {
		curr = curr.Next
		k--
	}
	return curr
}

// reverseKGroup разворачивает только полные группы из k узлов.
// n — длина списка; время O(n), рабочая память O(1).
// Результат использует прежние узлы, дополнительные узлы ответа не нужны.
// Побочный эффект: меняются Next во входном списке; значения Val сохранены.
func reverseKGroup(head *ListNode, k int) *ListNode {
    // dummy позволяет одинаково переподключать первую и следующие группы.
    // groupPrev — последний узел уже обработанного префикса.
    dummy := &ListNode{0, head}
	groupPrev := dummy

	for {
		// От groupPrev нужно пройти k связей, чтобы найти конец группы.
		// nil означает неполный хвост: его связи оставляем прежними.
		kth := getKthNode(groupPrev, k)
		if kth == nil {
			break
		}
		groupNext := kth.Next
		// Первая изменённая связь сразу ведёт в остаток списка groupNext.
		// prev — развёрнутый префикс группы, curr — ещё не обработанный узел.
		prev, curr := groupNext, groupPrev.Next
		for curr != groupNext {
			// Сохраняем старую следующую связь до её перезаписи.
			next := curr.Next
			curr.Next = prev
			prev = curr
			curr = next
		}
		// Прежняя голова стала хвостом: сохраняем её до замены ссылки.
		// kth теперь голова группы, next — новый groupPrev для следующей.
		next := groupPrev.Next
		groupPrev.Next = kth
		groupPrev = next
	}
	return dummy.Next
}

