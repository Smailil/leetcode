package main

/*
Дан целочисленный массив nums длины n с индексацией от нуля.
Изначально вы находитесь на индексе 0.
Каждый элемент nums[i] задаёт максимальную длину прыжка вперёд с индекса i.
Если вы находитесь на индексе i, можно перейти на любой индекс i + j, где:
0 <= j <= nums[i] и
i + j < n
Верните минимальное число прыжков для достижения индекса n - 1.
Тестовые примеры гарантируют, что индекс n - 1 достижим.

Пример 1:
Вход: nums = [2,3,1,1,4]
Выход: 2
Пояснение: минимальное число прыжков до последнего индекса равно 2.
Прыгните на 1 шаг с индекса 0 на индекс 1, затем на 3 шага до конца массива.

Пример 2:
Вход: nums = [2,3,0,1,4]
Выход: 2

Ограничения:
1 <= nums.length <= 10^4
0 <= nums[i] <= 1000
Гарантируется, что можно достичь nums[n - 1].
*/

// jump считает минимальные прыжки, обходя слои достижимых индексов.
// Интервал [l,r] — новый слой, а не выбранный маршрут прыжков.
// Время: O(n), n = len(nums), интервалы обхода не пересекаются.
// Дополнительная память: O(1); nums не изменяется.
// Гарантия достижимости последнего индекса необходима для продвижения слоёв.
func jump(nums []int) int {
    res := 0
    // Стартовый слой состоит из индекса 0, достижимого за 0 прыжков.
    l, r := 0, 0

    // Все индексы до r достижимы за не более res прыжков.
    // [l,r] добавились на последнем шаге расширения.
    // При n == 1 старт уже является целью и цикл не выполняется.
    for r < len(nums)-1 {
        // Максимальный правый конец, доступный за ещё один прыжок.
        // Благодаря допустимым длинам от 0 до nums[i] новый слой непрерывен.
        farthest := 0
        // Пока условие внешнего цикла истинно, r < n-1:
        // все обращаемые индексы находятся внутри nums.
        // i+nums[i] <= 10^4-1+1000, поэтому int не переполняется.
        for i := l; i <= r; i++ {
			if farthest < i+nums[i] {
				farthest = i+nums[i]
			}
        }
        // Старые позиции уже обработаны; расширяемся только на новые.
        // Достижимость цели гарантирует farthest > r, пока цель не покрыта.
        // Если farthest выходит за последний индекс,
        // следующий цикл не начнётся.
        l = r + 1
        r = farthest
        res++
    }

    // Первый слой, покрывший цель, задаёт минимальное число прыжков.
    return res
}
