package main

/*
Дана строка s, состоящая только из символов 'a', 'b' и 'c'.
К ней можно применить следующую операцию любое число раз:

Выберите непустой префикс строки s, состоящий из одинаковых символов.
Выберите непустой суффикс строки s, состоящий из одинаковых символов.
Префикс и суффикс не должны пересекаться ни в одной позиции.
Префикс и суффикс должны состоять из одного и того же символа.
Удалите и префикс, и суффикс.

Верните минимальную длину s после любого числа таких операций,
в том числе после нуля операций.

Пример 1:
Вход: s = "ca"
Выход: 2
Пояснение: удалить ни один символ нельзя, поэтому строка не меняется.

Пример 2:
Вход: s = "cabaabac"
Выход: 0
Пояснение: оптимальная последовательность операций:
- Удаляем префикс "c" и суффикс "c", получаем s = "abaaba".
- Удаляем префикс "a" и суффикс "a", получаем s = "baab".
- Удаляем префикс "b" и суффикс "b", получаем s = "aa".
- Удаляем префикс "a" и суффикс "a", получаем s = "".

Пример 3:
Вход: s = "aabccabba"
Выход: 3
Пояснение: оптимальная последовательность операций:
- Удаляем префикс "aa" и суффикс "a", получаем s = "bccabb".
- Удаляем префикс "b" и суффикс "bb", получаем s = "cca".

Ограничения:
1 <= s.length <= 10^5
Строка s состоит только из символов 'a', 'b' и 'c'.
*/

// minimumLength возвращает минимальную длину строки после удаления
// префикса и суффикса, состоящих из одного и того же символа.
// Два указателя обозначают остаток строки, сами символы не копируются.
// Время: O(n), где n = len(s): каждый указатель проходит строку один раз.
// Дополнительная память: O(1), только два индекса и текущий символ.
func minimumLength(s string) int {
	// [l, r] — включительные границы ещё не удалённой части строки.
	// Символы ASCII, поэтому байтовые индексы совпадают с позициями символов.
	l, r := 0, len(s)-1

	// Нужны хотя бы два символа для непустых непересекающихся фрагментов.
	// Если крайние символы различны, выбрать допустимую пару уже нельзя.
	// Короткое замыкание && защищает чтение после пересечения указателей.
	for l < r && s[l] == s[r] {
		// Снимаем крайние группы целиком: частичное удаление либо
		// потребует снять их остатки позже, либо раньше остановит процесс.
		// tmp сохраняет общий символ обеих групп: после сдвига l
		// значение s[l] может стать другим или индекс выйдет за остаток.
		tmp := s[l]
		// l <= r проверяется до чтения s[l], чтобы не выйти за границу.
		for l <= r && s[l] == tmp {
			l++
		}
		// Сравниваем с прежним tmp, а не с символом на новой позиции l.
		// Если остаток был однородным, первый цикл мог пройти его весь.
		// Это допустимо: при длине >= 2 его можно разделить на два
		// непустых непересекающихся фрагмента и удалить одной операцией.
		for l <= r && s[r] == tmp {
			r--
		}
	}
	// "aabccabba": [0,8] -> [2,7] -> [3,5], остаётся "cca" длины 3.
	// При l == r остаётся один символ: его удалить отдельно нельзя.
	// При l == r+1 удалено всё, и формула даёт 0 без отдельной ветки.
	return r - l + 1
}