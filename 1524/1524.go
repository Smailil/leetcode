package main

/*
Дан массив целых чисел arr. Верните количество подмассивов с нечётной
суммой.

Поскольку ответ может быть очень большим, верните его по модулю 10^9 + 7.

Пример 1:
Ввод: arr = [1,3,5]
Вывод: 4
Пояснение: все подмассивы: [[1],[1,3],[1,3,5],[3],[3,5],[5]].
Их суммы: [1,4,9,3,8,5].
Нечётные суммы: [1,9,3,5], поэтому ответ равен 4.

Пример 2:
Ввод: arr = [2,4,6]
Вывод: 0
Пояснение: все подмассивы: [[2],[2,4],[2,4,6],[4],[4,6],[6]].
Их суммы: [2,6,12,4,10,6].
Все подмассивы имеют чётную сумму, поэтому ответ равен 0.

Пример 3:
Ввод: arr = [1,2,3,4,5,6,7]
Вывод: 16

Ограничения:
1 <= arr.length <= 10^5
1 <= arr[i] <= 100
*/

// numOfSubarrays считает подмассивы с нечётной суммой по чётности
// префиксных сумм.
// Время: O(n), где n = len(arr). Дополнительная память: O(1).
func numOfSubarrays(arr []int) int {
    // oddCnt и evenCnt хранят количество уже пройденных непустых
    // префиксов соответствующей чётности.
    curSum, oddCnt, evenCnt, res := 0, 0, 0, 0
    mod := int(1e9 + 7)

    for _, n := range arr {
        curSum += n

        // Сумма подмассива равна разности двух префиксных сумм и будет
        // нечётной ровно тогда, когда их чётности различаются.
        if curSum%2 != 0 {
            // Нечётный текущий префикс сочетается со всеми предыдущими
            // чётными префиксами. Единица учитывает пустой префикс.
            res = (res + 1 + evenCnt) % mod
            oddCnt++
        } else {
            // Чётный текущий префикс сочетается с каждым предыдущим
            // нечётным префиксом.
            res = (res + oddCnt) % mod
            evenCnt++
        }
    }

    return res
}