package main

/*
Дан непустой массив целых чисел nums,
в котором каждый элемент встречается дважды, кроме одного.
Найдите этот единственный элемент.
Вы должны реализовать решение с линейной временной сложностью
и использовать только постоянное дополнительное пространство.

Пример 1:
Вход: nums = [2,2,1]
Выход: 1

Пример 2:
Вход: nums = [4,1,2,1,2]
Выход: 4

Пример 3:
Вход: nums = [1]
Выход: 1

Ограничения:
1 <= nums.length <= 3 * 10^4
-3 * 10^4 <= nums[i] <= 3 * 10^4
Каждый элемент массива появляется дважды, за исключением одного элемента,
который появляется только один раз.
*/

// singleNumber сворачивает массив операцией XOR: x ^ x = 0,
// а x ^ 0 = x. Ассоциативность и коммутативность гасят пары в любом порядке.
// Время O(n), n = len(nums), при фиксированной машинной разрядности.
// Рабочая память и результат O(1); исходный nums не изменяется.
func singleNumber(nums []int) int {
	// Ноль — нейтральный элемент. После каждой итерации res равен
	// XOR уже просмотренного префикса, включая отрицательные int.
	res := 0
	for _, num := range nums {
		res ^= num
	}
	// По условию все значения, кроме одного, встретились ровно дважды.
	// После взаимного погашения пар остаётся единственный элемент.
	return res
}
