package main

/*
Дан массив nums из положительных целых чисел с индексацией с нуля.

К массиву можно любое число раз применить одну из двух операций:
- выбрать два элемента с одинаковыми значениями и удалить их;
- выбрать три элемента с одинаковыми значениями и удалить их.

Верните минимальное число операций, необходимое, чтобы сделать массив
пустым, или -1, если это невозможно.

Пример 1:
Вход: nums = [2,3,3,2,2,4,2,3,4]
Выход: 4
Пояснение: массив можно очистить следующим образом:
- Применяем первую операцию к элементам с индексами 0 и 3.
  Получаем nums = [3,3,2,4,2,3,4].
- Применяем первую операцию к элементам с индексами 2 и 4.
  Получаем nums = [3,3,4,3,4].
- Применяем вторую операцию к элементам с индексами 0, 1 и 3.
  Получаем nums = [4,4].
- Применяем первую операцию к элементам с индексами 0 и 1.
  Получаем nums = [].
Можно показать, что очистить массив менее чем за 4 операции нельзя.

Пример 2:
Вход: nums = [2,1,2,2,3,3]
Выход: -1
Пояснение: очистить массив невозможно.

Ограничения:
2 <= nums.length <= 10^5
1 <= nums[i] <= 10^6
*/

// minOperations находит минимум удалений пар и троек одинаковых значений.
// Считаем частоты и складываем минимумы для каждой группы; nums не меняется.
// Среднее время: O(n + k) = O(n), где n = len(nums), k — число различных
// значений (k <= n). Доступ к map в среднем занимает O(1).
// Дополнительная память: O(k). По условию k <= min(n, 10^6);
// при фиксированном диапазоне 1..10^6 это O(1) по n с большой константой.
func minOperations(nums []int) int {
    // count[num] хранит число появлений num в уже просмотренной части nums.
    // Позиции не важны: операция выбирает любые равные элементы.
    count := make(map[int]int)
    for _, num := range nums {
        count[num]++
    }

    // Операция не смешивает разные значения, поэтому группы независимы.
    // Общий минимум равен сумме их минимумов; порядок обхода map не важен.
    res := 0
    for _, cnt := range count {
        // Единственный элемент этого значения не с кем объединить в пару
        // или тройку. Другие значения не помогут, и весь массив не очистить.
        if cnt == 1 {
            return -1
        }
        // За операцию удаляется не более 3 элементов, поэтому нужно
        // хотя бы ceil(cnt/3) операций. Эта нижняя граница достижима:
        // - остаток 0 при делении на 3: удаляем только тройки;
        // - остаток 2: удаляем тройки и одну пару;
        // - остаток 1 (cnt >= 4): вместо одной тройки и одиночного
        //   остатка удаляем две пары, остальные элементы — тройками.
        // Например, cnt=4 удаляется как 2+2, а не как 3+1.
        // Для целого cnt округление вверх даёт (cnt+2)/3: целочисленное
        // деление в Go отбрасывает дробную часть положительного результата.
        // cnt <= len(nums) <= 10^5, поэтому cnt+2 не переполняет int.
        res += (cnt + 2) / 3
    }

    return res
}