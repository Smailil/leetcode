package main

/*
Дан целочисленный массив nums, отсортированный в неубывающем порядке.

Постройте и верните целочисленный массив result той же длины, что и nums,
в котором result[i] равен сумме модулей разностей между nums[i]
и всеми остальными элементами массива.

Иначе говоря, result[i] = sum(|nums[i]-nums[j]|),
где 0 <= j < nums.length и j != i (индексация с 0).

Пример 1:
Вход: nums = [2,3,5]
Выход: [4,3,5]
Пояснение: При индексации с 0 получаем:
result[0] = |2-2| + |2-3| + |2-5| = 0 + 1 + 3 = 4,
result[1] = |3-2| + |3-3| + |3-5| = 1 + 0 + 2 = 3,
result[2] = |5-2| + |5-3| + |5-5| = 3 + 2 + 0 = 5.

Пример 2:
Вход: nums = [1,4,6,8,10]
Выход: [24,15,13,15,21]

Ограничения:
2 <= nums.length <= 10^5
1 <= nums[i] <= nums[i + 1] <= 10^4
*/

// getSumAbsoluteDifferences возвращает суммы модулей разностей
// каждого nums[i] со всеми остальными элементами массива.
// В отсортированном nums снимаем модули отдельно слева и справа;
// суммы этих групп позволяют вычислить каждый ответ за O(1).
// Время: O(n), n = len(nums): два прохода по массиву.
// Рабочая память без результата: O(1); память результата: O(n).
// Исходный массив nums не изменяется.
func getSumAbsoluteDifferences(nums []int) []int {
    n := len(nums)
    res := make([]int, n)

    // Сначала считаем сумму всех элементов, чтобы знать сумму правой части.
    // Во втором проходе totalSum будет уменьшаться, а не оставаться общей.
    // По условию n <= 10^5, nums[i] <= 10^4: сумма и n*nums[i] <= 10^9.
    // Каждый ответ <= (n-1)*9999 < 10^9, где 9999 — максимальная разность.
    // Поэтому все вычисления помещаются в int даже на 32-битной платформе.
    totalSum := 0
    for _, num := range nums {
        totalSum += num
    }

    // Перед первым элементом левая группа пуста, поэтому её сумма равна 0.
    prefixSum := 0
    // На входе итерации prefixSum = sum(nums[:i]), totalSum = sum(nums[i:]).
    // То есть prefixSum исключает текущий элемент, а totalSum ещё включает.
    for i := range n {
        // Убираем nums[i]: теперь totalSum = sum(nums[i+1:]), только справа.
        // Индекс i безопасен: range n даёт 0..n-1, а n = len(nums).
        totalSum -= nums[i]
        // Слева i элементов, каждый <= nums[i], поэтому модуль снимается
        // как nums[i] - nums[j].
        // Складывая эти разности, получаем
        // i*nums[i] - sum(nums[:i]) = i*nums[i] - prefixSum.
        leftSum := i*nums[i] - prefixSum
        // Справа n-i-1 элементов, каждый >= nums[i], поэтому разность
        // равна nums[j] - nums[i].
        // Их сумма — сумма правой группы минус
        // n-i-1 копий nums[i]: totalSum - (n-i-1)*nums[i].
        rightSum := totalSum - (n-i-1)*nums[i]
        // Например, nums = [2,3,5], i = 1: prefixSum = 2, totalSum = 5.
        // leftSum = 1*3-2 = 1, rightSum = 5-1*3 = 2, ответ равен 3.
        // При i == 0 левая часть равна 0; при i == n-1 правая равна 0.
        res[i] = leftSum + rightSum
        // Лишь после расчёта добавляем nums[i] в левую сумму:
        // для следующего индекса этот элемент уже находится слева.
        prefixSum += nums[i]
    }

    return res
}