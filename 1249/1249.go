package main

/*
Дана строка s, состоящая из символов '(' и ')' и строчных английских букв.

Удалите минимально возможное количество скобок '(' или ')' из любых
позиций, чтобы получившаяся строка со скобками стала корректной.
Верните любую такую корректную строку.

Формально строка со скобками корректна тогда и только тогда, когда
выполняется хотя бы одно из условий:
- она пустая или содержит только строчные буквы;
- её можно представить как AB (конкатенацию A и B), где строки A и B
  корректны;
- её можно представить как (A), где строка A корректна.

Пример 1:
Вход: s = "lee(t(c)o)de)"
Выход: "lee(t(c)o)de"
Пояснение: строки "lee(t(co)de)" и "lee(t(c)ode)" тоже подходят.

Пример 2:
Вход: s = "a)b(c)d"
Выход: "ab(c)d"

Пример 3:
Вход: s = "))(("
Выход: ""
Пояснение: пустая строка тоже корректна.

Ограничения:
1 <= s.length <= 10^5
s[i] — '(' или ')' либо строчная английская буква.
*/

// minRemoveToMakeValid удаляет минимальное число скобок для корректности s.
// Сначала отбрасывает лишние ')', затем удаляет лишние '(' справа налево
// и разворачивает результат, восстановив исходный порядок символов.
// n = len(s). Время: O(n), рабочая память: O(n) для res и filtered.
// Возвращаемая строка занимает O(n) памяти. Исходная строка s не изменяется.
func minRemoveToMakeValid(s string) string {
    // res накапливает символы первого прохода без лишних ')'.
    // cnt — число сохранённых '(', пока не получивших пару ')'.
    res := []byte{}
    cnt := 0

    // Если cnt == 0, у текущей ')' нет свободной '(' слева.
    // Будущая '(' не исправит этот префикс: хотя бы одну ')' нужно удалить.
    // Выбираем текущую ')' — она не попадает ни в одну ветку ниже.
    // Поэтому в каждом префиксе res открывающих не меньше закрывающих.
    for i := 0; i < len(s); i++ {
        // По условию символы ASCII: один символ занимает один байт.
        // Поэтому здесь можно обходить s по байтовым индексам, а не по рунам.
        c := s[i]
        if c == '(' {
            res = append(res, c)
            cnt++
        } else if c == ')' && cnt > 0 {
            // Эта ')' закрывает ранее сохранённую '('.
            // Оставляем её и уменьшаем число незакрытых скобок.
            res = append(res, c)
            cnt--
        } else if c != ')' {
            // Буквы сохраняем: они не меняют баланс скобок.
            res = append(res, c)
        }
    }

    // После первого прохода cnt — точное число оставшихся лишних '('.
    // Чтобы уравнять количества '(' и ')', нужно удалить хотя бы cnt '('.
    // Второй проход удалит ровно столько, не удаляя другие символы.
    filtered := []byte{}
    // Удаляем самые правые '(', оставляя самые ранние открывающие.
    // Перед k-й ')' в res есть как минимум k скобок '('. Первые k остаются,
    // поэтому каждая ')' по-прежнему имеет пару слева.
    // Например, для "(()" cnt = 1: удаляется вторая '(', остаётся "()".
    // Если res пуст, i начнётся с -1 и цикл не выполнится.
    for i := len(res) - 1; i >= 0; i-- {
        c := res[i]
        if c == '(' && cnt > 0 {
            // Пропускаем очередную лишнюю '(' и уменьшаем число удалений.
            // Когда cnt станет нулём, все оставшиеся '(' нужно сохранить.
            cnt--
        } else {
            filtered = append(filtered, c)
        }
    }

    // filtered собран в обратном порядке: разворачиваем его на месте.
    // При длине 0 или 1 условие i < j ложно, обращений к элементам не будет.
    for i, j := 0, len(filtered)-1; i < j; i, j = i+1, j-1 {
        filtered[i], filtered[j] = filtered[j], filtered[i]
    }
    return string(filtered)
}
