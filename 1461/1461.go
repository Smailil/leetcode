package main

/*
Дана двоичная строка s и целое число k. Верните true, если каждая двоичная
последовательность длины k встречается в s как подстрока. Иначе верните false.

Пример 1:
Вход: s = "00110110", k = 2
Выход: true
Пояснение: Двоичные последовательности длины 2 — "00", "01", "10" и "11".
Все они встречаются в s, начиная с индексов 0, 1, 3 и 2 соответственно.

Пример 2:
Вход: s = "0110", k = 1
Выход: true
Пояснение: Двоичные последовательности длины 1 — "0" и "1"; обе
встречаются в s как подстроки.

Пример 3:
Вход: s = "0110", k = 2
Выход: false
Пояснение: Двоичная последовательность "00" длины 2 не встречается в s.

Ограничения:
1 <= s.length <= 5 * 10^5
s[i] равно '0' или '1'.
1 <= k <= 20
*/

// hasAllCodes проверяет, встречается ли в s каждый двоичный код длины k.
// Окно представляется числом от 0 до 2^k-1, а codeSet отмечает найденные.
// Время O(n + 2^k), память O(2^k), где n = len(s): создаём массив флагов
// для всех 2^k кодов и один раз обходим строку.
func hasAllCodes(s string, k int) bool {
    n := len(s)
    // При n < 2^k окон заведомо меньше, чем возможных кодов.
    // Это лишь быстрая отсечка: окончательный ответ даёт подсчёт ниже.
    if n < (1 << k) {
        return false
    }

    // Индекс массива равен значению k-битного окна; have считает только
    // различные коды, которые уже были отмечены в codeSet.
    codeSet := make([]bool, 1<<k)
    cur, have := 0, 0

    for i := range n {
        // Сдвиг добавляет место для нового бита, маска оставляет младшие
        // k бит, а s[i]-'0' переводит очередной символ в число 0 или 1.
        cur = ((cur << 1) & ((1 << k) - 1)) | int(s[i]-'0')

        // Начиная с i = k-1, cur содержит полное окно из k символов.
        // Повторное появление того же кода не увеличивает have.
        if i >= k-1 {
            if !codeSet[cur] {
                codeSet[cur] = true
                have++
            }
        }
    }

    // Всего возможно 2^k разных кодов; равенство означает, что есть все.
    return have == (1 << k)
}