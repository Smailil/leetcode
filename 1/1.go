package main

/*
Даны массив целых чисел nums и целое число target.
Верните индексы двух чисел, сумма которых равна target.

Можно считать, что для каждого входа существует ровно одно решение.
Нельзя использовать один и тот же элемент дважды.

Ответ можно вернуть в любом порядке.

Пример 1:
Вход: nums = [2,7,11,15], target = 9
Выход: [0,1]
Пояснение: поскольку nums[0] + nums[1] == 9, возвращаем [0, 1].

Пример 2:
Вход: nums = [3,2,4], target = 6
Выход: [1,2]

Пример 3:
Вход: nums = [3,3], target = 6
Выход: [0,1]

Ограничения:
2 <= nums.length <= 10^4
-10^9 <= nums[i] <= 10^9
-10^9 <= target <= 10^9
Существует ровно один допустимый ответ.
*/

// twoSum за один проход ищет индексы чисел с суммой target.
// Карта хранит только уже просмотренные элементы, поэтому найденная пара
// всегда использует две разные позиции.
// Среднее время O(n), где n = len(nums): один проход и map с ключами int.
// Рабочая память O(k), k — число записанных различных значений, k <= n.
// Память результата O(1): два индекса либо пустой срез.
// nums не изменяется.
func twoSum(nums []int, target int) []int {
	// Для каждого значения запоминаем его индекс, чтобы за O(1) в среднем
	// проверять наличие недостающего слагаемого среди пройденной части.
	viewedNums := make(map[int]int)
	for i, num := range nums {
		// Разность по ограничениям лежит в [-2*10^9, 2*10^9],
		// поэтому недостающее слагаемое помещается в int.
		oldNum := target - num
		oldi, ok := viewedNums[oldNum]
		if ok {
			// oldi относится к ранее просмотренному числу, а i — к текущему,
			// поэтому возвращаемые индексы заведомо различаются.
			return []int{oldi, i}
		}

		// Записываем num после проверки: один элемент не сможет образовать
		// пару сам с собой, если target == 2*num.
		viewedNums[num] = i
	}

	// Пустой срез обозначает, что среди всех элементов пара не найдена.
	return []int{}
}
