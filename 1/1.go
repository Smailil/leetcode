package main

// twoSum за один проход ищет индексы чисел с суммой target.
// Карта хранит только уже просмотренные элементы, поэтому найденная пара
// всегда использует две разные позиции.
func twoSum(nums []int, target int) []int {
	// Для каждого значения запоминаем его индекс, чтобы за O(1) в среднем
	// проверять наличие недостающего слагаемого среди пройденной части.
	viewedNums := make(map[int]int)
	for i, num := range nums {
		oldNum := target - num
		oldi, ok := viewedNums[oldNum]
		if ok {
			// oldi относится к ранее просмотренному числу, а i — к текущему,
			// поэтому возвращаемые индексы заведомо различаются.
			return []int{oldi, i}
		}

		// Записываем num после проверки: один элемент не сможет образовать
		// пару сам с собой, если target == 2*num.
		viewedNums[num] = i
	}

	// Пустой срез обозначает, что среди всех элементов пара не найдена.
	return []int{}
}
