package main

import "container/heap"

/*
Дан целочисленный массив nums и целое число k,
верните k-й по величине элемент массива.
Обратите внимание, что это k-й по величине элемент в отсортированном порядке,
а не k-й среди различных значений.
Можно ли решить задачу без сортировки?

Пример 1:
Вход: nums = [3,2,1,5,6,4], k = 2
Выход: 5

Пример 2:
Вход: nums = [3,2,3,1,2,4,5,5,6], k = 4
Выход: 4

Ограничения:
1 <= k <= nums.length <= 10^5
-10^4 <= nums[i] <= 10^4
*/

type MinHeap []int

// Len сообщает размер кучи: время/память O(1), h не меняет.
func (h MinHeap) Len() int {return len(h)}
// Less задаёт min-heap: меньшее значение имеет больший приоритет.
// Время/память O(1); i/j допустимы по вызовам container/heap.
func (h MinHeap) Less(i, j int) bool {return h[i] < h[j]}
// Swap меняет элементы общего буфера h за O(1) времени и памяти.
func (h MinHeap) Swap(i, j int) {h[i], h[j] = h[j], h[i]}
// Push добавляет int в конец; структуру кучи восстанавливает heap.Push.
// s — размер h: время амортизированно O(1), худшее O(s+1) при росте.
// При росте новый буфер O(s+1), иначе память O(1); меняет *h.
// Здесь передаются только int; после Pop длины k-1 уже есть ёмкость k.
func (h *MinHeap) Push(x interface{}) {*h = append(*h, x.(int))}
// Pop удаляет последний элемент за O(1) времени и рабочей памяти.
// Именно heap.Pop перед этим переносит минимум в конец; не этот метод.
// Меняет длину *h, сохраняет буфер; ответ interface{} с int занимает O(1).
// Куча непуста по контракту вызова: в findKthLargest её размер k>=1.
func (h *MinHeap) Pop() interface{} {
    n := len(*h)
    x := (*h)[n-1]
    *h = (*h)[0:n-1]
    return x
}

// findKthLargest держит min-heap из k наибольших просмотренных значений.
// n=len(nums), p — число замен: время O(n+p*log(k+1)),
// в худшем O(n*log(k+1)); рабочая память O(k), ответ int O(1).
// nums не меняется: куча хранит копию. По условию 1<=k<=n.
func findKthLargest(nums []int, k int) int {
    mh := make(MinHeap, k)
    copy(mh, nums[:k])
    // Первые k значений образуют исходных кандидатов; heap.Init стоит O(k).
    // Корень — наименьший среди них, то есть k-й по величине в префиксе.
    heap.Init(&mh)
    
    for i := k; i < len(nums); i++ {
        // Значение не выше корня не улучшает набор top-k, включая равные.
        // Более крупное заменяет минимум; два heap-вызова возвращают размер k.
        // После Pop при k=1 куча пуста, но Push идёт до нового доступа mh[0].
        if nums[i] > mh[0] {
            heap.Pop(&mh)
            heap.Push(&mh, nums[i])
        }
    }
    return mh[0]
}