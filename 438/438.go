package main

/*
Даны строки s и p. Верните массив всех индексов, с которых в s начинаются
анаграммы p. Ответ можно вернуть в любом порядке.

Пример 1:
Вход: s = "cbaebabacd", p = "abc"
Выход: [0,6]
Пояснение:
Подстрока с начальным индексом 0 — "cba", анаграмма "abc".
Подстрока с начальным индексом 6 — "bac", анаграмма "abc".

Пример 2:
Вход: s = "abab", p = "ab"
Выход: [0,1,2]
Пояснение:
Подстрока с начальным индексом 0 — "ab", анаграмма "ab".
Подстрока с начальным индексом 1 — "ba", анаграмма "ab".
Подстрока с начальным индексом 2 — "ab", анаграмма "ab".

Ограничения:
1 <= s.length, p.length <= 3 * 10^4
s и p состоят из строчных английских букв.
*/

// findAnagrams находит все начальные индексы анаграмм p в s.
// Окно длины m хранит частоты букв и число совпавших частот.
// Время O(n + m), где n = len(s), m = len(p); рабочая память O(1)
// при алфавите из 26 букв. Результат занимает O(n - m + 1) при m <= n.
func findAnagrams(s string, p string) []int {
    n, m := len(s), len(p)
    // Если p длиннее s, окно нужной длины не помещается в строке.
    if m > n {
        return []int{}
    }

    // Считаем частоты в p и в первом окне s длины m.
    // Индекс буквы относительно 'a' корректен по ограничению на алфавит.
    pCount := make([]int, 26)
    sCount := make([]int, 26)
    for i := range m {
        pCount[p[i]-'a']++
        sCount[s[i]-'a']++
    }

    // match — число букв с равными частотами в p и текущем окне.
    // Учитываем и нулевые частоты: анаграмме соответствуют все 26 совпадений.
    match := 0
    for i := range 26 {
        if pCount[i] == sCount[i] {
            match++
        }
    }

    // Проверяем начальное окно до первого сдвига.
    res := []int{}
    if match == 26 {
        res = append(res, 0)
    }

    // Сдвигаем окно: убираем букву слева и добавляем следующую справа.
    l := 0
    for r := m; r < n; r++ {
        // До изменения частоты убираем старое совпадение, если оно было.
        // После удаления буквы учитываем возможное новое совпадение.
        c := s[l] - 'a'
        if sCount[c] == pCount[c] {
            match--
        }
        sCount[c]--
        l++
        if sCount[c] == pCount[c] {
            match++
        }

        // Для входящей буквы так же сверяем частоты до и после добавления.
        c = s[r] - 'a'
        if sCount[c] == pCount[c] {
            match--
        }
        sCount[c]++
        if sCount[c] == pCount[c] {
            match++
        }

        // После сдвига l указывает на начало проверяемого окна.
        if match == 26 {
            res = append(res, l)
        }
    }

    return res
}