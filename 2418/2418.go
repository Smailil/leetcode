package main

import "sort"

/*
Даны массив строк names и массив heights, состоящий из различных
положительных целых чисел. Оба массива имеют длину n.

Для каждого индекса i элементы names[i] и heights[i] задают имя и рост
i-го человека.

Верните имена, отсортированные по убыванию роста людей.

Пример 1:
Вход: names = ["Mary","John","Emma"], heights = [180,165,170]
Выход: ["Mary","Emma","John"]
Пояснение: Mary — самая высокая, за ней следуют Emma и John.

Пример 2:
Вход: names = ["Alice","Bob","Bob"], heights = [155,185,150]
Выход: ["Bob","Alice","Bob"]
Пояснение: первый Bob — самый высокий, за ним следуют Alice и второй Bob.

Ограничения:
n == names.length == heights.length
1 <= n <= 10^3
1 <= names[i].length <= 20
1 <= heights[i] <= 10^5
names[i] состоит из строчных и прописных английских букв.
Все значения heights различны.
*/

// sortPeople возвращает имена в порядке убывания роста.
// Функция связывает каждый уникальный рост с именем, сортирует heights
// по возрастанию на месте и затем читает этот срез с конца.
// Среднее время: O(n log n), где n = len(names): сортировка требует
// O(n log n), а обращение к map в среднем занимает O(1).
// Дополнительная рабочая память: O(n) для map; результат занимает O(n).
// Срез heights изменяется, потому что sort.Ints сортирует его на месте.
func sortPeople(names []string, heights []int) []string {
    // Равная длина срезов гарантирует существование names[i], а уникальность
    // значений heights не позволяет одному ключу перезаписать другое имя.
    m := make(map[int]string)
    for i, h := range heights {
        m[h] = names[i]
    }

    // После сортировки по возрастанию самые высокие люди находятся в конце.
    sort.Ints(heights)
    res := make([]string, len(heights))
    // На шаге i берём i-й рост с конца; индекс остаётся в границах, потому что
    // цикл проходит ровно len(heights) элементов.
    for i := range heights {
        res[i] = m[heights[len(heights)-1-i]]
    }

    return res
}