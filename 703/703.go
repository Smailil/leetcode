package main

/*
Вы работаете в приемной комиссии университета и вам необходимо отслеживать k-й
наивысший результат 
тестов абитуриентов в режиме реального времени.
Это помогает динамически определять пороговые баллы
для собеседований и поступления по мере того, как новые кандидаты представляют
свои баллы.
Вам поручено реализовать класс, который для заданного целого числа k
поддерживает поток результатов тестов
и постоянно возвращает k-й наивысший результат теста после подачи нового
результата.
Точнее, мы ищем k-й наивысший балл в отсортированном списке всех баллов.

Реализуйте класс KthLargest:
KthLargest(int k, int[] nums) Инициализирует объект целым числом k и потоком
чисел результатов тестов.
int add(int val) Добавляет в поток новое значение теста и возвращает элемент,
представляющий k-й по величине элемент в пуле результатов тестов на данный
момент.

Пример 1:
Вход:
["KthLargest", "add", "add", "add", "add", "add"]
[[3, [4, 5, 8, 2]], [3], [5], [10], [9], [4]]
Выход: [null, 4, 5, 5, 8, 8]
Объяснение:
KthLargest kthLargest = new KthLargest(3, [4, 5, 8, 2]);
kthLargest.add(3); // возвращает 4
kthLargest.add(5); // возвращает 5
kthLargest.add(10); // возвращает 5
kthLargest.add(9); // возвращает 8
kthLargest.add(4); // возвращает 8

Пример 2:
Вход:
["KthLargest", "add", "add", "add", "add"]
[[4, [7, 7, 7, 7, 8, 3]], [2], [10], [9], [9]]
Выход: [null, 7, 7, 7, 8]
Объяснение:
KthLargest kthLargest = new KthLargest(4, [7, 7, 7, 7, 8, 3]);
kthLargest.add(2); // возвращает 7
kthLargest.add(10); // возвращает 7
kthLargest.add(9); // возвращает 7
kthLargest.add(9); // возвращает 8

Ограничения:
0 <= nums.length <= 10^4
1 <= k <= nums.length + 1
-10^4 <= nums[i] <= 10^4
-10^4 <= val <= 10^4
Для добавления будет сделано не более 10^4 вызовов.
*/

import "container/heap"

type IntHeap []int

// Len возвращает размер за O(1) времени и памяти, не меняя кучу.
func (h IntHeap) Len() int           { return len(h) }
// Less задаёт min-heap: меньший элемент выше; время и память O(1).
func (h IntHeap) Less(i, j int) bool { return h[i] < h[j] }
// Swap меняет два элемента кучи за O(1) времени и памяти.
func (h IntHeap) Swap(i, j int)      { h[i], h[j] = h[j], h[i] }

// Push — callback heap: добавляет int, меняя срез.
// Время амортизированно O(1); рост буфера требует O(k) времени и памяти.
func (h *IntHeap) Push(x interface{}) {
    *h = append(*h, x.(int))
}

// Pop — callback после переноса выбранного корня в конец container/heap.
// Снимает хвост непустого среза за O(1) времени и памяти, меняя его длину.
func (h *IntHeap) Pop() interface{} {
    n := h.Len()
    x := (*h)[n-1]
    *h = (*h)[0:n-1]
    return x
}

// KthLargest хранит до k наибольших значений, учитывая повторы отдельно.
// При заполнении корень min-heap — k-й по величине; состояние занимает O(k).
type KthLargest struct {
    k int
    minHeap *IntHeap
}

// Constructor пропускает исходный поток через Add; nums не меняется.
// n = len(nums): время O(n log(k + 1)), рабочая память роста буфера O(k).
// Возвращаемое состояние занимает O(k); пустой heap.Init здесь стоит O(1).
func Constructor(k int, nums []int) KthLargest {
    minHeap := &IntHeap{}
    heap.Init(minHeap)
    kthLargest := KthLargest{k, minHeap}
    // До заполнения Add возвращает минимум увиденного, не полный k-й ранг.
    // Эти промежуточные значения конструктор игнорирует.
    for _, num := range nums {
        kthLargest.Add(num)
    }
    return kthLargest
}

// Add сохраняет top-k: дополняет кучу или заменяет самый малый кандидат.
// Время амортизированно O(log(k + 1)); отдельный рост буфера стоит O(k).
// Рабочая память O(1), кроме роста буфера O(k); меняет состояние receiver.
// Результат O(1): минимум сохранённого, k-й ранг при хотя бы k значениях.
func (this *KthLargest) Add(val int) int {
    // После первых k значений куча хранит именно k крупнейших увиденных.
    // До этого она хранит все; k >= 1 делает корень доступным после Push.
    if this.minHeap.Len() < this.k {
        heap.Push(this.minHeap, val)
    } else if val > (*this.minHeap)[0] {
        // Значение выше порога заменяет минимум; остальные top-k остаются.
        heap.Pop(this.minHeap)
        heap.Push(this.minHeap, val)
    }
    // При публичном Add после Constructor виденных значений уже не меньше k:
    // контракт k <= len(nums) + 1 гарантирует это с первого такого вызова.
    return (*this.minHeap)[0]
}