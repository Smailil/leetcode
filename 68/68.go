package main

import "strings"

/*
Даны массив строк words и ширина maxWidth. Отформатируйте текст так,
чтобы каждая строка содержала ровно maxWidth символов и была выровнена
по обоим краям — левому и правому.

Используйте жадный подход: помещайте в каждую строку как можно больше слов.
При необходимости добавляйте пробелы ' ', чтобы длина каждой строки
составляла ровно maxWidth символов.

Распределяйте дополнительные пробелы между словами как можно равномернее.
Если число пробелов в строке не делится поровну между промежутками,
в промежутках слева должно быть больше пробелов, чем в промежутках справа.

Последнюю строку текста выровняйте по левому краю.
Не вставляйте в ней дополнительные пробелы между словами.

Примечание:
Слово — это последовательность символов, не содержащая пробелов.
Гарантируется, что длина каждого слова больше 0 и не превышает maxWidth.
Входной массив words содержит хотя бы одно слово.

Пример 1:
Вход: words = ["This", "is", "an", "example", "of", "text", "justification."],
maxWidth = 16
Выход:
[
   "This    is    an",
   "example  of text",
   "justification.  "
]

Пример 2:
Вход: words = ["What","must","be","acknowledgment","shall","be"], maxWidth = 16
Выход:
[
  "What   must   be",
  "acknowledgment  ",
  "shall be        "
]
Пояснение: последняя строка — "shall be    ", а не "shall     be",
поскольку её нужно выровнять по левому краю, а не по обоим краям.
Вторая строка тоже выровнена по левому краю, так как содержит только одно слово.

Пример 3:
Вход: words = ["Science","is","what","we","understand","well","enough","to",
              "explain","to","a","computer.","Art","is","everything","else",
              "we","do"], maxWidth = 20
Выход:
[
  "Science  is  what we",
  "understand      well",
  "enough to explain to",
  "a  computer.  Art is",
  "everything  else  we",
  "do                  "
]

Ограничения:
1 <= words.length <= 300
1 <= words[i].length <= 20
words[i] состоит только из английских букв и символов.
1 <= maxWidth <= 100
words[i].length <= maxWidth

*/

// fullJustify жадно набирает слова в строки и выравнивает их пробелами.
// Все строки, кроме последней, выравниваются по обоим краям; последняя — слева.
// Время O(n + r * w), где n = len(words), w = maxWidth, r — число строк
// результата: набор слов линейный, а создание текста требует O(r * w).
// Рабочая память без результата O(w); память результата O(r * w).
// Срез words и его строки не изменяются: line хранит отдельные копии ссылок.
func fullJustify(words []string, maxWidth int) []string {
    res := []string{}
    line := []string{}
    // При наборе строки length — сумма длин слов без пробелов.
    // line хранит выбранные слова, i — индекс ещё не добавленного слова.
    length := 0
    i := 0

    for i < len(words) {
        // Если сейчас слов k = len(line), после добавления станет k + 1,
        // а минимальных промежутков — k. Поэтому прибавляем len(line),
        // а не len(line)-1. Равенство означает, что строка заполнена точно.
        if length+len(words[i])+len(line) <= maxWidth {
            line = append(line, words[i])
            length += len(words[i])
            i++
        } else {
            // Следующее слово не помещается даже с одиночными пробелами:
            // текущая строка набрана максимально плотно по числу слов.
            // Все maxWidth-length свободных позиций заполняем пробелами.
            extraSpace := maxWidth - length
            // Для k > 1 делим пробелы между k-1 промежутками.
            // Для единственного слова используем один промежуток справа:
            // max(1, ...) исключает деление на ноль и даёт нужное дополнение.
            // line не пуст: первое слово всегда помещается по условию задачи.
            gaps := max(1, len(line)-1)
            remainder := extraSpace % gaps
            space := extraSpace / gaps

            // Каждый промежуток получает space пробелов, первые remainder
            // промежутков — ещё по одному. Например, 5 пробелов на 2
            // промежутка распределяются как 3 слева и 2 справа.
            for j := 0; j < max(1, len(line)-1); j++ {
                line[j] += strings.Repeat(" ", space)
                if remainder > 0 {
                    line[j] += " "
                    remainder--
                }
            }

            // Пробелы уже присоединены к словам, поэтому Join не добавляет
            // свои. Индекс i не меняем: не поместившееся слово начнёт
            // следующую строку. Сбрасываем только состояние текущей строки,
            // сохраняя готовую в res.
            res = append(res, strings.Join(line, ""))
            line = []string{}
            length = 0
        }
    }

    // После обработки всех слов в line остаётся последняя строка.
    // Между словами нужен ровно один пробел, а весь остаток ширины — справа.
    // trailSpace неотрицателен: при наборе уже учтены минимальные промежутки.
    lastLine := strings.Join(line, " ")
    trailSpace := maxWidth - len(lastLine)
    res = append(res, lastLine+strings.Repeat(" ", trailSpace))

    return res
}