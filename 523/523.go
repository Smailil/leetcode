package main

/*
Дан массив целых чисел nums и целое число k.
Верните true, если в nums есть подходящий подмассив.
В противном случае верните false.

Подмассив считается подходящим, если:
- его длина не меньше двух;
- сумма его элементов кратна k.

Примечание:
- Подмассив — это непрерывная часть массива.
- Целое число x кратно k, если существует целое число n, для которого x = n * k.
  Ноль всегда кратен k.

Пример 1:
Вход: nums = [23,2,4,6,7], k = 6
Выход: true
Пояснение: [2, 4] — непрерывный подмассив длины 2.
Сумма его элементов равна 6.

Пример 2:
Вход: nums = [23,2,6,4,7], k = 6
Выход: true
Пояснение: [23, 2, 6, 4, 7] — непрерывный подмассив длины 5,
сумма элементов которого равна 42.
Число 42 кратно 6, поскольку 42 = 7 * 6, а 7 — целое число.

Пример 3:
Вход: nums = [23,2,6,4,7], k = 13
Выход: false

Ограничения:
1 <= nums.length <= 10^5
0 <= nums[i] <= 10^9
0 <= sum(nums[i]) <= 2^31 - 1
1 <= k <= 2^31 - 1

*/

// checkSubarraySum проверяет, есть ли в nums подмассив длины от 2,
// сумма которого кратна k.
// Равные остатки префиксных сумм означают, что их разность кратна k.
// Среднее время O(n), n = len(nums): map в среднем O(1), % для int — O(1).
// Рабочая память O(u), где u — число сохранённых разных остатков,
// u <= min(n + 1, k).
func checkSubarraySum(nums []int, k int) bool {
    // Остаток 0 у пустого префикса соответствует индексу -1.
    // Это позволяет находить подходящий подмассив с начала nums.
    remainder := map[int]int{0: -1}
    total := 0

    // После прибавления num значение total — сумма nums[0:i+1].
    // nums неотрицательны, а sum(nums) <= 2^31 - 1: int не переполнится.
    // k >= 1, поэтому вычисление остатка не делит на ноль.
    for i, num := range nums {
        total += num
        r := total % k
        // Если остаток уже был у префикса до idx, то разность сумм
        // равна sum(nums[idx+1:i+1]) и кратна k.
        // Например, при k=6 префиксы 23 и 29 имеют остаток 5:
        // разность 29-23=6 равна сумме элементов nums[1:3] (2+4).
        if idx, ok := remainder[r]; !ok {
            // Храним первый индекс остатка: он даст наибольшую длину
            // при следующем появлении того же остатка.
            remainder[r] = i
        } else if i-idx > 1 {
            // i-idx — длина найденного участка; она не меньше двух.
            return true
        }
    }

    return false
}
