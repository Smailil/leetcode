package main

/*
Даны входная строка s и шаблон p.
Реализуйте сопоставление с регулярным выражением, поддерживающим '.' и '*':
'.' соответствует любому одному символу.
'*' соответствует нулю или более повторений предыдущего элемента.
Верните логическое значение, указывающее, охватывает ли сопоставление
всю входную строку, а не только её часть.

Пример 1:
Вход: s = "aa", p = "a"
Выход: false
Пояснение: "a" не соответствует всей строке "aa".

Пример 2:
Вход: s = "aa", p = "a*"
Выход: true
Пояснение: '*' означает ноль или более повторений предыдущего элемента 'a'.
Следовательно, повторив «a» ещё один раз, получим «aa».

Пример 3:
Вход: s = "ab", p = ".*"
Выход: true
Пояснение: «.*» означает «ноль или более (*) любого символа (.)».

Ограничения:
1 <= s.length <= 20
1 <= p.length <= 20
s содержит только строчные английские буквы.
p содержит только строчные английские буквы, «.» и «*».
Гарантируется, что каждому символу «*» предшествует допустимый символ.
*/

// isMatch проверяет полное совпадение ASCII-строк через DP по суффиксам.
// D(i,j) означает совпадение s[i:] с p[j:]; храним лишь две строки.
// Время O(m*n), m = len(s), n = len(p); рабочая память O(n).
// Результат bool занимает O(1); входные строки не меняются.
// За вызов выделяется O(m*n) ячеек, одновременно нужны O(n).
func isMatch(s, p string) bool {
	m, n := len(s), len(p)

	// При i<m dp хранит D(i+1,j), уже вычисленную нижнюю строку.
	// На первом шаге i=m match=false: предыдущий dp не читается.
	dp := make([]bool, n+1)
	// Начальный флаг не участвует в переходах первого шага.
	// Настоящую базу D(m,n) задаёт nextDp[n] внутри цикла.
	dp[n] = true

	// Проходим по строке s с конца к началу.
	// Каждая итерация вычисляет значения для текущей строки i.
	for i := m; i >= 0; i-- {
		// nextDp будет хранить результаты для текущей строки i.
		nextDp := make([]bool, n+1)

		// Базовый случай для текущей строки:
		// Если паттерн пуст (j == n), совпадение возможно только тогда,
		// когда и суффикс строки пуст (i == m).
		nextDp[n] = i == m

		// Проходим по паттерну p с конца к началу.
		// j+1<n для '*' даёт j+2<=n: индекс nextDp[j+2] безопасен.
		// Английские буквы и знаки шаблона занимают по одному байту.
		for j := n - 1; j >= 0; j-- {
			// Проверяем совпадение текущих символов.
			// i < m защищает от паники при выходе за границы строки.
			match := i < m && (s[i] == p[j] || p[j] == '.')

			if j+1 < n && p[j+1] == '*' {
				// Обработка '*': ноль или более повторений предыдущего символа.
				// nextDp[j+2] → dp[i][j+2]: пропускаем символ и '*' (0 повторений).
				// Значение уже вычислено в этой итерации, так как j убывает.
				// dp[j] → dp[i+1][j]: символ совпал, "съедаем" его из s,
				// но остаёмся на том же паттерне (1+ повторений).
				// Значение взято из предыдущей итерации внешнего цикла.
				nextDp[j] = nextDp[j+2] || (match && dp[j])
			} else if match {
				// Обычный символ или '.':
				// dp[j+1] → dp[i+1][j+1]: символы совпали,
				// двигаемся дальше по обеим строкам.
				// Значение также взято из предыдущей итерации.
				nextDp[j] = dp[j+1]
			}
			// Если совпадения нет, nextDp[j] остаётся false
			// (значение по умолчанию в Go).
		}

		// "Сдвигаем" окно: текущая вычисленная строка становится нижней
		// для следующей итерации (i-1).
		// Прежний массив больше не нужен; момент работы GC не фиксирован.
		dp = nextDp
	}

	// dp[0] содержит результат для полных строк: s[0:] и p[0:].
	return dp[0]
}

