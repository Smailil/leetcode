package main

import "strings"

/*
Дано n пар круглых скобок.
Напишите функцию, которая генерирует все правильные комбинации этих скобок.

Пример 1:
Вход: n = 3
Выход: ["((()))","(()())","(())()","()(())","()()()"]

Пример 2:
Вход: n = 1
Выход: ["()"]

Ограничения:
1 <= n <= 8
*/

// generateParenthesis строит только префиксы правильных скобочных строк.
// C_n — n-е число Каталана, то есть количество результатов.
// Время O(n*C_n): каждый ответ длины 2n собирается strings.Join.
// Рабочая память O(n) для текущего пути и рекурсии;
// память результата O(n*C_n) для отдельных строк и их заголовков.
// Внешнее состояние и вход не изменяются.
func generateParenthesis(n int) []string {
	res := make([]string, 0)
	stack := make([]string, 0, n*2)
    var backtrack func (int, int)
	// backtrack достраивает текущий путь, сохраняя 0 <= closedN <= openN <= n.
	// Глубина рекурсии не больше 2n; stack хранит скобки этого пути.
	// q = 2*n-openN-closedN, t — число ответов из данного префикса.
	// Время поддерева O(2^q+n*t), стек O(q+1); общий буфер stack O(n).
	// Меняет stack и res локального генератора, строки ответа независимы.
	backtrack = func(openN, closedN int) {
		if openN == n && closedN == n {
			// Join копирует полный путь в отдельную строку: откат stack
			// после возврата не изменит уже сохранённый ответ.
			res = append(res, strings.Join(stack, ""))
			return 
		}
		// Открывающая скобка допустима, пока не использованы все n пар.
		if openN < n {
			stack = append(stack, "(")
			backtrack(openN+1, closedN)
			// Откат восстанавливает ровно путь родителя перед другой веткой.
			stack = stack[:len(stack)-1]
		}
		// Закрывающая допустима лишь при незакрытой открывающей:
		// ни один префикс не получает отрицательный баланс.
		if closedN < openN {
			stack = append(stack, ")")
			backtrack(openN, closedN+1)
			// Откат восстанавливает ровно путь родителя перед другой веткой.
			stack = stack[:len(stack)-1]
		}
	}
	backtrack(0, 0)
	return res
}
