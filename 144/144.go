package main

/*
Дан корень root двоичного дерева.
Верните прямой обход (preorder) значений его узлов.

Пример 1:
Вход: root = [1,null,2,3]
Выход: [1,2,3]
Пояснение:
https://assets.leetcode.com/uploads/2024/08/29/screenshot-2024-08-29-202743.png

Пример 2:
Вход: root = [1,2,3,4,5,null,8,null,null,6,7,9]
Выход: [1,2,4,5,6,7,3,8,9]
Пояснение:
https://assets.leetcode.com/uploads/2024/08/29/tree_2.png

Пример 3:
Вход: root = []
Выход: []

Пример 4:
Вход: root = [1]
Выход: [1]

Ограничения:
Количество узлов в дереве — в диапазоне [0, 100].
-100 <= Node.val <= 100
*/

/**
 * Определение узла бинарного дерева.
 * type TreeNode struct {
 *     Val int
 *     Left *TreeNode
 *     Right *TreeNode
 * }
 */
// preorderTraversal собирает прямой обход: узел, левое, правое поддерево.
// Время O(n) амортизированно, n — число узлов дерева.
// Рабочая память O(h) для рекурсии, h — высота дерева;
// результат O(n) для res. Дерево не изменяется.
func preorderTraversal(root *TreeNode) []int {
    res := []int{}
    var preorder func(node *TreeNode)
    // preorder обходит текущее поддерево и дописывает значения в общий res.
    // Время O(t) амортизированно, t — число его узлов; рабочий стек O(d),
    // d — высота этого поддерева. Добавляет t значений в результат,
    // чей итоговый размер O(n); изменяет захваченный res, но не дерево.
    preorder = func(node *TreeNode) {
        // Пустое поддерево не добавляет значений и завершает ветвь.
        if node == nil {
            return
        }
        // Записываем корень до рекурсивных вызовов, затем полностью
        // левую ветвь до правой: это и задаёт порядок preorder.
        res = append(res, node.Val)
        preorder(node.Left)
        preorder(node.Right)
    }
    // При root == nil останется пустой срез; иначе обход посетит
    // каждый узел ровно один раз.
    preorder(root)
    return res
}
