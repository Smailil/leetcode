package main

/*
Дан массив строк strs.
Сгруппируйте анаграммы.
Ответ можно вернуть в любом порядке.

Пример 1:
Вход: strs = ["eat","tea","tan","ate","nat","bat"]
Выход: [["bat"],["nat","tan"],["ate","eat","tea"]]
Пояснение:
В strs нет строки, которую можно перестановкой букв превратить в "bat".
Строки "nat" и "tan" — анаграммы: перестановкой букв получаем одну из другой.
Строки "ate", "eat" и "tea" — анаграммы:
перестановкой букв любую из них можно превратить в любую другую.

Пример 2:
Вход: strs = [""]
Выход: [[""]]

Пример 3:
Вход: strs = ["a"]
Выход: [["a"]]

Ограничения:
1 <= strs.length <= 10^4
0 <= strs[i].length <= 100
strs[i] состоит из строчных английских букв.
*/

// hashKey строит точную частотную сигнатуру 26 строчных ASCII-букв.
// m = len(s); время O(m+26), рабочая память и результат O(26) = O(1).
// При m <= 100 частоты помещаются в byte; строка не изменяется.
func hashKey(s string) [26]byte {
	key := [26]byte{}
	for i := range s {
		// Контракт 'a'..'z' даёт индекс 0..25 без выхода из массива.
		key[s[i]-'a']++
	}
	return key

}

// groupAnagrams объединяет строки с одинаковыми частотами всех букв.
// n = len(strs), L — сумма длин, g — число различных сигнатур.
// Время O(L+26*n) в среднем, то есть O(L+n) при фиксированных 26 буквах.
// Хеширование и сравнение ключа map стоят O(26), а не зависят от длины str.
// Рабочая память без ответа O(g) для map; новые буферы ответа O(n+g).
// Заголовки строк копируются без байтов: ответ удерживает их общие буферы.
// Вход не меняется; порядок групп зависит от обхода map.
func groupAnagrams(strs []string) [][]string {
	strMap := make(map[[26]byte][]string)
	for _, str := range strs {
		// Частотная сигнатура равна ровно у анаграмм в допустимом алфавите.
		// map сравнивает массивы полностью, разрешая свои hash-коллизии.
		key := hashKey(str)
		strMap[key] = append(strMap[key], str)

	}
	// Буферы групп уже составляют ответ; переносим только их заголовки,
	// не создавая вторых копий групп или строк.
	res := make([][]string, 0, len(strMap))
	for _, val := range strMap {
		res = append(res, val)
	}
	return res
}
