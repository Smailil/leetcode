package main

import "math"

/*
Квадратная тройка (a,b,c) — это тройка, где a, b и c — целые числа
и a^2 + b^2 = c^2.
Дано целое число n.
Верните количество квадратных троек, для которых 1 <= a, b, c <= n.

Пример 1:
Вход: n = 5
Выход: 2
Пояснение: квадратные тройки — это (3,4,5) и (4,3,5).

Пример 2:
Вход: n = 10
Выход: 4
Пояснение: квадратные тройки — это (3,4,5), (4,3,5), (6,8,10) и (8,6,10).

Ограничения:
1 <= n <= 250
*/

// countTriples перебирает пары a<=b и проверяет, даёт ли сумма квадратов
// квадрат целого c в допустимом диапазоне; разные порядки катетов считаются.
// Время O(n²), рабочая память и результат int O(1).
func countTriples(n int) int {
    count := 0
    // При n<=250 квадраты до62500, сумма двух — до125000, int32 безопасен.
    nSquared := n * n
    
    for a := 1; a <= n; a++ {
        aSquared := a * a
        for b := a; b <= n; b++ {
            bSquared := b * b
            cSquared := aSquared + bSquared
            
            // С ростом b сумма увеличивается, следующие c тоже больше n.
            if cSquared > nSquared {
                break
            }
            
            // Здесь cSquared<=62500 точно представим в float64. Sqrt даёт
            // кандидата, а сравнение целых квадратов точно проверяет равенство.
            c := int(math.Sqrt(float64(cSquared)))
            if c*c == cSquared {
                // Для a!=b есть две упорядоченные тройки: (a,b,c) и (b,a,c).
                if a == b {
                    count++
                } else {
                    count += 2
                }
            }
        }
    }
    
    return count
}
