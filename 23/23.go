package main

/*
Дан массив из k связных списков.
Каждый список отсортирован по возрастанию.
Объедините все списки в один отсортированный связный список и верните его.

Пример 1:
Вход: связные списки
[
 1->4->5,
 1->3->4,
 2->6
]
Выход: объединённый отсортированный связный список
1->1->2->3->4->4->5->6

Пример 2:
Вход: lists = []
Выход: []

Пример 3:
Вход: lists = [[]]
Выход: []

Ограничения:
k == lists.length
0 <= k <= 10^4
0 <= lists[i].length <= 500
-10^4 <= lists[i][j] <= 10^4
lists[i] отсортирован по возрастанию.
Сумма lists[i].length не превышает 10^4.
*/

type ListNode struct {
	Val  int
	Next *ListNode
}

// mergeTwoLists сливает два отсортированных списка по их текущим головам.
// Время: O(m + n), m и n — числа узлов входных списков.
// Рабочая память: O(1), включая фиктивную голову.
// Память результата: O(m + n), удерживаются исходные узлы без копирования.
// Новые узлы данных не создаются.
// Побочный эффект: меняются Next входных узлов, списки не копируются.
func mergeTwoLists(list1, list2 *ListNode) *ListNode {
	// dummy позволяет одинаково присоединять первый и последующие узлы.
	dummy := &ListNode{}
	tail := dummy
	// До tail построен отсортированный префикс из наименьших узлов.
	// list1 и list2 указывают на головы ещё не включённых остатков.
	for list1 != nil && list2 != nil {
		// Обе головы существуют благодаря условию цикла.
		// При равенстве берём первый список; порядок по значениям сохранён.
		if list1.Val <= list2.Val {
			tail.Next = list1
			list1 = list1.Next
		} else {
			tail.Next = list2
			list2 = list2.Next
		}
		tail = tail.Next

	}
	// Один остаток пуст: другой уже отсортирован и не меньше префикса.
	// Его целиком присоединяем без дополнительного обхода.
	if list1 != nil {
		tail.Next = list1
	} else if list2 != nil {
		tail.Next = list2
	}
	return dummy.Next
}

// mergeKLists попарно сливает списки, сокращая их число вдвое по раундам.
// Пусть k = len(lists), N — суммарное число исходных узлов.
// Время: O(k + N log(k+1)); член O(k) учитывает и пустые списки.
// Рабочая память: O(k) для массивов голов текущего и следующего раундов.
// Память результата: O(N), переиспользуются исходные узлы.
// Новые узлы данных не создаются.
// Побочный эффект: mergeTwoLists меняет Next исходных узлов.
// Сам исходный массив голов lists не перезаписывается.
func mergeKLists(lists []*ListNode) *ListNode {
	// При k == 0 нет даже единственной головы для итогового lists[0].
	if len(lists) == 0 {
		return nil
	}
	// В каждом раунде все списки отсортированы и покрывают те же N узлов.
	// Один узел участвует не более чем в одном слиянии за раунд.
	// Число раундов не больше ceil(log2(k)).
	for len(lists) > 1 {
		// Пара даёт одну голову, нечётный хвост — ещё одну: ceil(len/2).
		// len(lists) <= 10^4, поэтому сложение с 1 безопасно.
		mergedLists := make([]*ListNode, 0, (len(lists)+1)/2)
		for i := 0; i < len(lists); i += 2 {
			// Проверка защищает вторую голову пары при нечётной длине.
			if i+1 < len(lists) {
				mergedLists = append(mergedLists, mergeTwoLists(lists[i], lists[i+1]))
			} else {
				// Непарный список уже отсортирован и перейдёт в следующий раунд.
				mergedLists = append(mergedLists, lists[i])
			}
		}
		lists = mergedLists
	}
	// Непустой набор голов сократился до одной, возможно равной nil.
	return lists[0]
}
