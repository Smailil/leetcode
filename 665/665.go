package main

/*
Дан массив nums из n целых чисел. Определите, можно ли сделать его
неубывающим, изменив не более одного элемента.

Массив называется неубывающим, если для каждого i от 0 до n - 2
выполняется nums[i] <= nums[i + 1] (индексация с нуля).

Пример 1:
Вход: nums = [4,2,3]
Выход: true
Пояснение: Можно заменить 4 в начале массива на 1 — получится
неубывающий массив.

Пример 2:
Вход: nums = [4,2,1]
Выход: false
Пояснение: Нельзя получить неубывающий массив, изменив не более
одного элемента.

Ограничения:
n == nums.length
1 <= n <= 10^4
-10^5 <= nums[i] <= 10^5
*/

// checkPossibility проверяет, можно ли сделать nums неубывающим,
// изменив не более одного элемента. Жадно исправляем первое нарушение:
// понижаем левый элемент, если это безопасно, иначе повышаем правый.
// Функция изменяет nums на месте; изменение может сохраниться даже
// при возврате false, если позже встретится ещё одно нарушение.
// Время: O(n), где n = len(nums). Дополнительная память: O(1).
func checkPossibility(nums []int) bool {
    // Показывает, использовано ли единственное разрешённое изменение.
    changed := false

    // Проверяем соседние пары слева направо. До текущей пары префикс
    // nums[0..i] уже неубывающий; выбранная правка должна сохранить это.
    // Для одного элемента пар нет, и массив уже неубывающий.
    for i := range len(nums)-1 {
        // Правильная пара не расходует разрешённое изменение.
        if nums[i] <= nums[i+1] {
            continue
        }
        // Найдено nums[i] > nums[i+1]. Если изменение уже использовано,
        // новое нарушение потребует второй правки. Первую выбирали так,
        // чтобы оставить как можно больше свободы для следующих пар.
        if changed {
            return false
        }
        // Если слева нет элемента либо nums[i-1] <= nums[i+1],
        // понижение nums[i] не испортит уже проверенную левую пару.
        // Предпочитаем его: не увеличиваем nums[i+1], чтобы не осложнять
        // сравнение со следующим элементом. [4,2,3] -> [2,2,3].
        // Короткое замыкание || при i == 0 защищает доступ к nums[i-1].
        if i == 0 || nums[i+1] >= nums[i-1] {
            nums[i] = nums[i+1]
        } else {
            // Иначе nums[i-1] > nums[i+1]: понижение сломало бы левую
            // пару. Остаётся поднять nums[i+1] до nums[i].
            // Например, [3,4,2] -> [3,4,4]. Если справа есть следующая
            // пара, проверим её уже с повышенным значением.
            nums[i+1] = nums[i]
        }
        changed = true
    }
    // Все соседние пары проверены; понадобилось не более одной правки.
    return true
}