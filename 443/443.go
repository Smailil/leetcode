package main

import "fmt"

/*
Дан массив символов chars, который нужно сжать следующим образом:
Начните с пустой строки s.
Для каждой группы подряд идущих одинаковых символов в chars:
Если длина группы равна 1, добавьте этот символ в s.
Иначе добавьте символ, а после него — длину группы.

Сжатую строку s не нужно возвращать отдельно.
Вместо этого сохраните её во входном массиве символов chars.
Длины групп от 10 и выше записываются в chars несколькими символами.

После изменения входного массива верните его новую длину.
Алгоритм должен использовать только постоянную дополнительную память.

Примечание: символы массива за пределами возвращённой длины не важны;
их следует игнорировать.

Пример 1:
Вход: chars = ["a","a","b","b","c","c","c"]
Выход: 6
Пояснение: группы — "aa", "bb" и "ccc".
Результат сжатия — "a2b2c3".
После изменения входного массива на месте первые 6 символов chars
должны быть ["a","2","b","2","c","3"].

Пример 2:
Вход: chars = ["a"]
Выход: 1
Пояснение: единственная группа — "a".
Это одиночный символ, поэтому он остаётся несжатым.
После изменения входного массива на месте первый символ chars
должен быть ["a"].

Пример 3:
Вход: chars = ["a","b","b","b","b","b","b","b","b","b","b","b","b"]
Выход: 4
Пояснение: группы — "a" и "bbbbbbbbbbbb".
Результат сжатия — "ab12".
После изменения входного массива на месте первые 4 символа chars
должны быть ["a","b","1","2"].

Ограничения:
1 <= chars.length <= 2000
chars[i] — строчная или заглавная английская буква, цифра или символ.
*/

// compress сжимает группы одинаковых байтов в самом chars и возвращает
// длину значимого префикса. Длина среза не меняется, его хвост не важен.
// Идея: полностью прочитать группу, затем записать её краткое представление
// в начало массива, используя отдельные индексы чтения и записи.
//
// Время: O(n), где n = len(chars). Индекс чтения проходит вход один раз,
// а суммарное число записанных байтов не превышает n. Вложенные циклы
// обрабатывают разные группы, а не заново весь массив для каждого символа.
// Дополнительная память: O(1) при ограничениях задачи. fmt.Sprintf создаёт
// временную строку, затем используется []byte(in): это не код без выделений.
// В общей модели представление счётчика требует O(d) памяти, где d — число
// его десятичных цифр. Здесь count <= 2000, d <= 4, поэтому размер ограничен
// константой. Отдельный массив результата не создаётся.
func compress(chars []byte) int {
	// i читает исходные группы; res указывает на следующую позицию записи.
	// В chars[0:res] уже находится готовый результат, с i начинается
	// ещё не обработанная часть. Запись не должна затронуть эту часть.
	i, res := 0, 0
	// n — исходная длина: при записи сжатого префикса она не уменьшается.
	n := len(chars)
	for i < n {
		// Сохраняем символ группы до перезаписи массива. Сначала считаем
		// всю группу: после внутреннего цикла i уже у следующей группы
		// или равен n, а c и count содержат всё нужное для записи.
		c := chars[i]
		count := 0
		// && проверяет условия слева направо: при i == n обращение
		// chars[i] не выполняется, поэтому выхода за границу нет.
		for i < n && chars[i] == c {
			count++
			i++
		}
		// В рамках задачи символ занимает один байт. Сжатая группа
		// занимает 1 байт при count == 1, иначе 1 + число цифр count.
		// Эта длина не больше count: например, 12 байтов b дают "b12".
		// Поэтому запись остаётся в прочитанной области (res <= i)
		// и не портит следующие группы, даже когда chars меняется на месте.
		if count == 1 {
			// Одиночный символ пишем без цифры 1: она лишь удлинила бы результат.
			chars[res] = c
			res++
		} else {
			// %c записывает символ, %d — количество в десятичном виде.
			// Например, c == 'b' и count == 12 дают временную строку "b12".
			in := fmt.Sprintf("%c%d", c, count)
			// Переносим символ и каждую цифру отдельными байтами.
			// res растёт после каждой записи и равен длине готового префикса.
			for _, char := range []byte(in) {
				chars[res] = char
				res++
			}
		}
	}
	// Возвращаем длину, а не новый срез: результат лежит в chars[:res].
	// Оставшиеся элементы chars[res:] могут содержать старые данные.
	return res
}
