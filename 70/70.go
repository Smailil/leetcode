package main

/*
Вы поднимаетесь по лестнице.
Чтобы достичь вершины, нужно преодолеть n ступеней.
Каждый раз вы можете подняться на 1 или 2 ступеньки.
Сколькими различными способами вы можете подняться на вершину?

Пример 1:
Вход: n = 2
Выход: 2
Пояснение: Есть два способа подняться на вершину.
1. 1 шаг + 1 шаг
2. 2 шага

Пример 2:
Вход: n = 3
Выход: 3
Пояснение: Есть три способа подняться на вершину.
1. 1 шаг + 1 шаг + 1 шаг
2. 1 шаг + 2 шага
3. 2 шага + 1 шаг

Ограничения:
1 <= n <= 45
*/

// climbStairs считает способы подъёма на n ступеней динамикой.
// Последний шаг имеет длину 1 или 2: ways(k)=ways(k-1)+ways(k-2).
// Хранит только два соседних значения вместо массива всей динамики.
// Время O(n); рабочая память и память результата O(1).
// Побочных эффектов нет; при n до 45 результат помещается в 32-битный int.
func climbStairs(n int) int {
    // Один пустой маршрут для высоты 0; prev=0 — служебная база для шага 1.
    curr, prev := 1, 0

    // После k итераций curr=ways(k), prev=ways(k-1).
    for range n {
        // Обе правые части вычисляются по старым значениям до присваивания.
        curr, prev = curr + prev, curr
    }
    return curr
}