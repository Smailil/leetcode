package main

func isAnagram(s string, t string) bool {
	// Для каждой строчной латинской буквы храним баланс её вхождений:
	// положительное значение означает перевес в s, отрицательное — в t.
	chars := make([]int, 26)

	// Сначала учитываем все символы s, увеличивая соответствующие балансы.
	for _, c := range s {
		i := int(c - 'a')
		chars[i]++
	}

	// Вхождения из t погашают ранее накопленные вхождения тех же букв.
	for _, c := range t {
		i := int(c - 'a')
		chars[i]--
	}

	// Строки являются анаграммами, только если частоты каждой буквы совпали,
	// то есть все накопленные балансы вернулись к нулю.
	for _, v := range chars {
		if v != 0 {
			return false
		}
	}
	return true
}
