package main

/*
Даны две строки s и t.
Верните true, если t является анаграммой s, и false в противном случае.

Пример 1:
Вход: s = "anagram", t = "nagaram"
Выход: true

Пример 2:
Вход: s = "rat", t = "car"
Выход: false

Ограничения:
1 <= s.length, t.length <= 5 * 10^4
s и t состоят из строчных английских букв.
*/

// isAnagram сравнивает частоты букв через баланс прибавлений и вычитаний.
// Время O(m+n+A), m=len(s), n=len(t), A=26 — размер алфавита.
// Рабочая память O(A), при фиксированных 26 буквах O(1); результат bool O(1).
// Строки не изменяются; индексы c-'a' в [0,25] по ограничению на буквы.
func isAnagram(s string, t string) bool {
	// Для каждой строчной латинской буквы храним баланс её вхождений:
	// положительное значение означает перевес в s, отрицательное — в t.
	chars := make([]int, 26)

	// Сначала учитываем все символы s, увеличивая соответствующие балансы.
	for _, c := range s {
		i := int(c - 'a')
		chars[i]++
	}

	// Вхождения из t погашают ранее накопленные вхождения тех же букв.
	for _, c := range t {
		i := int(c - 'a')
		chars[i]--
	}

	// Строки являются анаграммами, только если частоты каждой буквы совпали,
	// то есть все накопленные балансы вернулись к нулю.
	for _, v := range chars {
		if v != 0 {
			return false
		}
	}
	return true
}
