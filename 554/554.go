package main

/*
Перед вами прямоугольная кирпичная стена, состоящая из n рядов кирпичей.
i-я строка содержит некоторое количество кирпичей одинаковой высоты
(то есть высотой в одну единицу), но их ширина может различаться.
Общая ширина каждой строки одинакова.

Проведите вертикальную линию сверху вниз так, чтобы она пересекла как можно
меньше кирпичей. Если линия проходит по краю кирпича, этот кирпич не считается
пересечённым. Нельзя проводить линию вдоль одной из двух вертикальных границ
стены, поскольку в этом случае она, очевидно, не пересечёт ни одного кирпича.

Дан двумерный массив wall, содержащий информацию о стене.
Верните минимальное количество кирпичей, которые пересечёт такая вертикальная
линия.

Пример 1:
https://assets.leetcode.com/uploads/2025/01/17/a.png
Вход: wall = [[1,2,2,1],[3,1,2],[1,3,2],[2,4],[3,1,2],[1,3,1,1]]
Выход: 2

Пример 2:
Вход: wall = [[1],[1],[1]]
Выход: 3

Ограничения:
n == wall.length
1 <= n <= 10^4
1 <= wall[i].length <= 10^4
1 <= sum(wall[i].length) <= 2 * 10^4
sum(wall[i]) одинаково для каждой строки i.
1 <= wall[i][j] <= 2^31 - 1
*/

// leastBricks выбирает разрез, совпадающий с максимумом внутренних границ.
// Если граница встречается в g строках, линия пересечёт len(wall) - g кирпичей.
// Пусть B — общее число кирпичей, K — число разных внутренних границ.
// Среднее время: O(B + K), то есть O(B), так как K <= B; операции map в
// среднем занимают O(1). Дополнительная память: O(K).
func leastBricks(wall [][]int) int {
    // countGap[x] хранит число строк с внутренней границей в координате x.
    // Запись 0:0 не влияет на максимум, даже если других границ нет.
    countGap := map[int]int{0: 0}

    // Для каждой строки координату границы считаем своей накопленной суммой.
    for _, row := range wall {
        total := 0

        // Последний кирпич пропускаем: его правый край является внешней
        // границей стены, вдоль которой проводить линию запрещено.
        for i := 0; i < len(row)-1; i++ {
            total += row[i]

            // Одинаковая накопленная ширина означает общую границу строк.
            countGap[total]++
        }
    }

    // Чем больше строк разделяет одна граница, тем меньше кирпичей пересечём.
    maxGaps := 0
    for _, count := range countGap {
        if count > maxGaps {
            maxGaps = count
        }
    }

    // Строки без выбранной границы неизбежно дают по одному пересечению.
    return len(wall) - maxGaps
}