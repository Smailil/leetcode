package main

import "sort"

/*
Дан массив интервалов, где intervals[i] = [start_i, end_i].
Объедините все перекрывающиеся интервалы и верните массив
непересекающихся интервалов,
который охватывает все интервалы во входных данных.

Пример 1:
Вход: intervals = [[1,3],[2,6],[8,10],[15,18]]
Выход: [[1,6],[8,10],[15,18]]
Пояснение: поскольку интервалы [1,3] и [2,6] перекрываются,
объедините их в [1,6].

Пример 2:
Вход: intervals = [[1,4],[4,5]]
Выход: [[1,5]]
Пояснение: интервалы [1,4] и [4,5] считаются перекрывающимися.

Пример 3:
Вход: intervals = [[4,7],[1,4]]
Выход: [[1,7]]
Пояснение: интервалы [1,4] и [4,7] считаются перекрывающимися.

Ограничения:
1 <= intervals.length <= 10^4
intervals[i].length == 2
0 <= start_i <= end_i <= 10^4
*/

// merge сортирует интервалы по началу и расширяет последний в ответе.
// n = len(intervals); время O(n log n), рабочая память O(log n) сортировки.
// Ответ имеет O(n) новой памяти: его внешний срез заранее получает cap n.
// Первый интервал разделяет входной буфер и может удерживать его целиком.
// Побочный эффект: intervals переставляется, конец его первого интервала
// может меняться через общую ссылку output[0]. Контракт n >= 1.
func merge(intervals [][]int) [][]int {
    sort.Slice(intervals, func(i, j int) bool {
        return intervals[i][0] < intervals[j][0]
    })
	
	// Первый интервал добавляется без копирования его внутреннего среза.
	// Следующие непересекающиеся группы получают отдельные пары чисел.
	output := make([][]int, 0, len(intervals))
    output = append(output, intervals[0])

    // Все готовые группы, кроме последней, уже не могут перекрыться
    // с будущими: их начала отсортированы. Обновляем лишь последнюю.
    for _, interval := range intervals[1:] {
        start, end := interval[0], interval[1]
        lastEnd := output[len(output)-1][1]

        // Равенство тоже является перекрытием закрытых интервалов.
        // Максимум концов сохраняет полное покрытие всей текущей группы.
        if start <= lastEnd {
            output[len(output)-1][1] = max(lastEnd, end)
        } else {
            output = append(output, []int{start, end})
        }
    }
    return output
}