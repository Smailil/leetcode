package main

/*
Дан массив строк words (индексация начинается с 0).

За одну операцию выберите два различных индекса i и j, причём words[i] —
непустая строка, и переместите любой символ из words[i] в любую позицию
строки words[j].

Верните true, если с помощью любого количества операций можно сделать все
строки в words одинаковыми, и false в противном случае.

Пример 1:
Вход: words = ["abc","aabc","bc"]
Выход: true
Пояснение: Переместим первый символ 'a' из words[1] в начало words[2].
Тогда words[1] = "abc" и words[2] = "abc".
Теперь все строки равны "abc", поэтому возвращаем true.

Пример 2:
Вход: words = ["ab","a"]
Выход: false
Пояснение: С помощью разрешённой операции невозможно сделать строки
одинаковыми.

Ограничения:
1 <= words.length <= 100
1 <= words[i].length <= 100
words[i] состоит из строчных английских букв.
*/

// makeEqual проверяет, можно ли поровну распределить каждую
// букву между всеми строками. Для этого частота каждой буквы
// должна делиться на число строк.
// Время: O(S), где S — общее число символов в words.
// Дополнительная память: O(1), так как букв ровно 26.
func makeEqual(words []string) bool {
    // Для каждой буквы freq хранит остаток её общей частоты
    // по модулю n. Инвариант: flag равен минус числу букв
    // с ненулевым остатком.
    freq := make([]int, 26)
    flag := 0
    n := len(words)

    for _, w := range words {
        for _, c := range w {
            i := int(c - 'a')
            if freq[i] != 0 {
                freq[i]++
                // Кратность n закрывает ненулевой остаток,
                // поэтому одна проблемная буква исчезает.
                if freq[i]%n == 0 {
                    flag++
                }
            } else {
                freq[i]++
                // Первый ненулевой остаток делает букву проблемной.
                // При n = 1 остаток сразу равен нулю.
                if freq[i]%n != 0 {
                    flag--
                }
            }
            freq[i] %= n
        }
    }

    // flag равен нулю, только если частота каждой буквы
    // делится на число строк.
    return flag == 0
}
