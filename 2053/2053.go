package main

/*
Уникальная строка — это строка, которая встречается в массиве ровно один раз.

Дан массив строк arr и целое число k. Верните k-ю уникальную строку в arr.
Если уникальных строк меньше k, верните пустую строку "".

Строки рассматриваются в том порядке, в котором они расположены в массиве.

Пример 1:
Вход: arr = ["d","b","c","b","c","a"], k = 2
Выход: "a"
Пояснение:
В arr уникальными являются только строки "d" и "a".
Строка "d" встречается раньше, поэтому она является первой уникальной строкой.
Строка "a" встречается следующей, поэтому она является второй уникальной
строкой.
Поскольку k == 2, возвращается "a".

Пример 2:
Вход: arr = ["aaa","aa","a"], k = 1
Выход: "aaa"
Пояснение:
Все строки в arr уникальны, поэтому возвращается первая строка "aaa".

Пример 3:
Вход: arr = ["a","b","a"], k = 3
Выход: ""
Пояснение:
Единственная уникальная строка — "b". Поскольку уникальных строк меньше
трёх, возвращается пустая строка "".

Ограничения:
1 <= k <= arr.length <= 1000
1 <= arr[i].length <= 5
arr[i] состоит из строчных английских букв.
*/

// kthDistinct возвращает k-ю строку, которая встречается в arr ровно один раз,
// сохраняя порядок исходного массива.
// Первый проход собирает частоты, а второй выбирает уникальные строки
// в исходном порядке.
// Время: O(n), где n = len(arr). Дополнительная память: O(n).
func kthDistinct(arr []string, k int) string {
    // Частоты позволяют отличить действительно уникальные строки от тех,
    // которые встречаются в массиве несколько раз.
    count := make(map[string]int)

    for _, s := range arr {
        count[s]++
    }

    // Повторный обход arr сохраняет исходный порядок, которого нет у map.
    // Счётчик k уменьшается только для строк с частотой 1.
    for _, s := range arr {
        if count[s] == 1 {
            k--

            // При достижении нуля текущая строка является искомой.
            if k == 0 {
                return s
            }
        }
    }

    // Если уникальных строк меньше исходного k, требуемой строки нет.
    return ""
}