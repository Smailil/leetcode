package main

/*
Спроектируйте хэш-множество без использования встроенных библиотек хэш-таблиц.

Реализуйте класс MyHashSet:
void add(key) — вставляет значение key в хэш-множество.
bool contains(key) — возвращает true, если key присутствует в хэш-множестве,
иначе false.
void remove(key) — удаляет key из хэш-множества.
Если key не существует — ничего не делать.

Пример 1:
Входные данные
["MyHashSet", "add", "add", "contains", "contains", "add", "contains", "remove",
"contains"]
[[], [1], [2], [1], [3], [2], [2], [2], [2]]
Выходные данные
[null, null, null, true, false, null, true, null, false]
Пояснение
MyHashSet myHashSet = new MyHashSet();
myHashSet.add(1);      // множество = [1]
myHashSet.add(2);      // множество = [1, 2]
myHashSet.contains(1); // вернуть True
myHashSet.contains(3); // вернуть False (не найдено)
myHashSet.add(2);      // множество = [1, 2]
myHashSet.contains(2); // вернуть True
myHashSet.remove(2);   // множество = [1]
myHashSet.contains(2); // вернуть False (уже удалено)

Ограничения:
0 <= key <= 10^6
Не более 10^4 вызовов будет сделано к add, remove и contains.
*/

// ListNode представляет узел односвязного списка.
// Используется для организации цепочек в бакетах хеш-таблицы
// (разрешение коллизий методом цепочек).
type ListNode struct {
	key  int
	next *ListNode
}

// MyHashSet реализует множество с помощью хеш-таблицы.
// Коллизии обрабатываются с помощью отдельных связных списков.
type MyHashSet struct {
	set []*ListNode // Срез указателей на головные (фиктивные) узлы бакетов
}

// Constructor создает и инициализирует новое множество.
// Выделяет память под 10000 бакетов.
// Каждый бакет начинается с фиктивного узла,
// что значительно упрощает логику Add и Remove (не нужно отдельно обрабатывать
// случай, когда удаляемый/добавляемый элемент является первым в цепочке).
// Время O(B), B=10000; рабочая память O(1), начальное состояние O(B).
// При фиксированном B оценки постоянны; узлы ключей добавляются позже.
func Constructor() MyHashSet {
	set := make([]*ListNode, 10000)
	for i := range set {
		// Фиктивный узел с нейтральным ключом.
		// Реальные данные всегда будут добавляться в cur.next
		set[i] = &ListNode{key: 0}
	}
	return MyHashSet{set: set}
}

// hash вычисляет индекс бакета для заданного ключа.
// Использует простую хеш-функцию на основе операции взятия остатка от деления.
// Время и рабочая память O(1), результат индекс O(1); this не меняется.
// Требуется Constructor: len(set)>0; key неотрицателен по условию.
func (this *MyHashSet) hash(key int) int {
	return key % len(this.set)
}

// Add ищет ключ в одной цепочке и добавляет его только при отсутствии.
// Время O(L+1), L — длина цепочки; рабочая память O(1), новый узел O(1).
// Меняет set, отдельного результата нет. Всё состояние занимает O(B+S),
// S — число ключей. При key до10^6 и B=10000 в цепочке до101 ключа.
func (this *MyHashSet) Add(key int) {
	// Начинаем обход с фиктивного узла бакета
	cur := this.set[this.hash(key)]
	
	// Ищем конец цепочки или дубликат ключа
	for cur.next != nil {
		if cur.next.key == key {
			return // Ключ уже существует, ничего не делаем
		}
		cur = cur.next
	}
	// Добавляем новый узел в конец цепочки
	cur.next = &ListNode{key: key}
}


// Remove находит предшественника и исключает узел ключа из его цепочки.
// Время O(L+1), рабочая память O(1); меняет set, отдельного результата нет.
// Исключённый узел доступен GC, но немедленное освобождение не обещается.
func (this *MyHashSet) Remove(key int) {
	cur := this.set[this.hash(key)]
	
	// Ищем узел, СЛЕДУЮЩИЙ ЗА КОТОРЫМ находится целевой ключ.
	// Благодаря фиктивному головному узлу мы всегда имеем доступ к предыдущему
	// узлу.
	for cur.next != nil {
		if cur.next.key == key {
			// Исключаем узел из цепочки: предыдущий теперь указывает на следующий за
			// удаляемым
			cur.next = cur.next.next
			return
		}
		cur = cur.next
	}
}

// Contains просматривает одну цепочку без изменения множества.
// Время O(L+1), рабочая память и результат bool O(1).
// Сравнение ключей точно разрешает коллизии; фиктивный узел не является ключом.
func (this *MyHashSet) Contains(key int) bool {
	cur := this.set[this.hash(key)]
	for cur.next != nil {
		if cur.next.key == key {
			return true
		}
		cur = cur.next
	}
	return false
}


