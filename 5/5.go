package main

/*
Дана строка s, нужно вернуть самую длинную палиндромную подстроку в s.

Пример 1:
Вход: s = "babad"
Выход: "bab"
Пояснение: "aba" также является допустимым ответом.

Пример 2:
Вход: s = "cbbd"
Выход: "bb"

Ограничения:
1 <= s.length <= 1000
s состоит только из цифр и английских букв.
*/

// longestPalindrome расширяет палиндромы из каждого возможного центра.
// n = len(s); время O(n^2), рабочая память O(1).
// Результат не копирует байты: новые метаданные O(1), но срез строки
// удерживает исходный буфер O(n). Вход не изменяется.
func longestPalindrome(s string) string {
    resIdx, resLen := 0, 0

    for i := range len(s) {
        // Нечётная длина.
        // Центр — один байт; внутренняя часть уже палиндромна.
        // Равные концы расширяют её, а проверки границ защищают индексы.
        l, r := i, i
        for l >= 0 && r < len(s) && s[l] == s[r] {
            // Более длинный найденный интервал заменяет текущий лучший.
            if r-l+1 > resLen {
                resIdx = l
                resLen = r - l + 1
            }
            l--
            r++
        }

        // Чётная длина.
        // Центр — промежуток между i и i+1; даже пустая середина допустима.
        l, r = i, i+1
        for l >= 0 && r < len(s) && s[l] == s[r] {
            // Более длинный найденный интервал заменяет текущий лучший.
            if r-l+1 > resLen {
                resIdx = l
                resLen = r - l + 1
            }
            l--
            r++
        }
    }

    // Хотя бы одно нечётное окно найдено при непустом входе.
    // resIdx/resLen всегда описывают уже проверенный допустимый интервал.
    return s[resIdx : resIdx+resLen]
}