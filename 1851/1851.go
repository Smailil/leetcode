package main

/*
Дан двумерный целочисленный массив intervals,
где intervals[i] = [left_i, right_i]
описывает i-й интервал с началом left_i и концом right_i включительно.
Размер интервала — количество содержащихся в нём целых чисел,
то есть right_i - left_i + 1.
Также дан целочисленный массив queries.
Ответ на j-й запрос — размер наименьшего интервала i,
для которого left_i <= queries[j] <= right_i.
Если такого интервала нет, ответ равен -1.
Верните массив ответов на запросы.

Пример 1:
Вход: intervals = [[1,4],[2,4],[3,6],[4,4]], queries = [2,3,4,5]
Выход: [3,3,1,4]
Пояснение: запросы обрабатываются следующим образом:
- Запрос = 2: интервал [2,4] — наименьший интервал, содержащий 2.
  Ответ: 4 - 2 + 1 = 3.
- Запрос = 3: интервал [2,4] — наименьший интервал, содержащий 3.
  Ответ: 4 - 2 + 1 = 3.
- Запрос = 4: интервал [4,4] — наименьший интервал, содержащий 4.
  Ответ: 4 - 4 + 1 = 1.
- Запрос = 5: интервал [3,6] — наименьший интервал, содержащий 5.
  Ответ: 6 - 3 + 1 = 4.

Пример 2:
Вход: intervals = [[2,3],[2,5],[1,8],[20,25]], queries = [2,19,5,22]
Выход: [2,-1,4,6]
Пояснение: запросы обрабатываются следующим образом:
- Запрос = 2: интервал [2,3] — наименьший интервал, содержащий 2.
  Ответ: 3 - 2 + 1 = 2.
- Запрос = 19: ни один из интервалов не содержит 19.
  Ответ: -1.
- Запрос = 5: интервал [2,5] — наименьший интервал, содержащий 5.
  Ответ: 5 - 2 + 1 = 4.
- Запрос = 22: интервал [20,25] — наименьший интервал, содержащий 22.
  Ответ: 25 - 20 + 1 = 6.

Ограничения:
1 <= intervals.length <= 10^5
1 <= queries.length <= 10^5
intervals[i].length == 2
1 <= left_i <= right_i <= 10^7
1 <= queries[j] <= 10^7
*/

import (
	"container/heap"
	"sort"
)

// Interval представляет элемент кучи: размер интервала и его правый конец
type Interval struct {
	size int // r - l + 1
	end  int // r
}

// MinHeap реализует интерфейс heap.Interface для минимальной кучи
type MinHeap []Interval

// Len читает размер за O(1) времени и памяти без изменений.
func (h MinHeap) Len() int           { return len(h) }
// Less сравнивает размеры для min-heap; время и рабочая память O(1).
// Индексы корректны по контракту heap, результат bool O(1).
func (h MinHeap) Less(i, j int) bool { return h[i].size < h[j].size } //
// минимальная куча по размеру
// Swap меняет общий срез за O(1) времени и рабочей памяти.
func (h MinHeap) Swap(i, j int)      { h[i], h[j] = h[j], h[i] }

// Push добавляет Interval: время O(1) амортизированно, O(h) при росте.
// Рабочая память при росте O(h), h — размер кучи; очередь меняется.
// Тип x гарантирует вызывающий heap.Push; это callback, не вся операция heap.
func (h *MinHeap) Push(x interface{}) {
	*h = append(*h, x.(Interval))
}

// Pop снимает последний элемент после перестановки heap; очередь непуста.
// Время, рабочая память и результат Interval O(1); длина очереди уменьшается.
func (h *MinHeap) Pop() interface{} {
	old := *h
	n := len(old)
	x := old[n-1]
	*h = old[:n-1]
	return x
}

// minInterval идёт по отсортированным запросам, добавляя начавшиеся интервалы
// в min-heap по длине и лениво удаляя просроченные вершины.
// Среднее время O(I*log(I+1)+Q*log(Q+1)), I=len(intervals), Q=len(queries).
// Каждый интервал добавляется и снимается не более одного раза.
// Рабочая память O(I+Q), независимый результат O(Q); queries не меняется.
// intervals меняет порядок при сортировке, но значения границ не изменяются.
func minInterval(intervals [][]int, queries []int) []int {
	// Сортируем интервалы по началу
	// Компаратор читает начало; время, память и результат bool O(1).
	// Индексы предоставляет sort, по условию в интервале две границы.
	sort.Slice(intervals, func(i, j int) bool {
		return intervals[i][0] < intervals[j][0]
	})

	// Создаём копию запросов для сортировки
	sortedQueries := make([]int, len(queries))
	copy(sortedQueries, queries)
	sort.Ints(sortedQueries)

	// Результат для каждого запроса
	// Повторный q имеет тот же ответ; ключ — значение запроса, не его позиция.
	// Map резервируется по Q, даже когда различных ключей меньше.
	res := make(map[int]int, len(queries))
	minHeap := &MinHeap{}
	heap.Init(minHeap)

	i := 0
	for _, q := range sortedQueries {
		// Добавляем все интервалы, которые начинаются до или в момент запроса
		for i < len(intervals) && intervals[i][0] <= q {
			l, r := intervals[i][0], intervals[i][1]
			// Интервал включительный, его длина до10^7 безопасна для int32.
			heap.Push(minHeap, Interval{size: r - l + 1, end: r})
			i++
		}

		// Удаляем просроченные интервалы, пока они находятся на вершине.
		for minHeap.Len() > 0 && (*minHeap)[0].end < q {
			heap.Pop(minHeap)
		}

		// Просроченные записи глубже могут остаться: пока вершина допустима,
		// их размеры не меньше её размера и не улучшают ответ.
		// Записываем результат
		if minHeap.Len() > 0 {
			res[q] = (*minHeap)[0].size
		} else {
			res[q] = -1
		}
	}

	// Возвращаем результаты в оригинальном порядке запросов
	result := make([]int, len(queries))
	for i, q := range queries {
		result[i] = res[q]
	}

	return result
}
