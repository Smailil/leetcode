package main

/*
Дана сбалансированная скобочная строка s.
Верните её оценку.

Правила подсчёта оценки:
Строка "()" имеет оценку 1.
Оценка строки AB равна сумме оценок A и B.
Здесь A и B — сбалансированные скобочные строки.
Оценка строки (A) равна удвоенной оценке A.
Здесь A — сбалансированная скобочная строка.

Пример 1:
Вход: s := "()"
Выход: 1

Пример 2:
Вход: s := "(())"
Выход: 2

Пример 3:
Вход: s := "()()"
Выход: 2

Ограничения:
2 <= s.length <= 50
Строка s состоит только из символов '(' и ')'.
Строка s является сбалансированной скобочной строкой.
*/

// scoreOfParentheses вычисляет оценку сбалансированной скобочной строки s.
// Каждая пара "()" даёт 1, а каждая внешняя пара удваивает её вклад.
// Соседние группы складываются, поэтому суммируем вклады отдельных пар "()".
// Время: O(n), где n = len(s). Дополнительная память: O(1).
func scoreOfParentheses(s string) int {
	// depth — число открытых и ещё не закрытых скобок.
	// res — сумма вкладов уже закрытых пар вида "()".
	res, depth := 0, 0
	for i := 0; i < len(s); i++ {
		if s[i] == '(' {
			depth++
		} else {
			depth--
			// После закрытия в depth остаётся число окружающих пар.
			// Сбалансированная строка не начинается с ')': i-1 допустим.
			// Если предыдущий символ '(', закрылась пара "()". Иначе
			// вклады внутренних пар уже были учтены, повтор не нужен.
			if s[i-1] == '(' {
				// depth удвоений единицы дают вклад 2^depth = 1 << depth.
				// В "(()(()))" глубины 1 и 2 дают вклады 2 + 4 = 6.
				// При n <= 50 у пары "()" не больше 24 внешних пар.
				// Даже 25 вкладов по 2^24 помещаются в 32-битный int.
				res += 1 << depth
			}
		}
	}
	return res
}