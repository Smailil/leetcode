package main

/*
Даны строка num, представляющая неотрицательное целое число, и целое число k.
Удалите из num ровно k цифр и верните наименьшее возможное число.

Пример 1:
Вход:
num := "1432219"
k := 3
Выход: "1219"
Пояснение: Удаляем цифры 4, 3 и 2 и получаем наименьшее число 1219.

Пример 2:
Вход:
num := "10200"
k := 1
Выход: "200"
Пояснение: Удаляем первую цифру 1 и получаем число 200.
В ответе не должно быть ведущих нулей.

Пример 3:
Вход:
num := "10"
k := 2
Выход: "0"
Пояснение: Удаляем все цифры.
Цифр не остаётся, поэтому возвращаем "0".

Ограничения:
1 <= k <= num.length <= 10^5
Строка num состоит только из цифр.
В num нет ведущих нулей, кроме случая, когда num — это "0".
*/

// removeKdigits возвращает наименьшее число после удаления ровно k цифр.
// Жадно убираем большие цифры перед меньшими с помощью монотонного стека.
// Время: O(n), n = len(num): каждая цифра кладётся и снимается не более раза.
// Рабочая память: O(n) для стека. Строка результата тоже занимает до O(n).
func removeKdigits(num string, k int) string {
	// Стек хранит оставленные цифры в исходном порядке, k — остаток удалений.
	stack := []byte{}
	for i := 0; i < len(num); i++ {
		c := num[i]
		// Меньшая цифра на более ранней позиции уменьшает число.
		// Например, в "143" при k = 1 удаляем 4: "13" меньше "14" и "43".
		// Вершину читаем только после проверки, что стек не пуст.
		for k > 0 && len(stack) > 0 && stack[len(stack)-1] > c {
			stack = stack[:len(stack)-1]
			k--
		}
		stack = append(stack, c)
	}

	// Если k ещё положительно, цифры в стеке идут по неубыванию.
	// Удаляем с конца, чтобы сохранить наименьший префикс нужной длины.
	for k > 0 && len(stack) > 0 {
		stack = stack[:len(stack)-1]
		k--
	}

	// Ведущие нули не меняют число, поэтому не расходуют остаток k.
	i := 0
	for i < len(stack) && stack[i] == '0' {
		i++
	}

	// Пустой остаток (нет цифр или остались только нули) записываем как "0".
	res := string(stack[i:])
	if res == "" {
		return "0"
	}
	return res
}