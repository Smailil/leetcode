package main

/*
Дан корень двоичного дерева.
Верните значения его узлов при обходе по уровням
(то есть слева направо, уровень за уровнем).

Пример 1:
https://assets.leetcode.com/uploads/2021/02/19/tree1.jpg
Вход: root = [3,9,20,null,null,15,7]
Выход: [[3],[9,20],[15,7]]

Пример 2:
Вход: root = [1]
Выход: [[1]]

Пример 3:
Вход: root = []
Выход: []

Ограничения:
Количество узлов в дереве находится в диапазоне [0, 2000].
-1000 <= Node.val <= 1000
*/

type TreeNode struct {
    Val int
    Left *TreeNode
    Right *TreeNode
}

// levelOrder обходит дерево в ширину и собирает значения по уровням.
// Очередь хранит текущий уровень перед началом внешней итерации.
// Время O(n), n — число узлов; append учитывается амортизированно.
// Рабочая память O(w) для очереди, w — максимальная ширина дерева.
// Результат O(n) хранит копии значений; дерево не изменяется.
func levelOrder(root *TreeNode) [][]int {
    res := make([][]int, 0)
	if root == nil {
		return res
	}
	q := []*TreeNode{root}
	for len(q) != 0 {
		// Фиксируем размер уровня: добавленные дети относятся к следующему.
		qLen := len(q)
		level := make([]int, 0)
		for i := 0; i < qLen; i++ {
			// q не пуста: ещё остались узлы из исходных qLen.
			node := q[0]
			// Срез сдвигает голову за O(1), не копируя хвост.
			// Старые слоты массива не зануляются; очередь хранит ссылки на узлы.
			q = q[1:]
			level = append(level, node.Val)
			// Левый ребёнок добавляется раньше правого, сохраняя порядок уровня.
			if node.Left != nil {
				q = append(q, node.Left)
			}
			if node.Right != nil {
				q = append(q, node.Right)
			}
		}
		// В q теперь только следующий уровень; level полностью готов.
		res = append(res, level)
	}
	return res
}
