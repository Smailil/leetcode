package main

/*
Дан целочисленный массив nums.
Поверните его вправо на k шагов, где k — неотрицательное число.

Пример 1:
Вход: nums = [1,2,3,4,5,6,7], k = 3
Выход: [5,6,7,1,2,3,4]
Пояснение:
повернуть на 1 шаг вправо: [7,1,2,3,4,5,6]
повернуть на 2 шага вправо: [6,7,1,2,3,4,5]
повернуть на 3 шага вправо: [5,6,7,1,2,3,4]

Пример 2:
Вход: nums = [-1,-100,3,99], k = 2
Выход: [3,99,-1,-100]
Пояснение:
повернуть на 1 шаг вправо: [99,-1,-100,3]
повернуть на 2 шага вправо: [3,99,-1,-100]

Ограничения:
1 <= nums.length <= 10^5
-2^31 <= nums[i] <= 2^31 - 1
0 <= k <= 10^5
*/

// rotate поворачивает nums вправо тремя разворотами на месте.
// n=len(nums): время O(n), рабочая память O(1); отдельного результата нет.
// Меняет nums; k — локальная копия.
// По условию n>=1, деление по модулю допустимо.
func rotate(nums []int, k int) {
    n := len(nums)
    // Полный круг не меняет порядок: оставляем 0<=k<n эффективных шагов.
    k %= n

    // reverse разворачивает включительный отрезок nums[l:r+1].
    // m=max(0,r-l+1): время O(m+1), дополнительная память O(1).
    // Меняет захваченный nums. При l>=r ничего не индексирует;
    // иначе вызывающие границы лежат в 0..n-1.
    reverse := func(l, r int) {
        for l < r {
            nums[l], nums[r] = nums[r], nums[l]
            l++
            r--
        }
    }

    // Пусть исходный массив A B, где B — последние k элементов.
    // Разворот целого даёт reverse(B) reverse(A), а развороты частей — B A.
    // Например, [1,2,3|4,5] -> [5,4|3,2,1] -> [4,5|1,2,3].
    // При k=0 второй вызов имеет (0,-1) и пуст; два полных разворота
    // восстанавливают исходный массив без обращения по индексу -1.
    reverse(0, n-1)
    reverse(0, k-1)
    reverse(k, n-1)
}
