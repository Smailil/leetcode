package main

/*
Даны две строки text1 и text2, верните длину их самой длинной общей
подпоследовательности.
Если общей подпоследовательности нет, верните 0.

Подпоследовательность строки — это новая строка, созданная из исходной строки с
удалением некоторых символов (может быть и ни одного) без изменения
относительного порядка оставшихся символов.

Например, «ace» — это подпоследовательность «abcde».
Общая подпоследовательность двух строк — это подпоследовательность, общая для
обеих строк.

Пример 1:
Вход: text1 = "abcde", text2 = "ace" 
Выход: 3  
Пояснение: Самая длинная общая подпоследовательность — «ace», ее длина равна 3.

Пример 2:
Вход: text1 = "abc", text2 = "abc"
Выход: 3
Пояснение: Самая длинная общая подпоследовательность — «abc», ее длина равна 3.

Пример 3:
Вход: text1 = "abc", text2 = "def"
Выход: 0
Объяснение: Такой общей подпоследовательности не существует, поэтому результат
равен 0.

Ограничения:
1 <= text1.length, text2.length <= 1000
text1 и text2 состоят только из строчных английских символов.
*/

// longestCommonSubsequence считает LCS суффиксов, храня только две строки DP.
// m = len(text1), n = len(text2) до обмена: время O(m*n).
// Рабочая память O(min(m, n)), результат O(1); исходные строки не меняются.
func longestCommonSubsequence(text1 string, text2 string) int {
    // Это позволяет использовать меньше памяти для DP
    if len(text1) < len(text2) {
        text1, text2 = text2, text1
    }

    // Теперь text2 не длиннее text1; колонка len(text2) — пустой суффикс.
    // Его LCS равна 0. Последняя ячейка обеих строк всегда остаётся нулевой.
    prev := make([]int, len(text2)+1)
    curr := make([]int, len(text2)+1)

    // Перед строкой i: prev[j] — LCS для text1[i+1:] и text2[j:].
    // Сначала prev описывает пустой суффикс text1, поэтому заполнена нулями.
    for i := len(text1) - 1; i >= 0; i-- {
        // Идём справа налево: curr[j+1] уже относится к текущему i,
        // а prev[j] и prev[j+1] — к следующему. j+1 не превышает длину DP.
        // По контракту одна английская буква — один байт строки.
        for j := len(text2) - 1; j >= 0; j-- {
            // Совпавшие начальные буквы можно взять обе: один символ плюс
            // оптимальная LCS оставшихся суффиксов даёт 1 + prev[j+1].
            if text1[i] == text2[j] {
                curr[j] = 1 + prev[j+1]
            } else {
                // Если символы не совпадают, берём максимум из:
                // - curr[j+1] (пропуск символа из text2)
                // - prev[j] (пропуск символа из text1)
                curr[j] = max(curr[j+1], prev[j])
            }
        }
        // Готовая строка становится prev для следующего i.
        // Старый prev станет curr: на следующем i его ячейки перепишутся.
        prev, curr = curr, prev
    }

    // После строки i=0 prev[0] описывает обе полные строки.
    // Это длина наибольшей общей подпоследовательности
    return prev[0]
}
