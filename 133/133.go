// cloneGraph копирует достижимый граф DFS с отображением старых адресов.
// V — число узлов, A — число записей во всех списках Neighbors:
// среднее время O(V+A), рабочая память O(V) для map и стека,
// память клона O(V+A). Для неориентированного графа A=2*E, E — число рёбер.
// Исходные узлы и списки не меняются; nil возвращает nil.
func cloneGraph(node *Node) *Node {
    if node == nil {
        return nil
    }
    
    visited := make(map[*Node]*Node) // map старый -> новый узел
    var dfs func(*Node) *Node
    
    // dfs возвращает единственный клон n и достраивает его соседей.
    // В сумме все вызовы: среднее время O(V+A), рабочие map/стек O(V),
    // новые узлы/списки O(V+A). Повторно посещённый n обрабатывается за O(1).
    // Меняет visited и новые узлы, а не исходный граф.
    dfs = func(n *Node) *Node {
        // Ключ — адрес исходного узла, не его Val. Одному адресу соответствует
        // один клон; повторное ребро к уже встреченному узлу не создаёт копию.
        if cloned, ok := visited[n]; ok {
            return cloned
        }
        
        newN := &Node{Val: n.Val}
        // Регистрируем до обхода рёбер: обратное ребро найдёт этот клон,
        // даже если его Neighbors ещё строятся, и рекурсия не зациклится.
        visited[n] = newN
        
        // Добавляем ссылки только на новые узлы, сохраняя порядок соседей.
        // append строит отдельный список, не разделяемый со старым n.
        for _, neighbor := range n.Neighbors {
            newN.Neighbors = append(newN.Neighbors, dfs(neighbor))
        }
        
        return newN
    }
    
    return dfs(node)
}
