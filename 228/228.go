package main

import "fmt"

/*
Дан отсортированный массив уникальных целых чисел nums.

Диапазон [a,b] — это множество всех целых чисел от a до b включительно.

Верните отсортированный список диапазонов минимального размера,
который в точности покрывает все числа массива.
Каждый элемент nums должен покрываться ровно одним диапазоном.
Не должно быть целого x, которое входит в один из диапазонов,
но отсутствует в nums.

Каждый диапазон [a,b] должен выводиться так:
"a->b", если a != b
"a", если a == b

Пример 1:
Вход: nums = [0,1,2,4,5,7]
Выход: ["0->2","4->5","7"]
Пояснение: диапазоны:
[0,2] --> "0->2"
[4,5] --> "4->5"
[7,7] --> "7"

Пример 2:
Вход: nums = [0,2,3,4,6,8,9]
Выход: ["0","2->4","6","8->9"]
Пояснение: диапазоны:
[0,0] --> "0"
[2,4] --> "2->4"
[6,6] --> "6"
[8,9] --> "8->9"

Ограничения:
0 <= nums.length <= 20
-2^31 <= nums[i] <= 2^31 - 1
Все значения nums уникальны.
nums отсортирован по возрастанию.
*/

// summaryRanges объединяет максимальные цепочки соседних целых чисел.
// Время O(n+B), n=len(nums), B — число байтов результата.
// Рабочая память O(1), результат O(k+B), k — число диапазонов.
// Для фиксированных 32-битных значений B=O(k), поэтому время O(n).
// Строки результата новые; nums не изменяется.
func summaryRanges(nums []int) []string {
	out := make([]string, 0)
	if len(nums) == 0 {
		return out
	}
	// Непустой вход проверен; [begin,end] — текущая непрерывная цепочка.
	begin := nums[0]
	end := nums[0]
	for i := range nums {
		if i == 0 {
			continue
		}
		// end — предыдущее число; наличие следующего строго большего числа
		// гарантирует end не выше MaxInt32-1: end+1 безопасен.
		if end+1 == nums[i] {
			end++
		} else {
			// Разрыв завершает цепочку; текущее число начинает новую.
			if begin == end {
				out = append(out, fmt.Sprintf("%v", end))
			} else {
				out = append(out, fmt.Sprintf("%v->%v", begin, end))
			}
			begin = nums[i]
			end = nums[i]
		}
	}
	// После цикла ещё не добавлена последняя цепочка.
	if begin == end {
		out = append(out, fmt.Sprintf("%v", end))
	} else {
		out = append(out, fmt.Sprintf("%v->%v", begin, end))
	}
	return out
}
