package main

import (
	"sort"
	"strconv"
	"strings"
)

/*
Дана строка formula, представляющая химическую формулу.
Определите число атомов каждого элемента.

Обозначение элемента начинается с заглавной буквы.
За ней следует ноль или больше строчных букв.

Если атомов элемента больше одного, их количество записывается
одной или несколькими цифрами после обозначения.
Если атом один, цифры не пишутся.

Например, "H2O" и "H2O2" допустимы, а "H1O2" — нет.
Соединение двух формул образует новую формулу.

Например, "H2O2He3Mg4" — тоже формула.
Формула в скобках, после которых может стоять число, тоже допустима.

Например, "(H2O2)" и "(H2O2)3" — допустимые формулы.
Верните число атомов всех элементов в виде строки.
Перечислите обозначения элементов в отсортированном порядке.
После каждого обозначения укажите число атомов, если их больше одного.

Тесты составлены так, что все числа в ответе помещаются в 32-битное целое.

Пример 1:
Ввод:
formula := "H2O"
Вывод: "H2O"
Пояснение: Числа атомов по элементам: {'H': 2, 'O': 1}.

Пример 2:
Ввод:
formula := "Mg(OH)2"
Вывод: "H2MgO2"
Пояснение: Числа атомов по элементам: {'H': 2, 'Mg': 1, 'O': 2}.

Пример 3:
Ввод:
formula := "K4(ON(SO3)2)2"
Вывод: "K4N2O14S4"
Пояснение: Числа атомов по элементам: {'K': 4, 'N': 2, 'O': 14, 'S': 4}.

Ограничения:
1 <= formula.length <= 1000
Строка formula состоит из английских букв, цифр и скобок '(' и ')'.
Формула всегда корректна.
*/

// countOfAtoms возвращает элементы по алфавиту и их суммарные количества.
// Обход справа налево позволяет прочитать множитель до атома или группы.
// Время: O(n + k log k * L) при среднем поведении map, где n = len(formula),
// k — число разных элементов, L — максимальная длина их обозначения.
// Рабочая память: O(k + d), где d — глубина скобок; результат: O(r),
// где r — длина возвращаемой строки.
func countOfAtoms(formula string) string {
	counts := map[string]int64{}
	// factors хранит множители открытых справа групп, factor — их произведение.
	// number ждёт ближайший слева атом или закрывающую скобку; 0 = числа нет.
	factors := []int64{}
	factor, number := int64(1), int64(0)
	i := len(formula) - 1
	for i >= 0 {
		c := formula[i]
		if c >= '0' && c <= '9' {
			// Ищем начало числа справа налево, но читаем срез в исходном
			// порядке: например, «12» должно стать 12, а не 21.
			end := i + 1
			for i >= 0 && formula[i] >= '0' && formula[i] <= '9' {
				i--
			}
			number, _ = strconv.ParseInt(formula[i+1:end], 10, 64)
			continue
		}
		switch c {
		case ')':
			// При входе в группу учитываем её множитель до обработки атомов.
			// Например, в Mg(OH)2 и O, и H получат множитель 2, а Mg — нет.
			mult := number
			if mult == 0 {
				mult = 1
			}
			factors = append(factors, mult)
			factor *= mult
			number = 0
			i--
		case '(':
			// Для корректной формулы парная «)» уже положила множитель
			// в стек. Он входит в factor, поэтому деление точное.
			factor /= factors[len(factors)-1]
			factors = factors[:len(factors)-1]
			i--
		default:
			// Убираем хвост из строчных букв: в корректном обозначении
			// перед ним есть заглавная, поэтому индекс не уйдёт за начало.
			end := i + 1
			for formula[i] >= 'a' && formula[i] <= 'z' {
				i--
			}
			atom := formula[i:end]
			mult := number
			if mult == 0 {
				mult = 1
			}
			// Вклад атома равен его собственному количеству, умноженному
			// на множители всех групп, к которым он принадлежит.
			counts[atom] += factor * mult
			number = 0
			i--
		}
	}
	// Обход map не задаёт порядок. Сортируем только уникальные обозначения.
	names := []string{}
	for atom := range counts {
		names = append(names, atom)
	}
	sort.Strings(names)
	var answer strings.Builder
	for _, atom := range names {
		answer.WriteString(atom)
		// По формату ответа единицу после обозначения не печатаем.
		if counts[atom] > 1 {
			answer.WriteString(strconv.FormatInt(counts[atom], 10))
		}
	}
	return answer.String()
}
