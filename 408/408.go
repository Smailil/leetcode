package main

/*
Строку можно сократить, заменив любое количество непустых подстрок,
не соседствующих друг с другом, на их длины без ведущих нулей.

Например, строку "implementation" можно сократить несколькими способами:
"i12n" -> ("i mplementatio n")
"imp4n5n" -> ("imp leme n tatio n")
"14" -> ("implementation")
"implemetation" -> (подстроки не заменялись)

Недопустимые сокращения:
"i57n" -> (i mplem entatio n, заменены соседние подстроки.)
"i012n" -> (есть ведущие нули)
"i0mplementation" (заменена пустая подстрока)

Даны строка word и сокращение abbr.
Верните true, если abbr является корректным сокращением word,
иначе верните false.

Подстрока — это непрерывная непустая последовательность символов строки.

Пример 1:
Вход: word = "apple", abbr = "a3e"
Выход: true

Пример 2:
Вход: word = "international", abbr = "i9l"
Выход: false

Пример 3:
Вход: word = "abbreviation", abbr = "abbreviation"
Выход: true

Ограничения:
1 <= word.length <= 100
word состоит только из строчных английских букв.
1 <= abbr.length <= 100
abbr состоит из строчных английских букв и цифр.
Все подстроки abbr, состоящие только из цифр,
помещаются в 32-битное целое число.

*/

// validWordAbbreviation проверяет, описывает ли abbr всю строку word.
// Буквы сопоставляем напрямую, числа обозначают пропуск символов в word.
// Время: O(m), где m = len(abbr): каждый символ сокращения обрабатываем
// за постоянное время; пропущенные символы word не обходим.
// Дополнительная память: O(1): только длины, указатели и текущее число.
func validWordAbbreviation(word string, abbr string) bool {
    n, m := len(word), len(abbr)
    // i — позиция следующего символа word, j — следующего символа abbr.
    // До этих позиций сокращение уже совпало с соответствующей частью word.
    i, j := 0, 0

    // Сопоставлять букву можно лишь пока обе строки ещё не закончились.
    // Если число вывело i за конец word, цикл остановится, а ответ будет false.
    for i < n && j < m {
        // Здесь начинается новый элемент сокращения, поэтому '0' недопустим:
        // он означал бы ведущий ноль или пропуск нулевой длины.
        // Ноль внутри уже начатого числа, например в "10", допустим.
        if abbr[j] == '0' {
            return false
        }

        // Буква сокращения должна совпасть именно с текущей буквой word.
        // При 64-битном int i неотрицателен, а j всегда растёт с нуля.
        // Условие цикла проверяет верхние границы обоих индексов.
        if abbr[j] >= 'a' && abbr[j] <= 'z' {
            if word[i] == abbr[j] {
                // Совпавшая буква потребляет по одному символу обеих строк.
                i++
                j++
            } else {
                return false
            }
        } else {
            // По условию любой небуквенный символ abbr является цифрой.
            // Читаем всё число подряд, а не считаем каждую цифру пропуском.
            subLen := 0
            for j < m && abbr[j] >= '0' && abbr[j] <= '9' {
                // Сдвигаем уже прочитанные цифры на разряд и добавляем новую:
                // для "12" сначала получаем 1, затем 1*10 + 2 = 12.
                // Всё число помещается в 32-битный int по условию;
                // его неотрицательные префиксы также не переполняют subLen.
                subLen = subLen*10 + int(abbr[j]-'0')
                j++
            }
            // Пропускаем subLen символов без обхода этих символов.
            // При 64-битном int сумма безопасна: i < n <= 100,
            // а subLen <= 2^31-1. При 32-битном int сумма может переполниться.
            i += subLen
        }
    }

    // Обе строки должны закончиться одновременно и без выхода за границы.
    // i > n — пропущено слишком много; i < n — в word остался хвост.
    // j < m — остались необработанные буквы или числа сокращения.
    return i == n && j == m
}

