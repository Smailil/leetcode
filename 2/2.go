package main

/*
Даны два непустых связных списка, представляющих два неотрицательных
целых числа.
Цифры хранятся в обратном порядке, и каждый узел содержит одну цифру.
Сложите два числа и верните сумму в виде связного списка.
Можно считать, что числа не содержат ведущих нулей, кроме самого числа 0.

Пример 1:
https://assets.leetcode.com/uploads/2020/10/02/addtwonumber1.jpg
Вход: l1 = [2,4,3], l2 = [5,6,4]
Выход: [7,0,8]
Пояснение: 342+465=807.

Пример 2:
Вход: l1 = [0], l2 = [0]
Выход: [0]

Пример 3:
Вход: l1 = [9,9,9,9,9,9,9], l2 = [9,9,9,9]
Выход: [8,9,9,9,0,0,0,1]

Ограничения:
Количество узлов в каждом связном списке находится в диапазоне [1, 100].
0 <= Node.val <= 9
Гарантируется, что список представляет число без ведущих нулей.
*/

type ListNode struct {
    Val int
    Next *ListNode
}


// addTwoNumbers складывает числа от младших разрядов к старшим.
// На каждом шаге перенос carry связывает текущую цифру со следующей.
// Время O(m + n), где m и n — длины l1 и l2.
// Рабочая память без результата O(1); результат занимает O(m + n):
// создаётся не более max(m, n) + 1 новых узлов.
// Узлы входных списков не меняются, результат строится отдельно.
func addTwoNumbers(l1 *ListNode, l2 *ListNode) *ListNode {
    // Фиктивная голова унифицирует вставку первой и следующих цифр.
    // tail — последний узел построенной цепочки, сначала это dummy.
    dummy := &ListNode{}
	tail := dummy
	// Перенос из уже обработанных младших разрядов равен 0 или 1.
	carry := 0
	// После исчерпания одного списка его цифры считаются нулями.
	// Ненулевой последний перенос создаст ещё один узел результата.
	for l1 != nil || l2 != nil || carry != 0 {
		// Складываем две доступные цифры и прежний перенос.
		// По условию каждая цифра в [0, 9], поэтому сумма не больше 19.
		val := carry
		if l1 != nil {
			val += l1.Val
		}
		if l2 != nil {
			val += l2.Val
		}
		// val = 10*(val/10) + val%10: десятки уходят в следующий разряд,
		// единицы остаются текущей цифрой. Сначала сохраняем перенос,
		// затем уменьшаем val до диапазона [0, 9].
		carry = val / 10
		val %= 10
		// Новый узел не переиспользует узлы l1/l2 и не меняет их связи.
		tail.Next = &ListNode{Val: val}
		// Продвигаем только локальные указатели на существующие разряды.
		if l1 != nil {
			l1 = l1.Next
		}
		if l2 != nil {
			l2 = l2.Next
		}
		tail = tail.Next
	}
	// Фиктивный узел не представляет цифру и не входит в ответ.
	return dummy.Next
}
