package main

/*
Вы профессиональный грабитель, планирующий грабить дома на улице.
В каждом доме хранится определенная сумма денег.
Все дома в этом месте расположены по кругу.
Это означает, что первый дом является соседом последнего.
При этом в соседних домах подключена система безопасности,
и она автоматически обратится в полицию, если в одну ночь были взломаны
два соседних дома.
Дан целочисленный массив nums, представляющий сумму денег в каждом доме.
Верните максимальную сумму денег, которую можно украсть сегодня вечером,
не вызвав полицию.

Пример 1:
Вход: nums = [2,3,2]
Выход: 3
Пояснение: Вы не можете ограбить дом 1 (деньги = 2),
а затем ограбить дом 3 (деньги = 2), потому что это соседние дома.

Пример 2:
Вход: nums = [1,2,3,1]
Выход: 4
Пояснение: Ограбить дом 1 (деньги = 1), а затем ограбить дом 3 (деньги = 3).
Общая сумма, которую вы можете ограбить = 1 + 3 = 4.

Пример 3:
Вход: nums = [1,2,3]
Выход: 3

Ограничения:
1 <= nums.length <= 100
0 <= nums[i] <= 1000
*/

// rob решает круговую задачу двумя линейными случаями без одного края.
// Соседние первый и последний дома нельзя взять вместе: исключаем один из них.
// Время O(n), n=len(nums); рабочая память и результат O(1).
// Срезы разделяют входной массив без копии; nums не изменяется.
func rob(nums []int) int {
	// helper решает линейный отрезок без соседних выбранных домов.
	// Время O(k), k=len(nums) этого среза; рабочая память и результат O(1).
	var helper = func (nums []int) int {
		rob1, rob2 := 0, 0
		// rob2 — лучший префикс, rob1 — лучший префикс без предыдущего дома.
		for _, num := range nums {
			// Пропускаем дом или прибавляем его к несоседнему префиксу.
			// Правые части используют старые значения перед записью.
			rob1, rob2 = rob2, max(rob1+num, rob2)
		}
		return rob2
	}
    // nums непуст; при n=1 оба среза пусты, отдельный nums[0] даёт ответ.
    return max(nums[0], max(helper(nums[1:]),
                            helper(nums[:len(nums)-1])))
}