package main

/*
Дана строка s. Найдите первый символ, который не повторяется, и верните его
индекс. Если такого символа нет, верните -1.

Пример 1:
Вход: s = "leetcode"
Выход: 0
Пояснение:
Символ 'l' с индексом 0 — первый символ, который больше не встречается
ни на одной другой позиции.

Пример 2:
Вход: s = "loveleetcode"
Выход: 2

Пример 3:
Вход: s = "aabb"
Выход: -1

Ограничения:
1 <= s.length <= 10^5
s состоит только из строчных английских букв.
*/

// firstUniqChar сохраняет первый индекс каждой буквы и помечает значением n
// буквы, которые повторились. Затем выбирает минимальный допустимый индекс.
// Время: O(n + k), где n = len(s), а k — число различных букв в строке.
// Так как k <= 26, в рамках задачи оценка упрощается до O(n).
// Дополнительная память: O(k); при k <= 26 она упрощается до O(1).
func firstUniqChar(s string) int {
    n := len(s)

    // Значение в count — первый индекс буквы или n, если она повторилась.
    // Маркер n безопасен: все реальные индексы строки лежат в диапазоне [0, n).
    count := make(map[rune]int)

    // range возвращает байтовые индексы. По условию строка состоит только
    // из строчных английских букв, поэтому каждый символ занимает один байт
    // и байтовый индекс совпадает с требуемым индексом символа.
    for i, c := range s {
        if _, exists := count[c]; !exists {
            count[c] = i
        } else {
            // После первого повтора прежний индекс больше не подходит.
            count[c] = n
        }
    }

    // Порядок обхода map не определён, но для поиска минимума он не важен.
    // Значения n автоматически исключаются, пока найден индекс меньше n.
    res := n
    for _, index := range count {
        if index < res {
            res = index
        }
    }

    // Если res не изменился, ни одна буква не встретилась ровно один раз.
    if res == n {
        return -1
    }
    return res
}