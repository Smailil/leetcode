package main

/*
Предположим, что массив длины n, отсортированный в порядке возрастания,
поворачивается от 1 до n раз.
Например, массив nums = [0,1,2,4,5,6,7] может выглядеть следующим образом:
[4,5,6,7,0,1,2], если его повернули 4 раза.
[0,1,2,4,5,6,7], если его повернули 7 раз.
Обратите внимание, что вращение массива [a[0], a[1], a[2], ..., a[n-1]]
1 раз приводит к созданию массива
[a[n-1], a[0], a[1], a[2], ..., a[n-2]].
Дан массив nums из уникальных элементов, сначала отсортированный
по возрастанию, а затем повёрнутый.
Верните минимальный элемент этого массива.
Вы должны написать алгоритм, который работает за время O(log n).

Пример 1:
Вход: nums = [3,4,5,1,2]
Выход: 1
Пояснение: Исходный массив был [1,2,3,4,5] повёрнут 3 раза.

Пример 2:
Вход: nums = [4,5,6,7,0,1,2]
Выход: 0
Пояснение: Исходный массив был [0,1,2,4,5,6,7] и был повернут 4 раза.

Пример 3:
Вход: nums = [11,13,15,17]
Выход: 11
Пояснение: Исходный массив был [11,13,15,17] и был повернут 4 раза.

Ограничения:
n == nums.length
1 <= n <= 5000
-5000 <= nums[i] <= 5000
Все целые числа nums уникальны.
nums сортируется и вращается от 1 до n раз.
*/

// findMin пытается найти минимум повёрнутого массива бинарным сужением.
// Исходная реализация некорректна: [3,4,5,1,2] даёт 3 вместо 1.
// Время O(log n), n=len(nums): диапазон каждый раз сокращается примерно вдвое.
// Рабочая память и результат O(1); вход не изменяется.
func findMin(nums []int) int {
    // Массив непуст по условию; res — минимум только посещённых значений.
    res := nums[0]
	l, r := 0, len(nums) - 1
	for l <= r {
		// У отсортированного участка минимум слева, но потерянные ранее
		// значения это условие восстановить не может.
		if nums[l] < nums[r] {
			res = min(res, nums[l])
			break
		}
		// При n до 5000 сумма l+r не превышает 9998 и не переполняет int.
		med := (l+r)/2
		res = min(res, nums[med])
		// Эти ветки НЕ сохраняют инвариант нахождения минимума в [l,r].
		if nums[med] <= nums[l] {
			l = med + 1
		} else {
			// [3,4,5,1,2]: med=2, затем r=1; минимум 1 исключён из диапазона.
			r = med - 1
		}
	}
	return res
}
