package main

/*
Дано положительное целое число n.
Напишите функцию, которая возвращает количество установленных битов
в его двоичном представлении (также известном как вес Хэмминга).

Пример 1:
Вход: n = 11
Выход: 3
Объяснение:
Входная двоичная строка 1011 имеет в общей сложности три установленных бита.

Пример 2:
Вход: n = 128
Выход: 1
Объяснение:
Входная двоичная строка 10000000 содержит всего один установленный бит.

Пример 3:
Вход: n = 2147483645
Выход: 30
Объяснение:
Входная двоичная строка 11111111111111111111111111111101
имеет в общей сложности тридцать установленных битов.

Ограничения:
1 <= n <= 2^31 - 1
*/

// hammingWeight считает единичные биты, удаляя по одному за итерацию.
// Время O(b), b — число установленных битов; при фиксированных 31 битах O(1).
// Рабочая память и результат O(1); меняется лишь локальная копия n.
func hammingWeight(n int) int {
	res := 0
	for n != 0 {
		// n-1 убирает младшую единицу и ставит единицы во все биты правее.
		// AND с прежним n удаляет только эту единицу; остальные сохраняются.
		// n положителен до вычитания: n-1 не переполняется.
		n &= n - 1 //1100 & 1011 = 1000
        res++
	}
	return res
}

