package main

/*
Дана строка s и словарь строк wordDict,
верните true, если s можно сегментировать в разделенную пробелами
последовательность из одного или нескольких словарных слов.
Обратите внимание, что одно и то же слово в словаре
может использоваться при сегментации несколько раз.

Пример 1:
Вход: s = "leetcode", wordDict = ["leet","code"]
Выход: true
Объяснение: Возвращайте true,
потому что "leetcode" можно сегментировать как "leet code".

Пример 2:
Вход: s = "applepenapple", wordDict = ["apple","pen"]
Выход: true
Объяснение: Возвращайте true,
поскольку "applepenapple" можно сегментировать как "apple pen apple".
Обратите внимание, что вам разрешено повторно использовать словарное слово.

Пример 3:
Вход: s = "catsandog", wordDict = ["cats","dog","sand","and","cat"]
Выход: false

Ограничения:
1 <= s.length <= 300
1 <= wordDict.length <= 1000
1 <= wordDict[i].length <= 20
s и wordDict[i] состоят только из строчных английских букв.
Все строки wordDict уникальны.
*/

// wordBreak заполняет DP по суффиксам справа налево, пробуя первое слово.
// Время O(n*q), n = len(s), q — сумма длин слов wordDict:
// сравнение подходящего фрагмента требует O(L), L = len(w), в худшем случае.
// Рабочая память O(n) для dp; скалярный результат O(1).
// Строка s и словарь wordDict не изменяются.
func wordBreak(s string, wordDict []string) bool {
    // dp[i] означает, что суффикс s[i:] можно разбить на слова.
    // Пустой суффикс уже разобран — база для слова, заканчивающего строку.
    dp := make([]bool, len(s)+1)
    dp[len(s)] = true

    // Длины слов положительны, поэтому dp[i+len(w)] уже вычислено.
    for i := len(s) - 1; i >= 0; i-- {
        for _, w := range wordDict {
            // Граница проверяется до среза. ASCII из условия делает
            // байтовые индексы границами букв; срез строки не копирует байты.
            if i+len(w) <= len(s) && s[i:i+len(w)] == w {
                dp[i] = dp[i+len(w)]
            }
            // Один успешный вариант достаточен. Выход также не даёт
            // следующему неудачному совпадению перезаписать true на false.
            if dp[i] {
                break
            }
        }
    }

    // Нужен ответ для всей строки, то есть суффикса с позиции ноль.
    return dp[0]
}
