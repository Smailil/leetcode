package main

/*
Дан массив целых чисел nums, содержащий n + 1 целых чисел,
где каждое целое число находится в диапазоне [1, n] включительно.
В nums есть только одно повторяющееся число.
Верните это повторяющееся число.
Вы должны решить проблему, не изменяя числа массива
и используя только постоянное дополнительное пространство.

Пример 1:
Вход: nums = [1,3,4,2,2]
Выход: 2

Пример 2:
Вход: nums = [3,1,3,4,2]
Выход: 3

Пример 3:
Вход: nums = [3,3,3,3,3]
Выход: 3

Ограничения:
1 <= n <= 10^5
nums.length == n + 1
1 <= nums[i] <= n
Все целые числа в nums встречаются только один раз,
за исключением одного целого числа, которое встречается два или более раз.
*/

// findDuplicate рассматривает nums как переход i -> nums[i] и находит
// вход в цикл алгоритмом Флойда. Этот вход — повторяющееся значение.
// Время O(n), n = len(nums)-1; рабочая память и результат O(1).
// Массив nums не изменяется, дополнительный граф не создаётся.
func findDuplicate(nums []int) int {
    // Из 0 идём по конечному графу, поэтому обязательно попадём в цикл.
    // В 0 переходов нет, так как значения лежат в [1,n]: вход в цикл
    // имеет разных предшественников из пути и цикла, то есть дубликат.
    // Все значения — допустимые индексы, включая вложенное nums[nums[fast]].
	slow, fast := 0, 0
	for {
		slow = nums[slow]
		fast = nums[nums[fast]]
		// slow сделал t шагов, fast — 2*t. При встрече разность t
		// кратна длине цикла; это не обязательно сам его вход.
		if slow == fast {
			break
		}
	}
	// Пусть mu — число шагов от 0 до входа. Встретившийся slow
	// расположен на t-mu шагов по циклу от входа. Через mu шагов
	// его смещение станет t, кратным длине цикла, а slow2 дойдёт
	// до входа из 0. Поэтому теперь движем оба по одному переходу.
	slow2 := 0
	for slow != slow2 {
		slow = nums[slow]
		slow2 = nums[slow2]
	}
	// Найден именно вход в цикл; по условию других дубликатов нет.
	return slow2
}
