package main

/*
Целое число имеет последовательные цифры тогда и только тогда,
когда каждая следующая цифра на 1 больше предыдущей.

Верните отсортированный список всех целых чисел с последовательными цифрами
в диапазоне [low, high] включительно.

Пример 1:
Вход: low = 100, high = 300
Выход: [123,234]

Пример 2:
Вход: low = 1000, high = 13000
Выход: [1234,2345,3456,4567,5678,6789,12345]

Ограничения:
10 <= low <= high <= 10^9
*/

// sequentialDigits строит числа с соседними цифрами обходом в ширину (BFS).
// Время O(1), рабочая память O(1): всего возможны 45 таких кандидатов.
// k — число ответов; память результата O(k), k <= 36, то есть также O(1).
// Вход не меняется; результат и очередь используют отдельные буферы.
func sequentialDigits(low int, high int) []int {
    res := []int{}
    queue := []int{}

    // Корни девяти цепочек: 1 -> 12 -> 123 -> ..., 2 -> 23 -> 234 -> ... .
    // Цепочка от i имеет 10-i чисел: суммарно 9+8+...+1 = 45 кандидатов.
    // Сами однозначные числа не войдут в ответ: по условию low >= 10.
    for i := 1; i < 10; i++ {
        queue = append(queue, i)
    }

    // FIFO обрабатывает все числа текущей длины раньше более длинных.
    // Внутри уровня порядок сохраняется: продолжения возрастают вместе с n.
    // Ответ уже отсортирован: фильтрация сохраняет порядок обхода.
    for len(queue) > 0 {
        n := queue[0]
        // Срез не копирует элементы и может удерживать прежний буфер очереди.
        queue = queue[1:]

        // Потомки больше n. Если n > high, вся его цепочка уже вне диапазона.
        // continue не добавляет потомка, но обход остальных чисел продолжается.
        if n > high {
            continue
        }
        // Число ниже low пока не подходит, но его цепочку нельзя отбрасывать:
        // например, при low = 100 число 12 ещё даст подходящее число 123.
        if n >= low && n <= high {
            res = append(res, n)
        }
        ones := n % 10
        // Дописываем следующую цифру: 23 -> 234. После цифры 9 продолжения нет.
        // Максимальное число — 123456789; выражение помещается в 32-битный int.
        if ones < 9 {
            queue = append(queue, n*10+(ones+1))
        }
    }

    return res
}