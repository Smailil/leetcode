package main

/*
Дан отсортированный массив целых чисел.
Каждый элемент встречается ровно два раза, кроме одного, который встречается
ровно один раз.

Верните элемент, который встречается только один раз.

Ваше решение должно работать за время O(log n) и использовать O(1) памяти.

Пример 1:
Вход: nums = [1,1,2,3,3,4,4,8,8]
Выход: 2

Пример 2:
Вход: nums = [3,3,7,7,10,11,11]
Выход: 10

Ограничения:
1 <= nums.length <= 10^5
0 <= nums[i] <= 10^5
*/

// singleNonDuplicate находит число, которое встречается только один раз.
// Бинарный поиск выбирает половину по чётности числа элементов до пары.
// Время: O(log n), где n = len(nums). Дополнительная память: O(1).
// Входной срез nums не изменяется.
func singleNonDuplicate(nums []int) int {
    // Инвариант: индекс искомого элемента находится внутри [l, r].
    // Остальные значения образуют соседние пары: массив отсортирован.
    l, r := 0, len(nums)-1

    for l <= r {
        // При l <= r середина лежит в [l, r]; сумма l+r не вычисляется.
        m := l + (r-l)/2
        // Число без пары отличается от обоих соседей, если они есть.
        // || не читает nums[m-1] при m = 0 и nums[m+1] при m = n-1.
        if (m-1 < 0 || nums[m-1] != nums[m]) &&
            (m+1 == len(nums) || nums[m] != nums[m+1]) {
            return nums[m]
        }

        // После проверки выше nums[m] обязательно входит в пару.
        // leftSize — число элементов перед парой, от начала nums, не от l.
        // Если m — первый элемент пары, это m; если второй — m-1.
        leftSize := m
        if m-1 >= 0 && nums[m-1] == nums[m] {
            leftSize = m - 1
        }

        // Полные пары дают чётное число элементов. Нечётный leftSize
        // означает, что перед этой парой находится одиночный элемент.
        // Для [1,1,2,3,3,4,4,8,8]: m = 4, leftSize = 3.
        // Значит, нужно искать слева, где находится число 2.
        if leftSize%2 == 1 {
            // Одиночный элемент левее пары, значит, и левее m.
            r = m - 1
        } else {
            // Одиночный элемент правее пары, значит, и правее m.
            l = m + 1
        }
    }

    // На допустимом входе ответ найдётся в цикле; -1 — запасной исход.
    return -1
}