package main

/*
Дан бинарный массив nums. Верните максимальное количество идущих подряд
единиц в массиве.

Пример 1:
Ввод: nums = [1,1,0,1,1,1]
Вывод: 3
Пояснение: первые две единицы и последние три единицы идут подряд.
Максимальное количество идущих подряд единиц равно 3.

Пример 2:
Ввод: nums = [1,0,1,1,0,1]
Вывод: 2

Ограничения:
1 <= nums.length <= 10^5
nums[i] равен 0 или 1.
*/

// findMaxConsecutiveOnes за один проход отслеживает текущую серию единиц
// и самую длинную из уже найденных. Время — O(len(nums)), память — O(1).
func findMaxConsecutiveOnes(nums []int) int {
    // res хранит глобальный максимум, а cnt — длину текущей серии единиц.
    res, cnt := 0, 0

    // После обработки каждого префикса cnt равен длине его суффикса из единиц.
    for _, num := range nums {
        // Единица продолжает текущую серию, а ноль полностью её прерывает.
        if num == 1 {
            cnt++
        } else {
            cnt = 0
        }

        // Обновляем максимум после изменения cnt, чтобы учесть текущий элемент.
        if cnt > res {
            res = cnt
        }
    }

    // После полного прохода res содержит длину самой длинной серии единиц.
    return res
}
