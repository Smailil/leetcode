package main

/*
Дана строка s. Верните количество уникальных палиндромов длины 3, являющихся
подпоследовательностями s.

Обратите внимание: даже если одну и ту же подпоследовательность можно получить
несколькими способами, она учитывается только один раз.

Палиндром — это строка, одинаково читающаяся слева направо и справа налево.

Подпоследовательность строки — это новая строка, полученная удалением из
исходной строки некоторых символов (возможно, ни одного) без изменения
относительного порядка оставшихся символов.

Например, "ace" является подпоследовательностью "abcde".

Пример 1:
Вход: s = "aabca"
Выход: 3
Пояснение: Существуют 3 палиндромные подпоследовательности длины 3:
- "aba" (подпоследовательность "aabca")
- "aaa" (подпоследовательность "aabca")
- "aca" (подпоследовательность "aabca")

Пример 2:
Вход: s = "adc"
Выход: 0
Пояснение: В строке "adc" нет палиндромных подпоследовательностей длины 3.

Пример 3:
Вход: s = "bbcbaba"
Выход: 4
Пояснение: Существуют 4 палиндромные подпоследовательности длины 3:
- "bbb" (подпоследовательность "bbcbaba")
- "bcb" (подпоследовательность "bbcbaba")
- "bab" (подпоследовательность "bbcbaba")
- "aba" (подпоследовательность "bbcbaba")

Ограничения:
3 <= s.length <= 10^5
s состоит только из строчных английских букв.
*/

// countPalindromicSubsequence подсчитывает различные подпоследовательности
// вида x y x. Для каждой крайней буквы x достаточно рассмотреть символы между
// её первым и последним вхождениями: любой встретившийся там y образует ровно
// один уникальный палиндром x y x.
// Время работы — O(26 * n) = O(n), где n = len(s), поскольку алфавит содержит
// 26 букв. Дополнительная память — O(26) = O(1). Строка s не изменяется.
func countPalindromicSubsequence(s string) int {
    // Индекс массива соответствует букве: 0 — 'a', ..., 25 — 'z'.
    firstIndex := make([]int, 26)
    lastIndex := make([]int, 26)

    // Значение -1 отличает букву, которая ещё не встречалась, от позиции 0.
    for i := range firstIndex {
        firstIndex[i] = -1
        lastIndex[i] = -1
    }

    // Первый индекс записываем один раз, а последний обновляем при каждом
    // вхождении. В результате получаем самый широкий интервал для каждой
    // возможной крайней буквы палиндрома.
    for i := 0; i < len(s); i++ {
        j := int(s[i] - 'a')
        if firstIndex[j] == -1 {
            firstIndex[j] = i
        }
        lastIndex[j] = i
    }

    res := 0
    for ends := range 26 {
        // Для двух одинаковых крайних символов нужны хотя бы два вхождения.
        if firstIndex[ends] == -1 || firstIndex[ends] == lastIndex[ends] {
            continue
        }

        // Первая и последняя позиции образуют максимальный интервал. Поэтому
        // он содержит любую среднюю букву, которую могла бы заключать другая
        // пара той же крайней буквы. Например, для "aabca" между крайними
        // 'a' находятся 'a', 'b' и 'c': получаются "aaa", "aba" и "aca".
        l, r := firstIndex[ends], lastIndex[ends]

        // Бит c в mask означает, что палиндром с текущей крайней буквой и
        // средней буквой c уже учтён. Маска создаётся заново для каждого ends.
        mask := 0
        for i := l + 1; i < r; i++ {
            c := int(s[i] - 'a')

            // По условию c лежит в [0, 25], поэтому сдвиг 1 << c безопасен.
            // Повторная средняя буква задаёт ту же строку x y x и не должна
            // увеличивать результат второй раз.
            if mask&(1<<c) != 0 {
                continue
            }
            mask |= (1 << c)
            res++
        }
    }
    return res
}