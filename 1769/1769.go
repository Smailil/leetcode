package main

/*
Имеется n коробок. Дана двоичная строка boxes длины n, где boxes[i] равен
'0', если i-я коробка пуста, и '1', если в ней находится один шар.

За одну операцию можно переместить один шар из коробки в соседнюю коробку.
Коробка i соседствует с коробкой j, если abs(i - j) == 1. После перемещения
в некоторых коробках может находиться больше одного шара.

Верните массив answer размера n, где answer[i] — минимальное число операций,
необходимых для перемещения всех шаров в i-ю коробку.

Каждый элемент answer[i] вычисляется относительно начального состояния
коробок.

Пример 1:
Вход: boxes = "110"
Выход: [1,1,3]
Пояснение: ответ для каждой коробки вычисляется следующим образом:
1) Первая коробка: один шар нужно переместить из второй коробки в первую
за одну операцию.
2) Вторая коробка: один шар нужно переместить из первой коробки во вторую
за одну операцию.
3) Третья коробка: один шар нужно переместить из первой коробки в третью
за две операции, а ещё один шар — из второй коробки в третью за одну операцию.

Пример 2:
Вход: boxes = "001011"
Выход: [11,8,5,4,3,4]

Ограничения:
n == boxes.length
1 <= n <= 2000
boxes[i] равен либо '0', либо '1'.
*/

// minOperations вычисляет для каждой коробки стоимость переноса в неё всех шаров.
// Первый проход учитывает шары слева, второй — справа, а их вклады суммируются.
// Время: O(n), где n = len(boxes).
// Дополнительная рабочая память: O(1), возвращаемый срез занимает O(n).
func minOperations(boxes string) []int {
    n := len(boxes)
    res := make([]int, n)

    // В первом проходе balls — число шаров слева от текущей коробки,
    // а moves — стоимость их переноса к предыдущей коробке.
    balls, moves := 0, 0
    for i := range n {
        // Один дополнительный шаг для каждого шара переносит стоимость
        // с предыдущей коробки на текущую.
        res[i] = balls + moves

        // Запоминаем полученную стоимость, а символ '0' или '1' превращаем
        // в прибавку к числу шаров для следующих позиций.
        moves += balls
        balls += int(boxes[i] - '0')
    }

    // Второй проход симметрично считает вклад шаров справа.
    // Сброс состояния не даёт смешать стоимости двух направлений.
    balls, moves = 0, 0
    for i := n - 1; i >= 0; i-- {
        // Правый вклад прибавляется к уже записанному левому.
        res[i] += balls + moves

        // Состояние суффикса обновляется для следующей позиции слева.
        moves += balls
        balls += int(boxes[i] - '0')
    }

    return res
}