// NumMatrix хранит матрицу двумерных префиксных сумм
// для быстрого вычисления сумм подматриц.
type NumMatrix struct {
	sumMat [][]int // sumMat[i][j] = сумма элементов исходной матрицы
	// в прямоугольнике от (0,0) до (i-1, j-1)
}

// Constructor инициализирует структуру,
// вычисляя двумерные префиксные суммы.
// R=len(matrix), C=len(matrix[0]): время O(R*C), рабочая память O(1)
// без возвращаемой таблицы; таблица результата занимает O(R*C).
// matrix не меняется и не удерживается объектом, создаются новые буферы.
// R>=1, C>=1. Любой префикс по модулю <= R*C*10^4 <= 4*10^8,
// поэтому prefix+above помещается в int32, а значит и в int.
func Constructor(matrix [][]int) NumMatrix {
	rows, cols := len(matrix), len(matrix[0])
	
	// Создаём матрицу префиксных сумм размером (rows+1) x (cols+1).
	// Дополнительная нулевая строка и столбец упрощают граничные случаи
	// и избавляют от проверок на выход за границы.
	sumMat := make([][]int, rows+1)
	for i := range sumMat {
		sumMat[i] = make([]int, cols+1)
	}

	// Заполняем таблицу префиксных сумм.
	// Оптимизация: вместо стандартной формулы с 4 слагаемыми,
	// используем накопление по строкам + сумму сверху.
	for r := range rows {
		prefix := 0 // Сумма элементов текущей строки от 0 до текущего столбца c
		for c := range cols {
			prefix += matrix[r][c]
			
			// above хранит сумму прямоугольника над текущей ячейкой:
			// sumMat[r][c+1]
			above := sumMat[r][c+1]
			
			// Сумма прямоугольника (0,0) -> (r,c)
			// равна сумме текущей строки до c + сумме всего, что выше.
			sumMat[r+1][c+1] = prefix + above
		}
	}

	return NumMatrix{sumMat: sumMat}
}

// SumRegion вычисляет сумму заданного прямоугольника включением-исключением.
// Время, рабочая память и ответ int O(1); готовая таблица не перестраивается.
// Объект не меняется, смещаются только локальные копии индексов.
// Каждый из четырёх префиксов по модулю <=4*10^8; даже суммарная граница
// 16*10^8 безопасна для промежуточных операций int32.
func (this *NumMatrix) SumRegion(row1 int, col1 int, row2 int, col2 int) int {
	// Смещаем индексы на +1, так как sumMat использует индексацию с 1
	// из-за нулевой строки/столбца.
	// Исходные индексы в пределах matrix: после сдвига row2<=R, col2<=C,
	// а row1-1 и col1-1 неотрицательны. Таблица имеет размеры R+1 на C+1.
	row1++; col1++; row2++; col2++
	
	// Применяем принцип включения-исключения:
	bottomRight := this.sumMat[row2][col2]      // Сумма всего прямоугольника
	// исходной матрицы от (0,0) до (row2-1, col2-1) включительно
	above       := this.sumMat[row1-1][col2]    // Вычитаем область выше
	// целевой подматрицы
	left        := this.sumMat[row2][col1-1]    // Вычитаем область левее
	// целевой подматрицы
	topLeft     := this.sumMat[row1-1][col1-1]  // Прибавляем пересечение,
	// которое было вычтено дважды
	
	return bottomRight - above - left + topLeft
}

