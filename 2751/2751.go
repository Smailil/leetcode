package main

import "sort"

/*
На прямой находятся n роботов, пронумерованных от 1 до n.
У каждого есть положение, запас здоровья и направление движения.

Даны целочисленные массивы positions и healths, а также строка directions.
Индексация в них начинается с нуля.
Символ directions[i] равен 'L' (влево) или 'R' (вправо).
Все значения в positions различны.

Роботы одновременно начинают двигаться в заданных направлениях.
Скорость у всех одинаковая.
Два робота сталкиваются, если во время движения окажутся в одной точке.

При столкновении робот с меньшим запасом здоровья удаляется с прямой.
Запас здоровья второго робота уменьшается на один.
Выживший робот продолжает двигаться в прежнем направлении.
Если запас здоровья у обоих одинаковый, оба робота удаляются с прямой.

Определите запас здоровья роботов, переживших все столкновения.
Когда столкновения станут невозможны, верните их запас здоровья
в исходном порядке: сначала робота 1 (если он выжил), затем робота 2
(если он выжил) и так далее.
Если никто не выжил, верните пустой массив.

Примечание: значения в positions могут быть не отсортированы.

Пример 1:
https://assets.leetcode.com/uploads/2023/05/15/image-20230516011718-12.png
Ввод:
positions := []int{5, 4, 3, 2, 1}
healths := []int{2, 17, 9, 15, 10}
directions := "RRRRR"
Вывод: [2,17,9,15,10]
Пояснение:
Все роботы движутся в одном направлении, поэтому столкновений нет.
Возвращаем запас здоровья роботов в исходном порядке: [2, 17, 9, 15, 10].

Пример 2:
https://assets.leetcode.com/uploads/2023/05/15/image-20230516004433-7.png
Ввод:
positions := []int{3, 5, 2, 6}
healths := []int{10, 10, 15, 12}
directions := "RLRL"
Вывод: [14]
Пояснение:
Происходят два столкновения.
Сначала сталкиваются роботы 1 и 2, у них одинаковый запас здоровья.
Оба удаляются с прямой.
Затем сталкиваются роботы 3 и 4.
У робота 4 запас здоровья меньше, поэтому он удаляется с прямой.
У робота 3 остаётся 15 - 1 = 14 единиц здоровья.
В живых остаётся только робот 3, поэтому возвращаем [14].

Пример 3:
https://assets.leetcode.com/uploads/2023/05/15/image-20230516005114-9.png
Ввод:
positions := []int{1, 2, 5, 6}
healths := []int{10, 10, 11, 11}
directions := "RLRL"
Вывод: []
Пояснение:
Роботы 1 и 2 сталкиваются, и оба удаляются: у них равный запас здоровья.
Роботы 3 и 4 тоже сталкиваются и удаляются по той же причине.
Поэтому возвращаем пустой массив [].

Ограничения:
1 <= positions.length == healths.length == directions.length == n <= 10^5
1 <= positions[i], healths[i] <= 10^9
directions[i] == 'L' или directions[i] == 'R'
Все значения в positions различны.
*/

// survivedRobotsHealths возвращает здоровье выживших в исходном порядке.
// Сортируем роботов по позиции и разрешаем столкновения через стек.
// Время: O(n log n), где n = len(positions); сам проход занимает O(n).
// Рабочая память: O(n); результат занимает O(k), где k — число выживших.
// Изменяет healths на месте: 0 означает, что робот удалён.
func survivedRobotsHealths(positions []int, healths []int, directions string) []int {
	// Сортируем индексы, чтобы не менять positions и сохранить связь
	// каждого робота с его здоровьем, направлением и исходным номером.
	order := make([]int, len(positions))
	for i := range order {
		order[i] = i
	}
	sort.Slice(order, func(a, b int) bool { return positions[order[a]] < positions[order[b]] })
	// В стеке — живые роботы R слева от текущей позиции.
	// Ближайший к текущей позиции робот находится на вершине.
	stack := []int{}
	for _, i := range order {
		if directions[i] == 'R' {
			// Столкновение с этим R возможно только с ещё не встреченным L.
			stack = append(stack, i)
			continue
		}
		// Текущий L сначала встречает ближайшего R слева.
		// Каждая итерация удаляет хотя бы одного робота: всего O(n).
		for len(stack) > 0 && healths[i] > 0 {
			j := stack[len(stack)-1]
			if healths[j] < healths[i] {
				// Например, L со здоровьем 4 убирает R со здоровьем 2
				// и продолжает движение влево со здоровьем 3.
				healths[j] = 0
				healths[i]--
				stack = stack[:len(stack)-1]
			} else if healths[j] > healths[i] {
				// R остаётся на вершине и может встретить следующий L.
				healths[j]--
				healths[i] = 0
			} else {
				// При равном здоровье исчезают оба: снимаем R со стека.
				healths[j] = 0
				healths[i] = 0
				stack = stack[:len(stack)-1]
			}
		}
	}
	// healths не переупорядочивали: пропускаем нули в исходном порядке.
	answer := []int{}
	for _, h := range healths {
		if h > 0 {
			answer = append(answer, h)
		}
	}
	return answer
}

