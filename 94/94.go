package main

/*
Дан корень бинарного дерева — верните значения его узлов в порядке
симметричного (inorder) обхода.

Пример 1:
Вход: root = [1,null,2,3]
Выход: [1,3,2]
Пояснение:
https://assets.leetcode.com/uploads/2024/08/29/screenshot-2024-08-29-202743.png

Пример 2:
Вход: root = [1,2,3,4,5,null,8,null,null,6,7,9]
Выход: [4,2,6,5,7,1,3,9,8]
Пояснение:
https://assets.leetcode.com/uploads/2024/08/29/tree_2.png

Пример 3:
Вход: root = []
Выход: []

Пример 4:
Вход: root = [1]
Выход: [1]

Ограничения:
Количество узлов дерева находится в диапазоне [0, 100].
-100 <= Node.val <= 100
*/

/**
 * Определение узла бинарного дерева.
 * type TreeNode struct {
 *     Val int
 *     Left *TreeNode
 *     Right *TreeNode
 * }
 */

// inorderTraversal возвращает значения в порядке "лево — корень — право".
// n — число узлов, h — высота: время O(n) с амортизированным append,
// рабочий стек O(h), результат O(n). Пустое дерево даёт пустой срез.
// Исходное дерево не меняется.
func inorderTraversal(root *TreeNode) []int {
    res := []int{}
    var inorder func(node *TreeNode)
    // inorder добавляет поддерево node в общий res в симметричном порядке.
    // Для s узлов время амортизированно O(s), стек O(h),
    // где h — высота поддерева; память res учтена внешней функцией.
    // Меняет только res; ссылки и значения дерева сохраняет.
    inorder = func(node *TreeNode) {
        // nil — пустое поддерево: никаких значений добавлять не нужно.
        if node == nil {
            return
        }
        // Левое поддерево дописывается целиком до значения текущего узла.
        inorder(node.Left)
        res = append(res, node.Val)
        // Затем дописывается правое поддерево; порядок сохраняется рекурсией.
        inorder(node.Right)
    }
    inorder(root)
    return res
}