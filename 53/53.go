package main

/*
Дан целочисленный массив nums.
Найдите подмассив с наибольшей суммой и верните эту сумму.

Пример 1:
Вход: nums = [-2,1,-3,4,-1,2,1,-5,4]
Выход: 6
Пояснение: подмассив [4,-1,2,1] имеет наибольшую сумму 6.

Пример 2:
Вход: nums = [1]
Выход: 1
Пояснение: подмассив [1] имеет наибольшую сумму 1.

Пример 3:
Вход: nums = [5,4,-1,7,8]
Выход: 23
Пояснение: подмассив [5,4,-1,7,8] имеет наибольшую сумму 23.

Ограничения:
1 <= nums.length <= 10^5
-10^4 <= nums[i] <= 10^4
*/

// maxSubArray находит максимум суммы непустого подмассива (алгоритм Кадане).
// n = len(nums): время O(n), дополнительная память O(1).
// nums не меняется. По условию n >= 1, поэтому обращение nums[0] безопасно.
func maxSubArray(nums []int) int {
    // maxSub хранит лучший непустой ответ, curSum — лучший суффикс префикса.
    // Начальная nums[0] сохраняет ответ для всех отрицательных чисел.
    maxSub, curSum := nums[0], 0
    // Абсолютная сумма не превосходит 10^5 * 10^4 = 10^9: int безопасен.
    for _, num := range nums {
        // Отрицательный прежний суффикс ухудшает любой новый подмассив:
        // забываем его и начинаем с текущего num. Нулевой можно сохранить.
        if curSum < 0 {
            curSum = 0
        }
        // После добавления curSum — лучшая сумма с этим правым концом.
        curSum += num
		if curSum > maxSub {
			maxSub = curSum
		}
    }
    return maxSub
}