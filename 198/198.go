package main

/*
Вы профессиональный грабитель, планирующий грабить дома на улице.
В каждом доме спрятана определенная сумма денег.
Единственное ограничение, которое мешает вам ограбить каждый из них,
это то, что в соседних домах подключены системы безопасности,
и она автоматически обратится в полицию,
если в одну ночь взломали два соседних дома.
Дан целочисленный массив чисел, представляющий сумму денег в каждом доме.
Верните максимальную сумму денег, которую вы можете ограбить сегодня вечером,
не вызвав полицию.

Пример 1:
Вход: nums = [1,2,3,1]
Выход: 4
Пояснение: Ограбить дом 1 (деньги = 1), а затем ограбить дом 3 (деньги = 3).
Общая сумма, которую вы можете ограбить = 1 + 3 = 4.

Пример 2:
Вход: nums = [2,7,9,3,1]
Выход: 12
Пояснение: Ограбить дом 1 (деньги = 2), ограбить дом 3 (деньги = 9)
и ограбить дом 5 (деньги = 1).
Общая сумма, которую вы можете ограбить = 2 + 9 + 1 = 12.

Ограничения:
1 <= nums.length <= 100
0 <= nums[i] <= 400
*/

// rob ведёт DP максимальной суммы без соседних домов в двух переменных.
// Время O(n), n = len(nums); рабочая память и результат O(1).
// Исходный nums не изменяется.
func rob(nums []int) int {
    // Перед текущим домом rob2 — лучший результат для всего префикса,
    // rob1 — для префикса без его последнего дома. Пустые базы равны нулю.
    rob1, rob2 := 0, 0
	for _, n := range nums {
		// Либо берём n вместе с rob1, пропуская предыдущий дом,
		// либо сохраняем rob2. Обе правые части используют старые значения:
		// одновременное присваивание сдвигает DP на один дом.
		// По условию сумма <= 100*400, поэтому int не переполняется.
		rob1, rob2 = rob2, max(rob1 + n, rob2)
	}
	// rob2 уже учитывает все дома; выбор последнего не обязателен.
	return rob2
}
