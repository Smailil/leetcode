package main

/*
Дано целое число numRows. Верните первые numRows строк треугольника Паскаля.

В треугольнике Паскаля каждое число равно сумме двух чисел,
расположенных непосредственно над ним, как показано ниже:

Пример 1:
Вход: numRows = 5
Выход: [[1],[1,1],[1,2,1],[1,3,3,1],[1,4,6,4,1]]
Пример 2:
Вход: numRows = 1
Выход: [[1]]

Ограничения:
1 <= numRows <= 30
*/

// generate последовательно строит строки треугольника Паскаля,
// используя только последнюю готовую строку.
// Время: O(numRows^2), дополнительная память без результата: O(numRows).
func generate(numRows int) [][]int {
    // Первая строка всегда состоит из единицы. По условию numRows >= 1,
    // поэтому она сразу входит в результат.
    res := [][]int{{1}}

    // Первая строка уже построена, поэтому остаётся добавить numRows - 1 строк.
    // Перед каждой итерацией последняя строка res полностью готова.
    for range numRows-1 {
        // Нули по краям моделируют отсутствующих соседей предыдущей строки.
        // Благодаря этому крайние элементы новой строки также станут единицами.
        temp := make([]int, len(res[len(res)-1])+2)
        copy(temp[1:], res[len(res)-1])

        // Каждый элемент новой строки равен сумме двух соседних элементов
        // дополненной предыдущей строки.
        row := make([]int, len(res[len(res)-1])+1)
        for j := range row {
            row[j] = temp[j] + temp[j+1]
        }

        // Сохраняем готовую строку: на следующей итерации
        // она станет предыдущей.
        res = append(res, row)
    }
    return res
}
