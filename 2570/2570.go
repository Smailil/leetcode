package main

/*
Даны два двумерных целочисленных массива nums1 и nums2.

nums1[i] = [id_i, val_i] означает, что идентификатору id_i
соответствует значение val_i.
nums2[i] = [id_i, val_i] означает, что идентификатору id_i
соответствует значение val_i.
В каждом массиве идентификаторы уникальны и отсортированы по возрастанию.

Объедините массивы в один, отсортированный по возрастанию идентификаторов,
соблюдая следующие условия:
- В результат входят только идентификаторы хотя бы из одного входного массива.
- Каждый идентификатор включается ровно один раз, а его значение равно сумме
  значений этого идентификатора в двух массивах.
  Если идентификатора нет в одном из массивов, считайте его значение
  в этом массиве равным 0.
Верните полученный массив.
Он должен быть отсортирован по возрастанию идентификаторов.

Пример 1:
Вход: nums1 = [[1,2],[2,3],[4,5]], nums2 = [[1,4],[3,2],[4,1]]
Выход: [[1,6],[2,3],[3,2],[4,6]]
Пояснение: полученный массив содержит следующие элементы:
- id = 1, значение этого идентификатора равно 2 + 4 = 6.
- id = 2, значение этого идентификатора равно 3.
- id = 3, значение этого идентификатора равно 2.
- id = 4, значение этого идентификатора равно 5 + 1 = 6.

Пример 2:
Вход: nums1 = [[2,4],[3,6],[5,5]], nums2 = [[1,3],[4,3]]
Выход: [[1,3],[2,4],[3,6],[4,3],[5,5]]
Пояснение: общих идентификаторов нет, поэтому в результат включаются
все идентификаторы со своими значениями.

Ограничения:
1 <= nums1.length, nums2.length <= 200
nums1[i].length == nums2[j].length == 2
1 <= id_i, val_i <= 1000
В обоих массивах идентификаторы уникальны.
Оба массива строго отсортированы по возрастанию идентификаторов.
*/

// mergeArrays объединяет массивы, суммируя значения одинаковых id.
// totals хранит суммы по id; обход id по возрастанию упорядочивает ответ.
// m = len(nums1), n = len(nums2), U = 1000 — максимальный id.
// k — число разных id в ответе; k <= min(U, m + n).
// Время: O(m + n + U); расширения answer учтены амортизированно.
// При фиксированном U это O(m + n).
// Рабочая память без результата: O(U), здесь U фиксирован, значит O(1).
// Память результата: O(k); входные массивы не меняются.
func mergeArrays(nums1 [][]int, nums2 [][]int) [][]int {
	// totals[id] — сумма значений id во всех уже просмотренных строках.
	// Размер 1001 позволяет обращаться к id от 1 до 1000 включительно.
	// Ячейка 0 не используется; изначально все суммы равны нулю.
	totals := make([]int, 1001)

	// В строке ровно два числа: row[0] — id, row[1] — его значение.
	// Поэтому оба индекса допустимы, а row[0] попадает внутрь totals.
	for _, row := range nums1 {
		totals[row[0]] += row[1]
	}

	// Дополняем те же суммы вторым массивом, объединяя общие id.
	// Например, для id = 1 из примера 1 накоплено 2, затем 2 + 4 = 6.
	// В каждом массиве id уникален, поэтому слагаемых для него не больше 2.
	// Максимальная сумма 1000 + 1000 = 2000 безопасна даже для 32-битного int.
	for _, row := range nums2 {
		totals[row[0]] += row[1]
	}

	// Перебор диапазона id даёт сортировку без сравнения строк входов.
	// До каждого шага answer содержит все встретившиеся id меньше текущего.
	// Каждый id посещается один раз, поэтому повторов в ответе не будет.
	answer := [][]int{}
	for id := 1; id <= 1000; id++ {
		// Значения положительны: сумма > 0 тогда и только тогда, когда id был.
		// Нулевые ячейки соответствуют отсутствующим id и пропускаются.
		if totals[id] > 0 {
			// Создаём отдельную строку, не переиспользуя строки nums1 или nums2.
			// Расширения внешнего среза суммарно требуют O(k) времени.
			answer = append(answer, []int{id, totals[id]})
		}
	}
	return answer
}
