package main

import "container/heap"

/*
Дана строка s.
Переставьте символы строки s так, чтобы любые два соседних символа не совпадали.

Верните любую возможную перестановку строки s или верните "", если это
невозможно.

Пример 1:
Вход: s = "aab"
Выход: "aba"

Пример 2:
Вход: s = "aaab"
Выход: ""

Ограничения:
1 <= s.length <= 500
s состоит из строчных английских букв.
*/

// MaxHeap — максимальная куча, хранящая пары [частота, символ].
// Каждый элемент — это []int из двух значений: {частота символа, индекс символа
// (0-25)}.
// Куча упорядочивается по убыванию частоты, чтобы извлекать самый частый символ
// первым.
type MaxHeap [][]int

// Len возвращает количество элементов в куче.
// Время и память O(1); куча не меняется.
func (h MaxHeap) Len() int { return len(h) }

// Less определяет порядок: возвращает true, если элемент i больше элемента j.
// Это превращает стандартную минимальную кучу Go в максимальную — всегда на
// вершине будет
// элемент с наибольшей частотой (h[i][0] > h[j][0]).
// Время и память O(1); пары из двух int создаются алгоритмом ниже.
func (h MaxHeap) Less(i, j int) bool { return h[i][0] > h[j][0] }

// Swap меняет местами элементы по индексам i и j.
// Время и память O(1); меняет два элемента кучи.
func (h MaxHeap) Swap(i, j int) { h[i], h[j] = h[j], h[i] }

// Push добавляет новый элемент в кучу.
// Принимает any и приводит к []int, затем добавляет в слайс.
// Вызывается пакетом heap при heap.Push(); меняет срез.
// Время амортизированно O(1); рост буфера из k элементов стоит O(k).
// Рабочая память O(1), кроме O(k) при росте буфера.
func (h *MaxHeap) Push(x any) { *h = append(*h, x.([]int)) }

// Pop снимает хвост непустого среза за O(1) времени и памяти.
// При heap.Pop выбранный корень уже переставлен в конец пакетом heap.
// Меняет длину среза; этот хвост не является текущим корнем после просеивания.
func (h *MaxHeap) Pop() any {
	old := *h
	n := len(old)
	x := old[n-1]        // Бывший корень уже перенесён в хвост
	*h = old[0 : n-1]    // Удаляем последний элемент из слайса
	return x
}

// reorganizeString строит строку, выбирая самый частый доступный символ.
// n = len(s), V — размер алфавита, k — число различных букв.
// Время O(n log(k + 1) + V), рабочая память O(n + V + k), включая res.
// Строка результата занимает O(n); s не изменяется.
// Здесь V = 26, k <= 26: время и рабочая память упрощаются до O(n).
func reorganizeString(s string) string {
	// По контракту rune c — английская буква: c-'a' находится в 0..25.
	// Считаем частоту каждого символа в массиве из 26 элементов (a-z).
	freq := make([]int, 26)
	for _, c := range s {
		freq[c-'a']++
	}

	// Инициализируем максимальную кучу и заполняем её символами с ненулевой
	// частотой.
	h := &MaxHeap{}
	heap.Init(h)
	for i := range 26 {
		if freq[i] > 0 {
			// Добавляем пару: {частота, индекс символа}
			heap.Push(h, []int{freq[i], i})
		}
	}

	res := []byte{}   // Результирующая строка (в виде байтов для эффективности)
	var prev []int    // Символ, использованный на предыдущем шаге (задерживается
	// на 1 шаг)

	// В куче все оставшиеся буквы, кроме последней записанной в res.
	// prev удерживает её остаток, поэтому соседние буквы не совпадут.
	// Продолжаем, пока в куче есть элементы или есть отложенный символ.
	for h.Len() > 0 || prev != nil {
		// Если куча пуста, но есть отложенный символ — значит, мы не можем
		// поставить его рядом с ним же.
		// Перестройка невозможна.
		if prev != nil && h.Len() == 0 {
			return ""
		}

		// Самую частую доступную букву расходуем первой: её экземплярам
		// нужны другие буквы как разделители. Непустая куча даёт пару int.
		// Извлекаем самый частый символ из кучи.
		curr := heap.Pop(h).([]int)
		res = append(res, byte(curr[1]+'a')) // Добавляем символ в результат
		curr[0]--                             // Уменьшаем его частоту на 1

		// Возвращаем отложенный (предыдущий) символ обратно в кучу.
		// Теперь он снова доступен для выбора, т.к. прошёл один шаг
		// и он не будет стоять рядом с собой же.
		if prev != nil {
			heap.Push(h, prev)
			prev = nil
		}

		// Если у текущего символа ещё остались неиспользованные экземпляры,
		// откладываем его на следующий шаг (нельзя ставить подряд).
		if curr[0] > 0 {
			prev = curr
		}
	}

	return string(res)
}