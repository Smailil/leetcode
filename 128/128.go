package main

/*
Дан несортированный массив целых чисел nums.
Верните длину самой длинной последовательности идущих подряд целых чисел.

Вы должны написать алгоритм, который выполняется за O(n) времени.

Пример 1:
Вход: nums = [100,4,200,1,3,2]
Выход: 4
Объяснение: самая длинная последовательность идущих подряд чисел — [1, 2, 3, 4].
Следовательно, её длина равна 4.

Пример 2:
Вход: nums = [0,3,7,2,5,8,4,6,0,1]
Выход: 9

Пример 3:
Вход: nums = [1,0,1,2]
Выход: 3

Ограничения:
0 <= nums.length <= 10^5
-10^9 <= nums[i] <= 10^9
*/
// longestConsecutive ищет начала непрерывных последовательностей в set.
// n = len(nums), k — число различных значений: среднее время O(n+k),
// то есть O(n), рабочая память O(k), ответ int занимает O(1).
// Средняя оценка использует O(1) поиска int-ключа в map; nums не меняется.
func longestConsecutive(nums []int) int {
	maxLen := 0
    // Дубликаты объединяются: длина последовательности зависит от значений,
    // а не от числа их повторений.
    hm := make(map[int]struct{})
	for _, num := range nums {
		hm[num] = struct{}{}
	}
	for num := range hm {
		// Только значение без предшественника начинает новый обход цепочки.
		// Иначе этот num будет учтён при обходе от начала той же цепочки.
		if _, ok := hm[num-1]; ok {
			continue
		}
		// Все значения num..num+conLen-1 уже есть в set; проверяем следующее.
		// Каждая цепочка обходится один раз, суммарно проходы занимают O(k).
		// Границы +/-10^9 и k <= 10^5 исключают переполнение num-1/num+conLen.
		conLen := 1
		for {
			if _, ok := hm[num+conLen]; !ok {
				break
			}
			conLen++
		}
		maxLen = max(maxLen, conLen)
	}
	return maxLen
}