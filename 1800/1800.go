package main

/*
Дан массив положительных целых чисел nums. Верните максимальную возможную
сумму строго возрастающего подмассива nums.

Подмассив — это непрерывная последовательность элементов массива.

Пример 1:
Вход: nums = [10,20,30,5,10,50]
Выход: 65
Пояснение: [5,10,50] — строго возрастающий подмассив с максимальной суммой 65.

Пример 2:
Вход: nums = [10,20,30,40,50]
Выход: 150
Пояснение: [10,20,30,40,50] — строго возрастающий подмассив с максимальной
суммой 150.

Пример 3:
Вход: nums = [12,17,15,13,10,11,12]
Выход: 33
Пояснение: [10,11,12] — строго возрастающий подмассив с максимальной суммой
33.

Ограничения:
1 <= nums.length <= 100
1 <= nums[i] <= 100
*/

// maxAscendingSum возвращает максимальную сумму строго возрастающего
// непрерывного подмассива. За один проход алгоритм накапливает сумму текущего
// участка и начинает новый участок, когда строгий рост прерывается.
//
// Пусть n = len(nums). Время работы — O(n), дополнительная память — O(1).
func maxAscendingSum(nums []int) int {
    // По условию nums непуст. Первый элемент одновременно начинает текущий
    // возрастающий участок и задаёт начальный лучший результат.
    res, curSum := nums[0], nums[0]

    for i := 1; i < len(nums); i++ {
        // Равный или меньший элемент прерывает строгий рост, поэтому его сумма
        // должна начать новый участок без накопленного ранее значения.
        if nums[i] <= nums[i-1] {
            curSum = 0
        }

        // После возможного сброса curSum всегда равна сумме возрастающего
        // подмассива, который заканчивается на nums[i].
        curSum += nums[i]

        // Сохраняем максимум среди всех возрастающих участков, завершившихся
        // не дальше текущей позиции.
        if curSum > res {
            res = curSum
        }
    }
    return res
}