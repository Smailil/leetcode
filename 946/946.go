package main

/*
Даны два целочисленных массива pushed и popped.
В каждом из них все значения различны.

Стек изначально пуст.
Верните true, если можно выполнить последовательность операций со стеком,
добавляя элементы в порядке pushed и извлекая их в порядке popped.
Иначе верните false.

Пример 1:
Вход:
pushed := []int{1, 2, 3, 4, 5}
popped := []int{4, 5, 3, 2, 1}
Выход: true
Пояснение: Возможная последовательность операций:
push(1), push(2), push(3), push(4),
pop() -> 4,
push(5),
pop() -> 5, pop() -> 3, pop() -> 2, pop() -> 1

Пример 2:
Вход:
pushed := []int{1, 2, 3, 4, 5}
popped := []int{4, 3, 5, 1, 2}
Выход: false
Пояснение: Нельзя извлечь 1 раньше 2.

Ограничения:
1 <= pushed.length <= 1000
0 <= pushed[i] <= 1000
Все элементы pushed уникальны.
popped.length == pushed.length
Массив popped — перестановка массива pushed.
*/

// validateStackSequences проверяет, можно ли извлечь элементы в порядке popped.
// Функция перезаписывает pushed: его начало используется как буфер стека.
// Время: O(n), n = len(pushed): каждый элемент кладём и снимаем не более раза.
// Дополнительная память: O(1), отдельный стек не выделяется.
func validateStackSequences(pushed []int, popped []int) bool {
	// pushed[:l] — текущий стек, r — число уже извлечённых элементов.
	l, r := 0, 0
	for _, num := range pushed {
		// l не больше числа уже прочитанных элементов до текущего num.
		// Текущий элемент уже в num, поэтому запись не портит будущие чтения.
		pushed[l] = num
		l++
		// Если вершина совпала с popped[r], снимаем её сразу: новая
		// вставка закрыла бы вершину, а извлекать другой элемент нельзя.
		// В примере 1 после добавления 5 снимаем подряд 5, 3, 2 и 1.
		// r + l — число добавленных элементов и не больше len(popped).
		// Поэтому при l > 0 индекс r допустим; иначе сравнения не будет.
		for l > 0 && pushed[l-1] == popped[r] {
			r++
			l--
		}
	}
	// Все элементы добавлены. Пустой стек означает, что совпал весь popped.
	return l == 0
}
