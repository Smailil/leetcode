package main

/*
Даны две строки s1 и s2, верните true, если s2 содержит перестановку s1,
или false в противном случае.
Другими словами, верните true,
если одна из перестановок s1 является подстрокой s2.

Пример 1:
Вход: s1 = "ab", s2 = "eidbaooo"
Выход: true
Пояснение: s2 содержит одну перестановку s1 ("ba").

Пример 2:
Вход: s1 = "ab", s2 = "eidboaoo"
Выход: false

Ограничения:
1 <= s1.length, s2.length <= 10^4
s1 и s2 состоят из строчных английских букв.
*/

// checkInclusion ищет окно с частотами s1, не перечисляя перестановки.
// m = len(s1), n = len(s2), A — размер алфавита: время O(m + n + A).
// Рабочая память O(A); при A = 26 это O(1), время O(m + n).
// Результат — bool; строки не изменяются.
func checkInclusion(s1 string, s2 string) bool {
    // Более длинный образец не помещается; дальше m <= n защищает первое окно.
    if len(s1) > len(s2) {
		return false
	}
	// Английские строчные буквы дают допустимые индексы от 0 до 25.
	countS1, countS2 := make([]int, 'z'-'a'+1), make([]int, 'z'-'a'+1)
	l, r := 0, 0
	for ; r < len(s1); r++ {
		countS1[s1[r]-'a']++
		countS2[s2[r]-'a']++
	}
	// match — число букв с равными частотами, включая нулевые частоты.
	// На границах сдвига countS2 описывает окно [l, r) длины m.
	match := 0
	for i, count := range countS1 {
		if count == countS2[i] {
			match++
		}
	}
	// Сначала проверяем готовое окно, затем сдвигаем его на один символ.
	for ;r < len(s2); r++ {
		if match == 'z'-'a'+1 {
			return true
		}
		i := s2[r]-'a'
		// После ++ равенство создаёт совпадение; превышение на 1 означает,
		// что прежнее равенство исчезло. В других случаях match не меняется.
		countS2[i]++
		if countS1[i] == countS2[i] {
			match++
		} else if countS1[i] + 1 == countS2[i] {
			match--
		}
		i = s2[l]-'a'
		// После -- равенство создаёт совпадение; недобор на 1 убирает прежнее.
		// Эти два обновления верны и для одинаковых входящей и уходящей букв.
		countS2[i]--
		if countS1[i] == countS2[i] {
			match++
		} else if countS1[i] - 1 == countS2[i] {
			match--
		}
		l++

	}
	// Последнее окно не имело следующего символа для входа в цикл.
	// Проверяем его отдельно; все 26 совпадений означают перестановку.
	return match == 'z'-'a'+1
}
