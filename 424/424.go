package main

import "slices"

/*
Вам дана строка s и целое число k.
Вы можете выбрать любой символ строки и заменить его
на любой другой символ английского верхнего регистра.
Эту операцию можно выполнить не более k раз.
Верните длину самой длинной подстроки, содержащей только одну и ту же букву,
которую можно получить после выполнения вышеуказанных операций.

Пример 1:
Вход: s = "ABAB", k = 2
Выход: 4
Пояснение: Замените две буквы "A" двумя буквами "B" или наоборот.

Пример 2:
Вход: s = "AABABBA", k = 1
Выход: 4
Пояснение: Замените букву "A" посередине на "B" и получите "AABBBBA".
Подстрока "BBBB" имеет наибольшую длину среди таких подстрок — 4.
Могут существовать и другие способы получить этот ответ.

Ограничения:
1 <= s.length <= 10^5
s состоит только из заглавных английских букв.
0 <= k <= s.length
*/

// characterReplacement ищет максимальное окно, выравниваемое за k замен.
// n = len(s), A — размер алфавита; время O(n*A), рабочая память O(A).
// При фиксированных A = 26 это O(n) времени и O(1) памяти.
// Результат — число; s не меняется, максимум частот каждый раз точный.
func characterReplacement(s string, k int) int {
    maxRes := 0
	l, r := 0, 0
	count := make([]int, 'Z'-'A'+1)
	// count хранит точные частоты окна [l, r]; по контракту A..Z
	// дают допустимые индексы от 0 до 25.
	for ; r < len(s); r++ {
		count[s[r]-'A']++
		// Сохраняем самую частую букву: замен нужно длина - максимум.
		// Если их больше k, удаляем слева и пересчитываем максимум.
		// При k >= 0 односимвольное окно всегда допустимо.
		for (r - l + 1) - slices.Max(count) > k {
			count[s[l]-'A']--
			l++
		}
		// Окно допустимо; l суммарно сдвигается не более n раз.
		maxRes = max(maxRes, r - l + 1)
	}
	return maxRes
}
