package main

/*
Даны две строки s и t.
Верните количество различных подпоследовательностей s, равных t.
Тестовые примеры генерируются таким образом,
чтобы ответ соответствовал 32-битному целому числу со знаком.

Пример 1:
Вход: s = "rabbbit", t = "rabbit"
Выход: 3
Объяснение:
Как показано ниже, существует три способа создания «rabbit» из s.
(rabb)b(it)
(ra)b(bbit)
(rab)b(bit)

Пример 2:
Вход: s = "babgbag", t = "bag"
Выход: 5
Объяснение:
Как показано ниже, существует 5 способов создания «bag» из s.
(ba)b(g)bag
(ba)bgba(g)
(b)abgb(ag)
ba(b)gb(ag)
babg(bag)

Ограничения:
1 <= s.length, t.length <= 1000
s и t состоят из английских букв.
*/

// numDistinct считает способы собрать t из суффиксов s через одномерный DP.
// m = len(s), n = len(t); время O(m*n), рабочая память O(n).
// Ответ — число; строки не изменяются, сравнения работают с байтами букв.
func numDistinct(s string, t string) int {
    m, n := len(s), len(t)
    // D(i,j) — число способов получить t[j:] из s[i:].
    // Пустую t можно получить ровно одним способом: выбрать ничего.
    // Из пустой s непустую t получить нельзя, поэтому другие клетки — 0.
    dp := make([]int, n+1)
    dp[n] = 1

    for i := m - 1; i >= 0; i-- {
        // Перед строкой i массив хранит D(i+1,j).
        // prev сохраняет старое D(i+1,j+1), несмотря на обход j справа.
        prev := dp[n]
        for j := n - 1; j >= 0; j-- {
            // Сохраняем старую клетку для следующего j-1 до перезаписи.
            temp := dp[j]
            if s[i] == t[j] {
                // Пропуск s[i] оставляет старое dp[j]; при совпадении
                // добавляем использование s[i] и остаток D(i+1,j+1).
                // Не берём уже обновлённое dp[j+1]: это повторило бы s[i].
                // Промежуточные счётчики int не защищены от переполнения;
                // лимит итогового ответа не ограничивает все суффиксы.
                dp[j] += prev
            }
            prev = temp
        }
    }

    // После i=0 это D(0,0), количество способов для обеих полных строк.
    return dp[0]
}