package main

/*
Дана голова односвязного списка.
Переверните список и верните начало нового списка.

Пример 1:
Вход: head = [0,1,2,3]
Выход: [3,2,1,0]

Пример 2:
Вход: head = []
Выход: []

Ограничения:
0 <= Длина списка <= 1000.
-1000 <= Node.val <= 1000
*/

// Определение узла односвязного списка.
type ListNode struct {
    Val int
    Next *ListNode
}

// reverseList разворачивает Next на месте, перенося узлы в новый префикс.
// Время O(n), n — число узлов; рабочая память и возвращаемый указатель O(1).
// Новые узлы не создаются; связи исходного списка изменяются.
func reverseList(head *ListNode) *ListNode {
    var prev *ListNode = nil
	// prev — голова уже развёрнутой части, curr — начало нетронутого
	// суффикса; изначально развёрнутая часть пуста.
	curr := head
	for curr != nil {
		// Сохраняем путь к суффиксу до перезаписи Next, иначе он потеряется.
		next := curr.Next
		curr.Next = prev
		// Текущий узел стал головой префикса; переходим к сохранённому
		// следующему узлу и восстанавливаем инвариант для новой итерации.
		prev = curr
		curr = next
	}
	// Когда curr == nil, весь список развёрнут. Для пустого head
	// prev также останется nil.
	return prev
}

