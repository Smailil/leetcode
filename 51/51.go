package main

import "strings"

/*
Задача о n ферзях состоит в размещении n ферзей на доске размера n x n
так, чтобы никакие два ферзя не атаковали друг друга.
Дано целое число n.
Найдите все различные решения задачи о n ферзях.
Ответ можно вернуть в любом порядке.
Каждое решение содержит отдельную конфигурацию доски с n ферзями.
Символ 'Q' обозначает ферзя, а '.' — пустую клетку.

Пример 1:
https://assets.leetcode.com/uploads/2020/11/13/queens.jpg
Вход: n = 4
Выход: [[".Q..","...Q","Q...","..Q."],["..Q.","Q...","...Q",".Q.."]]
Пояснение: существует два различных решения задачи о четырёх ферзях,
как показано выше.

Пример 2:
Вход: n = 1
Выход: [["Q"]]

Ограничения:
1 <= n <= 9
*/

// solveNQueens размещает по одному ферзю в строке с поиском и откатом.
// S — число решений. Среднее время O(n*n! + S*n*n), включая сборку строк;
// проверки int-ключей в map предполагаются O(1) в среднем.
// Рабочая память O(n*n) для доски, O(n) для множеств и стека;
// результат занимает O(S*n*n). Внешние данные функция не меняет.
func solveNQueens(n int) [][]string {
    // Множества отмечают занятые столбцы и диагонали уже заполненных строк.
    col := make(map[int]struct{})
	posDiag := make(map[int]struct{}) // (r+c)
	negDiag := make(map[int]struct{}) // (r-c)
	var res [][]string
	// Рабочая доска меняется на месте; "." и "Q" — однобайтовые клетки.
	board := make([][]string, n)
	for i := range n {
		board[i] = make([]string, n)
		for j := range n {
			board[i][j] = "."
		}
	}
	var backtrack func(int)
	// backtrack заполняет строку r при корректно расставленных строках до неё.
	// Для t = n-r и R решений поддерева среднее время O(n*t! + R*n*n).
	// Дополнительный стек O(t); новые доски результата занимают O(R*n*n).
	// Общие board/col/posDiag/negDiag откатываются; res только пополняется.
	backtrack = func(r int) {
		// Все строки заполнены: Join фиксирует их строковые значения в out.
		// Откат меняет клетки board, но сохранённые строки неизменяемы.
		if r == n {
			out := make([]string, n)
			for i, row := range board {
				out[i] = strings.Join(row, "")
			}
			res = append(res, out)
			return
		}
		// Равные r+c или r-c означают общую диагональ; отрицательные ключи
		// допустимы. При n <= 9 вычисления безопасны, r/c — индексы доски.
		for c := range n {
			if _, ok := col[c]; ok {
				continue
			}
			if _, ok := posDiag[r+c]; ok {
				continue
			}
			if _, ok := negDiag[r-c]; ok {
				continue
			}
			// Все три проверки пройдены: заносим один согласованный ход.
			col[c] = struct{}{}
			posDiag[r+c] = struct{}{}
			negDiag[r-c] = struct{}{}
			board[r][c] = "Q"

			backtrack(r+1)

			// Симметричный откат возвращает состояние до выбора столбца c.
			delete(col, c)
			delete(posDiag, r+c)
			delete(negDiag, r-c)
			board[r][c] = "."
		}
	}
	backtrack(0)
	return res
}
