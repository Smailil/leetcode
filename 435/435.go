package main

import "sort"

/*
Дан массив интервалов intervals, где intervals[i] = [start_i, end_i].
Верните минимальное количество интервалов, которое нужно удалить,
чтобы остальные интервалы не перекрывались.
Обратите внимание, что интервалы, соприкасающиеся только в одной точке,
не перекрываются.
Например, [1, 2] и [2, 3] не перекрываются.

Пример 1:
Вход: intervals = [[1,2],[2,3],[3,4],[1,3]]
Выход: 1
Пояснение: [1,3] можно удалить, а остальные интервалы не будут перекрываться.

Пример 2:
Вход: intervals = [[1,2],[1,2],[1,2]]
Выход: 2
Пояснение: Вам нужно удалить два [1,2],
чтобы остальные интервалы не перекрывались.

Пример 3:
Вход: intervals = [[1,2],[2,3]]
Выход: 0
Объяснение: Вам не нужно удалять какие-либо интервалы,
поскольку они уже не перекрываются.

Ограничения:
1 <= intervals.length <= 10^5
intervals[i].length == 2
-5 * 10^4 <= start_i < end_i <= 5 * 10^4
*/

// eraseOverlapIntervals жадно сохраняет более ранний конец при пересечении.
// n = len(intervals); время O(n log n), рабочая память O(log n) сортировки.
// Ответ — число удалений, O(1) памяти; сортировка меняет intervals на месте.
func eraseOverlapIntervals(intervals [][]int) int {
    // Comparator сравнивает начала за O(1) времени и памяти.
    // Порядок по началу позволяет рассматривать очередной интервал справа.
    sort.Slice(intervals, func(i, j int) bool {
        return intervals[i][0] < intervals[j][0]
    })

    res := 0
    // Вход непуст. prevEnd — конец последнего пока оставленного интервала.
    prevEnd := intervals[0][1]

    for _, interval := range intervals[1:] {
        start, end := interval[0], interval[1]
        // Касание в одной точке допустимо, поэтому равенство не конфликтует.
        if start >= prevEnd {
            prevEnd = end
        } else {
            // Из двух конфликтующих оставляем один: число выбранных то же.
            // Меньший конец не ухудшает совместимость со следующими началами.
            res++
			if end < prevEnd {
				prevEnd = end
			}
        }
    }
    return res
}
