package main

/*
Дан массив целых чисел arr.
Найдите сумму min(b) по всем непрерывным подмассивам b массива arr.
Так как ответ может быть большим, верните его по модулю 10^9 + 7.

Пример 1:
Ввод:
arr := []int{3, 1, 2, 4}
Вывод: 17
Пояснение:
Подмассивы: [3], [1], [2], [4], [3,1], [1,2], [2,4],
[3,1,2], [1,2,4], [3,1,2,4].
Их минимумы: 3, 1, 2, 4, 1, 1, 2, 1, 1, 1.
Сумма минимумов равна 17.

Пример 2:
Ввод:
arr := []int{11, 81, 94, 43, 3}
Вывод: 444

Ограничения:
1 <= arr.length <= 3 * 10^4
1 <= arr[i] <= 3 * 10^4
*/

// sumSubarrayMins складывает минимумы всех непрерывных подмассивов arr.
// Монотонный стек определяет, в каких подмассивах элемент даёт минимум.
// Время: O(n), каждый элемент кладём в стек и снимаем не более одного раза.
// Дополнительная память: O(n) для копии массива и стека, где n = len(arr).
func sumSubarrayMins(arr []int) int {
	MOD := int(1e9 + 7)
	res := 0
	// Сторожевые значения меньше любого элемента arr. Левое служит
	// границей, правое снимает все оставшиеся реальные элементы со стека.
	newArr := make([]int, len(arr)+2)
	newArr[0] = -1 << 31
	newArr[len(newArr)-1] = -1 << 31
	copy(newArr[1:], arr)

	// Стек хранит пары [индекс, значение] в порядке неубывания значений.
	// Равные значения не снимаем: общий подмассив учтёт левый минимум.
	stack := [][2]int{}

	for i := range newArr {
		for len(stack) > 0 && newArr[i] < stack[len(stack)-1][1] {
			top := stack[len(stack)-1]
			stack = stack[:len(stack)-1]
			j, m := top[0], top[1]
			// i — ближайший индекс справа от j со значением строго меньше m.
			// Вершина после снятия j — ближайший слева элемент не больше m.
			// Для реального элемента слева есть как минимум сторож.
			left := j + 1
			if len(stack) > 0 {
				left = j - stack[len(stack)-1][0]
			}
			// Начало выбираем после левой границы и до j включительно,
			// конец — от j до i-1. Число независимых пар равно left*right.
			right := i - j
			// В [3,1,2,4] для 1 это 2 начала и 3 конца: 6 подмассивов.
			// Остаток берётся после умножения: здесь нужен 64-битный int.
			res = (res + m*left*right) % MOD
		}
		stack = append(stack, [2]int{i, newArr[i]})
	}

	return res
}