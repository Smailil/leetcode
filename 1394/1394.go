package main

/*
Дан массив целых чисел arr. Счастливым называется число, частота которого
в массиве равна значению этого числа.

Верните наибольшее счастливое число в массиве. Если счастливых чисел нет,
верните -1.

Пример 1:
Вход: arr = [2,2,3,4]
Выход: 2
Пояснение: единственное счастливое число в массиве — 2,
поскольку frequency[2] == 2.

Пример 2:
Вход: arr = [1,2,2,3,3,3]
Выход: 3
Пояснение: числа 1, 2 и 3 являются счастливыми, поэтому возвращаем
наибольшее из них.

Пример 3:
Вход: arr = [2,2,2,3,3]
Выход: -1
Пояснение: в массиве нет счастливых чисел.

Ограничения:
1 <= arr.length <= 500
1 <= arr[i] <= 500

*/

// findLucky возвращает наибольшее число, равное количеству своих появлений.
// Для подсчёта частот функция использует сам arr: исходное значение остаётся
// в младших 10 битах элемента, а частота накапливается в старших. Поэтому
// дополнительный массив не нужен, но содержимое arr изменяется.
//
// Время: O(n), где n = len(arr). Дополнительная память: O(1).
func findLucky(arr []int) int {
    for _, num := range arr {
        // Предыдущие итерации могли добавить к num частоту, кратную 2^10.
        // Маска из 10 единиц отбрасывает её и восстанавливает исходное число,
        // которое по условию не превышает 500 и целиком помещается в 10 бит.
        idx := num & ((1 << 10) - 1)

        // Счастливое число не может быть больше n: в массиве из n элементов
        // невозможно встретить его более n раз. При idx <= n позиция idx-1
        // существует, поскольку по условию idx >= 1. Прибавление 2^10 меняет
        // только старшие биты и не повреждает сохранённое исходное значение.
        // Даже в худшем случае элемент не превысит 500 + 500 * 2^10 = 512500,
        // поэтому значение безопасно помещается в стандартный Go int.
        if idx <= len(arr) {
            arr[idx-1] += (1 << 10)
        }
    }

    // В старших битах arr[i] записана частота числа i+1. Идём от большего
    // кандидата к меньшему, поэтому первое совпадение сразу является ответом.
    for i := len(arr) - 1; i >= 0; i-- {
        cnt := arr[i] >> 10
        if cnt == i+1 {
            return i + 1
        }
    }

    // Ни для одного допустимого значения его частота не совпала с ним самим.
    return -1
}