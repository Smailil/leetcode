package main

import "unicode"

/*
Дана строка s из строчных и прописных букв английского алфавита.

Строка считается хорошей, если в ней нет соседних символов s[i] и s[i + 1],
удовлетворяющих обоим условиям:
0 <= i <= s.length - 2
Один символ — строчная буква, а другой — та же буква в верхнем регистре.

Чтобы сделать строку хорошей, можно выбрать такую пару символов и удалить её.
Повторяйте удаление, пока строка не станет хорошей.

Верните строку, полученную после этих удалений.
При данных ограничениях ответ гарантированно единственный.

Пустая строка тоже считается хорошей.

Пример 1:
Вход: s = "leEeetcode"
Выход: "leetcode"
Пояснение: На первом шаге можно выбрать i = 1 или i = 2.
В обоих случаях из "leEeetcode" получится "leetcode".

Пример 2:
Вход: s = "abBAcC"
Выход: ""
Пояснение: Порядок удалений может быть разным.
Все варианты приводят к одному результату.
Например:
"abBAcC" --> "aAcC" --> "cC" --> ""
"abBAcC" --> "abBA" --> "aA" --> ""

Пример 3:
Вход: s = "s"
Выход: "s"

Ограничения:
1 <= s.length <= 100
Строка s содержит только строчные и прописные буквы английского алфавита.
*/

// makeGood удаляет соседние пары одинаковых букв в разных регистрах.
// Стек хранит уже прочитанный префикс после удаления из него таких пар.
// Время: O(n), n = len(s): один проход и сборка строки из оставшихся рун.
// Память в худшем случае: O(n) для стека и отдельно O(n) для результата.
func makeGood(s string) string {
	stack := []rune{}
	for _, c := range s {
		// В стеке нет удаляемых пар: c может образовать пару лишь с вершиной.
		// len(stack) > 0 проверяем первым, чтобы не читать пустой стек.
		// ToLower проверяет совпадение буквы, а != исключает пары "aa" и "AA".
		if len(stack) > 0 && stack[len(stack)-1] != c &&
			unicode.ToLower(stack[len(stack)-1]) == unicode.ToLower(c) {
			// Снимаем вершину и пропускаем c: удалены обе буквы пары.
			// В "abBA" сначала удаляем "bB"; после этого a и A соседние.
			stack = stack[:len(stack)-1]
		} else {
			// Пары нет: сохраняем c, и стек остаётся без удаляемых пар.
			stack = append(stack, c)
		}
	}
	return string(stack)
}