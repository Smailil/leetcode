package main

import "sort"

/*
Представьте, что вы замечательный родитель и хотите дать детям печенье.
Но каждому ребёнку можно дать не более одного печенья.

У каждого ребёнка i есть показатель требовательности g[i] —
минимальный размер печенья, которым он будет доволен.
У каждого печенья j есть размер s[j].
Если s[j] >= g[i], печенье j можно дать ребёнку i, и он будет доволен.
Ваша цель — сделать довольными как можно больше детей
и вернуть их максимальное число.

Пример 1:
Вход: g = [1,2,3], s = [1,1]
Выход: 1
Пояснение: У вас 3 ребёнка и 2 печенья.
Показатели требовательности этих детей равны 1, 2, 3.
Хотя у вас есть 2 печенья, размер каждого равен 1,
поэтому довольным можно сделать только ребёнка
с показателем требовательности 1.
Нужно вернуть 1.

Пример 2:
Вход: g = [1,2], s = [1,2,3]
Выход: 2
Пояснение: У вас 2 ребёнка и 3 печенья.
Показатели требовательности этих детей равны 1, 2.
Размеров этих печений достаточно, чтобы сделать довольными обоих детей.
Нужно вернуть 2.

Ограничения:
1 <= g.length <= 3 * 10^4
0 <= s.length <= 3 * 10^4
1 <= g[i], s[j] <= 2^31 - 1

*/

// findContentChildren возвращает максимальное число довольных детей.
// Жадный выбор: наименее требовательному ребёнку даём минимальное
// подходящее печенье, сохраняя более крупные для следующих детей.
// n = len(g), m = len(s).
// Время: O(n log(n + 1) + m log(m + 1)); после сортировки — O(n + m).
// Рабочая память: O(log(n + m + 1)) для стека сортировки; обход — O(1).
// Память результата: O(1), возвращается одно число.
// Изменяет g и s: сортировка переставляет элементы исходных срезов.
func findContentChildren(g []int, s []int) int {
    // Упорядочиваем требования детей и размеры печенья по возрастанию.
    // Это позволяет искать подходящее печенье, не возвращаясь к меньшим.
    sort.Ints(g)
    sort.Ints(s)

    // i — число довольных детей и индекс следующего ребёнка.
    // j — индекс первого ещё не использованного и не отброшенного печенья.
    // Инвариант: дети g[:i] уже довольны; оставшиеся кандидаты — s[j:].
    i, j := 0, 0
    // j не сбрасывается для нового ребёнка и сдвигается не более m раз.
    // Поэтому оба цикла суммарно дают O(n + m), а не O(n * m).
    for i < len(g) {
        // Если s[j] < g[i], печенье мало даже для самого нетребовательного
        // оставшегося ребёнка, а значит, и для всех последующих: пропускаем.
        // j < len(s) проверяется до s[j], поэтому пустой срез s безопасен.
        // Индекс i безопасен благодаря условию внешнего цикла i < len(g).
        for j < len(s) && g[i] > s[j] {
            j++
        }
        // Печенье закончилось: для текущего ребёнка подходящего уже нет.
        // Следующие дети требуют не меньше, поэтому продолжать бессмысленно.
        if j == len(s) {
            break
        }
        // s[j] — наименьшее подходящее печенье; любое подходящее даёт +1
        // довольного ребёнка, но крупное полезнее сохранить для следующих.
        // Например, при g = [1, 2], s = [1, 2] выдаём сначала 1, затем 2.
        // Если первому дать 2, оставшееся 1 не подойдёт второму ребёнку.
        // Сдвигаем оба указателя: ребёнок доволен, печенье использовано.
        i++
        j++
    }
    // i увеличивался только при успешной выдаче печенья, поэтому это ответ.
    return i
}