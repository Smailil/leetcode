package main

import "strconv"

/*
Вам дан массив строковых токенов, который представляет
арифметическое выражение в обратной польской нотации.
Вычислите выражение.
Верните целое число, представляющее значение выражения.

Обратите внимание, что:
Допустимыми операторами являются '+', '-', '*', и '/'.
Каждый операнд может быть целым числом или другим выражением.
Деление между двумя целыми числами всегда усекается к нулю.
Никакого деления на ноль не будет.
Входные данные представляют собой допустимое арифметическое выражение
в обратной польской нотации.
Ответ и все промежуточные вычисления могут быть представлены
в виде 32-разрядного целого числа.

Пример 1:
Вход: tokens = ["2","1","+","3","*"]
Выход: 9
Пояснение: ((2 + 1) * 3) = 9

Пример 2:
Вход: tokens = ["4","13","5","/","+"]
Выход: 6
Пояснение: (4 + (13 / 5)) = 6

Пример 3:
Вход: tokens = ["10","6","9","3","+","-11","*","/","*","17","+","5","+"]
Выход: 22
Пояснение: ((10 * (6 / ((9 + 3) * -11))) + 17) + 5
= ((10 * (6 / (12 * -11))) + 17) + 5
= ((10 * (6 / -132)) + 17) + 5
= ((10 * 0) + 17) + 5
= (0 + 17) + 5
= 17 + 5
= 22

Ограничения:
1 <= tokens.length <= 10^4
tokens[i] — это либо оператор: «+», «-», «*» или «/»,
либо целое число в диапазоне [-200, 200] в виде строки.
*/

// pop снимает вершину за O(1) времени и O(1) рабочей памяти.
// Меняет длину *st, но не освобождает его общий буфер; ответ int O(1).
// Предусловие: стек непустой. В evalRPN это гарантирует корректная нотация.
func pop(st *[]int) int {
	num := (*st)[len(*st)-1]
	*st = (*st)[:len(*st)-1]
	return num
}

// push дописывает число, изменяя заголовок *st и его буфер.
// k — длина *st: амортизированное время O(1), худшее O(k+1) при росте.
// Новый буфер при росте занимает O(k+1), иначе дополнительная память O(1).
func push(st *[]int, num int) {
	*st = append(*st, num)
}

// evalRPN вычисляет обратную польскую запись стеком значений подвыражений.
// n=len(tokens), B — суммарное число байтов токенов: время O(n+B),
// с учётом разбора чисел и амортизированного append; рабочая память O(n).
// Ответ int занимает O(1); tokens не меняется, общий буфер стека локален.
func evalRPN(tokens []string) int {
	stack := make([]int, 0)
	// После каждого префикса стек хранит ещё не объединённые подвыражения.
	// Оператор снимает num2 (правое), затем num1 (левое): для '-' и '/'
	// порядок важен. Например, "13 5 /" означает 13/5, а не 5/13.
	for _, t := range tokens {
		switch t {
		case "+":
			num2 := pop(&stack)
			num1 := pop(&stack)
			push(&stack, num1 + num2)
		case "-":
			num2 := pop(&stack)
			num1 := pop(&stack)
			push(&stack, num1 - num2)
		case "*":
			num2 := pop(&stack)
			num1 := pop(&stack)
			push(&stack, num1 * num2)
		// По условию num2 не равен 0; Go делит int с усечением к нулю.
		// Все промежуточные результаты помещаются в int32, поэтому int безопасен.
		case "/":
			num2 := pop(&stack)
			num1 := pop(&stack)
			push(&stack, num1 / num2)
		// Любой неоператор — допустимое целое по условию; поэтому ошибка Atoi
		// не ожидается. Стоимость разбора зависит от числа байтов t.
		default:
			num, _ := strconv.Atoi(t)
			push(&stack, num)
		}
	}
	// Корректное полное выражение оставляет ровно одно значение в стеке.
	return pop(&stack)

}