package main

/*
Дан корень двоичного дерева.
Представьте, что вы стоите на его правой стороне,
и верните значения узлов, которые вы видите, упорядоченные сверху вниз.

Пример 1:
Вход: root = [1,2,3,null,5,null,4]
Выход: [1,3,4]
Пояснение:
https://assets.leetcode.com/uploads/2024/11/24/tmpd5jn43fs-1.png

Пример 2:
Вход: root = [1,2,3,4,null,null,null,5]
Выход: [1,3,4,5]
Пояснение:
https://assets.leetcode.com/uploads/2024/11/24/tmpkpe40xeh-1.png

Пример 3:
Вход: root = [1,null,3]
Выход: [1,3]

Пример 4:
Вход: root = []
Выход: []

Ограничения:
Количество узлов в дереве находится в диапазоне [0, 100].
-100 <= Node.val <= 100
*/

type TreeNode struct {
    Val int
    Left *TreeNode
    Right *TreeNode
}

// rightSideView обходит дерево по уровням и берёт последний узел каждого.
// Время O(n) амортизированно, n — число узлов. Рабочая память O(w)
// для очереди, w — максимальная ширина уровня; результат O(h),
// h — число уровней. Исходное дерево не изменяется.
func rightSideView(root *TreeNode) []int {
	res := make([]int, 0)
	if root == nil {
		return res
	}
	// В очереди узлы текущего уровня идут слева направо.
	q := []*TreeNode{root}
	for len(q) != 0 {
		rightNode := &TreeNode{}
		// Фиксируем длину до добавления детей: они относятся к следующему
		// уровню и не должны обрабатываться в текущем внутреннем цикле.
		qLen := len(q)
		for i := 0; i<qLen ; i++ {
			rightNode = q[0]
			q = q[1:]
			// Левый ребёнок ставится раньше правого, сохраняя порядок
			// следующего уровня. Срез q[1:] снимает уже обработанный узел.
			if rightNode.Left != nil {
				q = append(q, rightNode.Left)
			}
			if rightNode.Right != nil {
				q = append(q, rightNode.Right)
			}
		}
		// Последний извлечённый узел — крайний справа на этом уровне,
		// даже если у его родителя отсутствует правый ребёнок.
		res = append(res, rightNode.Val)
	}
	return res
}
