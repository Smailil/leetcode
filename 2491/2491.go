package main

/*
Дан массив положительных целых чисел skill чётной длины n,
где skill[i] обозначает мастерство i-го игрока.
Разделите игроков на n / 2 команд по 2 человека так,
чтобы суммарное мастерство каждой команды было одинаковым.

Сыгранность команды равна произведению значений мастерства её игроков.

Верните сумму значений сыгранности всех команд или -1,
если разделить игроков на команды с одинаковым суммарным мастерством невозможно.

Пример 1:
Вход: skill = [3,2,5,1,3,4]
Выход: 22
Пояснение:
Разделим игроков на команды (1, 5), (2, 4), (3, 3),
каждая из которых имеет суммарное мастерство 6.
Сумма сыгранности всех команд:
1 * 5 + 2 * 4 + 3 * 3 = 5 + 8 + 9 = 22.

Пример 2:
Вход: skill = [3,4]
Выход: 12
Пояснение:
Два игрока образуют команду с суммарным мастерством 7.
Сыгранность команды: 3 * 4 = 12.

Пример 3:
Вход: skill = [1,1,2,3]
Выход: -1
Пояснение:
Невозможно разделить игроков на команды с одинаковым суммарным мастерством.

Ограничения:
2 <= skill.length <= 10^5
skill.length — чётное число.
1 <= skill[i] <= 1000
*/

// dividePlayers объединяет игроков в пары с одинаковой суммой мастерства
// и возвращает сумму их сыгранности, либо -1, если разбиение невозможно.
// Два указателя обходят частоты как отсортированные группы игроков.
// Исходный массив не меняется, отсортированная копия не создаётся.
// Время: O(n + k), где n = len(skill), k = 1000 — диапазон мастерства.
// Память: O(k), то есть O(1) при фиксированном диапазоне задачи.
func dividePlayers(skill []int) int64 {
	// Если игроков двое, единственная команда всегда подходит.
	if len(skill) == 2 {
		return int64(skill[0]) * int64(skill[1])
	}

	// В counts[value] хранится размер группы с мастерством value.
	// Одновременно найдём крайние значения, чтобы не обходить весь диапазон.
	var counts [1001]int
	left, right := skill[0], skill[0]
	for _, value := range skill {
		counts[value]++
		if value < left {
			left = value
		}
		if value > right {
			right = value
		}
	}

	// Партнёр минимума не больше максимума, значит сумма <= left + right.
	// Партнёр максимума не меньше минимума, значит сумма >= left + right.
	// Поэтому общая сумма команды однозначно определяется крайними группами.
	target := left + right

	var answer int64
	for left <= right {
		if counts[left] == 0 {
			left++
			continue
		}
		if counts[right] == 0 {
			right--
			continue
		}
		// Крайние непустые группы остатка тоже обязаны давать сумму target.
		if left+right != target {
			return -1
		}
		if left == right {
			// Осталась одна группа. Её размер чётный: исходное n чётное,
			// а на прошлых шагах убирали только целые пары.
			return answer + int64(counts[left]/2)*int64(left*left)
		}
		if counts[left] != counts[right] {
			// У каждого из этих игроков партнёр может быть только из
			// противоположной группы. Лишнего игрока не с кем соединить.
			return -1
		}
		// Например, три игрока со значением 2 и три со значением 4
		// образуют сразу три команды, добавляем 3 * 2 * 4.
		// Произведение мастерства <= 10^6, но сумма может быть 5*10^10.
		answer += int64(counts[left]) * int64(left*right)
		left++
		right--
	}
	return answer
}
