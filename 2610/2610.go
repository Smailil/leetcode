package main

/*
Дан целочисленный массив nums.
Создайте из nums двумерный массив, удовлетворяющий следующим условиям:
Двумерный массив должен содержать только элементы массива nums.
Каждая строка двумерного массива содержит различные целые числа.
Число строк двумерного массива должно быть минимальным.
Верните полученный массив.
Если ответов несколько, верните любой из них.

Обратите внимание: в строках двумерного массива может быть разное
число элементов.

Пример 1:
Вход: nums = [1,3,4,1,2,3,1]
Выход: [[1,3,4,2],[1,3],[1]]
Пояснение: можно создать двумерный массив со следующими строками:
- 1,3,4,2
- 1,3
- 1
Все элементы nums использованы, и в каждой строке двумерного массива
целые числа различны, поэтому это допустимый ответ.
Можно показать, что допустимый массив не может содержать меньше 3 строк.

Пример 2:
Вход: nums = [1,2,3,4]
Выход: [[4,3,2,1]]
Пояснение: все элементы массива различны, поэтому их можно поместить
в первую строку двумерного массива.

Ограничения:
1 <= nums.length <= 200
1 <= nums[i] <= nums.length
*/

// findMatrix распределяет элементы nums по строкам без повторов в строке.
// Номер строки для числа равен количеству его предыдущих появлений.
// Исходный nums не изменяется.
// Здесь n = len(nums), k — количество различных значений в nums.
// Время: в среднем O(n) благодаря map и амортизированному append.
// Рабочая память: O(k); память результата: O(n).
func findMatrix(nums []int) [][]int {
    // count[num] хранит число уже размещённых копий num.
    // Для ещё не встречавшегося числа map возвращает нулевой счётчик.
    count := make(map[int]int)
    res := [][]int{}

    for _, num := range nums {
        // Предыдущие копии num заняли строки от 0 до count[num]-1.
        // Следующая копия идёт в строку count[num], где её ещё нет.
        // Например, третья единица попадёт в строку 2, а не в 0 или 1.
        row := count[num]

        // Число строк равно максимальному счётчику среди размещённых чисел.
        // Поэтому row <= len(res).
        // При равенстве строки row ещё нет:
        // создаём её, чтобы следующее обращение res[row] было безопасным.
        if len(res) == row {
            res = append(res, []int{})
        }

        // В строку row попадает только одна копия каждого числа.
        // Другие числа могут использовать ту же строку, не создавая повторов.
        res[row] = append(res[row], num)

        // Обновляем счётчик после размещения: следующая копия пойдёт ниже.
        count[num]++
    }

    // Если число встречается f раз, ему нужны как минимум f разных строк.
    // Здесь строк ровно столько, какова максимальная частота числа в nums,
    // поэтому построенный ответ использует минимально возможное число строк.
    return res
}