package main

/*
Дан массив paths, где paths[i] = [cityA_i, cityB_i] означает, что существует
прямой путь из города cityA_i в город cityB_i. Верните город назначения —
город, из которого не выходит путь в другой город.

Гарантируется, что граф путей образует линию без циклов, поэтому существует
ровно один город назначения.

Пример 1:
Вход: paths = [["London","New York"],["New York","Lima"],
["Lima","Sao Paulo"]]
Выход: "Sao Paulo"
Пояснение: начав в городе "London", вы достигнете города назначения
"Sao Paulo". Маршрут: "London" -> "New York" -> "Lima" -> "Sao Paulo".

Пример 2:
Вход: paths = [["B","C"],["D","B"],["C","A"]]
Выход: "A"
Пояснение: все возможные маршруты:
"D" -> "B" -> "C" -> "A".
"B" -> "C" -> "A".
"C" -> "A".
"A".
Очевидно, что городом назначения является "A".

Пример 3:
Вход: paths = [["A","Z"]]
Выход: "Z"

Ограничения:
1 <= paths.length <= 100
paths[i].length == 2
1 <= cityA_i.length, cityB_i.length <= 10
cityA_i != cityB_i
Все строки состоят из строчных и заглавных английских букв, а также пробелов.
*/

// destCity находит конечный город линейного маршрута.
// Сначала функция собирает все города отправления, а затем ищет город,
// который встречается только как пункт назначения.
// Время: O(n), где n = len(paths); выполняются два линейных прохода.
// Дополнительная память: O(n) для множества городов отправления.
func destCity(paths [][]string) string {
    s := make(map[string]bool)
    // Запоминаем каждый город, из которого существует исходящий путь.
    for _, p := range paths {
        s[p[0]] = true
    }

    // Единственный город без исходящего пути не входит в множество
    // отправлений и является искомым концом маршрута.
    for _, p := range paths {
        if !s[p[1]] {
            return p[1]
        }
    }
    // По условию конечный город существует, поэтому сюда код не дойдёт.
    return ""
}