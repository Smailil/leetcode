package main

/*
На круговом маршруте имеется n заправочных станций,
где количество бензина на i-й заправке равно gas[i].
У вас есть машина с неограниченным бензобаком, и поездка от i-й станции
до следующей (i + 1)-й станции стоит cost[i] бензина.
Вы начинаете путешествие с пустым баком на одной из заправок.
По двум целочисленным массивам gas и cost верните индекс начальной заправки,
если можно объехать круг один раз по часовой стрелке,
в противном случае верните -1.
Если решение существует, то оно гарантированно единственное.

Пример 1:
Вход: gas = [1,2,3,4,5], cost = [3,4,5,1,2]
Выход: 3
Объяснение:
Начните со станции 3 (индекс 3) и заправьте 4 единицы бензина.
Ваш бак = 0 + 4 = 4
Отправляйтесь на станцию 4.
Ваш бак = 4 -1 + 5 = 8.
Отправляйтесь на станцию 0.
Ваш бак = 8 -2 + 1 = 7.
Отправляйтесь на станцию 1.
Ваш бак = 7 -3 + 2 = 6.
Отправляйтесь на станцию 2.
Ваш бак = 6 -4 + 3 = 5.
Езжайте до станции 3.
Стоимость — 5.
Запаса бензина как раз хватит, чтобы вернуться на станцию 3.
Поэтому верните 3 в качестве начального индекса.

Пример 2:
Вход: gas = [2,3,4], cost = [3,4,3]
Выход: -1
Объяснение:
Вы не можете начать со станции 0 или 1,
так как для поездки на следующую станцию недостаточно бензина.
Начнем со станции 2 и заправим 4 единицы бензина.
Ваш бак = 0 + 4 = 4
Отправляйтесь на станцию 0.
Ваш бак = 4 -3 + 2 = 3.
Отправляйтесь на станцию 1.
Ваш бак = 3 -3 + 3 = 3.
Вы не можете вернуться на станцию 2, так как для нее требуется
4 единицы бензина, а у вас есть только 3.
Поэтому вы не сможете объехать трассу один раз, где бы вы ни начали.

Ограничения:
n == gas.length == cost.length
1 <= n <= 10^5
0 <= gas[i], cost[i] <= 10^4
Входные данные формируются таким образом, что ответ уникален.
*/

// canCompleteCircuit ищет старт кругового маршрута жадным отсевом кандидатов.
// Общий запас должен покрывать расход; затем ищем неубыточный старт.
// Время O(n), где n=len(gas): две суммы и один проход.
// Рабочая память и результат-индекс O(1); входные массивы не изменяются.
func canCompleteCircuit(gas []int, cost []int) int {
    // При суммарном дефиците никакой порядок обхода не поможет.
    // По ограничениям каждая сумма не больше 10^9 и помещается в int32.
    if sum(gas) < sum(cost) {
        return -1
    }

    total := 0
    res := 0

    // total — баланс от текущего res до i, а не сумма всего круга.
    for i := range gas {
        total += gas[i] - cost[i]
        // До провала все префиксы от res имели неотрицательный баланс.
        // Старт k в [res,i]: баланс total-баланс(res..k-1) тоже меньше 0.
        // Значит, весь диапазон исключён; следующий кандидат — i+1.
        if total < 0 {
            total = 0
            res = i + 1
        }
    }

    // Общая сумма неотрицательна: последний кандидат пройдёт и обёртку.
    return res
}

// sum складывает массив без изменения входа.
// Время O(n), n=len(nums); рабочая память и скалярный результат O(1).
func sum(nums []int) int {
    var total int
    for _, num := range nums {
        total += num
    }
    return total
}
