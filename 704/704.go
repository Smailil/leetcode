package main

/*
Даны массив целых чисел nums, отсортированный по возрастанию,
и целое число target.
Напишите функцию для поиска target в nums.
Если target существует, верните его индекс.
В противном случае верните -1.
Алгоритм должен иметь временную сложность O(log n).

Пример 1:
Вход: nums = [-1,0,3,5,9,12], target = 9
Выход: 4
Объяснение: число 9 существует в nums, а его индекс равен 4.

Пример 2:
Вход: nums = [-1,0,3,5,9,12], target = 2
Выход: -1
Объяснение: числа 2 не существует в nums, поэтому верните -1.

Ограничения:
1 <= nums.length <= 10^4
-10^4 < nums[i], target < 10^4
Все целые числа в nums уникальны.
nums отсортирован в порядке возрастания.
*/

// search сужает диапазон возможного индекса двоичным поиском.
// n = len(nums): время O(log(n + 1)), рабочая память и результат O(1).
// nums не изменяется; строгая сортировка и уникальность заданы контрактом.
func search(nums []int, target int) int {
    l, r := 0, len(nums) - 1
	// В начале итерации, если target существует, его индекс лежит в [l, r].
	for l <= r {
		// 0 <= l <= r < n, поэтому mid допустим; n <= 10000 исключает
		// переполнение суммы индексов даже для 32-битного int.
		mid := (l+r)/2
		// По сортировке одна половина вместе с mid не может содержать target.
		// Удаление mid обеспечивает прогресс даже в одноэлементном диапазоне.
		if target > nums[mid] {
			l = mid + 1
		} else if target < nums[mid] {
			r = mid - 1
		} else {
			return mid
		}
	}
	// Диапазон опустел без равенства: target отсутствует.
	return -1
}
