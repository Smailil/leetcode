package main

/*
Предложение — это список слов, разделённых одним пробелом, без пробелов
в начале и конце.

Например, "Hello World", "HELLO" и "hello world hello world" являются
предложениями. Слова состоят только из строчных и заглавных английских букв.
Заглавные и строчные английские буквы считаются различными.

Предложение является циклическим, если:
- последний символ каждого слова совпадает с первым символом следующего слова;
- последний символ последнего слова совпадает с первым символом первого слова.

Например, "leetcode exercises sound delightful", "eetcode" и
"leetcode eats soul" — циклические предложения. Однако "Leetcode is cool",
"happy Leetcode", "Leetcode" и "I like Leetcode" не являются циклическими.

Дана строка sentence. Верните true, если предложение является циклическим.
В противном случае верните false.

Пример 1:
Вход: sentence = "leetcode exercises sound delightful"
Выход: true
Пояснение: слова в sentence — ["leetcode", "exercises", "sound",
"delightful"].
- последний символ "leetcode" совпадает с первым символом "exercises";
- последний символ "exercises" совпадает с первым символом "sound";
- последний символ "sound" совпадает с первым символом "delightful";
- последний символ "delightful" совпадает с первым символом "leetcode".
Предложение является циклическим.

Пример 2:
Вход: sentence = "eetcode"
Выход: true
Пояснение: слова в sentence — ["eetcode"].
- последний символ "eetcode" совпадает с его первым символом.
Предложение является циклическим.

Пример 3:
Вход: sentence = "Leetcode is cool"
Выход: false
Пояснение: слова в sentence — ["Leetcode", "is", "cool"].
- последний символ "Leetcode" не совпадает с первым символом "is".
Предложение не является циклическим.

Ограничения:
1 <= sentence.length <= 500
Строка sentence состоит только из строчных и заглавных английских букв
и пробелов.
Слова в sentence разделены одним пробелом.
В начале и конце строки нет пробелов.
*/

// isCircularSentence проверяет, образуют ли слова замкнутую цепочку:
// последняя буква каждого слова должна совпадать с первой буквой следующего.
//
// Время: O(n), где n — длина sentence. Строка просматривается один раз.
// Дополнительная память: O(1), новые строки и массивы не создаются.
func isCircularSentence(sentence string) bool {
    // Каждый пробел обозначает границу двух соседних слов. Сравниваем
    // последний символ левого слова с первым символом правого.
    for i := 0; i < len(sentence); i++ {
        // Первое несовпадение означает, что цепочка уже не циклическая.
        if sentence[i] == ' ' && sentence[i-1] != sentence[i+1] {
            return false
        }
    }
    // Все соседние слова согласованы. Остаётся замкнуть цепочку, сравнив
    // первый символ предложения с последним символом последнего слова.
    return sentence[0] == sentence[len(sentence)-1]
}