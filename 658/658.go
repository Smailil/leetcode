package main

/*
Дан отсортированный массив целых чисел arr, два целых числа k и x.
Верни k ближайших к x целых чисел из массива.
Результат должен быть отсортирован по возрастанию.

Целое число a ближе к x, чем целое число b, если:
|a - x| < |b - x|, или
|a - x| == |b - x| и a < b

Пример 1:
Вход: arr = [1,2,3,4,5], k = 4, x = 3
Выход: [1,2,3,4]

Пример 2:
Вход: arr = [1,1,2,3,4,5], k = 4, x = -1
Выход: [1,1,2,3]

Ограничения:
1 <= k <= arr.length
1 <= arr.length <= 10^4
arr отсортирован по возрастанию.
-10^4 <= arr[i], x <= 10^4
*/

// findClosestElements находит начало окна k ближайших значений к x.
// Соседнее окно отличается только выбывшим и добавленным краем.
// n — число элементов arr; время O(log(n-k+2)), рабочая память O(1).
// Результат — заголовок среза O(1), а не новый массив из k элементов:
// он разделяет буфер с arr и может удерживать весь исходный массив.
// Функция не меняет arr; последующие записи через срезы будут общими.
func findClosestElements(arr []int, k int, x int) []int {
	// Ищем начальный индекс окна длины k.
	// Диапазон возможных стартовых позиций: [0, n-k].
	l, r := 0, len(arr)-k

	// Бинарный поиск сохраняет хотя бы одно подходящее начало в [l,r].
	for l < r {
		m := (l + r) / 2

		// m < r <= n-k, поэтому элемент arr[m+k] существует.
		// Это знаковые разности, а не абсолютные расстояния.
		// Условие равносильно arr[m]+arr[m+k] < 2*x в точной арифметике.
		// Сумма краёв не убывает по m: подходящий переход ищется бинарно.
		// Ограничения задачи исключают переполнение этих int-вычислений.
		if x-arr[m] > arr[m+k]-x {
			// Для разных краёв добавляемый элемент ближе к x.
			// При равных краях расстояния тоже равны: сдвиг меняет
			// позиции дубликатов, но не набор возвращаемых значений.
			l = m + 1
		} else {
			// Сохраняем m и левую часть возможных стартов.
			// При равенстве знаковых разностей меньший край остаётся:
			// это реализует предпочтение меньших значений при ничьей.
			r = m
		}
	}

	// l и r сошлись в оптимальном стартовом индексе.
	// Уже отсортированный срез длины k возвращается без копирования.
	return arr[l : l+k]
}
