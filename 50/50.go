package main

import "math"

/*
Реализуй pow(x, n) — функцию возведения x в степень n (то есть x^n).

Пример 1:
Вход: x = 2.00000, n = 10
Выход: 1024.00000

Пример 2:
Вход: x = 2.10000, n = 3
Выход: 9.26100

Пример 3:
Вход: x = 2.00000, n = -2
Выход: 0.25000
Пояснение: 2^(-2) = 1/2^2 = 1/4 = 0.25

Ограничения:
-100.0 < x < 100.0
-2^31 <= n <= 2^31-1
n — целое число.
Либо x ≠ 0, либо n > 0.
-10^4 <= x^n <= 10^4
*/

// myPow использует двоичное возведение в степень и обратное значение.
// b — число битов |n|: время O(b), рабочая память и результат O(1).
// При заданном 32-битном диапазоне n имеем b <= 32, то есть время O(1).
// x и power меняются локально, внешних побочных эффектов нет.
func myPow(x float64, n int) float64 {
    // По контракту при x == 0 степень положительна; случай 0^0 исключён.
    if x == 0 {
        return 0
    }
    if n == 0 {
        return 1
    }

    res := 1.0
    // |n| точно представим в float64 в пределах int32.
    // Для n == -2^31 модуль 2^31 помещается в int только на 64-битной
    // платформе; эта строка не переносима на 32-битный int в этом случае.
    power := int(math.Abs(float64(n)))

    // Инвариант: res * x^power равен исходному основанию в степени |n|
    // с поправкой на обычное округление float64.
    for power > 0 {
        // Нечётная степень отдаёт один множитель в res.
        // Затем x^power = (x*x)^(power/2) для оставшейся чётной степени.
        if power&1 != 0 {
            res *= x
        }
        x *= x
        power >>= 1
    }

    // Для отрицательной степени используем x^(-p) = 1 / x^p.
    // Математически основание ненулевое; float64 может терять точность.
    if n >= 0 {
        return res
    }
    return 1 / res
}
