package main

/*
Дана строка s, состоящая из строчных английских букв.

Необходимо найти максимальную разность
diff = freq(a_1) - freq(a_2) между частотами символов a_1 и a_2 при условиях:
a_1 встречается в строке нечётное число раз.
a_2 встречается в строке чётное число раз.
Верните максимальную разность.

Пример 1:
Вход: s = "aaaaabbc"
Выход: 3
Пояснение:
Символ 'a' встречается нечётное число раз — 5, а символ 'b' —
чётное число раз — 2.
Максимальная разность равна 5 - 2 = 3.

Пример 2:
Вход: s = "abcabcab"
Выход: 1
Пояснение:
Символ 'a' встречается нечётное число раз — 3, а символ 'c' —
чётное число раз — 2.
Максимальная разность равна 3 - 2 = 1.

Ограничения:
3 <= s.length <= 100
s состоит только из строчных английских букв.
s содержит хотя бы один символ с нечётной частотой и один — с чётной.
*/

// maxDifference независимо выбирает наибольшую нечётную и наименьшую
// положительную чётную частоты. Время работы — O(len(s)), память — O(1),
// поскольку размер алфавита фиксирован.
func maxDifference(s string) int {
    // Индекс элемента соответствует букве: 0 — 'a', 1 — 'b' и так далее.
    // Массив из 26 счётчиков не растёт вместе с длиной строки.
    count := make([]int, 26)

    // Сначала собираем частоты всех букв, чтобы затем сравнивать только их.
    for _, c := range s {
        count[c-'a']++
    }

    // oddMax и evenMin хранят нужные экстремумы среди уже просмотренных букв.
    // len(s) — безопасная начальная верхняя граница для чётного минимума.
    oddMax, evenMin := 0, len(s)
    for _, c := range count {
        if c&1 == 1 {
            // Большая нечётная частота увеличивает уменьшаемое разности.
            if c > oddMax {
                oddMax = c
            }
        } else if c > 0 {
            // Нулевые частоты исключены: отсутствующая буква не может быть a_2.
            // Из положительных чётных частот выбираем наименьшую.
            if c < evenMin {
                evenMin = c
            }
        }
    }

    // По условию оба типа частот существуют, а выбранные экстремумы дают
    // максимально возможное значение oddMax - evenMin.
    return oddMax - evenMin
}