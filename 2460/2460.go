package main

/*
Дан массив nums из n неотрицательных целых чисел с индексацией с 0.

К этому массиву нужно применить n - 1 операций.
На i-й операции (нумерация с 0) выполните следующее для nums[i]:
Если nums[i] == nums[i + 1], умножьте nums[i] на 2,
а nums[i + 1] присвойте 0.
Иначе пропустите эту операцию.
После выполнения всех операций перенесите все нули в конец массива.

Например, после переноса всех нулей массива [1,0,2,0,0,1] в конец
получится [1,2,1,0,0,0].
Верните полученный массив.

Обратите внимание: операции выполняются последовательно, а не одновременно.

Пример 1:
Вход: nums = [1,2,2,1,1,0]
Выход: [1,4,2,0,0,0]
Пояснение: выполняем следующие операции:
- i = 0: nums[0] и nums[1] не равны, поэтому пропускаем эту операцию.
- i = 1: nums[1] и nums[2] равны, поэтому умножаем nums[1] на 2
  и присваиваем nums[2] значение 0.
  Массив становится [1,4,0,1,1,0].
- i = 2: nums[2] и nums[3] не равны, поэтому пропускаем эту операцию.
- i = 3: nums[3] и nums[4] равны, поэтому умножаем nums[3] на 2
  и присваиваем nums[4] значение 0.
  Массив становится [1,4,0,2,0,0].
- i = 4: nums[4] и nums[5] равны, поэтому умножаем nums[4] на 2
  и присваиваем nums[5] значение 0.
  Массив становится [1,4,0,2,0,0].
После этого переносим нули в конец и получаем массив [1,4,2,0,0,0].

Пример 2:
Вход: nums = [0,1]
Выход: [1,0]
Пояснение: ни одну операцию применить нельзя, просто переносим 0 в конец.

Ограничения:
2 <= nums.length <= 2000
0 <= nums[i] <= 1000
*/

// applyOperations выполняет слияния соседних равных значений слева направо,
// затем собирает ненулевые элементы в новом срезе, сохраняя их порядок.
// nums изменяется при слияниях; перенос нулей выполняется только в answer.
// Время: O(n), где n = len(nums), два последовательных прохода.
// Дополнительная рабочая память без результата: O(1).
// Память результата: O(n); всего дополнительной памяти: O(n).
func applyOperations(nums []int) []int {
	n := len(nums)
	// Сначала выполняем все n - 1 операций, не сдвигая элементы.
	// На шаге i читаем значения с учётом предыдущей операции: nums[i]
	// мог стать нулём при слиянии пары (i-1, i). Условие i+1 < n
	// гарантирует, что оба индекса текущей пары находятся в границах.
	for i := 0; i+1 < n; i++ {
		if nums[i] == nums[i+1] {
			// Удвоенное значение остаётся слева, а справа появляется ноль.
			// Следующая операция начнётся справа, поэтому уже удвоенное
			// значение повторно не сливается. Например, [2,2,4] станет
			// [4,0,4], а не [8,0,0]. Равенство двух нулей ничего не меняет.
			// Ненулевое значение удваивается не более одного раза:
			// при исходной границе 1000 результат не превышает 2000.
			nums[i] *= 2
			nums[i+1] = 0
		}
	}
	// Новый срез сразу заполнен нулями и не разделяет буфер с nums.
	// write — следующая свободная позиция для ненулевого элемента.
	answer := make([]int, n)
	write := 0
	// Инвариант: answer[:write] содержит все ненулевые элементы
	// обработанной части nums в исходном для этого прохода порядке.
	// Нули пропускаем, а ненулевые значения записываем подряд.
	for _, x := range nums {
		if x != 0 {
			// До записи write не больше числа уже просмотренных элементов,
			// поэтому для текущего элемента write < n: место всегда есть.
			answer[write] = x
			write++
		}
	}
	// Хвост answer[write:] не заполнялся и остался нулевым.
	// Например, после слияний [4,0,4] превращается здесь в [4,4,0].
	return answer
}

