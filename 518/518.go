package main

/*
Дан целочисленный массив coins с номиналами монет
и целочисленная сумма amount, представляющая общую сумму денег.
Верните количество комбинаций монет, составляющих эту сумму.
Если сумму невозможно составить ни одной комбинацией монет, верните 0.
Можно предположить, что монет каждого номинала бесконечно много.
Ответ гарантированно умещается в 32-битное целое число со знаком.

Пример 1:
Вход: amount = 5, coins = [1,2,5]
Выход: 4
Пояснение: существует четыре способа составить сумму:
5=5
5=2+2+1
5=2+1+1+1
5=1+1+1+1+1

Пример 2:
Вход: amount = 3, coins = [2]
Выход: 0
Пояснение: сумму 3 невозможно составить только монетами номиналом 2.

Пример 3:
Вход: amount = 10, coins = [10]
Выход: 1

Ограничения:
1 <= coins.length <= 300
1 <= coins[i] <= 5000
Все номиналы монет уникальны.
0 <= amount <= 5000
*/

// change считает комбинации неограниченных монет динамикой по сумме.
// A = amount, c = len(coins): время O(c*(A + 1)), память O(A + 1).
// Результат — число; coins не изменяется, порядок комбинации не учитывается.
func change(amount int, coins []int) int {
    // A >= 0, поэтому таблица содержит допустимую базовую сумму 0.
    // После полного прохода по очередному номиналу dp[a] учитывает
    // комбинации только из уже обработанных номиналов.
    dp := make([]int, amount+1)
    
    // Базовый случай: есть 1 способ собрать сумму 0 (не брать монеты)
    dp[0] = 1

    // Фиксируем номинал внешним циклом: не считаем перестановки монет
    // разными комбинациями. Обратный порядок номиналов на ответ не влияет.
    for i := len(coins) - 1; i >= 0; i-- {
        // Рост a использует уже обновлённую меньшую сумму этой же стадии:
        // текущий номинал разрешено повторять. Например, 4 = 2 + 2.
        for a := 1; a <= amount; a++ {
            // coins[i] положителен: проверка даёт индекс в диапазоне 0..a-1.
            if a-coins[i] >= 0 {
                // К каждой комбинации dp[a-v] добавляется одна v = coins[i].
                // Это варианты с v; старое dp[a] считает варианты без v.
                // int хранит таблицу; гарантия 32 бит относится к dp[amount],
                // а значения для других сумм могут оказаться больше.
                dp[a] += dp[a - coins[i]]
            }
        }
    }

    // Возвращаем количество способов собрать целевую сумму
    return dp[amount]
}
