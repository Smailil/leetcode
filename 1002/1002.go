package main

import "math"

/*
Дан массив строк words. Верните массив всех символов, которые встречаются
в каждой строке из words, включая повторяющиеся символы. Ответ можно вернуть
в любом порядке.

Пример 1:
Вход: words = ["bella","label","roller"]
Выход: ["e","l","l"]

Пример 2:
Вход: words = ["cool","lock","cook"]
Выход: ["c","o"]

Ограничения:
1 <= words.length <= 100
1 <= words[i].length <= 100
words[i] состоит из строчных английских букв.
*/

// commonChars возвращает общие для всех слов буквы с учётом повторений.
// Для каждой из 26 букв функция хранит минимальную частоту среди уже
// обработанных слов, а затем восстанавливает по этим минимумам ответ.
//
// Время: O(s + 26n + r), где n = len(words), s — суммарная длина слов,
// r — размер результата. Для фиксированного алфавита это упрощается до O(s).
// Дополнительная рабочая память: O(26) = O(1); память результата: O(r).
func commonChars(words []string) []string {
    // Значение больше максимальной длины слова позволяет первому слову
    // без отдельной ветки задать начальные минимальные частоты всех букв.
    cnt := make([]int, 26)
    for i := range cnt {
        cnt[i] = math.MaxInt32
    }

    for _, word := range words {
        // Частоты считаются отдельно для текущего слова, чтобы повторения
        // одной буквы в разных словах не складывались между собой.
        curCnt := make([]int, 26)
        for _, c := range word {
            curCnt[c-'a']++
        }

        // После обновления cnt[i] равен минимуму частоты i-й буквы среди
        // всех обработанных слов — именно столько её копий пока общие.
        for i := range 26 {
            if curCnt[i] < cnt[i] {
                cnt[i] = curCnt[i]
            }
        }
    }

    // Каждую букву добавляем ровно cnt[i] раз, сохраняя общие повторения.
    res := []string{}
    for i := range 26 {
        for j := 0; j < cnt[i]; j++ {
            res = append(res, string(rune(i+'a')))
        }
    }

    return res
}