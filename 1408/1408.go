package main

import "strings"

/*
Дан массив строк `words`. Верните все строки из `words`, которые являются
подстроками другой строки этого массива. Ответ можно вернуть в любом порядке.

Пример 1:
Вход: words = ["mass","as","hero","superhero"]
Выход: ["as","hero"]
Пояснение: "as" является подстрокой "mass", а "hero" — подстрокой "superhero".
["hero","as"] также является допустимым ответом.

Пример 2:
Вход: words = ["leetcode","et","code"]
Выход: ["et","code"]
Пояснение: "et" и "code" являются подстроками "leetcode".

Пример 3:
Вход: words = ["blue","green","bu"]
Выход: []
Пояснение: ни одна строка из `words` не является подстрокой другой строки.

Ограничения:
1 <= words.length <= 100
1 <= words[i].length <= 30
words[i] содержит только строчные английские буквы.
Все строки в `words` уникальны.
*/

// stringMatching проверяет каждое слово как возможную подстроку
// и собирает все слова, которые встречаются внутри другого элемента массива.
func stringMatching(words []string) []string {
    // Результат растёт только при первом найденном совпадении для кандидата.
    res := []string{}

    // Внешний цикл выбирает слово, для которого ищется содержащая его строка.
    for i := range words {
        // Внутренний цикл перебирает все возможные строки-контейнеры.
        for j := range words {
            // Слово нельзя считать подстрокой самого себя в рамках этой задачи.
            if i == j {
                continue
            }

            // После первого совпадения слово уже гарантированно входит в ответ.
            // Ранний выход не позволяет добавить его повторно, если подходящих
            // строк-контейнеров несколько.
            if strings.Contains(words[j], words[i]) {
                res = append(res, words[i])
                break
            }
        }
    }

    return res
}