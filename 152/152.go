package main

/*
Дан целочисленный массив nums,
найдите подмассив с наибольшим произведением и верните произведение.
Тестовые случаи генерируются таким образом,
чтобы ответ соответствовал 32-битному целому числу.
Обратите внимание, что произведение массива с одним элементом
является значением этого элемента.

Пример 1:
Вход: nums = [2,3,-2,4]
Выход: 6
Пояснение: [2,3] имеет наибольшее произведение 6.

Пример 2:
Вход: nums = [-2,0,-1]
Выход: 0
Объяснение: Результат не может быть равен 2,
поскольку [-2,-1] не является подмассивом.

Ограничения:
1 <= nums.length <= 2 * 10^4
-10 <= nums[i] <= 10
Произведение любого подмассива чисел гарантированно помещается
в 32-битное целое число.
*/

// maxProduct хранит экстремумы суффиксов текущей ненулевой серии.
// n=len(nums): время O(n), рабочая память O(1), ответ int O(1).
// nums не меняется; nums[0] существует по условию n>=1.
// Любое произведение подмассива помещается в int32, значит и в int.
func maxProduct(nums []int) int {
    // Реальный первый элемент не позволит выбрать пустой подмассив
    // с произведением 1, например при единственном отрицательном числе.
    res := nums[0]
    // 1 — нейтральное начало новой серии. После ненулевого num curMin/curMax
    // — экстремумы её непустых суффиксов, а не всех суффиксов входа.
    // Суффиксы через прежний ноль дают 0: этот кандидат уже учтён в res.
    curMin, curMax := 1, 1
    for _, num := range nums {
        // Ноль разрывает ненулевую серию: новый суффикс начнётся позже,
        // а произведение 0 уже сейчас сравниваем с глобальным res.
        if num == 0 {
            curMax, curMin = 1, 1
            res = max(res, 0) // учитываем нулевое произведение
            continue
        }
        // Из отрицательного num минимум может стать максимумом и наоборот.
        // Кандидаты: продолжить прежний max/min либо начать с одного num.
        // tmp сохраняет прежний curMax*num до перезаписи curMax;
        // curMin пока ещё старый, поэтому второе обновление берёт верные
        // данные.
        tmp := curMax * num
        curMax = max(num*curMax, num*curMin, num)
        curMin = min(tmp, num*curMin, num)
        // Лучший суффикс завершает подмассив здесь; res хранит лучший
        // результат по всем уже обработанным конечным позициям.
        res = max(res, curMax)
    }
    return res
}