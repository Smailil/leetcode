package main

import "strings"

/*
Даны строка s с индексацией с 0 и массив целых чисел spaces
с индексацией с 0, задающий позиции в исходной строке для вставки пробелов.
Каждый пробел вставляется перед символом с указанным индексом.

Например, если s = "EnjoyYourCoffee" и spaces = [5, 9], вставляем пробелы
перед 'Y' и 'C' с индексами 5 и 9 соответственно.
Получаем "Enjoy Your Coffee".
Верните изменённую строку после добавления пробелов.

Пример 1:
Вход: s = "LeetcodeHelpsMeLearn", spaces = [8,13,15]
Выход: "Leetcode Helps Me Learn"
Пояснение:
Индексы 8, 13 и 15 соответствуют подчёркнутым символам
в строке "LeetcodeHelpsMeLearn".
Затем перед этими символами вставляются пробелы.

Пример 2:
Вход: s = "icodeinpython", spaces = [1,5,7,9]
Выход: "i code in py thon"
Пояснение:
Индексы 1, 5, 7 и 9 соответствуют подчёркнутым символам
в строке "icodeinpython".
Затем перед этими символами вставляются пробелы.

Пример 3:
Вход: s = "spacing", spaces = [0,1,2,3,4,5,6]
Выход: " s p a c i n g"
Пояснение:
Пробел можно вставить и перед первым символом строки.

Ограничения:
1 <= s.length <= 3 * 10^5
Строка s состоит только из строчных и прописных английских букв.
1 <= spaces.length <= 3 * 10^5
0 <= spaces[i] <= s.length - 1
Все значения в spaces расположены в строго возрастающем порядке.
*/

// addSpaces вставляет пробелы перед позициями spaces в исходной строке s.
// Фрагменты s последовательно копируются в общий буфер результата.
// Входные s и spaces не изменяются.
// Время: O(n + m), где n = len(s), m = len(spaces).
// Фрагменты не пересекаются: копируется n байтов и добавляется m пробелов.
// Память результата: O(n + m); рабочая память без него: O(1).
func addSpaces(s string, spaces []int) string {
	var result strings.Builder
	// Итоговая длина: n исходных байтов плюс m однобайтовых пробелов.
	// Grow резервирует ёмкость заранее, без расширений при дописывании.
	// По ограничениям n + m <= 600000, поэтому сумма помещается в int.
	result.Grow(len(s) + len(spaces))

	// start — начало ещё не скопированной части исходной строки.
	// Индексы spaces относятся к s: добавленные пробелы их не сдвигают.
	start := 0
	for _, index := range spaces {
		// По условию 0 <= index < len(s), а индексы строго возрастают.
		// Поэтому 0 <= start <= index: срез не выходит за границы.
		// Английские буквы однобайтовые, их индексы здесь — байтовые.
		// Копируем фрагмент до index, не включая символ в позиции index.
		result.WriteString(s[start:index])
		// Символ s[index] ещё не записан: пробел окажется перед ним.
		result.WriteByte(' ')
		// Следующий фрагмент начинается с этого же символа.
		// start = index + 1 пропустил бы его, поэтому оставляем index.
		start = index
	}
	// Дописываем хвост, включая символ на последнем индексе из spaces.
	// Для s="abcd", spaces=[1,3] буфер меняется так:
	// "a " -> "a bc " -> "a bc d" (последний шаг — дописывание хвоста).
	result.WriteString(s[start:])
	// String возвращает строку на том же буфере без копирования байтов.
	// Буфер уже учтён в памяти результата, второй раз его не считаем.
	return result.String()
}
