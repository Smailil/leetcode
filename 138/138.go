package main

/*
Связный список длины n дан так, что каждый узел содержит
дополнительный случайный указатель, который может указывать
на любой узел в списке или на null.
Создайте глубокую копию списка.
Глубокая копия должна состоять ровно из n совершенно новых узлов,
где каждому новому узлу присваивается значение,
равное значению соответствующего исходного узла.
И следующий, и случайный указатель новых узлов должны указывать
на новые узлы в скопированном списке так, чтобы указатели
в исходном и скопированном списках представляли одно и то же состояние.
Ни один из указателей в новом списке не должен указывать
на узлы исходного списка.
Например, если в исходном списке есть два узла X и Y, где X.random --> Y,
то для соответствующих узлов x и y в копии x.random --> y.
Верните голову скопированного связного списка.
Связный список представляется на входе/выходе как список из n узлов.
Каждый узел представлен парой [val, random_index], где:
val: целое число, представляющее Node.val.
random_index: индекс узла в диапазоне от 0 до n-1,
на который указывает случайный указатель, или null,
если он не указывает ни на один узел.
Вашему коду передаётся только голова исходного связного списка.

Пример 1:
https://assets.leetcode.com/uploads/2019/12/18/e1.png
Вход: head = [[7,null],[13,0],[11,4],[10,2],[1,0]]
Выход: [[7,null],[13,0],[11,4],[10,2],[1,0]]

Пример 2:
https://assets.leetcode.com/uploads/2019/12/18/e2.png
Вход: head = [[1,1],[2,1]]
Выход: [[1,1],[2,1]]

Пример 3:
https://assets.leetcode.com/uploads/2019/12/18/e3.png
Вход: head = [[3,null],[3,0],[3,null]]
Выход: [[3,null],[3,0],[3,null]]

Ограничения:
0 <= n <= 1000
-10^4 <= Node.val <= 10^4
Node.random имеет значение null
или указывает на какой-либо узел в связанном списке.
*/

type Node struct {
    Val int
    Next *Node
    Random *Node
}

// copyRandomList создаёт новые узлы, затем связывает их через соответствие
// «исходный указатель -> копия», включая произвольные связи Random.
// Время в среднем O(n), n — число узлов: ключи map имеют постоянный размер.
// Рабочая память O(n) для hash; результат O(n) для n новых узлов.
// Исходный список не изменяется, указатели результата ведут только в копию.
func copyRandomList(head *Node) *Node {
    curr := head
	// Запись nil -> nil сохраняет отсутствующие связи и пустую голову.
	hash := map[*Node]*Node{nil: nil}
	// Сначала создаём все копии без связей: Random может вести вперёд,
	// поэтому на этом этапе нельзя требовать наличия копии его цели.
	for curr != nil {
		newNode := &Node{Val: curr.Val}
		hash[curr] = newNode
		curr = curr.Next
	}
	// Теперь копия есть для каждого исходного узла. Связи восстанавливаем
	// по адресам, а не значениям: одинаковые Val не смешивают разные узлы.
	curr = head
	for curr != nil {
		newNode := hash[curr]
		newNode.Next = hash[curr.Next]
		newNode.Random = hash[curr.Random]
		curr = curr.Next
	} 
	// Даже если head == nil, таблица возвращает nil без отдельной ветки.
	return hash[head]
}
