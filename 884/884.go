package main

import "strings"

/*
Предложение — это строка из слов, разделённых одиночными пробелами.
Каждое слово состоит только из строчных букв.

Слово считается необычным, если встречается ровно один раз
в одном из предложений и не встречается в другом.

Даны два предложения s1 и s2. Верните список всех необычных слов.
Ответ можно вернуть в любом порядке.

Пример 1:
Вход: s1 = "this apple is sweet", s2 = "this apple is sour"
Выход: ["sweet","sour"]
Пояснение:
Слово "sweet" встречается только в s1, а слово "sour" — только в s2.

Пример 2:
Вход: s1 = "apple apple", s2 = "banana"
Выход: ["banana"]

Ограничения:
1 <= s1.length, s2.length <= 200
s1 и s2 состоят из строчных английских букв и пробелов.
У s1 и s2 нет пробелов в начале или в конце.
Все слова в s1 и s2 разделены одиночным пробелом.

*/

// uncommonFromSentences возвращает слова с общей частотой 1 в s1 и s2.
// Сначала считаем все появления слов, затем отбираем подходящие слова.
// Среднее время: O(m + n), где m = len(s1), n = len(s2).
// Доступ к map в среднем O(1) без учёта хеширования строки;
// суммарная длина всех хешируемых слов — O(m + n).
// Рабочая память: O(m + n) для общей строки и среза words,
// плюс O(k) для count, где k — число различных слов.
// По ограничениям k <= 200, поэтому отдельно память count — O(1).
// Результат: O(r) элементов среза res, где r — число возвращённых слов.
// Строки результата удерживают общий буфер длиной O(m + n).
// Входные строки s1 и s2 не изменяются.
func uncommonFromSentences(s1 string, s2 string) []string {
    // Добавленный пробел разделяет последнее слово s1 и первое слово s2:
    // без него, например, "apple" и "banana" слились бы в "applebanana".
    // По условию между словами ровно один пробел, а по краям пробелов нет,
    // поэтому Split выделяет слова без пустых элементов.
    words := strings.Split(s1 + " " + s2, " ")
    count := make(map[string]int)

    // count[w] хранит общее число появлений w в обоих предложениях.
    // Повторения внутри одного предложения тоже увеличивают счётчик:
    // для s1 = "apple apple", s2 = "banana" получим частоты 2 и 1.
    for _, w := range words {
        count[w]++
    }

    // В map каждое различное слово представлено одним ключом.
    // Порядок обхода map не определён, но задача допускает любой порядок
    // ответа, поэтому сортировать res не нужно.
    res := []string{}
    for w, c := range count {
        // Частота 1 означает одно появление в одном предложении
        // и ни одного в другом — именно это делает слово необычным.
        // Повторение в одном предложении или наличие в обоих дало бы c >= 2.
        if c == 1 {
            res = append(res, w)
        }
    }

    return res
}