package main

/*
Дана строка s, состоящая только из символов '0' и '1'. За одну операцию
можно заменить любой символ '0' на '1' или наоборот.

Строка называется чередующейся, если никакие два соседних символа не равны.
Например, строка "010" является чередующейся, а строка "0100" — нет.

Верните минимальное количество операций, необходимое, чтобы сделать строку s
чередующейся.

Пример 1:
Вход: s = "0100"
Выход: 1
Пояснение: Заменим последний символ на '1'.
Строка s станет "0101" и будет чередующейся.

Пример 2:
Вход: s = "10"
Выход: 0
Пояснение: Строка s уже является чередующейся.

Пример 3:
Вход: s = "1111"
Выход: 2
Пояснение: Достаточно двух операций, чтобы получить "0101" или "1010".

Ограничения:
1 <= s.length <= 10^4
s[i] равен '0' или '1'.
*/

// minOperations возвращает минимальное число замен, после которых соседние
// символы в s будут различаться. Сначала функция считает несовпадения с
// шаблоном "1010..."; для противоположного шаблона "0101..." каждая позиция
// меняет статус совпадения, поэтому достаточно выбрать меньшую стоимость.
// Время: O(n), где n = len(s). Дополнительная память: O(1).
func minOperations(s string) int {
    // count — количество замен, необходимых для получения шаблона "1010...".
    count := 0

    // На чётных индексах ожидается '1', а на нечётных — '0'.
    for i := 0; i < len(s); i++ {
        if i%2 == 0 {
            if s[i] == '0' {
                count++
            }
        } else {
            if s[i] == '1' {
                count++
            }
        }
    }

    // Число замен для второго шаблона равно len(s) - count, потому что каждая
    // позиция совпадает ровно с одним из двух чередующихся шаблонов.
    if count < len(s)-count {
        return count
    }
    return len(s) - count
}
