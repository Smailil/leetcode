package main

import "container/heap"

/*
Дан массив задач ЦП, каждая из которых помечена буквой от A до Z,
и отдельное число n.
Каждый интервал ЦП может быть бездействующим
или разрешать выполнение одной задачи.
Задачи можно выполнять в любом порядке, но есть ограничение:
между двумя задачами с одинаковой меткой
должен быть промежуток не менее n интервалов.
Верните минимальное количество интервалов ЦП для выполнения всех задач.

Пример 1:
Вход: tasks = ["A","A","A","B","B","B"], n = 2
Выход: 8
Пояснение: Возможная последовательность:
A -> B -> ожидание -> A -> B -> ожидание -> A -> B.
После выполнения задачи A нужно подождать два интервала,
прежде чем снова выполнить A.
То же самое относится и к задаче B.
В 3-м интервале ни A, ни B сделать невозможно, поэтому вы бездействуете.
К 4-му интервалу можно снова выполнить A, так как прошло 2 интервала.

Пример 2:
Вход: tasks = ["A","C","A","B","D","B"], n = 1
Выход: 6
Пояснение: Возможная последовательность: A -> B -> C -> D -> A -> B.
Если интервал охлаждения равен 1,
задачу можно повторить уже после одной другой задачи.

Пример 3:
Вход: tasks = ["A","A","A", "B","B","B"], n = 3
Выход: 10
Пояснение: Возможная последовательность:
A -> B -> простой -> простой -> A -> B -> простой -> простой -> A -> B.
Есть всего два типа заданий A и B, которые нужно разделить 3 интервалами.
Это приводит к двойному простою между повторениями этих задач.

Ограничения:
1 <= tasks.length <= 10^4
tasks[i] — это заглавная английская буква.
0 <= n <= 100
*/

// MaxHeap хранит остатки частот; Less с обратным знаком даёт максимум в корне.
// Len/Less/Swap работают за O(1); Swap меняет элементы общего массива.
type MaxHeap []int	

func (h MaxHeap) Len() int {return len(h)}
func (h MaxHeap) Less(i, j int) bool {return h[i] > h[j]}
func (h MaxHeap) Swap(i, j int) {h[i], h[j] = h[j], h[i]}
// Push добавляет int в хвост; восстановлением кучи занимается container/heap.
// Время O(1) амортизированно, O(k) при росте буфера, k=len(*h).
// Дополнительный буфер при росте O(k); результата нет, h изменяется.
func (h *MaxHeap) Push(x interface{}) {*h = append(*h, x.(int))}
// Pop снимает хвост; container/heap заранее переносит туда максимум.
// Время, рабочая память и результат O(1); меняет h, ёмкость не освобождает.
// Требует непустой h; этот контракт проверяется перед heap.Pop ниже.
func (h *MaxHeap) Pop() interface{} {
    n := len(*h)
    x := (*h)[n-1]
    *h = (*h)[0:n-1]
    return x
}

// Queue хранит пары [оставшаяся частота, последний интервал ожидания].
// Времена возрастают: в один интервал создаётся не больше одной пары,
// а задержка n одинакова для всех задач.
type Queue [][2]int

// Push ставит пару в хвост и меняет q; результата нет.
// Время O(1) амортизированно, O(k) при росте; временный буфер O(k), k=len(*q).
func (q *Queue) Push(x [2]int) {*q = append(*q, x)}
// Pop снимает голову за O(1) времени и рабочей памяти; результат — пара O(1).
// Меняет q, не копируя хвост и не освобождая общий массив; требует непустую q.
func (q *Queue) Pop() [2]int {
    x := (*q)[0]
    *q = (*q)[1:]
    return x
}

// leastInterval моделирует интервалы, выбирая максимальный доступный остаток.
// Куча хранит готовые частоты, очередь — частоты на одинаковом cooldown n.
// Среднее время O(M+T*log(K+1)), M=len(tasks), K — число разных меток,
// T — число интервалов результата: простои также обходятся по одному.
// Карта занимает O(K), буферы резервируют A=26 мест: рабочая память O(K+A).
// При фиксированных 26 метках это O(1); результат int O(1).
// tasks не меняется; T не больше M*(n+1), поэтому счётчики безопасны для int32.
func leastInterval(tasks []byte, n int) int {
    count := make(map[byte]int, 26)
	for _, task := range tasks {
		count[task]++
	}
	mh := make(MaxHeap, 0, 26)
	for _, val := range count {
		heap.Push(&mh, val)
	}
	q := make(Queue, 0, 26)
	time := 0
	for len(mh) > 0 || len(q) > 0 {
		time++
		if len(mh) > 0 {
			val := heap.Pop(&mh).(int) - 1
			if val != 0 {
				// Повтор можно выполнять в time+n+1: возвращение из q происходит
				// после выбора задачи текущего интервала time+n.
				q.Push([2]int{val, time+n})
			}
		}
		if len(q) > 0 {
			// Сроки строго возрастают, поэтому здесь достаточно вернуть одну
			// частоту: два разных срока не совпадут при постоянном n.
			if q[0][1] == time {
				heap.Push(&mh, q.Pop()[0])
			}
		}
	}
	return time
}
