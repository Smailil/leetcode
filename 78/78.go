/*
Дан целочисленный массив уникальных элементов.
Верните все возможные подмножества (множество всех подмножеств).
Набор решений не должен содержать повторяющихся подмножеств.
Верните решение в любом порядке.

Пример 1:
Вход: nums = [1,2,3]
Выход: [[],[1],[2],[1,2],[3],[1,3],[2,3],[1,2,3]]

Пример 2:
Вход: nums = [0]
Выход: [[],[0]]

Ограничения:
1 <= nums.length <= 10
-10 <= nums[i] <= 10
Все числа nums уникальны.
*/

// IntPow вычисляет n в неотрицательной степени m последовательным умножением.
// Время O(m), рабочая память и память результата O(1); побочных эффектов нет.
// Вызов ниже использует 2^len(nums), что при len(nums) до 10 безопасно для int.
func IntPow(n, m int) int {
    // Любое число в нулевой степени принимаем равным 1.
    if m == 0 {
        return 1
    }

    if m == 1 {
        return n
    }

    // result=n^(i-1) перед очередным умножением для степени i.
    result := n
    for i := 2; i <= m; i++ {
        result *= n
    }
    return result
}


// subsets перебирает подмножества решениями «взять/пропустить» каждый элемент.
// Время O(n*2^n), где n=len(nums): копируются n*2^(n-1) элементов в листьях.
// Рабочая память O(n) для текущего subset и стека; результат O(n*2^n).
// Итоговые подмножества имеют отдельные массивы; nums не изменяется.
func subsets(nums []int) [][]int {
    // Всего 2^n вариантов; ёмкость заранее вмещает все заголовки результата.
    res := make([][]int, 0, IntPow(2, len(nums)))
	subset := make([]int, 0, len(nums))
	var dfs func(int)
	// dfs выбирает элементы с позиции i; subset содержит выбор префикса.
	// Время O(n*2^k), k=n-i; рабочая память O(n) для subset и стека.
	// Добавленные копии листьев в результат занимают O(n*2^k).
	dfs = func(i int) {
		if i >= len(nums) {
			// Без копии дальнейший откат и append испортили бы сохранённый выбор.
			copySubset := make([]int, len(subset))
			copy(copySubset, subset)
			res = append(res, copySubset)
			return
		}
		// Первая ветка включает nums[i].
		subset = append(subset, nums[i])
		dfs(i + 1)
		// Откат восстанавливает выбор префикса для ветки без nums[i].
		subset = subset[:len(subset)-1]
		dfs(i + 1)
	
	}
	dfs(0)
	return res
}
