package main

/*
Даны два целочисленных массива nums1 и nums2 с индексацией с нуля.
Верните список answer длины 2:
answer[0] — все различные числа из nums1, которых нет в nums2.
answer[1] — все различные числа из nums2, которых нет в nums1.
Порядок чисел внутри каждого списка может быть любым.

Пример 1:
Вход: nums1 = [1,2,3], nums2 = [2,4,6]
Выход: [[1,3],[4,6]]
Пояснение:
Число nums1[1] = 2 встречается в nums2 с индексом 0, а nums1[0] = 1
и nums1[2] = 3 там отсутствуют. Поэтому answer[0] = [1,3].
Число nums2[0] = 2 встречается в nums1 с индексом 1, а nums2[1] = 4
и nums2[2] = 6 там отсутствуют. Поэтому answer[1] = [4,6].

Пример 2:
Вход: nums1 = [1,2,3,3], nums2 = [1,1,2,2]
Выход: [[3],[]]
Пояснение:
Числа nums1[2] и nums1[3] отсутствуют в nums2. Они равны, поэтому
их значение входит в answer[0] только один раз: answer[0] = [3].
Каждое число из nums2 встречается в nums1. Поэтому answer[1] = [].

Ограничения:
1 <= nums1.length, nums2.length <= 1000
-1000 <= nums1[i], nums2[i] <= 1000
*/

// findDifference возвращает уникальные числа каждого среза, которых нет
// в другом. Множества удаляют повторы и позволяют проверять наличие.
// Среднее время O(m + n), где m = len(nums1), n = len(nums2): операции
// с map в среднем O(1), а добавление в срез амортизированно O(1).
// Рабочая память O(k1 + k2), где k1 и k2 — число разных значений
// в nums1 и nums2. Ответ занимает O(r1 + r2), где r1 = len(res1),
// r2 = len(res2). Из-за диапазона [-1000, 1000] обе оценки памяти
// в рамках задачи упрощаются до O(1).
func findDifference(nums1 []int, nums2 []int) [][]int {
    // Ключи map служат множеством чисел, а пустой struct{} не хранит
    // полезных данных. Повторная вставка не создаёт нового ключа.
    num1Set := make(map[int]struct{})
    num2Set := make(map[int]struct{})
    for _, num := range nums1 {
        num1Set[num] = struct{}{}
    }
    for _, num := range nums2 {
        num2Set[num] = struct{}{}
    }

    // Обход ключей num1Set рассматривает каждое значение лишь однажды.
    // В res1 попадают только те из них, которых нет в num2Set.
    res1, res2 := []int{}, []int{}
    for num := range num1Set {
        if _, exists := num2Set[num]; !exists {
            res1 = append(res1, num)
        }
    }

    // Аналогично res2 содержит значения только из nums2. Порядок чисел
    // в обоих списках не гарантирован из-за обхода ключей map.
    for num := range num2Set {
        if _, exists := num1Set[num]; !exists {
            res2 = append(res2, num)
        }
    }

    return [][]int{res1, res2}
}
