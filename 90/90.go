package main

import "sort"

/*
Дан целочисленный массив nums, который может содержать дубликаты,
верните все возможные подмножества (множество всех подмножеств).
Набор решений не должен содержать повторяющихся подмножеств.
Верните решение в любом порядке.

Пример 1:
Вход: nums = [1,2,2]
Выход: [[],[1],[1,2],[1,2,2],[2],[2,2]]

Пример 2:
Вход: nums = [0]
Выход: [[],[0]]

Ограничения:
1 <= nums.length <= 10
-10 <= nums[i] <= 10
*/

// subsetsWithDup сортирует nums и выбирает число копий каждого значения.
// n = len(nums), t — число ответов, L — сумма их длин.
// Время O(n*2^n) в худшем случае, рабочая память O(n) для пути/рекурсии.
// Результат O(t+L); побочный эффект — сортировка nums на месте.
func subsetsWithDup(nums []int) [][]int {
	res := make([][]int, 0)
	sort.Ints(nums)
	var backtrack func(int, []int)
	// backtrack дополняет cur элементами nums[i:], копируя путь в листе.
	// q=n-i; время поддерева O(n*2^q), рабочая память O(n) пути и стека.
	// Меняет рабочий буфер cur и захваченный res; ответы независимы.
	backtrack = func(i int, cur []int) {
		if i == len(nums) {
			// Следующие откаты и append не должны менять готовое подмножество.
			copyCur := make([]int, len(cur))
			copy(copyCur, cur)
			res = append(res, copyCur)
			return
		}
		// Взять одну копию: следующий индекс разрешает взять ещё одну
		// равную копию, если она есть в отсортированном массиве.
		cur = append(cur, nums[i])
		backtrack(i+1, cur)
		cur = cur[:len(cur)-1]
		// Исключение пропускает все оставшиеся копии текущего значения.
		// Так один и тот же выбор количества копий не дублируется.
		// i+1<len(nums) защищает чтение соседнего элемента.
		for i+1 < len(nums) && nums[i] == nums[i+1] {
			i++
		}
		backtrack(i+1, cur)
	}
	backtrack(0, make([]int, 0))
	return res
}
