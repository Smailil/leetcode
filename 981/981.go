package main

/*
Разработайте структуру данных «ключ-значение», основанную на времени.
Она должна хранить несколько значений одного ключа с разными метками времени
и получать значение ключа на определённую метку времени.
Реализуйте класс TimeMap:
TimeMap() Инициализирует объект структуры данных.
void set(String key, String value, int timestamp)
Сохраняет ключ key со значением value и меткой времени timestamp.
String get(String key, int timestamp)
Возвращает значение для key, записанное ранее вызовом set,
с timestamp_prev <= timestamp.
Если таких значений несколько, выбирает наибольшую метку timestamp_prev.
Если таких значений нет, возвращает "".

Пример 1:
Вход
["TimeMap", "set", "get", "get", "set", "get", "get"]
[[], ["foo", "bar", 1], ["foo", 1], ["foo", 3], ["foo", "bar2", 4], ["foo", 4],
["foo", 5]]
Выход
[null, null, "bar", "bar", null, "bar2", "bar2"]
Пояснение
TimeMap timeMap = new TimeMap();
timeMap.set("foo", "bar", 1);  // сохраните ключ «foo» и значение «bar» вместе с
меткой времени = 1.
timeMap.get("foo", 1);         // верните "bar"
timeMap.get("foo", 3);         // верните "bar", поскольку в метке времени 3 и
метке времени 2 нет значения, соответствующего foo, 
тогда единственное значение в метке времени 1 — это "bar".
timeMap.get("foo", 5);         // верните "bar2": во входных данных
значение "bar2" записано для "foo" с меткой времени 4.

Ограничения:
1 <= key.length, value.length <= 100
key и value состоят из строчных английских букв и цифр.
1 <= timestamp <= 10^7
Все метки timestamp вызовов set строго возрастают.
Будет сделано не более 2 * 10^5 вызовов set и get.
*/

type val struct {
	val string
	timestamp int
}

// TimeMap хранит для каждого ключа возрастающую последовательность записей.
// N — число записей, K — число ключей, B — их различные строковые буферы.
// Состояние занимает O(N + K + B), не копируя данные строк.
type TimeMap struct {
    data map[string][]val
}


// Constructor создаёт пустую инициализированную map для будущих Set.
// Время, рабочая память и начальное возвращаемое состояние O(1).
func Constructor() TimeMap {
	return TimeMap{
		data: make(map[string][]val),
	}
}


// Set дописывает значение и время в историю ключа, меняя состояние receiver.
// L = len(key), t — число старых записей ключа: среднее время
// амортизированно O(L + 1); отдельный рост среза стоит O(t).
// Рабочая память O(1), кроме O(t) при росте буфера истории.
// Строки сохраняются без копирования данных и удерживают свои буферы.
func (this *TimeMap) Set(key string, value string, timestamp int)  {
    // Общая строгая монотонность timestamp гарантирует порядок каждой истории.
    // Средняя O(1) операция map не включает O(L) хеширование/сравнение ключа.
    this.data[key] = append(this.data[key], val{value, timestamp})
}


// Get находит последнюю запись ключа с временем не позже timestamp.
// L = len(key), t — длина его истории: среднее время O(L + log(t + 1)).
// Рабочая память O(1), состояние не меняется.
// Результат — заголовок строки O(1), удерживающий её исходный буфер.
// Этот буфер может быть больше len(value); общий со state не считаем дважды.
func (this *TimeMap) Get(key string, timestamp int) string {
    res := ""
	// Отсутствующий ключ даёт пустой срез: цикл не выполняется, вернётся "".
	arr := this.data[key]
	l, r := 0, len(arr) - 1
	// res — последняя найденная допустимая запись; более свежую ищем в [l,r].
	// t <= 2*10^5: сумма допустимых индексов безопасна даже при int32.
	for l <= r {
		mid := (l+r)/2
		// Допустимость mid исключает всё левее из поиска более свежего ответа.
		// Если время слишком позднее, все позиции правее также недопустимы.
		if arr[mid].timestamp <= timestamp {
			res = arr[mid].val
			l = mid + 1
		} else {
			r = mid - 1
		}
	}
	// Диапазон исчерпан: res соответствует максимальному допустимому времени.
	return res
}


